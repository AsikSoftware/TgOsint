def _дата_время(значение) -> str:
    """«2026-11-25T14:46:02+05:00» → «25 ноября, 14:46». Сервер отдаёт время как есть."""
    текст = str(значение or "")
    if "T" not in текст:
        return текст
    дата, время = текст.split("T", 1)
    return f"{_датой(дата)}, {время[:5]}"


