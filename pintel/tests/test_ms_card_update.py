def test_a_barcode_that_is_not_the_imei_is_corrected(м):
    """Штрихкод приводим к IMEI 1 — по нему ищут, и битый штрихкод теряет телефон.

    Занятость проверяем перед записью: перехватить чужой штрихкод нельзя, иначе по нему
    начнут находиться два товара. На практике такой товар и так не дал бы себя обновить —
    поиск по двум IMEI нашёл бы обоих и отказался, — но проверка остаётся: в обычную выдачу
    не попадают архивные товары, а штрихкод у них занят по-настоящему."""
    наш = товар()
    наш["barcodes"] = [{"code128": "000000000000001"}, {"ean13": "4600000000000"}]
    ответ, журнал = выполнить(м, [наш], посылка(что="записать", товар_id="t-1"))
    assert пары(ответ)["Штрихкод товара"] == ("000000000000001", ИМЕИ[0])
    запись = next(тело for метод, _, тело in журнал if метод == "PUT")
    assert запись["barcodes"][0] == {"code128": ИМЕИ[0]}, "IMEI 1 становится первым"
    assert {"ean13": "4600000000000"} in запись["barcodes"], "прочие штрихкоды сохраняются"
