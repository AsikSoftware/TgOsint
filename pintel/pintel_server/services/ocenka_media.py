# -*- coding: utf-8 -*-
"""Обмен с ботом Оценки по коду: что дошло от сотрудника и сама сделка с точки.

Зачем это серверу. Программа на точке не видит базу Оценки — порт Postgres закрыт
наружу, — а сервер стоит на том же VPS и уже читает её (магазины, импорт оценок). Поэтому
через него идёт всё, что касса не может узнать или сделать сама:

* **что дошло в бота** — фото и видео по коду обмена. До этого касса не знала о них
  ничего: кнопка «Отправить в Оценку» нажималась и без медиа, а отказ прилетал позже,
  уже от бота, с телефоном клиента в руках.
* **сама сделка** — посылка с точки. Раньше она уходила файлом в чат Telegram, и бот
  получал её ТОЛЬКО когда кто-то нажимал кнопку под карточкой: свои исходящие сообщения
  бот не видит. Значит, сделка зависела от чата — а чат отказывал по-разному
  («chat not found», «bot was blocked by the user»), и тогда создать её было нельзя
  вовсе. Теперь посылка ложится в ту же таблицу обмена, бот забирает её оттуда сам и
  сразу создаёт сделку; подтверждать кнопкой больше нечего.

* **кто привязан и сколько стоит** (с 12.11.2026). Сотрудник сканирует QR в самом начале
  сделки, и касса показывает его имя — видно, что сделка привязана к тому, кто у стойки.
  Автоцену касса тоже спрашивает здесь, ДО медиа: запрос ложится в `quote_request`, бот
  считает своим прайсом и кладёт ответ в `quote`. Сервер прайс не читает и цену не считает.

Наружу отдаём счётчики, имя привязанного сотрудника (имя и первая буква фамилии — его и так
видят на этой кассе) и ответ о цене: `file_id` медиа и чат остаются в базе Оценки.
Строки по коду ещё нет (сотрудник не открывал ссылку) — это не ошибка, а «ничего не
прислали».

Ручной диагностики здесь нет и не спрашивается: её отмечают на экране самой программы, и
знает о ней она сама. Поля `диагностика_видна` и `не_отмечено` остались в ответе ради
сборок до doctor-64: они держали сделку, пока бот не подтвердит отметки, и ответ «я их не
вижу» для них означает «не держи» — ровно то, что нужно, пока такая точка не обновилась.
"""
from __future__ import annotations

import datetime as dt
import json
import logging
import re

from sqlalchemy import text

from pintel_core.external import ocenka_media as общее

log = logging.getLogger("pintel.ocenka")

КОД = re.compile(r"^[A-Za-z0-9]{4,16}$")
ПРЕДЕЛ_ПОСЫЛКИ = 300_000        # посылка — это текст; больше 300 КБ значит что-то не то


def состояние(код: str) -> dict:
    """Код обмена → что по нему уже есть у бота.

    `известно: False` значит ровно одно — сервер не смог посмотреть (связи с базой Оценки
    нет или она не настроена). Это не «медиа нет»: разницу обязана видеть и касса, иначе
    она либо остановит работу на ровном месте, либо назовёт собранным то, чего не видела.
    """
    код = str(код or "").strip()
    if not КОД.match(код):
        return {"известно": False, "почему": "код обмена не похож на код"}
    # что отдаём про диагностику: её тут нет, и держать из-за неё сделку нельзя
    диагностика = {"диагностика_видна": False, "не_отмечено": [],
                   "диагностика": "отмечается на экране программы"}
    try:
        строка = _строка(код)
    except Exception as exc:                                     # noqa: BLE001 — молчать нельзя
        log.warning("медиа %s: базу Оценки не спросить: %s", код, exc)
        return {"известно": False, "почему": "касса не видит базу Оценки"}
    if строка is None:
        # Строку заводит сам бот, когда сотрудник открывает ссылку из QR. Её нет — значит
        # ссылку ещё не открывали, и это нормальное начало сделки, а не сбой.
        return {"известно": True, "начали": False, "фото": 0, "видео": False,
                "готово": False, "сделка": None, "посылка_ждёт": False, "ошибка": "",
                "сотрудник": "", "оценка": None, "цену_считают": False,
                "медиа_просили": False, **диагностика}
    фото = len([x for x in str(строка["photos"] or "").split("||") if x])
    видео = bool(строка["video"])
    return {"известно": True, "начали": True, "фото": фото, "видео": видео,
            "готово": фото >= общее.НУЖНО_ФОТО and видео,
            # кто отсканировал QR: к нему привязана сделка, ему бот напишет про медиа
            "сотрудник": _имя_сотрудника(строка.get("user_id")),
            # что бот ответил о цене (None — ещё не спрашивали или ещё не ответил)
            "оценка": _оценка(строка.get("quote")),
            "цену_считают": bool(строка.get("quote_request")),
            # бот уже попросил у сотрудника фото и видео — касса показывает «ждём медиа»
            "медиа_просили": bool(строка.get("media_asked")),
            "сделка": строка["device_id"],
            # посылка уже у бота и ждёт своей очереди: касса по этому полю показывает
            # «ждём номер сделки», а не предлагает отправить ещё раз
            "посылка_ждёт": bool(строка.get("parcel")),
            # почему сделка не создалась — словами с той стороны. Пусто, пока всё хорошо.
            "ошибка": str(строка.get("parcel_error") or ""),
            **диагностика}


def принять(код: str, посылка: dict) -> dict:
    """Сделка с точки → в таблицу обмена, боту. → {принято: True} или `почему`.

    Касса по ответу решает, показывать ли «ждём сделку» или уходить в запасной путь —
    отправку карточки в Telegram. Поэтому каждый отказ назван словами: «не принято»
    без причины здесь хуже, чем ничего.
    """
    код = str(код or "").strip()
    if not КОД.match(код):
        return {"принято": False, "почему": "код обмена не похож на код"}
    if not isinstance(посылка, dict) or not посылка:
        return {"принято": False, "почему": "пустая посылка"}
    if str(посылка.get("код") or "") != код:
        return {"принято": False, "почему": "код в посылке не тот"}
    текст = json.dumps(посылка, ensure_ascii=False)
    if len(текст) > ПРЕДЕЛ_ПОСЫЛКИ:
        return {"принято": False, "почему": "посылка слишком большая"}
    try:
        строка = _строка(код)
    except Exception as exc:                                     # noqa: BLE001
        log.warning("посылка %s: базу Оценки не спросить: %s", код, exc)
        return {"принято": False, "почему": "сервер не видит базу Оценки"}
    if строка is None:
        # Строку заводит бот, когда сотрудник сканирует QR. Её нет — сделка ни к кому не
        # привязана: боту некого попросить о медиа и некому отдать карточку.
        return {"принято": False,
                "почему": "сделка не привязана к сотруднику: QR на кассе никто не сканировал"}
    if строка["device_id"]:
        return {"принято": True, "сделка": int(строка["device_id"]),
                "почему": "сделка по этому коду уже создана"}
    try:
        from .ocenka_import import _ocenka_engine
        with _ocenka_engine().begin() as conn:
            # `device_id IS NULL` в условии — чтобы посылка не легла поверх уже созданной
            # сделки, если бот успел её сделать, пока шёл этот запрос
            взято = conn.execute(text(
                "UPDATE kiosk_media SET parcel = :p, parcel_at = :t, parcel_error = NULL "
                "WHERE code = :c AND device_id IS NULL"),
                {"p": текст, "t": dt.datetime.now(dt.timezone.utc), "c": код}).rowcount
    except Exception as exc:                                     # noqa: BLE001
        # колонок может не быть (базу ещё не обновили) — тогда касса уйдёт в Telegram
        log.warning("посылка %s: не записать: %s", код, exc)
        return {"принято": False, "почему": "сервер не принял посылку"}
    if not взято:
        return {"принято": False, "почему": "строку обмена не нашли"}
    log.info("посылка %s принята, ждёт бота", код)
    return {"принято": True}


def спросить_цену(код: str, посылка: dict) -> dict:
    """Касса просит автоцену ДО сделки. → {принято: True} или `почему`.

    Запрос — та же посылка, что потом станет сделкой: бот считает цену по тем же полям и
    тем же правилам. Сюда кладём, бот забирает и отвечает в `quote`; прежний ответ стираем,
    чтобы касса не приняла цену от старых данных за новую. Сервер сам ничего не считает."""
    код = str(код or "").strip()
    if not КОД.match(код):
        return {"принято": False, "почему": "код обмена не похож на код"}
    if not isinstance(посылка, dict) or not посылка:
        return {"принято": False, "почему": "пустой запрос"}
    if str(посылка.get("код") or "") != код:
        return {"принято": False, "почему": "код в запросе не тот"}
    текст = json.dumps(посылка, ensure_ascii=False)
    if len(текст) > ПРЕДЕЛ_ПОСЫЛКИ:
        return {"принято": False, "почему": "запрос слишком большой"}
    try:
        from .ocenka_import import _ocenka_engine
        with _ocenka_engine().begin() as conn:
            взято = conn.execute(text(
                "UPDATE kiosk_media SET quote_request = :p, quote_at = :t, quote = NULL "
                "WHERE code = :c AND device_id IS NULL"),
                {"p": текст, "t": dt.datetime.now(dt.timezone.utc), "c": код}).rowcount
    except Exception as exc:                                     # noqa: BLE001
        # колонок может не быть: бот на сервере ещё прежний, цену до сделки он не считает
        log.warning("цена %s: запрос не записать: %s", код, exc)
        return {"принято": False, "почему": "бот Оценки ещё не умеет называть цену до сделки"}
    if not взято:
        return {"принято": False,
                "почему": "сделка не привязана к сотруднику: QR на кассе никто не сканировал"}
    return {"принято": True}


# ---------------------------------------------------------------- напоминание о медиа

ПАУЗА_НАПОМИНАНИЯ = 20          # секунд между напоминаниями по одной сделке
_напоминали: dict = {}          # код → когда напоминали (монотонные секунды)


def текст_напоминания(строка, точка: str = "") -> str:
    """Что бот напишет сотруднику по кнопке «Напомнить в боте».

    Сделка ждёт одного из двух: суммы клиенту (до отправки) или фото и видео (после неё)."""
    оценка = _оценка(строка.get("quote")) or {}
    if оценка.get("ждём_сумму") and оценка.get("цена") and not строка.get("parcel"):
        откуда = f" с кассы «{точка}»" if точка else " с кассы"
        цена = f"{оценка['цена']:,}".replace(",", " ")
        return (f"⏰ Напоминание{откуда}: клиент ждёт сумму.\n"
                f"Автоцена по прайсу: {цена} ₸ — это подсказка, на экране кассы её нет.\n\n"
                "Напишите сюда цифрами, какую сумму показать клиенту. Если вы начали в боте "
                "другое дело — сначала выйдите в главное меню.")
    фото = len([x for x in str(строка.get("photos") or "").split("||") if x])
    видео = bool(строка.get("video"))
    модель = ""
    try:
        посылка = json.loads(строка.get("parcel") or "{}")
        модель = str(((посылка or {}).get("сделка") or {}).get("model") or "").strip()[:50]
    except Exception:                                            # noqa: BLE001
        модель = ""
    что = "сделка" + (f" «{модель}»" if модель else "")
    откуда = f" с кассы «{точка}»" if точка else " с кассы"
    return (f"⏰ Напоминание{откуда}: {что} ждёт фото и видео.\n"
            f"Уже получено: фото {min(фото, общее.НУЖНО_ФОТО)} из {общее.НУЖНО_ФОТО}, "
            f"видео — {'есть' if видео else 'нет'}.\n\n"
            "Пришлите недостающее сюда, в этот чат, по одному. Если вы начали в боте другое "
            "дело — сначала выйдите в главное меню.")


def напомнить(код: str, токен: str, точка: str = "", часы=None) -> dict:
    """Кнопка «Напомнить в боте» на кассе. → {отправлено: bool, почему: str}.

    Сотрудник привязал сделку, бот попросил у него фото и видео — а он ушёл в другое место
    бота, и запрос уехал вверх по чату. Сама сделка при этом цела (лежит в таблице обмена,
    и присланное медиа бот отнесёт к ней), но человеку это неоткуда узнать. Сервер пишет
    ему от имени бота: токен бота тот же, что касса получает в настройках.

    Бота не трогаем и не перезапускаем: своё исходящее сообщение он не видит, а принять
    медиа без подсказки умеет и так. Токен в журнал и в ответ не попадает — в том числе
    через текст исключения, где он стоит внутри адреса."""
    import time
    import httpx
    код = str(код or "").strip()
    if not КОД.match(код):
        return {"отправлено": False, "почему": "код обмена не похож на код"}
    if not токен:
        return {"отправлено": False, "почему": "в настройках кассы не задан токен бота Оценки"}
    try:
        строка = _строка(код)
    except Exception as exc:                                     # noqa: BLE001
        log.warning("напоминание %s: базу Оценки не спросить: %s", код, exc)
        return {"отправлено": False, "почему": "касса не видит базу Оценки"}
    if строка is None or not строка.get("chat_id"):
        return {"отправлено": False, "почему": "сделка не привязана к сотруднику"}
    if строка.get("device_id"):
        return {"отправлено": False, "почему": f"сделка № {строка['device_id']} уже создана"}
    сейчас = (часы or time.monotonic)()
    if сейчас - _напоминали.get(код, -1e9) < ПАУЗА_НАПОМИНАНИЯ:
        return {"отправлено": False, "почему": "только что напоминали — подождите немного"}
    try:
        ответ = httpx.post(f"https://api.telegram.org/bot{токен}/sendMessage",
                           data={"chat_id": строка["chat_id"], "text": текст_напоминания(строка, точка)},
                           timeout=20).json()
    except Exception as exc:                                     # noqa: BLE001
        log.warning("напоминание %s: Telegram не ответил (%s)", код, type(exc).__name__)
        return {"отправлено": False, "почему": "Telegram не ответил — проверьте интернет и повторите"}
    if not (isinstance(ответ, dict) and ответ.get("ok")):
        почему = str((ответ or {}).get("description") or "причина не названа")[:120]
        log.warning("напоминание %s: Telegram отказал: %s", код, почему)
        if "blocked" in почему.lower() or "chat not found" in почему.lower():
            почему = "бот не может написать сотруднику — откройте бота Оценки и нажмите «Старт»"
        return {"отправлено": False, "почему": почему}
    _напоминали[код] = сейчас
    log.info("напоминание %s: отправлено сотруднику", код)
    return {"отправлено": True, "почему": ""}


def _оценка(сырое):
    """Ответ бота о цене → {цена, почему, запрос, сумма, ждём_сумму, беда} или None, если
    ответа ещё нет.

    `ждём_сумму` — бот посчитал цену по прайсу и спросил привязанного сотрудника, какую
    сумму показать клиенту; `сумма` — что тот ответил; `беда` — почему бот не смог ему
    написать. Касса цену из прайса клиенту не показывает: пока суммы нет, она ждёт."""
    if not сырое:
        return None
    try:
        d = json.loads(сырое)
    except Exception:                                            # noqa: BLE001
        return None
    if not isinstance(d, dict):
        return None
    def число(v):
        return int(v) if isinstance(v, (int, float)) and not isinstance(v, bool) and v > 0 else None

    return {"цена": число(d.get("цена")), "сумма": число(d.get("сумма")),
            "ждём_сумму": bool(d.get("ждём_сумму")), "беда": str(d.get("беда") or "")[:200],
            "почему": str(d.get("почему") or "")[:300], "запрос": str(d.get("запрос") or "")[:40]}


def _имя_сотрудника(user_id) -> str:
    """«Асылбек Н.» по id пользователя Оценки. Не прочиталось — пусто: имя тут для
    спокойствия сотрудника, и из-за него нельзя терять ответ про медиа и сделку."""
    if not user_id:
        return ""
    try:
        from .ocenka_import import _ocenka_engine
        with _ocenka_engine().connect() as conn:
            кто = conn.execute(text("SELECT first_name, last_name FROM users WHERE id = :i"),
                               {"i": int(user_id)}).mappings().first()
    except Exception:                                            # noqa: BLE001
        return ""
    if not кто:
        return ""
    имя = str(кто.get("first_name") or "").strip()
    фамилия = str(кто.get("last_name") or "").strip()
    return (имя + (f" {фамилия[0]}." if фамилия else "")).strip()[:60]


def _строка(код: str):
    """Строка обмена по коду или None. Берём целиком: таблица на сервере живёт своей
    жизнью (колонок `checks`, `parcel` может не быть), а запрос с несуществующей колонкой
    упал бы целиком — и касса перестала бы видеть даже фото с видео."""
    from .ocenka_import import _ocenka_engine
    with _ocenka_engine().connect() as conn:
        return conn.execute(text("SELECT * FROM kiosk_media WHERE code = :c"),
                            {"c": код}).mappings().first()
