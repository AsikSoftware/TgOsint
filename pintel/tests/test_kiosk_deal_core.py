def test_the_marks_come_from_the_program_not_from_the_bot(ядро):
    """Отметки приезжают в посылке: их ставит сотрудник на экране кассы, телефон у него в
    руках. Строку обмена смотрим только вторым — ради точек со старой сборкой.

    Так выглядит переход: пока такая точка не обновилась, бот спрашивает её кнопками, как
    раньше, и ни одна сделка из-за перехода не теряется."""
    своё = {k: True for k in ядро.КЛЮЧИ}
    с_отметками = посылка(ручная_диагностика=своё)
    # в строке обмена отметок нет вовсе (колонки checks может не быть в базе) — не мешает
    assert ядро.проверить(с_отметками, строка(ядро, checks=None)) == []
    assert ядро.отметки(с_отметками, {"checks": None}) == своё
    assert ядро.диагностика_из_посылки(с_отметками) == своё
    # посылка главнее строки: программа видела телефон, а в строке могли остаться старые нажатия
    плохое = {**своё, "glue": False}
    assert ядро.отметки(посылка(ручная_диагностика=плохое), строка(ядро))["glue"] is False
    # старая сборка отметок не присылает — тогда работают нажатия в боте
    assert ядро.отметки(посылка(), строка(ядро)) == своё
    assert ядро.диагностика_из_посылки(посылка()) == {}
    # и поломка, найденная руками, снимает автоцену, откуда бы отметки ни пришли
    поля = {"phone_status": ядро.СТАТУС_ЧИСТЫЙ, "price_grade_auto": 250000}
    п = тест(ядро, ручная_диагностика=плохое)
