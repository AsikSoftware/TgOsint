# -*- coding: utf-8 -*-
"""Карточка товара в МойСкладе: завести новые доп. поля и переименовать прежние.

    python3 ms_card_setup.py <.env бота> show              # что есть сейчас (только чтение)
    python3 ms_card_setup.py <.env бота> add --dry         # что добавится
    python3 ms_card_setup.py <.env бота> add               # добавить
    python3 ms_card_setup.py <.env бота> rename --dry      # что переименуется
    python3 ms_card_setup.py <.env бота> rename            # переименовать

МойСклад один — и у боевого бота, и у тестового. Всё, что делает этот файл, делается в
боевом аккаунте, поэтому два шага разведены:

* **add** — только добавление: новые поля товара и новые значения справочников. Ничего
  существующего не меняет, работающему боту не мешает: о новых полях он не знает.
* **rename** — переименование поля «Ремонт статус» в «Статус» и трёх его значений. Бот
  ищет поля и значения по имени, поэтому этот шаг — ТОЛЬКО после того, как в боте стоит
  `ms_card_patch.py` и бот перезапущен. Иначе приход из Excel откажет файлам.

Чего файл не делает: не удаляет ни полей, ни значений, не трогает ни один товар. Значения,
которые стоят у старых товаров, остаются при них; переименованное значение у них просто
начинает называться по-новому (смысл тот же).

Тип поля в МойСкладе изменить нельзя. Поэтому «АКБ» остаётся справочником — в него
добавляются значения по процентам; а «Sim Лоток» — новое поле-галочка, прежний справочник
«Sim слот» остаётся как есть.

Ключ берётся из .env бота (`API_KEY_SKLAD`) и никуда не печатается.
"""
import gzip
import json
import sys
import time
import urllib.error
import urllib.request

АДРЕС = "https://api.moysklad.ru/api/remap/1.2"

# новые поля товара: имя → тип МойСклада
НОВЫЕ_ПОЛЯ = (
    ("Sim Лоток", "boolean"),             # галочка: есть лоток / нет
    ("Цвет", "string"),
    ("Panic full", "boolean"),
    ("Сим без ограничений", "boolean"),
    ("Номер сделки", "long"),
    ("Отчёт диагностики", "string"),      # что не прошло проверку — только у «не в норме»
)
ПРОЦЕНТЫ = [f"{n}%" for n in range(60, 100)]      # «100%» в справочнике уже есть
ПОЛЕ_СТАТУСА_БЫЛО, ПОЛЕ_СТАТУСА_СТАЛО = "Ремонт статус", "Статус"
НОВОЕ_ЗНАЧЕНИЕ_СТАТУСА = "Запечатанный (новый)"
# значения справочника состояния: было → стало (как кнопки бота Оценки)
ЗНАЧЕНИЯ_СТАТУСА = (
    ("Не был в ремонте", "Б/у телефон в нормальном состоянии"),
    ("Ранее был ремонт", "Телефон был в ремонте"),
    ("Присутствует дефект", "Есть видимые дефекты"),
)


def ключ(путь):
    for строка in open(путь, encoding="utf-8", errors="replace"):
        if строка.startswith("API_KEY_SKLAD="):
            return строка.split("=", 1)[1].strip().strip('"').strip("'")
    sys.exit("в файле нет API_KEY_SKLAD")


class Склад:
    def __init__(self, токен, всухую):
        self.токен, self.всухую, self.сделано = токен, всухую, []

    def запрос(self, метод, адрес, тело=None):
        if not адрес.startswith("http"):
            адрес = АДРЕС + адрес
        данные = json.dumps(тело, ensure_ascii=False).encode("utf-8") if тело is not None else None
        req = urllib.request.Request(адрес, data=данные, method=метод, headers={
            "Authorization": "Bearer " + self.токен, "Accept-Encoding": "gzip",
            "Accept": "application/json;charset=utf-8", "Content-Type": "application/json"})
        try:
            with urllib.request.urlopen(req, timeout=40) as r:
                ответ = r.read()
                if r.headers.get("Content-Encoding") == "gzip":
                    ответ = gzip.decompress(ответ)
        except urllib.error.HTTPError as exc:
            текст = exc.read()
            try:
                текст = gzip.decompress(текст)
            except Exception:                                    # noqa: BLE001
                pass
            sys.exit(f"МойСклад отказал ({exc.code}) на {метод} {адрес.replace(АДРЕС, '')}: "
                     + текст.decode("utf-8", "replace")[:400])
        time.sleep(0.12)                                         # не чаще ~8 запросов в секунду
        return json.loads(ответ) if ответ else {}

    def писать(self, что, метод, адрес, тело):
        """Одна запись в МойСклад. Всухую — только говорим, что сделали бы."""
        print(("   [всухую] " if self.всухую else "   ") + что)
        if self.всухую:
            return {}
        self.сделано.append(что)
        return self.запрос(метод, адрес, тело)

    def поля(self):
        return self.запрос("GET", "/entity/product/metadata/attributes").get("rows") or []

    def значения(self, поле):
        cid = (поле.get("customEntityMeta") or {}).get("href", "").rstrip("/").rsplit("/", 1)[-1]
        все, сдвиг = [], 0
        while True:
            кусок = self.запрос("GET", f"/entity/customentity/{cid}?limit=100&offset={сдвиг}").get("rows") or []
            все += кусок
            if len(кусок) < 100:
                return cid, все
            сдвиг += 100


def найти(ряд, *имена):
    """Поле или значение по любому из имён, без учёта регистра."""
    for имя in имена:
        for x in ряд:
            if (x.get("name") or "").strip().casefold() == имя.casefold():
                return x
    return None


def показать(с):
    поля = с.поля()
    print(f"доп. полей товара: {len(поля)}")
    for a in поля:
        хвост = ""
        if a.get("type") == "customentity":
            _, знач = с.значения(a)
            хвост = f" — {len(знач)} значений: " + ", ".join(sorted(v.get("name") or "" for v in знач))[:150]
        print(f"   {a.get('name'):<24} {a.get('type'):<13}{хвост}")
    return поля


def добавить(с):
    поля = с.поля()
    print("== новые поля товара")
    for имя, вид in НОВЫЕ_ПОЛЯ:
        есть = найти(поля, имя)
        if есть:
            print(f"   уже есть: {имя} ({есть.get('type')})"
                  + ("" if есть.get("type") == вид else f" — ТИП ДРУГОЙ, ждали {вид}"))
            continue
        с.писать(f"создать поле «{имя}» ({вид})", "POST", "/entity/product/metadata/attributes",
                 {"name": имя, "type": вид, "required": False})
    print("== справочник «АКБ»: значения по процентам")
    акб = найти(поля, "АКБ")
    if not акб or акб.get("type") != "customentity":
        sys.exit("поле «АКБ» не найдено или это не справочник — не трогаю")
    cid, значения = с.значения(акб)
    добавлено = 0
    for п in ПРОЦЕНТЫ:
        if not найти(значения, п):
            с.писать(f"добавить значение «{п}»", "POST", f"/entity/customentity/{cid}", {"name": п})
            добавлено += 1
    print(f"   значений было {len(значения)}, добавляется {добавлено}")
    print("== справочник состояния: значение для запечатанного")
    статус = найти(поля, ПОЛЕ_СТАТУСА_СТАЛО, ПОЛЕ_СТАТУСА_БЫЛО)
    if not статус or статус.get("type") != "customentity":
        sys.exit("поле состояния не найдено или это не справочник — не трогаю")
    cid, значения = с.значения(статус)
    if найти(значения, НОВОЕ_ЗНАЧЕНИЕ_СТАТУСА):
        print(f"   уже есть: {НОВОЕ_ЗНАЧЕНИЕ_СТАТУСА}")
    else:
        с.писать(f"добавить значение «{НОВОЕ_ЗНАЧЕНИЕ_СТАТУСА}»", "POST",
                 f"/entity/customentity/{cid}", {"name": НОВОЕ_ЗНАЧЕНИЕ_СТАТУСА})


def переименовать(с):
    поля = с.поля()
    статус = найти(поля, ПОЛЕ_СТАТУСА_СТАЛО, ПОЛЕ_СТАТУСА_БЫЛО)
    if not статус or статус.get("type") != "customentity":
        sys.exit("поле состояния не найдено или это не справочник — не трогаю")
    print("== поле состояния")
    if (статус.get("name") or "").strip() == ПОЛЕ_СТАТУСА_СТАЛО:
        print(f"   уже называется «{ПОЛЕ_СТАТУСА_СТАЛО}»")
    else:
        с.писать(f"переименовать поле «{статус.get('name')}» → «{ПОЛЕ_СТАТУСА_СТАЛО}»", "PUT",
                 статус["meta"]["href"], {"name": ПОЛЕ_СТАТУСА_СТАЛО})
    print("== значения справочника состояния")
    cid, значения = с.значения(статус)
    for было, стало in ЗНАЧЕНИЯ_СТАТУСА:
        уже, старое = найти(значения, стало), найти(значения, было)
        if уже and not старое:
            print(f"   уже называется «{стало}»")
        elif уже and старое:
            print(f"   ЕСТЬ ОБА: «{было}» и «{стало}» — не трогаю, разберите руками")
        elif старое:
            с.писать(f"переименовать значение «{было}» → «{стало}»", "PUT",
                     f"/entity/customentity/{cid}/{старое['id']}", {"name": стало})
        else:
            print(f"   нет ни «{было}», ни «{стало}» — пропускаю")


def main():
    if len(sys.argv) < 3 or sys.argv[2] not in ("show", "add", "rename"):
        sys.exit(__doc__)
    с = Склад(ключ(sys.argv[1]), всухую="--dry" in sys.argv)
    шаг = sys.argv[2]
    if шаг == "show":
        показать(с)
        return
    добавить(с) if шаг == "add" else переименовать(с)
    print("записей в МойСклад:", len(с.сделано), "(всухую — ничего не менялось)" if с.всухую else "")


main()
