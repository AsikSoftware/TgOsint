def sql_devices(поля: dict) -> str:
    """INSERT по именам колонок. Имена — только из белого списка, значения — через bind."""
    лишние = set(поля) - set(КОЛОНКИ) - set(СВОИ)
    if лишние:
        raise ОшибкаПосылки("не наши колонки: " + ", ".join(sorted(лишние)))
    имена = [k for k in list(КОЛОНКИ) + list(СВОИ) if k in поля]
    return ("INSERT INTO devices (producer, online, " + ", ".join(имена) + ") "
            "VALUES ('Apple', false, " + ", ".join(":" + k for k in имена) + ") RETURNING id")


# ---------------------------------------------------------------- шаги приёма медиа

# Порядок важен дважды: в Оценке фото показываются в том порядке, в каком легли (первым —
# экран с IMEI), и по числу уже принятых фото бот понимает, какой шаг сейчас. Шаг считается
# по базе, а не держится в памяти бота: перезапуск бота не должен ронять приём на всех
# точках разом — строка в kiosk_media переживает его.
ЭТАПЫ_ФОТО = (
    "фото экрана с набранным <b>*#06#</b> — чтобы IMEI был виден на самом телефоне",
    "фото <b>лицевой</b> стороны — телефон целиком в кадре",
    "фото <b>задней</b> стороны",
)
ЭТАП_ВИДЕО = "<b>видео</b> телефона — без него сделка в Оценке не открывается"

ЖДЁМ_ФОТО, ЖДЁМ_ВИДЕО = "фото", "видео"


def сколько_фото(строка) -> int:
    """Фото копятся в одной колонке через «||», как в самой Оценке."""
    return len([x for x in str((строка or {}).get("photos") or "").split("||") if x])


def чего_не_хватает(строка) -> list:
    """Что ещё прислать, по порядку. Пусто — медиа собраны."""
    чего = list(ЭТАПЫ_ФОТО[сколько_фото(строка):])
    if not (строка or {}).get("video"):
        чего.append(ЭТАП_ВИДЕО)
    return чего


def что_ждём(строка):
    """Что принимаем прямо сейчас: ЖДЁМ_ФОТО, ЖДЁМ_ВИДЕО или None — медиа собраны.

    Порядок строгий, и принимается только своё. С точки пришла жалоба: на шаге «фото
    задней стороны» прислали видео, бот ответил «Видео принято. Теперь фото задней
    стороны» — и сотрудник решил, что видео уже учтено, хотя шаг видео был ещё впереди.
    Когда медиа собраны (None), принимается и то и другое: можно доложить фото дефекта
    или переснять видео."""
    осталось = чего_не_хватает(строка)
    if not осталось:
        return None
    return ЖДЁМ_ВИДЕО if осталось[0] == ЭТАП_ВИДЕО else ЖДЁМ_ФОТО


def не_то_прислали(строка, что: str) -> str:
    """Прислали не то, что нужно на этом шаге. → что ответить сотруднику.

    Главное в ответе — чего ждём, а не что получили: человек на точке держит в руках
    телефон клиента, ему нужно действие, а не отчёт."""
    если_видео = что == ЖДЁМ_ВИДЕО
    пришло, ждали = (ЖДЁМ_ВИДЕО, ЖДЁМ_ФОТО) if если_видео else (ЖДЁМ_ФОТО, ЖДЁМ_ВИДЕО)
    хвост = ("Видео — последним шагом, после фото." if если_видео
             else "Дополнительные фото можно прислать после видео.")
    return (f"❌ Нужно {ждали}, а пришло {пришло} — не принял.\n\n"
            f"Сейчас: {чего_не_хватает(строка)[0]}\n{хвост}")


def шаги_списком() -> str:
    return "\n".join(f"{n}. {ш}" for n, ш in enumerate(ЭТАПЫ_ФОТО + (ЭТАП_ВИДЕО,), 1))


# ---------------------------------------------------------------- ручная диагностика

# Что проверяет сотрудник РУКАМИ. Кабель и базы IMEI не умеют ничего из этого списка: они
# читают прошивку и привязку модулей, а не то, слышно ли динамик и жива ли кнопка. Поэтому
# список закрытый и одинаковый для всех точек — чтобы оценщик в карточке видел не
# «осмотрено», а по пунктам.
#
# Отмечают их на экране программы на точке (телефон клиента там же, на столе), и приезжают
# они в посылке. Кнопки в боте остались для точек со старой сборкой — она отметок не
# присылает; список здесь нужен обоим путям и чтобы назвать отметки словами в карточке.
#
# Экран, касание, камеры, динамик и микрофон здесь НЕ спрашиваются: их прогоняет сам телефон
# клиента на странице теста по QR с экрана кассы (ТЕСТЫ ниже, pintel_core/phonetest.py).
# Остались ровно те проверки, которых браузер сделать не может: кнопки и переключатель,
# вибрация, разблокировка лицом, зарядка, SIM и сеть, целость проклейки.
#
# Два последних пункта — не поломки, а то, что кабель НЕ может подтвердить и о чём отчёт
# прямо говорит «проверить на телефоне»: раздел «Детали и обслуживание» (подлинность
# деталей подтверждает только Apple, и только с экрана) и «VPN и управление устройством»
# (корпоративный надзор по кабелю определяется не на всех моделях).
#
# Ключи ASCII и короткие: они едут в callback_data кнопки (64 байта на всё) и в колонку
# checks. Надписи — русские, их читает сотрудник.
ПУНКТЫ = (
    ("keys", "Кнопки", "питание, громкость, бесшумный режим"),
    ("vibro", "Вибрация", "Taptic отзывается (браузер не умеет)"),
    ("bio", "Face ID", "разблокировка лицом или отпечатком"),
    ("charge", "Зарядка", "заряжается от кабеля"),
    ("net", "Связь", "SIM видна, сеть и Wi-Fi работают"),
    ("glue", "Герметик", "проклейка на месте, зазоров нет"),
    ("apple", "Детали Apple", "«Детали и обслуживание»: всё родное"),
    ("mdm", "Управление", "VPN и управление: чужих профилей нет"),
)
КЛЮЧИ = tuple(k for k, _, _ in ПУНКТЫ)
КОРОТКО = {k: s for k, s, _ in ПУНКТЫ}
ПОДРОБНО = {k: d for k, _, d in ПУНКТЫ}
# Ключ тоже ASCII, и по той же причине: он едет в callback_data кнопки рядом с ключами
# пунктов, а кириллица в ней съедает по два байта на букву.
ЗАПЕЧАТАН = "sealed"                       # коробку не вскрывали — проверять нечего


def диагностика_разобрать(сырое) -> dict:
    """Колонка `checks` → отметки. Всё лишнее и непонятное отбрасываем молча: это наши же
    данные, но полежавшие в базе между версиями обработчика."""
    if isinstance(сырое, (bytes, bytearray)):
        сырое = bytes(сырое).decode("utf-8", "replace")
    if isinstance(сырое, str):
        try:
            сырое = json.loads(сырое or "{}")
        except Exception:                                        # noqa: BLE001
            return {}
    if not isinstance(сырое, dict):
        return {}
    из = {}
    for k, v in сырое.items():
        if k == ЗАПЕЧАТАН and v:
            из[ЗАПЕЧАТАН] = True
        elif k in КЛЮЧИ and isinstance(v, bool):
            из[k] = v
    return из


def диагностика_сохранить(отметки: dict) -> str:
    return json.dumps(диагностика_разобрать(отметки), ensure_ascii=False, sort_keys=True)


def диагностика_переключить(отметки: dict, ключ: str) -> dict:
    """Нажатие на пункт: не отмечено → работает → не работает → не отмечено.

    Третьего состояния «не проверял» нет намеренно: оно стало бы способом пропустить шаг.
    Нечем проверить (нет SIM, телефон не включается) — это «не работает», и сделка уходит
    на ручную оценку. Ошибка в эту сторону стоит оценки человеком, обратная — денег.
    """
    d = dict(диагностика_разобрать(отметки))
    if ключ == ЗАПЕЧАТАН:
        if d.get(ЗАПЕЧАТАН):
            return {}
        return {ЗАПЕЧАТАН: True}
    if ключ not in КЛЮЧИ:
        return d
    d.pop(ЗАПЕЧАТАН, None)                 # отмечают по пунктам — значит коробка вскрыта
    текущее = d.get(ключ)
    if текущее is None:
        d[ключ] = True
    elif текущее is True:
        d[ключ] = False
    else:
        d.pop(ключ, None)
    return d


def запечатан(отметки: dict) -> bool:
    return bool(диагностика_разобрать(отметки).get(ЗАПЕЧАТАН))


def не_отмечено(отметки: dict) -> list:
    """Пункты, по которым ответа ещё нет, — короткими надписями, в порядке списка."""
    d = диагностика_разобрать(отметки)
    if d.get(ЗАПЕЧАТАН):
        return []
    return [КОРОТКО[k] for k in КЛЮЧИ if not isinstance(d.get(k), bool)]


def плохие(отметки: dict) -> list:
    """Пункты, отмеченные «не работает» → [(ключ, надпись)]."""
    d = диагностика_разобрать(отметки)
    return [(k, КОРОТКО[k]) for k in КЛЮЧИ if d.get(k) is False]


def диагностика_готова(отметки: dict) -> bool:
    d = диагностика_разобрать(отметки)
    return bool(d.get(ЗАПЕЧАТАН)) or not не_отмечено(d)


def диагностика_словами(отметки: dict) -> str:
    """Отметки → одна строка для комментария оценщика. Пусто — диагностики не было."""
    d = диагностика_разобрать(отметки)
    if d.get(ЗАПЕЧАТАН):
        return "Ручная диагностика: коробку не вскрывали"
    плох = [имя for _, имя in плохие(d)]
    нет = не_отмечено(d)
    если_всё = len([k for k in КЛЮЧИ if isinstance(d.get(k), bool)])
    if not если_всё:
        return ""
    куски = [f"Ручная диагностика ({если_всё} из {len(КЛЮЧИ)})"]
    куски.append("НЕ РАБОТАЕТ: " + ", ".join(плох) if плох else "всё работает")
    if нет:
        куски.append("не отмечено: " + ", ".join(нет))
    return " · ".join(куски)


# ---------------------------------------------------------------- тест на телефоне клиента

# КОПИЯ `pintel_core/phonetest.py` (ТЕСТЫ): там его показывает страница на телефоне клиента
# и экран кассы, здесь он нужен, чтобы назвать результат словами в карточке сделки. Живут в
# разных местах — программа в exe, обработчик на сервере; расхождение ловит тест.
#
# Телефон клиента открывает страницу по QR с экрана кассы (мини-сервер в самом киоске, своя
# локальная сеть) и сам прогоняет тесты: сетку закрасили целиком — сенсор жив, пять касаний
# поймались — мультитач жив, снимок не чёрный — камера снимает; пятна на залитом экране и
# хрип в динамике оценивает человек, который смотрит и слушает.
ТЕСТ_ОК, ТЕСТ_ПЛОХО, ТЕСТ_ПРОПУСК = "ok", "fail", "skip"
ТЕСТЫ = (
    ("sensor", "Сенсор", "закрасить пальцем всю сетку — зачёт автоматом"),
    ("multitouch", "Мультитач", "пять касаний одновременно — зачёт автоматом"),
    ("screen", "Экран", "заливка цветами: пятна, полосы, битые точки"),
    ("speaker", "Динамик", "мелодия через динамик"),
    ("mic", "Микрофон", "запись голоса и воспроизведение"),
    ("camera_back", "Камера сзади", "снимок: не чёрный, в фокусе"),
    ("camera_front", "Камера спереди", "снимок: не чёрный, в фокусе"),
)
ТЕСТ_КЛЮЧИ = tuple(k for k, _, _ in ТЕСТЫ)
ТЕСТ_ИМЕНА = {k: n for k, n, _ in ТЕСТЫ}


def тест_разобрать(посылка: dict) -> dict:
    """Посылка → ответы теста с телефона. Чужое и непонятное отбрасываем молча: страница
    открыта на аппарате клиента, то есть на устройстве, которого мы не знаем."""
    сырое = (посылка or {}).get("тест_телефона")
    if not isinstance(сырое, dict):
        return {}
    return {k: v for k, v in сырое.items()
            if k in ТЕСТ_КЛЮЧИ and isinstance(v, str) and v in (ТЕСТ_ОК, ТЕСТ_ПЛОХО, ТЕСТ_ПРОПУСК)}


def тест_плохие(тест: dict) -> list:
    """Тесты, которые телефон НЕ прошёл → [(ключ, имя)]. Это дефект аппарата."""
    return [(k, ТЕСТ_ИМЕНА[k]) for k in ТЕСТ_КЛЮЧИ if (тест or {}).get(k) == ТЕСТ_ПЛОХО]


def тест_пропущенные(тест: dict) -> list:
    """Тесты без ответа или «не проверили» → [(ключ, имя)]. Это неполная проверка."""
    return [(k, ТЕСТ_ИМЕНА[k]) for k in ТЕСТ_КЛЮЧИ
            if (тест or {}).get(k) in (None, ТЕСТ_ПРОПУСК)]


def тест_словами(посылка: dict) -> str:
    """Результат теста одной строкой — в комментарий оценщика.

    Теста нет вовсе — так и говорим: это неполная проверка, а не «всё хорошо». Сотрудник мог
    отметить, что телефона не было в сети кассы, — тогда называем и это, вместе с тем, кто
    отметил: пропуск возможен, но он записан."""
    тест = тест_разобрать(посылка)
    пропущен = str((посылка or {}).get("тест_пропущен") or "").strip()[:200]
    if not тест:
        return ("Тест на телефоне пропущен: " + пропущен if пропущен
                else "Теста на телефоне не было")
    плох = [имя for _, имя in тест_плохие(тест)]
    проп = [имя for _, имя in тест_пропущенные(тест)]
    куски = [f"Тест на телефоне ({len(тест)} из {len(ТЕСТ_КЛЮЧИ)})"]
    куски.append("НЕ ПРОШЛИ: " + ", ".join(плох) if плох else "всё прошло")
    if проп:
        куски.append("не проверили: " + ", ".join(проп))
    return " · ".join(куски)


def применить_диагностику(поля: dict, отметки: dict, посылка: dict = None) -> dict:
    """Отметки сотрудника, тест с телефона клиента и неполнота проверки → поля сделки.

    **Любой отказ — хоть в проверках руками, хоть в тесте на телефоне — это «Присутствует
    дефект»**, и автоцены у такой сделки нет. Неважно, какой именно пункт: не работает
    кнопка, молчит динамик, нет проклейки или Apple показала неизвестную деталь — всё это
    нашёл человек с телефоном в руках, и цену такому аппарату называет человек.

    «Ранее был в ремонте» остаётся за находками кабеля (замена детали, неоригинальная
    батарея, перепайка, надзор, реестр) — их приносит уже переклассифицированный
    `phone_status` из посылки.

    Состояние, которое и так не чистое, не переписываем: выбор сотрудника и вердикт кабеля
    стоят твёрже отметки.
    """
    посылка = посылка or {}
    out = dict(поля)
    плох = плохие(отметки)
    тест = тест_разобрать(посылка)
    плох_тест = тест_плохие(тест)
    if (плох or плох_тест) and out.get("phone_status") == СТАТУС_ЧИСТЫЙ:
        out["phone_status"] = СТАТУС_ДЕФЕКТ
    неполно = неполнота(посылка)
    # Строку про тест могла уже вписать сама программа на точке: новая сборка уезжает на все
    # точки сразу, а этот файл ставят руками, и в карточке результат нужен при любом порядке.
    было_про_тест = "Тест на телефоне" in str(поля.get("comment_ocenka") or "")
    хвосты = [диагностика_словами(отметки), "" if было_про_тест else тест_словами(посылка)]
    if неполно:
        хвосты.append("ПРОВЕРКА НЕПОЛНАЯ: " + "; ".join(str(x) for x in неполно)[:600])
    хвост = " · ".join(x for x in хвосты if x)
    if хвост:
        было = str(out.get("comment_ocenka") or "").strip()
        out["comment_ocenka"] = ((было + " · " if было else "") + хвост)[:ПРЕДЕЛЫ["comment_ocenka"]]
    return out


def неполнота(посылка: dict) -> list:
    """Что в проверке осталось непрочитанным и закрыть это нечем. → строки для оценщика.

    Сверку деталей на телефоне сюда НЕ кладём: её закрывает пункт «Детали Apple» ручной
    диагностики, то есть человек с телефоном в руках. Здесь только то, что закрыть нечем:
    непрочитанная батарея, неспрошенный чёрный список, молчащий реестр — и тест на телефоне
    клиента, если его не прогнали или довели не до конца.
    """
    посылка = посылка or {}
    нет = [str(x)[:200] for x in (посылка.get("не_прочиталось") or []) if str(x or "").strip()][:6]
    тест = тест_разобрать(посылка)
    if not тест:
        # Теста нет совсем: либо сотрудник отметил, что телефона не было в сети кассы, либо
        # на точке стоит старая программа, которая его ещё не умеет. И то и другое — неполная
        # проверка: автоцены нет, сделку смотрит человек. Отказывать нельзя, иначе точка со
        # старой сборкой перестанет работать совсем.
        нет.append(тест_словами(посылка))
    else:
        проп = [имя for _, имя in тест_пропущенные(тест)]
        if проп:
            нет.append("тест на телефоне не доведён: " + ", ".join(проп))
    return нет
