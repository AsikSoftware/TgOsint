# -*- coding: utf-8 -*-
"""Свободный номер приёмки — когда МойСклад отказывается проводить документ.

21.11.2026, сделка 17476: документ приёмки № 80879 создался, а провести его МойСклад не дал:

    HTTP 412 PUT /entity/supply/<id>
    {"error": "Ошибка сохранения объекта: нарушено ограничение уникальности параметра 'name'",
     "code": 3006, "parameter": "name"}

Живой приёмки с таким номером в МойСкладе ровно одна — наша. Значит номер держит удалённая:
она отдаёт его счётчику, но из-под себя не отпускает (это же мы ловили в сверке Pay, где
приёмки ищутся по номеру). В ту же секунду приёмку руками создавал сотрудник — ей достался
80880, и наш документ оказался на занятом номере.

Проверено на боевом: тот же документ с номером 80881 провёлся сразу, сумма и позиция те же.

Поэтому правило простое: отказ про уникальность имени — это НЕ повод бросать документ.
Берём следующий свободный номер, ставим его этому же документу и проводим. Второго документа
не появляется, деньги и телефон те же, а наружу бот называет итоговый номер — по нему потом
ищет сверка.
"""
import re

ПРИЗНАК = re.compile(r"уникальност\w*\s+параметра\s+'name'", re.I)
ПОСМОТРЕТЬ = 50            # сколько последних приёмок смотрим, чтобы узнать текущий счёт
ПОПЫТОК = 20               # сколько номеров подряд пробуем, прежде чем сдаться


def это_занятый_номер(ошибка) -> bool:
    """Отказ МойСклада именно про занятый номер документа? → да/нет.

    Про остальные отказы (нет прав, кончился тариф, позиция без цены) врать нельзя: там смена
    номера ничего не чинит, а повторная запись сделала бы хуже."""
    текст = str(ошибка or "")
    return bool(ПРИЗНАК.search(текст)) or ("'name'" in текст and "3006" in текст)


def свободный_номер(запросить, *, начать_с=None) -> str:
    """Следующий номер, которого в приёмках нет. `запросить(метод, путь, params=...)` — наш
    ход в МойСклад; возвращает разобранный ответ.

    Считаем от самого большого номера среди последних приёмок, а не от номера застрявшего
    документа: счётчик мог уйти вперёд, пока документ висел.
    """
    if начать_с is None:
        строки = (запросить("GET", "/entity/supply",
                            params={"order": "created,desc", "limit": ПОСМОТРЕТЬ}) or {}).get("rows") or []
        номера = [int(с["name"]) for с in строки if str(с.get("name") or "").strip().isdigit()]
        начать_с = (max(номера) + 1) if номера else 1
    кандидат = int(начать_с)
    for _ in range(ПОПЫТОК):
        занято = (запросить("GET", "/entity/supply",
                            params={"filter": f"name={кандидат}", "limit": 1}) or {}).get("rows") or []
        if not занято:
            return str(кандидат)
        кандидат += 1
    raise RuntimeError(f"свободный номер приёмки не нашёлся за {ПОПЫТОК} попыток "
                       f"(смотрел с {начать_с})")
