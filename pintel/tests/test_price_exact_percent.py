def test_the_diagnostics_parser_reads_the_percent_header():
    """Тот же лист читает и разбор прайса в ядре: сетка по процентам, база — цена 100%."""
    assert gsheet._wear_key("72%") == "72%" and gsheet._wear_key(" 100 % ") == "100%"
    assert gsheet._wear_key("150%") is None
    assert gsheet._wear_key("100 (0-30)") == "100новый" and gsheet._wear_key("96-99") == "96-99"

    база, сетка, _ = gsheet.parse([ШАПКА_ПРОЦЕНТЫ, СТРОКА_ПРОЦЕНТЫ], MODELS)
    assert база["iPhone17,2"]["1024"] == 420000
    клетки = сетка["iPhone17,2"]["1024"]
    assert клетки["88%"] == 354000 and клетки["72%"] == 294000 and len(клетки) == 29

    # вкладка по диапазонам разбирается как прежде
    база, сетка, _ = gsheet.parse([ШАПКА_ДИАПАЗОНЫ, СТРОКА_ДИАПАЗОНЫ], MODELS)
    assert база["iPhone17,2"]["1024"] == 420000 and сетка["iPhone17,2"]["1024"]["86-90"] == 370000


def test_the_sheet_is_requested_wide_enough_for_all_percent_columns():
    """«72% … 100%» кончаются на колонке AF; запрос «до T» молча отрезал бы всё выше 88%."""
    клетки = inspect.signature(gsheet.api_rows).parameters["клетки"].default
    правая = клетки.split(":")[1].rstrip("0123456789")
    номер = 0
    for буква in правая:
        номер = номер * 26 + ord(буква) - ord("A") + 1
    assert номер >= 3 + 29, клетки


def test_the_diagnostics_estimate_follows_the_exact_percent():
    _, сетка, _ = gsheet.parse([ШАПКА_ПРОЦЕНТЫ, СТРОКА_ПРОЦЕНТЫ], MODELS)
    grid = {"база": {"iPhone17,2": {"1024": 420000}}, "сетка_износа": сетка}
    оценка = lambda здоровье, циклы=200: pricing.estimate(grid, "iPhone17,2", 1024, здоровье, циклы)
    assert оценка(88)["цена"] == 354000 and "88%" in оценка(88)["основание"]
    assert оценка(100, 5)["цена"] == 420000
    assert оценка(104)["цена"] == 420000, "выше 100% — это 100%"
    ниже = оценка(60)
    assert ниже["цена"] is None and "не задаёт" in ниже["нехватка"][0], \
        "ниже таблицы цены нет — базовую цену идеала сюда не подставляем"
    assert оценка(None)["цена"] is None

    ровная = {"база": {"x": {"128": 100000}},
              "сетка_износа": {"x": {"128": {f"{p}%": 100000 for p in range(72, 101)}}}}
    без_батареи = pricing.estimate(ровная, "x", 128, None, None)
    assert без_батареи["цена"] == 100000 and "не зависит" in без_батареи["основание"]


def test_the_old_range_label_is_derived_from_the_percent(бот):
    """Продавец вводит процент; метка диапазона осталась служебным полем для МойСклада и Pay
    и выводится из процента сама."""
    ждём = {100: "100", 104: "100", 99: "96-99", 96: "96-99", 95: "91-95", 90: "86-90", 86: "86-90",
            85: "80-85", 80: "80-85", 79: "75-79", 75: "75-79", 74: "0-74", 1: "0-74"}
    for процент, метка in ждём.items():
        assert бот.akb_state_from_percent(процент) == метка, процент
        # и цена по такой паре берётся из колонки самого процента
        if 72 <= процент <= 100:
            assert бот.price_in_row(ШАПКА_ПРОЦЕНТЫ, СТРОКА_ПРОЦЕНТЫ, метка, процент) == \
                ЛЕСТНИЦА[процент - 72] * 1000
