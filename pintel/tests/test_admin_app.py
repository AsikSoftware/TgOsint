def test_every_section_fills_from_what_the_server_said(приложение):
    """Разделы показывают присланное сервером — и ровно столько строк, сколько пришло."""
    к = Клиент("http://сервер", "t", транспорт=сервер_который({
        "/api/admin/overview": (200, {"день": "2026-11-25", "проверок": 4, "выкуплено": 2,
                                      "выдано": 430_000, "средний_чек": 215_000,
                                      "оценил_человек": 1,
                                      "точки": [{"точка": "Тарлан", "проверок": 2, "выкуп": 1,
                                                 "выдано": 250_000}]}),
        "/api/admin/points": (200, {"точки": [{"точка": "Тарлан", "город": "Алматы",
                                               "на_смене": "Асем Н.", "касс": 1,
                                               "сборка": "doctor-114", "молчит_часов": 0.1,
                                               "сделок_сегодня": 2}]}),
        "/api/admin/machines": (200, {"компьютеры": [{"машина": "KASSA-TARLAN", "точка": "Тарлан",
                                                      "сборка": "doctor-114", "молчит_часов": None,
                                                      "работает": False}]}),
        "/api/admin/alerts": (200, {"тревоги": [{"важность": "беда", "что": "Шымкент молчит",
                                                 "почему": "4 ч назад"}]}),
        "/api/admin/people": (200, {"люди": [{"имя": "Данияр К.", "точка": "16/38",
                                              "роль_словами": "Кассир", "проверок_за_месяц": 187,
                                              "выкупов_за_месяц": 71, "выдано_за_месяц": 11_200_000,
                                              "доступ": True}]})}))
    окно = Окно(клиент=к)
    try:
        for ключ in ("обзор", "тревоги", "точки", "компьютеры", "люди"):
            окно.обновить(ключ)
            for задача in окно.задачи:
                задача.wait(3000)
            приложение.processEvents()

        обзор = окно.разделы["обзор"]
        assert "47" not in обзор.плитки["проверок"].значение.text()
        assert обзор.плитки["проверок"].значение.text() == "4"
        assert "215 000" in обзор.плитки["выдано"].пояснение.text()
        assert обзор.таблица.rowCount() == 1
        assert обзор.таблица.item(0, 0).text() == "Тарлан"

        assert окно.разделы["точки"].таблица.item(0, 2).text() == "Асем Н."
        машины = окно.разделы["компьютеры"].таблица
        assert машины.item(0, 3).text() == "не выходила на связь"
        assert машины.item(0, 4).text() == "закрыт"
        assert окно.разделы["тревоги"].таблица.item(0, 1).text() == "Шымкент молчит"
        assert окно.разделы["люди"].таблица.item(0, 5).text() == "11,20 млн"
    finally:
        окно.close()


def test_a_broken_wire_is_said_out_loud_not_shown_as_an_empty_table(приложение):
    """Оборвалась связь — на экране строка про это, а не пустая таблица.

    Пустая таблица читается как «сегодня ничего не было», и это худшая из возможных
    неправд на экране владельца."""
    def рвётся(_запрос):
        raise httpx.ConnectError("нет сети")
    окно = Окно(клиент=Клиент("http://сервер", "t", транспорт=httpx.MockTransport(рвётся)))
    try:
        окно.обновить("точки")
        for задача in окно.задачи:
            задача.wait(3000)
        приложение.processEvents()
        беда = окно.разделы["точки"].беда
        assert not беда.isHidden(), "строку про обрыв связи спрятали"
        assert "сервер не ответил" in беда.text()
    finally:
        окно.close()
