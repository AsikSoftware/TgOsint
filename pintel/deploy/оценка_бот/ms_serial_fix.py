# -*- coding: utf-8 -*-
"""Серийный номер телефона — правится в документах, а не в карточке.

Владелец, 23.11.2026: «софт не исправляет серийники — создался только пустой серийник без
тела, товар задвоился. Чтобы исправить серийник, надо менять его в документе приёмки или
оприходования». И отдельно: «проданные трогай».

Почему так. В МойСкладе вещь (серийный номер) принадлежит не карточке товара, а документу,
которым её приняли: запись в `things` карточки МойСклад молча не применяет — проверено на
боевых карточках 41132, 41917, 44212, 45134. Поэтому единственный способ — поменять серийник
в самом документе: снять проведение, исправить позицию, провести обратно.

Порядок, когда телефон уже продан, обратный и это важно: сначала снимается проведение с
продажи, потом с прихода; правятся оба; проводится сперва приход, потом продажа. Иначе
МойСклад откажет — отгрузить серийник, которого нет на складе, нельзя.

Здесь только правила и порядок; ходы в МойСклад делает тот, кто вызывает (`запрос`).
"""
ПРИХОД = ("supply", "enter")                 # приёмка, оприходование
РАСХОД = ("demand", "retaildemand", "loss", "move")   # отгрузка, розница, списание, перемещение
# Сколько документов на один телефон считаем нормой. Больше — не наш случай: разбирается
# человек. Телефон штучный, у него бывает приход и, если продан, расход.
ПРЕДЕЛ_ДОКУМЕНТОВ = 2


def разобрать(документы: list, неверный: str, правильный: str) -> dict:
    """Что делать с документами этого телефона. Ничего не меняет.

    `документы` — [{"тип", "id", "номер", "проведён", "позиции": [{"id", "вещи"}]}].
    → {"можно": bool, "почему": str, "правки": [{"тип", "id", "номер", "позиция", "было"}],
       "порядок_снятия": [...], "порядок_проведения": [...]}
    """
    пусто = {"можно": False, "правки": [], "порядок_снятия": [], "порядок_проведения": []}
    неверный, правильный = str(неверный or "").strip(), str(правильный or "").strip()
    if not правильный:
        return {**пусто, "почему": "не знаем правильный серийный номер — IMEI не прочитался"}
    if неверный == правильный:
        # Нечего менять. Без этой проверки документ сняли бы с проведения и провели обратно
        # впустую — а это движение по складу, пусть и нулевое.
        return {**пусто, "почему": "серийный номер уже верный"}
    if not документы:
        return {**пусто, "почему": "в МойСкладе нет документа, которым этот телефон приняли — "
                                   "серийный номер править негде"}
    if len(документы) > ПРЕДЕЛ_ДОКУМЕНТОВ:
        номера = ", ".join(str(д.get("номер") or "?") for д in документы)
        return {**пусто, "почему": f"телефон двигали больше двух раз (документы {номера}) — "
                                   f"серийный номер правит человек"}

    правки = []
    for д in документы:
        попали = [п for п in (д.get("позиции") or [])
                  if неверный and неверный in [str(в).strip() for в in (п.get("вещи") or [])]]
        if len(попали) > 1:
            return {**пусто, "почему": f"в документе {д.get('номер')} этот серийный номер стоит "
                                       f"в нескольких позициях — правит человек"}
        if попали:
            правки.append({"тип": д["тип"], "id": д["id"], "номер": д.get("номер"),
                           "позиция": попали[0]["id"], "было": неверный,
                           "вещи": [str(в).strip() for в in (попали[0].get("вещи") or [])],
                           "проведён": bool(д.get("проведён"))})
    if not правки:
        return {**пусто, "почему": f"серийного номера {неверный} нет ни в одном документе этого "
                                   f"телефона — похоже, он стоит только в карточке"}

    # Снимаем проведение с расхода первым, возвращаем — приходом первым. Иначе МойСклад не даст
    # провести продажу: серийника, которого нет на складе, отгрузить нельзя.
    приход = [п for п in правки if п["тип"] in ПРИХОД]
    расход = [п for п in правки if п["тип"] not in ПРИХОД]
    if not приход:
        номера = ", ".join(str(п.get("номер") or "?") for п in расход)
        return {**пусто, "почему": f"серийный номер нашёлся только в расходном документе "
                                   f"({номера}), а в приходном нет — правит человек"}
    return {"можно": True, "почему": "", "правки": правки,
            "порядок_снятия": расход + приход,
            "порядок_проведения": приход + расход}


def словами(план: dict, правильный: str) -> str:
    """Строка для показа сотруднику: что именно будет исправлено и где."""
    if not план.get("можно"):
        return план.get("почему") or ""
    куда = ", ".join(f"{_имя_типа(п['тип'])} № {п.get('номер') or '?'}" for п in план["правки"])
    было = план["правки"][0]["было"]
    return f"серийный номер {было} → {правильный} в документах: {куда}"


ИМЕНА = {"supply": "приёмка", "enter": "оприходование", "demand": "отгрузка",
         "retaildemand": "розничная продажа", "loss": "списание", "move": "перемещение"}


def _имя_типа(тип) -> str:
    return ИМЕНА.get(str(тип), str(тип))


def применить(план: dict, правильный: str, *, снять, записать, провести) -> dict:
    """Выполнить план. Ходы наружу — тремя переданными действиями.

    `снять(тип, id)` — снять проведение, `записать(тип, id, позиция, вещи)` — записать новые
    вещи в позицию, `провести(тип, id)` — провести обратно.
    → {"сделано": [...], "беда": "" | текст}. При беде возвращаем то, что успели: документы
    остаются непроведёнными, и это видно в МойСкладе — молча оставить так нельзя.
    """
    if not план.get("можно"):
        return {"сделано": [], "беда": план.get("почему") or "план не составлен"}
    сделано = []
    try:
        for п in план["порядок_снятия"]:
            if п["проведён"]:
                снять(п["тип"], п["id"])
                сделано.append(f"снято проведение: {_имя_типа(п['тип'])} № {п.get('номер')}")
        for п in план["правки"]:
            новые = [правильный if str(в).strip() == п["было"] else в for в in п["вещи"]]
            записать(п["тип"], п["id"], п["позиция"], новые)
            сделано.append(f"серийный номер исправлен: {_имя_типа(п['тип'])} № {п.get('номер')}")
        for п in план["порядок_проведения"]:
            if п["проведён"]:
                провести(п["тип"], п["id"])
                сделано.append(f"проведено обратно: {_имя_типа(п['тип'])} № {п.get('номер')}")
    except Exception as беда:                                     # noqa: BLE001
        return {"сделано": сделано,
                "беда": f"{type(беда).__name__}: {str(беда)[:200]}"}
    return {"сделано": сделано, "беда": ""}
