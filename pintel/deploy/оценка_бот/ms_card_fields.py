# -*- coding: utf-8 -*-
"""Карточка товара в МойСкладе: доп. поля из сделки Оценки.

Кладётся в `utils/` бота. `ms_auto_supply._soft_attributes` отдаёт сборку полей сюда
(правка одной функции — `ms_card_patch.py`), а прежний код остаётся запасным: если этот
модуль упал, поля ставятся по-старому. Приёмка важнее полей.

Зачем отдельный файл. 12.11.2026 владелец перестроил карточку товара:

* «АКБ» — точный процент («79%»), а не диапазон. Поле — справочник, и тип у поля в
  МойСкладе не меняется; поэтому в справочник добавлены значения по процентам, а диапазоны
  остались для старых товаров. Точного значения в справочнике нет — ставим диапазон.
* «Ремонт статус» → «Статус», значения — как кнопки бота: «Б/у телефон в нормальном
  состоянии», «Телефон был в ремонте», «Есть видимые дефекты», «Запечатанный (новый)».
* «Sim Лоток» — галочка (новое поле: справочник «Sim слот» галочкой не сделать). Прежний
  «Sim слот» заполняем, пока он есть: его значения стоят у десяти тысяч старых товаров, и по
  этой колонке собран шаблон прихода из Excel.
* новые: «Цвет», «Panic full», «Сим без ограничений», «Номер сделки», «Цикл» (было, не
  заполнялось) и «Отчёт диагностики» — короткая строка о том, что не прошло проверку. Её
  пишем, только когда состояние не «Б/у в нормальном состоянии».

Главное правило — **код работает при любом состоянии МойСклада**: до переименования, после
него и если его откатят. Поле ищем по всем его именам, значение справочника — по всем его
именам. Нет поля — молча пропускаем новое и называем в «пропущены» прежнее, как раньше.
Чужих товаров код не касается: поля ставятся тому товару, который бот создаёт или находит
по штрихкоду при выкупе.
"""
import logging
import re

log = logging.getLogger(__name__)

ЧИСТЫЙ = "Не был в ремонте"
# phone_status бота → имена этого значения в справочнике МойСклада. Первым — «как кнопка
# бота» (так справочник назван с 12.11.2026), дальше прежние имена.
СТАТУСЫ = {
    "Не был в ремонте": ("Б/у телефон в нормальном состоянии", "Не был в ремонте"),
    "Ранее был в ремонте": ("Телефон был в ремонте", "Ранее был ремонт", "Ранее был в ремонте"),
    "Присутствует дефект": ("Есть видимые дефекты", "Присутствует дефект"),
    "Прочее": ("Запечатанный (новый)", "Прочее"),
}
ПОЛЕ_СТАТУСА = ("Статус", "Ремонт статус")       # новое имя поля и прежнее
ПОЛЕ_ЛОТКА = "Sim Лоток"
ПОЛЕ_СЛОТА = "Sim слот"
ПОЛЕ_ОТЧЁТА = "Отчёт диагностики"
# Поля, которых в МойСкладе могло не быть: нет поля — молча пропускаем, админу в «пропущены
# доп. поля» о них не пишем.
НЕОБЯЗАТЕЛЬНЫЕ = {ПОЛЕ_ЛОТКА, ПОЛЕ_ОТЧЁТА, "Цвет", "Panic full", "Сим без ограничений",
                  "Номер сделки", "Цикл"}
ДЛИНА_СТРОКИ = 255                # предел поля типа «строка» в МойСкладе
ДЛИНА_ТЕКСТА = 4000

# Те же соответствия — для прихода из Excel (ms_prihod_importer): в шаблоне колонка и
# значения написаны по-прежнему, а в МойСкладе их переименовали. И наоборот.
ИМЕНА_ПОЛЕЙ = (ПОЛЕ_СТАТУСА,)
КОЛОНКИ_EXCEL = {"Доп. поле: Ремонт статус": "Доп. поле: Статус"}


def другие_имена_значения(значение) -> list:
    """Как ещё может называться это значение справочника: прежнее имя ↔ новое."""
    своё = str(значение or "").strip().casefold()
    for имена in СТАТУСЫ.values():
        if своё in (x.casefold() for x in имена):
            return [x for x in имена if x.casefold() != своё]
    return []


def дописать_прежние_имена(поля_по_имени: dict, норма=None) -> dict:
    """Словарь «имя поля → поле» дополнить вторым именем переименованного поля.

    Шаблон прихода из Excel зовёт колонку «Ремонт статус», а поле в МойСкладе уже
    «Статус» (или наоборот) — оба имени должны находить одно и то же поле."""
    норма = норма or (lambda s: s)
    for имена in ИМЕНА_ПОЛЕЙ:
        ключи = [норма(x) for x in имена]
        есть = next((поля_по_имени[k] for k in ключи if k in поля_по_имени), None)
        if есть is not None:
            for k in ключи:
                поля_по_имени.setdefault(k, есть)
    return поля_по_имени


def колонка_на_месте(колонка: str, есть) -> bool:
    """Колонка шаблона Excel присутствует — под своим именем или под новым."""
    if колонка in есть:
        return True
    другое = КОЛОНКИ_EXCEL.get(колонка)
    обратно = [старое for старое, новое in КОЛОНКИ_EXCEL.items() if новое == колонка]
    return bool((другое and другое in есть) or any(x in есть for x in обратно))


# ---------------------------------------------------------------- краткий отчёт

def _обрезать(текст: str, предел: int) -> str:
    текст = " ".join(str(текст).split())
    return текст if len(текст) <= предел else текст[:предел - 1].rstrip(" ;,·") + "…"


def краткий_отчёт(device) -> str:
    """Что не прошло проверку — одной строкой для карточки товара. Пусто — сказать нечего.

    Берём из комментария оценщика: касса пишет его по одному образцу (`ocenka.комментарий_
    оценщика` + `kiosk_core.применить_диагностику`), куски разделены « · ». Нужны только
    находки: почему состояние изменено, заменённые детали, не пройденные тесты, отказавшее
    при проверке руками, замки, паника ядра. «Всё работает», батарея, реестр и откуда
    сделка — не находки, в карточке товара им не место.

    После перевода строки в том же поле стоит заметка самого оценщика («камера», «акб и
    экран») — обычно это и есть суть, поэтому она идёт следом. У сделок, заведённых в боте
    руками, комментария кассы нет: тогда отчёт — отметки приёмщика (поломка, дефекты).
    """
    готовый = str(getattr(device, "diag_brief", "") or "").strip()
    if готовый:
        return _обрезать(готовый, ДЛИНА_СТРОКИ)
    текст = str(getattr(device, "comment_ocenka", "") or "")
    первая, _, заметка = текст.partition("\n")
    от_кассы = "Состояние:" in первая or "Киоск " in первая
    куски = []
    for часть in (первая.split(" · ") if от_кассы else []):
        часть = часть.strip()
        низ = часть.lower()
        if часть.startswith("Состояние:") and "→ изменено:" in часть:
            куски.append(часть.split("→ изменено:", 1)[1].strip())
        elif часть.startswith("Детали:") and "родн" not in низ:
            куски.append("детали: " + часть.split(":", 1)[1].strip())
        elif часть.startswith("НЕ ПРОШЛИ:"):
            куски.append("тест не прошли: " + часть.split(":", 1)[1].strip())
        elif часть.startswith("НЕ РАБОТАЕТ:"):
            куски.append("руками не работает: " + часть.split(":", 1)[1].strip())
        elif часть.startswith("Замки:"):
            куски.append("замки: " + часть.split(":", 1)[1].strip())
        elif низ.startswith("panic full: есть"):
            куски.append(низ)
    заметка = " ".join((заметка if от_кассы else текст).split())
    if заметка:
        куски.append("оценщик: " + заметка)
    поломка = str(getattr(device, "malfunction", "") or "").strip()
    if поломка:
        куски.append("неисправность: " + поломка)
    дефекты = ", ".join(x.strip() for x in str(getattr(device, "defects", "") or "").split(",")
                        if x.strip())
    if дефекты:
        куски.append("дефекты: " + дефекты)
    return _обрезать("; ".join(dict.fromkeys(куски)), ДЛИНА_СТРОКИ)


# ---------------------------------------------------------------- поля товара

def _лоток(sim):
    """Есть ли SIM-лоток по полю `sim` сделки. → True / False / None (не знаем)."""
    sim = str(sim or "").strip()
    if sim == "E-sim":
        return False
    if sim in ("Стандарт", "Dual sim", "Dual Sim"):
        return True
    return None


def _комплектация(device):
    box, cord = getattr(device, "box", None), getattr(device, "cord", None)
    if box is None and cord is None:
        return None
    if box and cord:
        return "Коробка + Шнур"
    if box:
        return "Коробка"
    if cord:
        return "Шнур"
    return "Без комплектации"


def поля_товара(session, device, *, запрос, кэш, pick_imeis, defect_fields=(), defect_set=None,
                dict_aliases=None):
    """Доп. поля товара по сделке. → (список для `attributes`, что не легло).

    `запрос` и `кэш` — `_ms_request` и `_cached` бота: свой доступ к МойСкладу здесь не
    заводим, чтобы ходить туда тем же ключом и с тем же ограничением частоты.
    """
    dict_aliases = dict_aliases or {}
    meta = кэш("product_meta", lambda: запрос(session, "GET", "/entity/product/metadata"))
    attrs = meta.get("attributes") or {}
    rows = attrs.get("rows") if isinstance(attrs, dict) else attrs
    if not rows and isinstance(attrs, dict):
        href = (attrs.get("meta") or {}).get("href")
        if href:
            rows = (запрос(session, "GET", href).get("rows") or [])
    по_имени = {(a.get("name") or "").strip(): a for a in (rows or [])}

    def поле(*имена):
        return next((по_имени[n] for n in имена if n in по_имени), None)

    def справочник(row):
        cem = row.get("customEntityMeta") or {}
        href = cem.get("href") or (cem.get("meta") or {}).get("href") or ""
        if not href:
            return []
        cid = href.rstrip("/").split("/")[-1]

        def загрузить():
            все, сдвиг = [], 0
            while True:
                кусок = запрос(session, "GET", f"/entity/customentity/{cid}",
                               params={"limit": 100, "offset": сдвиг}).get("rows") or []
                все += кусок
                if len(кусок) < 100 or сдвиг > 5000:
                    return все
                сдвиг += 100
        return кэш(f"ce:{cid}", загрузить)

    out, skipped = [], []

    def положить(имена, значение, кандидаты=None):
        """Одно поле. `имена` — все имена поля, `кандидаты` — все имена значения справочника."""
        имена = (имена,) if isinstance(имена, str) else tuple(имена)
        if значение in (None, ""):
            return
        row = поле(*имена)
        if row is None:
            if not set(имена) & НЕОБЯЗАТЕЛЬНЫЕ:
                skipped.append(имена[-1])
            return
        имя = (row.get("name") or имена[0]).strip()
        вид = (row.get("type") or "").lower()
        try:
            if вид == "boolean":
                out.append({"meta": row["meta"], "value": bool(значение) and значение != "Нет"})
            elif вид == "long":
                out.append({"meta": row["meta"], "value": int(значение)})
            elif вид == "double":
                out.append({"meta": row["meta"], "value": float(значение)})
            elif вид in ("string", "text"):
                if isinstance(значение, bool):
                    значение = "Да" if значение else "Нет"
                out.append({"meta": row["meta"], "value": _обрезать(
                    значение, ДЛИНА_СТРОКИ if вид == "string" else ДЛИНА_ТЕКСТА)})
            else:                                   # справочник
                варианты = [str(x).strip() for x in (кандидаты or [значение]) if str(x or "").strip()]
                все = справочник(row)
                нашли = next((v for имя_значения in варианты for v in все
                              if (v.get("name") or "").strip().casefold() == имя_значения.casefold()),
                             None)
                if нашли:
                    out.append({"meta": row["meta"], "value": {"meta": нашли["meta"]}})
                else:
                    skipped.append(f"{имя}={варианты[0] if варианты else значение}")
        except (TypeError, ValueError):
            skipped.append(f"{имя}={значение}")
        except Exception as exc:                                 # noqa: BLE001
            log.warning("Автоприёмка: доп. поле %s пропущено (%s)", имя, exc)
            skipped.append(имя)

    imeis = pick_imeis(device)
    положить("Imei 1", imeis[0] if imeis else None)
    положить("Imei 2", imeis[1] if len(imeis) > 1 else None)

    # АКБ: точный процент, а где его нет в справочнике (или в сделке) — прежний диапазон
    акб, точно = getattr(device, "akb", None), getattr(device, "akb_exact", None)
    диапазон = (dict_aliases.get("АКБ") or {}).get(str(акб or "").strip(), акб)
    варианты_акб = ([f"{int(точно)}%"] if точно else []) + ([диапазон] if диапазон else [])
    положить("АКБ", варианты_акб[0] if варианты_акб else None, варианты_акб)
    положить("Цикл", getattr(device, "akb_cycles", None))

    положить("Память", str(getattr(device, "ddr", "") or "") or None)

    # SIM-лоток: галочка в новом поле; прежний справочник заполняем, пока он есть
    sim = getattr(device, "sim", None)
    лоток_поле = поле(ПОЛЕ_ЛОТКА)
    if лоток_поле is not None and (лоток_поле.get("type") or "").lower() == "boolean":
        if _лоток(sim) is not None:
            out.append({"meta": лоток_поле["meta"], "value": _лоток(sim)})
    elif лоток_поле is not None:
        положить(ПОЛЕ_ЛОТКА, sim)                  # поле переименовали, а тип оставили
    if поле(ПОЛЕ_СЛОТА) is not None or лоток_поле is None:
        # нет ни прежнего поля, ни нового — так и скажем в «пропущены», как раньше
        положить(ПОЛЕ_СЛОТА, sim)
    sim_free = getattr(device, "sim_free", None)
    положить("Сим без ограничений", None if sim_free is None else ("Да" if sim_free else "Нет"))

    статус = str(getattr(device, "phone_status", "") or "").strip()
    старое = (dict_aliases.get("Ремонт статус") or {}).get(статус)
    кандидаты = list(СТАТУСЫ.get(статус, (статус,))) + ([старое] if старое else [])
    положить(ПОЛЕ_СТАТУСА, статус or None, list(dict.fromkeys(кандидаты)))

    положить("Комплектация", _комплектация(device))
    trade_type = str(getattr(device, "trade_type", "") or "").strip()
    положить("Способ приобретения", "Выкуп" if trade_type == "Выкуп" else "Trade-In")

    положить("Цвет", str(getattr(device, "color", "") or "").strip() or None)
    panic = getattr(device, "panic_full", None)
    положить("Panic full", None if panic is None else ("Да" if panic else "Нет"))
    положить("Номер сделки", getattr(device, "id", None))

    # галочки дефектов: ставим и снятые — видно, что приёмщик смотрел и дефекта нет
    выбраны = defect_set(device) if defect_set else set()
    for d in defect_fields:
        row = поле(d)
        if row is None:
            skipped.append(d)
        else:
            out.append({"meta": row["meta"], "value": d in выбраны})
    положить("Неисправность", str(getattr(device, "malfunction", "") or "").strip() or None)

    # что не прошло проверку — только когда аппарат не «б/у в нормальном состоянии»
    if статус and статус != ЧИСТЫЙ:
        положить(ПОЛЕ_ОТЧЁТА, краткий_отчёт(device) or None)

    if skipped:
        log.warning("Автоприёмка: пропущены доп. поля: %s", ", ".join(skipped))
    return out, skipped
