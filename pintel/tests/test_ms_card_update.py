def test_tests_and_manual_marks_become_checkboxes(м):
    """Отметки теста на телефоне и анкеты сотрудника ложатся галочками, пропуск — очисткой."""
    from pintel_core.external import ms_update
    доп = ms_update.доп_поля(
        {}, тест={"sensor": "ok", "speaker": "fail", "mic": "skip"},
        ручная={"keys": True, "glue": False}, сотрудник="Иван")
    assert доп["Тест: Сенсор"] is True
    assert доп["Тест: Динамики"] is False
    assert доп["Тест: Микрофон"] is None, "«пропуск» — это не «не прошло»"
    assert доп["Ручное: Кнопки"] is True and доп["Ручное: Герметик"] is False
    assert доп["Ручное: Вибрация"] is None
    assert доп["Ручное: кто проверял"] == "Иван"
    ответ, _ = выполнить(м, [товар()], посылка(что="найти", доп=доп),
                         карточка=карточка_со_всеми_полями)
    п = пары(ответ)
    # пустоту замена показывает как «—»: на экране кассы это читается лучше пустой клетки
    assert п["Тест: Сенсор"] == ("—", "Да") and п["Тест: Динамики"] == ("—", "Нет")
    assert "Тест: Микрофон" not in п, "пустое поле очищать нечем — записи быть не должно"
