# -*- coding: utf-8 -*-
"""Таблица ожиданий: что должно читаться у этой модели на этой iOS.

    python3 tools/посчитать_ожидания.py отчёты.jsonl > pintel_core/analysis/ожидания_данные.py

На вход — выгрузка отчётов кассы (по строке на оценку: `{"модель", "ios", "отчёт"}`), серийники
и IMEI в ней должны быть уже замаскированы. На выход — модуль с таблицей.

Зачем. «Не прочиталось» бывает трёх совершенно разных сортов, и по пустому полю их не
отличить: у этой модели такого не бывает вовсе (Taptic на части моделей, макс. температура
батареи на iOS 27, сверка датчика приближения с iPhone 15); прочитали и данных правда нет
(журнал Apple пуст — ремонтов не было); могли прочитать, но не прочитали (связь рвалась,
раздел Apple не открыли). Опасен только третий сорт: он выглядит как «всё хорошо».

Отличить их можно только сравнением с такими же телефонами: если величина читается у ВСЕХ
аппаратов этой модели на этой iOS, а у конкретного не прочиталась — это дыра. Если не
читается ни у кого — это особенность, и требовать её нельзя.

Правило отбора нарочно строгое: величина попадает в ожидания, только если группа набрала
не меньше `ПОРОГ_ПРОВЕРОК` чтений И величина пришла во ВСЕХ из них. Иначе ожидание начнёт
останавливать телефоны из-за того, чего у них не бывает.

Чего таблица НЕ умеет: систематической дыры она не видит. Если величину не читает никто,
статистика считает это нормой модели — именно так «Деталь: Телефото камера» была пустой у
всех Pro-моделей из-за расхождения в имени сигнала («Телефото» против «Телефото камера»).
Такие дыры ловятся только сверкой со списком «что у этой модели физически есть»; он лежит
рядом, в `ожидания.ЕСТЬ_ФИЗИЧЕСКИ`.
"""
import json
import re
import sys
from collections import defaultdict

sys.path.insert(0, ".")

ПОРОГ_ПРОВЕРОК = 4
# Доля чтений, в которых величина обязана прийти, чтобы стать ожиданием. Не 100%: при полном
# пороге одно сорванное чтение стирает ожидание целиком (достаточно одного телефона с
# разбитым портом — и батарея перестаёт считаться обязательной для всей модели). 0.9 оставляет
# место одной осечке в десятке и при этом не пускает в ожидания то, что читается через раз.
ДОЛЯ_ОЖИДАНИЯ = 0.9
# Не ожидания: эти поля говорят не про телефон, а про нашу же работу и про сотрудника.
# «Все проверки прошли» и итоги теста зависят от того, прогнали ли проверки; «не прочитано»
# по смыслу заполняется ровно тогда, когда чего-то не хватает. Ждать их от телефона нельзя.
НЕ_ОЖИДАНИЯ = frozenset({
    "Все проверки прошли", "Тест: итог", "Ручное: итог",
    "Детали: не прочитано", "Не прочитано",
})


def поколение(ios: str) -> str:
    """iOS 17.4.1 → «17». Внутри поколения доступы Apple не меняются, между — меняются."""
    m = re.match(r"\s*(\d+)", str(ios or ""))
    return m.group(1) if m else "?"


def главное(строки) -> dict:
    """{(модель, поколение iOS): {величина: (пришло, всего)}}"""
    from pintel_core.external import ms_update
    счёт = defaultdict(lambda: defaultdict(lambda: [0, 0]))
    for з in строки:
        ключ = (str(з.get("модель") or "?").strip(), поколение(з.get("ios")))
        поля = ms_update.доп_поля(з["отчёт"], тест={}, ручная={})
        for имя, значение in поля.items():
            if имя in НЕ_ОЖИДАНИЯ:
                continue
            с = счёт[ключ][имя]
            с[1] += 1
            if значение is not None and значение != "":
                с[0] += 1
    return счёт


def таблица(счёт: dict) -> dict:
    """{(модель, поколение): [величины, которые обязаны прийти]}"""
    итог = {}
    for (модель, ios), величины in счёт.items():
        всего = max((с[1] for с in величины.values()), default=0)
        if всего < ПОРОГ_ПРОВЕРОК:
            continue                       # мало данных — ожиданий не выставляем вовсе
        ждём = sorted(и for и, с in величины.items()
                      if с[1] == всего and с[0] >= всего * ДОЛЯ_ОЖИДАНИЯ)
        if ждём:
            итог[(модель, ios)] = ждём
    return итог


def main():
    строки = [json.loads(s) for s in open(sys.argv[1], encoding="utf-8") if s.strip()]
    счёт = главное(строки)
    т = таблица(счёт)
    всего_проверок = sum(max((с[1] for с in в.values()), default=0) for в in счёт.values())
    print("# -*- coding: utf-8 -*-")
    print('"""Таблица ожиданий — ПОСЧИТАНА, руками не правится.')
    print()
    print(f"Считана по {всего_проверок} проверкам: tools/посчитать_ожидания.py.")
    print(f"В таблицу попали группы «модель × поколение iOS» с {ПОРОГ_ПРОВЕРОК}+ проверками,")
    print(f"а в них — величины, пришедшие не меньше чем в {ДОЛЯ_ОЖИДАНИЯ:.0%} проверок группы.")
    print()
    print("Пересчитывать: Apple закрывает доступы с каждой iOS, и застывшая таблица начнёт")
    print('требовать то, чего больше нет."""')
    print()
    print(f"ПОСЧИТАНО_ПО = {всего_проверок}")
    print("ТАБЛИЦА = {")
    for (модель, ios) in sorted(т):
        print(f"    ({модель!r}, {ios!r}): (")
        for и in т[(модель, ios)]:
            print(f"        {и!r},")
        print("    ),")
    print("}")


if __name__ == "__main__":
    main()
