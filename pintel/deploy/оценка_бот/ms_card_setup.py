# -*- coding: utf-8 -*-
"""Карточка товара в МойСкладе: завести новые доп. поля и переименовать прежние.

    python3 ms_card_setup.py <.env бота> show              # что есть сейчас (только чтение)
    python3 ms_card_setup.py <.env бота> add --dry         # что добавится
    python3 ms_card_setup.py <.env бота> add               # добавить
    python3 ms_card_setup.py <.env бота> rename --dry      # что переименуется
    python3 ms_card_setup.py <.env бота> rename            # переименовать
    python3 ms_card_setup.py <.env бота> colour --dry      # «Цвет»: что станет справочником
    python3 ms_card_setup.py <.env бота> colour            # «Цвет» из строки — в справочник

МойСклад один — и у боевого бота, и у тестового. Всё, что делает этот файл, делается в
боевом аккаунте, поэтому два шага разведены:

* **add** — только добавление: новые поля товара и новые значения справочников. Ничего
  существующего не меняет, работающему боту не мешает: о новых полях он не знает.
* **rename** — переименование поля «Ремонт статус» в «Статус» и трёх его значений. Бот
  ищет поля и значения по имени, поэтому этот шаг — ТОЛЬКО после того, как в боте стоит
  `ms_card_patch.py` и бот перезапущен. Иначе приход из Excel откажет файлам.

* **colour** — поле «Цвет» из строки становится справочником (13.11.2026). Тип поля в
  МойСкладе не меняется, поэтому заводится новое поле «Цвет» типа «справочник», прежнее
  строковое переименовывается в «Цвет (старое)», а его значения у товаров переносятся в
  новое. Значения справочника — слова общего словаря цветов кассы (`pintel_core/colours.py`,
  КАНОН): BLACK, NATURAL, DEEP PURPLE… Бот ищет значение по имени без учёта регистра, так
  что прежний код бота с новым полем работает сразу: слово словаря находится, а написанное
  от руки («сини») — нет, и поле у такого товара остаётся пустым.

Чего файл не делает: не удаляет ни полей, ни значений. Значения, которые стоят у старых
товаров, остаются при них; переименованное значение у них просто начинает называться
по-новому (смысл тот же). «Цвет (старое)» тоже остаётся — удалить его можно руками, когда
убедитесь, что новое поле заполнено.

Тип поля в МойСкладе изменить нельзя. Поэтому «АКБ» остаётся справочником — в него
добавляются значения по процентам; а «Sim Лоток» — новое поле-галочка, прежний справочник
«Sim слот» остаётся как есть.

Ключ берётся из .env бота (`API_KEY_SKLAD`) и никуда не печатается.
"""
import gzip
import json
import os
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request

АДРЕС = "https://api.moysklad.ru/api/remap/1.2"

# новые поля товара: имя → тип МойСклада
НОВЫЕ_ПОЛЯ = (
    ("Sim Лоток", "boolean"),             # галочка: есть лоток / нет
    # «Цвет» здесь больше нет: с 13.11.2026 это справочник, его заводит шаг `colour`
    ("Panic full", "boolean"),
    ("Сим без ограничений", "boolean"),
    ("Номер сделки", "long"),
    ("Отчёт диагностики", "string"),      # что не прошло проверку — только у «не в норме»
    ("Заключение", "link"),               # ссылка на чек диагностики на домене кассы
)
ПОЛЕ_ЦВЕТА, ПОЛЕ_ЦВЕТА_СТАРОЕ, ПОЛЕ_ЦВЕТА_ВРЕМЕННОЕ = "Цвет", "Цвет (старое)", "Цвет (справочник)"
СПРАВОЧНИК_ЦВЕТА = "Цвет"
ПРОЦЕНТЫ = [f"{n}%" for n in range(60, 100)]      # «100%» в справочнике уже есть
ПОЛЕ_СТАТУСА_БЫЛО, ПОЛЕ_СТАТУСА_СТАЛО = "Ремонт статус", "Статус"
НОВОЕ_ЗНАЧЕНИЕ_СТАТУСА = "Запечатанный (новый)"
# значения справочника состояния: было → стало (как кнопки бота Оценки)
ЗНАЧЕНИЯ_СТАТУСА = (
    ("Не был в ремонте", "Б/у телефон в нормальном состоянии"),
    ("Ранее был ремонт", "Телефон был в ремонте"),
    ("Присутствует дефект", "Есть видимые дефекты"),
)


def ключ(путь):
    for строка in open(путь, encoding="utf-8", errors="replace"):
        if строка.startswith("API_KEY_SKLAD="):
            return строка.split("=", 1)[1].strip().strip('"').strip("'")
    sys.exit("в файле нет API_KEY_SKLAD")


class Склад:
    def __init__(self, токен, всухую):
        self.токен, self.всухую, self.сделано = токен, всухую, []

    def запрос(self, метод, адрес, тело=None):
        if not адрес.startswith("http"):
            адрес = АДРЕС + адрес
        данные = json.dumps(тело, ensure_ascii=False).encode("utf-8") if тело is not None else None
        req = urllib.request.Request(адрес, data=данные, method=метод, headers={
            "Authorization": "Bearer " + self.токен, "Accept-Encoding": "gzip",
            "Accept": "application/json;charset=utf-8", "Content-Type": "application/json"})
        try:
            with urllib.request.urlopen(req, timeout=40) as r:
                ответ = r.read()
                if r.headers.get("Content-Encoding") == "gzip":
                    ответ = gzip.decompress(ответ)
        except urllib.error.HTTPError as exc:
            текст = exc.read()
            try:
                текст = gzip.decompress(текст)
            except Exception:                                    # noqa: BLE001
                pass
            sys.exit(f"МойСклад отказал ({exc.code}) на {метод} {адрес.replace(АДРЕС, '')}: "
                     + текст.decode("utf-8", "replace")[:400])
        time.sleep(0.12)                                         # не чаще ~8 запросов в секунду
        return json.loads(ответ) if ответ else {}

    def писать(self, что, метод, адрес, тело):
        """Одна запись в МойСклад. Всухую — только говорим, что сделали бы."""
        print(("   [всухую] " if self.всухую else "   ") + что)
        if self.всухую:
            return {}
        self.сделано.append(что)
        return self.запрос(метод, адрес, тело)

    def поля(self):
        return self.запрос("GET", "/entity/product/metadata/attributes").get("rows") or []

    def справочники(self):
        """Все пользовательские справочники: [(имя, id, meta)]."""
        ряд = self.запрос("GET", "/context/companysettings/metadata").get("customEntities") or []
        out = []
        for c in ряд:
            m = c.get("entityMeta") or {}
            out.append(((c.get("name") or "").strip(),
                        (m.get("href") or "").rstrip("/").rsplit("/", 1)[-1], c.get("meta") or {}))
        return out

    def значения(self, поле):
        cid = (поле.get("customEntityMeta") or {}).get("href", "").rstrip("/").rsplit("/", 1)[-1]
        return cid, self.значения_справочника(cid)

    def значения_справочника(self, cid):
        все, сдвиг = [], 0
        while True:
            кусок = self.запрос("GET", f"/entity/customentity/{cid}?limit=100&offset={сдвиг}").get("rows") or []
            все += кусок
            if len(кусок) < 100:
                return все
            сдвиг += 100


def найти(ряд, *имена):
    """Поле или значение по любому из имён, без учёта регистра."""
    for имя in имена:
        for x in ряд:
            if (x.get("name") or "").strip().casefold() == имя.casefold():
                return x
    return None


def показать(с):
    поля = с.поля()
    print(f"доп. полей товара: {len(поля)}")
    for a in поля:
        хвост = ""
        if a.get("type") == "customentity":
            _, знач = с.значения(a)
            хвост = f" — {len(знач)} значений: " + ", ".join(sorted(v.get("name") or "" for v in знач))[:150]
        print(f"   {a.get('name'):<24} {a.get('type'):<13}{хвост}")
    return поля


def добавить(с):
    поля = с.поля()
    print("== новые поля товара")
    for имя, вид in НОВЫЕ_ПОЛЯ:
        есть = найти(поля, имя)
        if есть:
            print(f"   уже есть: {имя} ({есть.get('type')})"
                  + ("" if есть.get("type") == вид else f" — ТИП ДРУГОЙ, ждали {вид}"))
            continue
        с.писать(f"создать поле «{имя}» ({вид})", "POST", "/entity/product/metadata/attributes",
                 {"name": имя, "type": вид, "required": False})
    print("== справочник «АКБ»: значения по процентам")
    акб = найти(поля, "АКБ")
    if not акб or акб.get("type") != "customentity":
        sys.exit("поле «АКБ» не найдено или это не справочник — не трогаю")
    cid, значения = с.значения(акб)
    добавлено = 0
    for п in ПРОЦЕНТЫ:
        if not найти(значения, п):
            с.писать(f"добавить значение «{п}»", "POST", f"/entity/customentity/{cid}", {"name": п})
            добавлено += 1
    print(f"   значений было {len(значения)}, добавляется {добавлено}")
    print("== справочник состояния: значение для запечатанного")
    статус = найти(поля, ПОЛЕ_СТАТУСА_СТАЛО, ПОЛЕ_СТАТУСА_БЫЛО)
    if not статус or статус.get("type") != "customentity":
        sys.exit("поле состояния не найдено или это не справочник — не трогаю")
    cid, значения = с.значения(статус)
    if найти(значения, НОВОЕ_ЗНАЧЕНИЕ_СТАТУСА):
        print(f"   уже есть: {НОВОЕ_ЗНАЧЕНИЕ_СТАТУСА}")
    else:
        с.писать(f"добавить значение «{НОВОЕ_ЗНАЧЕНИЕ_СТАТУСА}»", "POST",
                 f"/entity/customentity/{cid}", {"name": НОВОЕ_ЗНАЧЕНИЕ_СТАТУСА})


def переименовать(с):
    поля = с.поля()
    статус = найти(поля, ПОЛЕ_СТАТУСА_СТАЛО, ПОЛЕ_СТАТУСА_БЫЛО)
    if not статус or статус.get("type") != "customentity":
        sys.exit("поле состояния не найдено или это не справочник — не трогаю")
    print("== поле состояния")
    if (статус.get("name") or "").strip() == ПОЛЕ_СТАТУСА_СТАЛО:
        print(f"   уже называется «{ПОЛЕ_СТАТУСА_СТАЛО}»")
    else:
        с.писать(f"переименовать поле «{статус.get('name')}» → «{ПОЛЕ_СТАТУСА_СТАЛО}»", "PUT",
                 статус["meta"]["href"], {"name": ПОЛЕ_СТАТУСА_СТАЛО})
    print("== значения справочника состояния")
    cid, значения = с.значения(статус)
    for было, стало in ЗНАЧЕНИЯ_СТАТУСА:
        уже, старое = найти(значения, стало), найти(значения, было)
        if уже and not старое:
            print(f"   уже называется «{стало}»")
        elif уже and старое:
            print(f"   ЕСТЬ ОБА: «{было}» и «{стало}» — не трогаю, разберите руками")
        elif старое:
            с.писать(f"переименовать значение «{было}» → «{стало}»", "PUT",
                     f"/entity/customentity/{cid}/{старое['id']}", {"name": стало})
        else:
            print(f"   нет ни «{было}», ни «{стало}» — пропускаю")


def словарь_цветов():
    """Общий словарь цветов кассы. Берём из репозитория, рядом с которым лежит этот файл:
    список значений справочника обязан совпадать с тем, что касса кладёт в сделку."""
    sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
    from pintel_core import colours
    return colours


def слово_справочника(имя, канон):
    """Каким словом словаря назвать значение справочника. → слово или None (не наше).

    «Natural» → NATURAL; «Black (Midnight)» → BLACK: уточнение в скобках в словаре кассы —
    отдельный цвет (MIDNIGHT), а не часть названия."""
    имя = " ".join(str(имя or "").split())
    for вариант in (имя, re.sub(r"\s*\(.*?\)", "", имя)):
        if вариант.strip().upper() in канон:
            return вариант.strip().upper()
    return None


def цвет(с):
    """«Цвет»: строковое поле товара → поле-справочник со словами общего словаря."""
    colours = словарь_цветов()
    канон = sorted(colours.КАНОН)

    print("== справочник «Цвет»")
    свой = [x for x in с.справочники() if x[0].casefold() == СПРАВОЧНИК_ЦВЕТА.casefold()]
    if len(свой) > 1:
        sys.exit("справочников «Цвет» больше одного — не трогаю, разберите руками")
    if свой:
        _, cid, _ = свой[0]
        значения = с.значения_справочника(cid)
        print(f"   есть, значений: {len(значения)}")
    else:
        ответ = с.писать(f"создать справочник «{СПРАВОЧНИК_ЦВЕТА}»", "POST", "/entity/customentity",
                         {"name": СПРАВОЧНИК_ЦВЕТА})
        cid = (ответ.get("id") or "").strip() or "НОВЫЙ"
        значения = []
    поля = с.поля()
    на_справочнике = [a for a in поля
                      if cid != "НОВЫЙ" and cid in (a.get("customEntityMeta") or {}).get("href", "")]
    чужие = [a for a in на_справочнике
             if (a.get("name") or "").strip() not in (ПОЛЕ_ЦВЕТА, ПОЛЕ_ЦВЕТА_ВРЕМЕННОЕ)]
    if чужие:
        sys.exit("справочник «Цвет» уже подключён к полю «" + (чужие[0].get("name") or "")
                 + "» — значения не переименовываю, разберите руками")
    занято = {(v.get("name") or "").strip().upper() for v in значения}
    for v in значения:
        имя = (v.get("name") or "").strip()
        стало = слово_справочника(имя, colours.КАНОН)
        if стало is None:
            print(f"   не из словаря, оставляю как есть: «{имя}»")
        elif имя == стало:
            continue
        elif стало in занято and имя.upper() != стало:
            print(f"   «{имя}»: слово {стало} в справочнике уже есть — оставляю как есть")
        else:
            с.писать(f"переименовать значение «{имя}» → «{стало}»", "PUT",
                     f"/entity/customentity/{cid}/{v['id']}", {"name": стало})
            занято.add(стало)
    добавлено = 0
    for слово in канон:
        if слово not in занято:
            с.писать(f"добавить значение «{слово}»", "POST", f"/entity/customentity/{cid}",
                     {"name": слово})
            добавлено += 1
    print(f"   слов в словаре {len(канон)}, добавляется {добавлено}")

    print("== поле товара «Цвет»")
    новое = next((a for a in поля if (a.get("name") or "").strip() in (ПОЛЕ_ЦВЕТА, ПОЛЕ_ЦВЕТА_ВРЕМЕННОЕ)
                  and a.get("type") == "customentity"), None)
    старое = next((a for a in поля if (a.get("name") or "").strip() in (ПОЛЕ_ЦВЕТА, ПОЛЕ_ЦВЕТА_СТАРОЕ)
                   and a.get("type") == "string"), None)
    if новое is None:
        # Сначала новое поле под временным именем, и только потом переименования: если
        # МойСклад откажет в создании, прежнее «Цвет» останется как было.
        образец = next((a.get("customEntityMeta") for a in поля if a.get("customEntityMeta")), None)
        if not образец:
            sys.exit("нет ни одного поля-справочника, с которого снять вид ссылки — не трогаю")
        ссылка = dict(образец)
        ссылка["href"] = образец["href"].rstrip("/").rsplit("/", 1)[0] + "/" + cid
        новое = с.писать(f"создать поле «{ПОЛЕ_ЦВЕТА_ВРЕМЕННОЕ}» (справочник «Цвет»)", "POST",
                         "/entity/product/metadata/attributes",
                         {"name": ПОЛЕ_ЦВЕТА_ВРЕМЕННОЕ, "type": "customentity", "required": False,
                          "customEntityMeta": ссылка})
        if isinstance(новое, list):
            новое = новое[0] if новое else {}
    else:
        print(f"   поле-справочник уже есть: «{новое.get('name')}»")
    if старое is not None and (старое.get("name") or "").strip() == ПОЛЕ_ЦВЕТА:
        с.писать(f"переименовать строковое поле «{ПОЛЕ_ЦВЕТА}» → «{ПОЛЕ_ЦВЕТА_СТАРОЕ}»", "PUT",
                 старое["meta"]["href"], {"name": ПОЛЕ_ЦВЕТА_СТАРОЕ})
    if (новое.get("name") or ПОЛЕ_ЦВЕТА_ВРЕМЕННОЕ).strip() != ПОЛЕ_ЦВЕТА:
        if с.всухую and not новое.get("meta"):
            print(f"   [всухую] переименовать поле «{ПОЛЕ_ЦВЕТА_ВРЕМЕННОЕ}» → «{ПОЛЕ_ЦВЕТА}»")
        else:
            с.писать(f"переименовать поле «{ПОЛЕ_ЦВЕТА_ВРЕМЕННОЕ}» → «{ПОЛЕ_ЦВЕТА}»", "PUT",
                     новое["meta"]["href"], {"name": ПОЛЕ_ЦВЕТА})

    print("== товары: цвет из прежнего поля — в справочник")
    if старое is None:
        print("   прежнего строкового поля нет — переносить нечего")
        return
    значения = [] if cid == "НОВЫЙ" else с.значения_справочника(cid)
    по_слову = {(v.get("name") or "").strip().upper(): v for v in значения}
    href = старое["meta"]["href"]
    товары, сдвиг = [], 0
    while True:
        кусок = с.запрос("GET", "/entity/product?" + urllib.parse.urlencode(
            {"filter": f"{href}!=", "limit": 100, "offset": сдвиг})).get("rows") or []
        товары += кусок
        if len(кусок) < 100:
            break
        сдвиг += 100
    print(f"   товаров с цветом в прежнем поле: {len(товары)}")
    перенесено, уже, без_слова = 0, 0, []
    for т in товары:
        поля_т = т.get("attributes") or []
        было = next((str(a.get("value") or "") for a in поля_т
                     if (a.get("meta") or {}).get("href") == href), "")
        if новое.get("meta") and any((a.get("meta") or {}).get("href") == новое["meta"]["href"]
                                     for a in поля_т):
            уже += 1
            continue
        слово = colours.цвет(было)
        # всухую справочник ещё прежний — считаем, что слова словаря в нём уже есть
        if not слово or слово not in (colours.КАНОН if с.всухую else по_слову):
            без_слова.append(было)
            continue
        if с.всухую:
            print(f"   [всухую] товар: «{было}» → {слово}")
        else:
            с.писать(f"товар: «{было}» → {слово}", "PUT", т["meta"]["href"],
                     {"attributes": [{"meta": новое["meta"], "value": {"meta": по_слову[слово]["meta"]}}]})
        перенесено += 1
    print(f"   переносится {перенесено}, уже стояло {уже}"
          + (f", слова в словаре нет у {len(без_слова)}: " + ", ".join(sorted(set(без_слова)))
             if без_слова else ""))


def main():
    if len(sys.argv) < 3 or sys.argv[2] not in ("show", "add", "rename", "colour"):
        sys.exit(__doc__)
    с = Склад(ключ(sys.argv[1]), всухую="--dry" in sys.argv)
    шаг = sys.argv[2]
    if шаг == "show":
        показать(с)
        return
    {"add": добавить, "rename": переименовать, "colour": цвет}[шаг](с)
    print("записей в МойСклад:", len(с.сделано), "(всухую — ничего не менялось)" if с.всухую else "")


if __name__ == "__main__":
    main()
