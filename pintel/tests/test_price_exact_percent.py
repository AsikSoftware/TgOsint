def test_an_empty_cell_or_a_missing_column_means_no_price(бот):
    """Пустая клетка и отсутствующая колонка — это «цены нет», соседнюю не берём."""
    с_дыркой = list(СТРОКА_ПРОЦЕНТЫ)
    с_дыркой[3 + 88 - 72] = ""
    assert бот.price_in_row(ШАПКА_ПРОЦЕНТЫ, с_дыркой, "86-90", 88) is None
    assert бот.price_in_row(ШАПКА_ПРОЦЕНТЫ, с_дыркой, "86-90", 87) == 346000
    без_83 = [я for я in ШАПКА_ПРОЦЕНТЫ if я != "83%"]
    строка = СТРОКА_ПРОЦЕНТЫ[:3 + 83 - 72] + СТРОКА_ПРОЦЕНТЫ[3 + 84 - 72:]
    assert бот.price_in_row(без_83, строка, "80-85", 83) is None
    assert бот.price_in_row(без_83, строка, "80-85", 84) == 327000
    assert бот.price_in_row(ШАПКА_ПРОЦЕНТЫ, СТРОКА_ПРОЦЕНТЫ[:20], "100", 100) is None, "строка короче шапки"


def test_the_column_is_found_by_the_header_not_by_its_number(бот):
    """Колонки можно двигать и подписывать с пробелами — ищем по подписи."""
    шапка = ["Модель", "Марка", "Память", "примечание", " 95 % ", "100%", "90%"]
    строка = ["Apple", "iPhone 13", "128", "уценка", "150 000", "160\xa0000", "140000"]
    assert бот.percent_columns(шапка) == {95: 4, 100: 5, 90: 6}
    assert бот.price_in_row(шапка, строка, "91-95") == 150000
    assert бот.price_in_row(шапка, строка, "100") == 160000
    assert бот.price_in_row(шапка, строка, "86-90", 88) is None, "колонки 88% нет"
    assert бот.percent_columns(ШАПКА_ДИАПАЗОНЫ) == {}, "«100» без знака % — это диапазон"


def test_the_common_price_passes_the_exact_percent_through(бот, monkeypatch):
    """Общий прайс бота: строка ищется как раньше, колонку выбирает шапка."""
    таблица = [ШАПКА_ПРОЦЕНТЫ, СТРОКА_ПРОЦЕНТЫ, РОВНАЯ_ПРОЦЕНТЫ]
    monkeypatch.setattr(бот, "_get_price_table", lambda: таблица)
    assert бот.get_price_sync("apple", " iPhone 16 Pro Max ", 1024, "86-90", 88) == 354000
    assert бот.get_price_sync("Apple", "iPhone 16 Pro Max", "1024", "86-90") == 370000
    assert бот.get_price_sync("Apple", "iPhone 16 Pro Max", 512, "86-90", 88) is None
    assert бот.get_price_sync("Apple", "iPhone 16 Pro Max", 1024, "почти новый", 88) is None

    class Сделка:
        producer, model, ddr, akb, akb_exact = "Apple", "iPhone 16 Pro Max", 1024, "86-90", 88
        shop_id_grade = None

    assert asyncio.run(бот.get_price_for_device(Сделка())) == 354000
    Сделка.akb_exact = None
    assert asyncio.run(бот.get_price_for_device(Сделка())) == 370000


