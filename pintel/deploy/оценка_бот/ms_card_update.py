# -*- coding: utf-8 -*-
"""Обновление карточки УЖЕ СУЩЕСТВУЮЩЕГО товара МойСклада данными диагностики с кассы.

Кладётся в `utils/` бота, рядом с `ms_card_fields.py`. Зовёт его обработчик кассы
(`handlers/kiosk_media.py`), когда касса в скрытом режиме обновления прочитала телефон со
склада и просит: «найди его товар по IMEI и покажи, что изменится» — а после подтверждения
сотрудника: «запиши».

Связующее звено — IMEI. У каждого телефона в папке «БУ телефоны» штрихкод товара — это его
IMEI (так товар заводит автоприёмка, и так же заведены все 7502 прежних товара — проверено
17.11.2026). Телефон отдаёт по кабелю оба своих IMEI; ищем по каждому.

Что обновляется — только то, что назвал владелец (17.11.2026):

* «АКБ» (точный процент; нет его в справочнике — диапазон), «Цикл», «Память», «Цвет»,
  «Sim Лоток», «Panic full», «Imei 2», «Заключение» (ссылка на сертификат диагностики);
* «Отчёт диагностики» — что не прошло проверку;
* «Статус» — только в одну сторону: кабель нашёл заменённую деталь, а товар значится
  «в нормальном состоянии» → «Телефон был в ремонте». «Есть видимые дефекты» и «Телефон был
  в ремонте» не трогаем: кабель не видит корпус и улучшать состояние не вправе.

Заполненное поле перезаписывается (решение владельца): «86-90%» становится «88%». Перед
записью касса показывает сотруднику «было → станет», и пишем только после его подтверждения.

Чего этот код не трогает никогда: название, цены и рассрочки, папку, штрихкод, комплектацию,
способ приобретения, номер сделки, галочки дефектов, «Ошибка/Дефект/Ремонт». В запросе на
запись уходят только изменившиеся доп. поля — остальные МойСклад оставляет как были. Товар не
создаётся: нет товара с таким IMEI — так и отвечаем.

Доступ к МойСкладу свой не заводим: `запрос` и `кэш` — это `_ms_request` и `_cached` бота,
тот же ключ и то же ограничение частоты. В тестах они подставные, сети там нет.
"""
import logging
import re
from types import SimpleNamespace


def _рядом(имя):
    """Модуль из той же папки: на сервере это `utils/`, в проверках — папка deploy.

    Через `from utils import …` не берём: у проверок этого пакета нет, а ставить ради них
    пути в sys.path — значит проверять не то, что поедет на сервер."""
    import importlib.util
    import os
    путь = os.path.join(os.path.dirname(os.path.abspath(__file__)), имя + ".py")
    спец = importlib.util.spec_from_file_location(имя, путь)
    модуль = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(модуль)
    return модуль


ms_serial_fix = _рядом("ms_serial_fix")               # порядок правки серийника в документах

log = logging.getLogger(__name__)

ПАПКА_БУ = "БУ телефоны"
СТАТУС_РЕМОНТ = "Ранее был в ремонте"          # phone_status бота: «Телефон был в ремонте»
# Состояния товара, которые находка кабеля вправе сменить на «был в ремонте»
СТАТУСЫ_НОРМЫ = ("б/у телефон в нормальном состоянии", "не был в ремонте", "")
ПОЛЕ_IMEI_1, ПОЛЕ_IMEI_2 = "Imei 1", "Imei 2"
СЛОТ_БЕЗ_ЛОТКА, СЛОТ_С_ЛОТКОМ = "E-sim", "Стандарт"
ИЗМЕНЕНИЙ_НЕ_БОЛЬШЕ = 30


def _словами(значение) -> str:
    """Значение доп. поля так, как его видит человек в карточке товара."""
    if isinstance(значение, dict):
        return str(значение.get("name") or "").strip()
    if isinstance(значение, bool):
        return "Да" if значение else "Нет"
    return "" if значение is None else str(значение).strip()


def _имеи(сырые) -> list:
    return list(dict.fromkeys(x for x in (re.sub(r"\D", "", str(i or "")) for i in (сырые or []))
                              if 14 <= len(x) <= 16))


# ---------------------------------------------------------------- какой модели эта карточка
#
# Штрихкод товара в папке «БУ телефоны» — это IMEI телефона, и должен быть один на один. На
# деле у 158 телефонов из 1626 штрихкод делит другой товар: при приёмке отсканировали не тот
# аппарат, и на чужой карточке остался лишний штрихкод. Тогда поиск по IMEI приносит две
# карточки, и обе лежат на складе — 27.11.2026 так и вышло: на телефон 16 Pro нашлись его
# карточка и карточка 14 Pro Max с лишним штрихкодом, и касса отказалась обновлять.
#
# Разводит их модель. Кабель знает, что в руках, а у карточки модель стоит и в названии, и в
# папке. Карточка другой модели — не этот телефон, и писать в неё нельзя ни при каких
# обстоятельствах: диагностика 16 Pro в карточке 14 Pro Max — это испорченная карточка
# чужого телефона, причём испорченная тихо.
#
# Правило строгое в одну сторону: модель карточки ОТСЕИВАЕТ, но не выбирает. Название не
# разобрали (не Apple, своё имя, опечатка) — карточка остаётся в списке, решают остаток и
# IMEI. Так лишний отказ не рождается там, где раньше всё работало.

МОДЕЛИ = (
    "iPhone 18 Pro Max", "iPhone 18 Pro", "iPhone 17 Pro Max", "iPhone 17 Pro", "iPhone 17e",
    "iPhone 17", "iPhone 16 Pro Max", "iPhone 16 Pro", "iPhone 16 Plus", "iPhone 16e",
    "iPhone 16", "iPhone 15 Pro Max", "iPhone 15 Pro", "iPhone 15 Plus", "iPhone 15",
    "iPhone 14 Pro Max", "iPhone 14 Pro", "iPhone 14 Plus", "iPhone 14", "iPhone 13 Pro Max",
    "iPhone 13 Pro", "iPhone 13 mini", "iPhone 13", "iPhone 12 Pro Max", "iPhone 12 Pro",
    "iPhone 12 mini", "iPhone 12", "iPhone 11 Pro Max", "iPhone 11 Pro", "iPhone 11",
    "iPhone XS Max", "iPhone XS", "iPhone XR", "iPhone X", "iPhone SE 2022", "iPhone SE 2020",
    "iPhone SE 2016", "iPhone SE", "iPhone Air", "iPhone 8 Plus", "iPhone 8", "iPhone 7 Plus",
    "iPhone 7", "iPhone 6s Plus", "iPhone 6s",
)
# Длинные впереди: «16 Pro Max» должно разбираться раньше «16 Pro», иначе Max потеряется.
_РЯД = tuple((м, re.compile(r"\b" + r"\s*".join(re.escape(ч) for ч in м[7:].lower().split())
                            + r"\b")) for м in МОДЕЛИ)


def _ключ(имя: str) -> str:
    """Имя модели справочника → ключ. Все SE — одна модель: год в названиях товаров пишут не
    всегда, а отказываться от обновления из-за ненаписанного года хуже, чем не различать
    поколения SE между собой."""
    ключ = имя[7:].lower()
    return "se" if ключ.startswith("se") else ключ


_ПО_КЛЮЧУ = {}
for _имя, _образец in _РЯД:
    _ПО_КЛЮЧУ.setdefault(_ключ(_имя), []).append(_образец)


def _норма(текст) -> str:
    """Строка к виду, в котором её разбирают. Объём памяти и заряд убираем: «IP 6S 16 GB» —
    это шестой айфон с памятью 16, а не шестнадцатый."""
    т = str(текст or "").lower().replace("+", " plus ")
    т = re.sub(r"[^0-9a-zа-яё%]+", " ", т)
    т = re.sub(r"\b\d{1,4}\s*(gb|tb|гб|тб)\b", " ", т)
    т = re.sub(r"\d+\s*%", " ", т)
    return " " + re.sub(r"\s+", " ", т).strip() + " "


def _ключ_модели(текст) -> str:
    """Строка с названием → короткий ключ модели («16 pro max»). Не опознали — пусто."""
    т = _норма(текст)
    for имя, образец in _РЯД:
        if образец.search(т):
            return _ключ(имя)
    return ""


def _названа(текст, ключ: str) -> bool:
    """Названа ли в строке именно эта модель. Папка может перечислять несколько («Ip X / XS»),
    и тогда разбор по первому совпадению врёт, а этот вопрос — нет."""
    т = _норма(текст)
    return any(о.search(т) for о in _ПО_КЛЮЧУ.get(ключ, ()))


def _модель_товара(товар) -> str:
    """Модель карточки: по названию и по папке сразу. Расходятся — значит не разобрали.

    Папка часто короче названия («14 Серия» против «Ip 14 Pro Max»): это не спор, а разная
    подробность, берём подробное. Спор («14 Pro Max» против «16 Pro») — повод промолчать, а
    не выбрать одно из двух: одна из двух надписей в карточке врёт, и какая — неизвестно."""
    имя, папка = (товар or {}).get("name"), (товар or {}).get("pathName")
    по_имени, по_папке = _ключ_модели(имя), _ключ_модели(папка)
    if not (по_имени and по_папке) or по_имени == по_папке:
        return по_имени or по_папке
    if _названа(папка, по_имени):           # папка перечисляет несколько моделей, и наша в ней
        return по_имени
    а, б = по_имени.split(), по_папке.split()
    if а[:len(б)] == б or б[:len(а)] == а:
        return по_имени if len(а) > len(б) else по_папке
    return ""


def _назвать(товары) -> str:
    """Карточки для сообщения сотруднику: «40156 — 14 Pro Max»."""
    куски = []
    for т in sorted(товары, key=lambda т: str(т.get("code") or "")):
        модель = _модель_товара(т)
        куски.append(f"{т.get('code') or '?'}" + (f" — {модель}" if модель else ""))
    return ", ".join(куски)


def найти(session, имеи, *, запрос, кэш=None, модель="", заметки=None):
    """Товар этого телефона по IMEI. → (товар, "") или (None, почему).

    Ищем двумя способами, и второй нужен не для красоты. Штрихкод — основной ключ: у 98.7%
    телефонов в остатке он знак в знак равен «Imei 1». Но 158 телефонов из 1626 носят
    штрихкод-двойник (его делит другой товар), а у 25 штрихкод вообще не IMEI — и по
    штрихкоду они не находятся вовсе. Их находит фильтр по доп. полям «Imei 1» и «Imei 2»:
    фильтр по значению доп. поля МойСклад поддерживает (в отличие от серийников — по ним
    поиск отвергается с 412).
    """
    имеи = _имеи(имеи)
    if not имеи:
        return None, "у телефона не прочитался IMEI — искать товар нечем"
    найдено = {}
    for imei in имеи:
        строки = запрос(session, "GET", "/entity/product",
                        params={"filter": f"barcode={imei}", "limit": 5}).get("rows") or []
        for товар in строки:
            найдено[товар.get("id")] = товар
    if not найдено and кэш is not None:
        # по штрихкоду не нашлось — пробуем по доп. полям, где лежит тот же IMEI
        по_имени = _поля_товара(session, запрос=запрос, кэш=кэш)
        for имя_поля in (ПОЛЕ_IMEI_1, ПОЛЕ_IMEI_2):
            row = по_имени.get(имя_поля)
            href = (row or {}).get("meta", {}).get("href")
            if not href:
                continue
            for imei in имеи:
                строки = запрос(session, "GET", "/entity/product",
                                params={"filter": f"{href}={imei}", "limit": 5}).get("rows") or []
                for товар in строки:
                    найдено[товар.get("id")] = товар
    if not найдено:
        return None, ("в МойСкладе нет товара с таким IMEI (или он в архиве). "
                      "Товар здесь не создаётся — только обновляется существующий")
    # 1. Чужая модель. Отсеиваем всегда, даже когда карточка одна: карточка другой модели
    #    с нашим IMEI — это чужая карточка с лишним штрихкодом, и писать в неё нельзя.
    наш = _ключ_модели(модель)
    чужие = [т for т in найдено.values() if наш and _модель_товара(т) and _модель_товара(т) != наш]
    if чужие and len(чужие) < len(найдено):
        чужие_ид = {str(т.get("id")) for т in чужие}
        найдено = {и: т for и, т in найдено.items() if str(и) not in чужие_ид}
        if заметки is not None:
            заметки.append(f"тот же IMEI носит чужая карточка ({_назвать(чужие)}) — у неё "
                           f"лишний штрихкод, уберите его в МойСкладе")
    elif чужие:
        return None, (f"по этому IMEI в МойСкладе только карточки другой модели "
                      f"({_назвать(чужие)}), а в руках {модель}. У них лишний штрихкод от "
                      f"этого телефона — уберите его в МойСкладе. Своей карточки у телефона "
                      f"нет: обновлять нечего")
    if len(найдено) > 1:
        # 2. Телефон продали и выкупили обратно у того же клиента: на него есть СТАРАЯ карточка
        # (продана, остаток 0) и новая, которую завела автоприёмка. Владелец, 23.11.2026:
        # «не даёт сделать обновление со словами есть два товара по серийнику, хотя с
        # остатком только 1». Значит выбирать есть из чего — берём тот, что лежит на складе.
        в_остатке = [т for т in найдено.values() if (_остаток(session, т, запрос=запрос) or 0) > 0]
        if len(в_остатке) == 1:
            найдено = {в_остатке[0].get("id"): в_остатке[0]}
        else:
            сколько = ("ни одного" if not в_остатке else f"{len(в_остатке)}")
            return None, (f"по IMEI этого телефона в МойСкладе нашлось несколько товаров "
                          f"({_назвать(найдено.values())}), в остатке {сколько} — обновлять "
                          f"не стал. Это один телефон на двух карточках: оставьте в МойСкладе "
                          f"одну")
    товар = next(iter(найдено.values()))
    if ПАПКА_БУ.casefold() not in str(товар.get("pathName") or "").casefold():
        return None, (f"товар {товар.get('code') or ''} лежит не в папке «{ПАПКА_БУ}» "
                      f"({товар.get('pathName') or 'без папки'}) — обновлять не стал")
    return товар, ""


ПЕРИОД_ДВИЖЕНИЙ = ("2023-01-01%2000:00:00", "2099-01-01%2000:00:00")


def _документы_товара(session, товар, *, запрос) -> list:
    """Какими документами двигали этот телефон. → список для ms_serial_fix.разобрать.

    Списка «документы по серийнику» у МойСклада нет, зато есть движения по товару: по ним и
    находим приход и продажу. Телефон штучный, движений у него считанные единицы."""
    href = (товар.get("meta") or {}).get("href") or ""
    if not href:
        return []
    строки = (запрос(session, "GET", "/report/turnover/byoperations",
                     params={"filter": f"product={href}",
                             "momentFrom": ПЕРИОД_ДВИЖЕНИЙ[0],
                             "momentTo": ПЕРИОД_ДВИЖЕНИЙ[1]}) or {}).get("rows") or []
    собрано = []
    for строка in строки:
        op = строка.get("operation") or {}
        мета = op.get("meta") or {}
        тип = str(мета.get("type") or "")
        ид = str(мета.get("href") or "").rstrip("/").split("/")[-1]
        if not тип or not ид:
            continue
        док = запрос(session, "GET", f"/entity/{тип}/{ид}", params={"expand": "positions"})
        позиции = ((док.get("positions") or {}).get("rows") or [])
        собрано.append({"тип": тип, "id": ид, "номер": док.get("name"),
                        "проведён": bool(док.get("applicable")),
                        "позиции": [{"id": п.get("id"), "вещи": list(п.get("things") or [])}
                                    for п in позиции]})
    return собрано


def _план_серийника(session, товар, неверный, правильный, *, запрос) -> dict:
    """План правки серийника в документах. Ничего не меняет."""
    try:
        документы = _документы_товара(session, товар, запрос=запрос)
    except Exception as беда:                                    # noqa: BLE001
        return {"можно": False, "почему": f"движения товара не прочитались ({type(беда).__name__})",
                "правки": []}
    return ms_serial_fix.разобрать(документы, неверный, правильный)


def _поправить_серийник(session, план, правильный, *, запрос) -> dict:
    """Выполнить план: снять проведение, исправить позиции, провести обратно."""
    def снять(тип, ид):
        запрос(session, "PUT", f"/entity/{тип}/{ид}", body={"applicable": False})

    def записать(тип, ид, позиция, вещи):
        запрос(session, "PUT", f"/entity/{тип}/{ид}/positions/{позиция}", body={"things": вещи})

    def провести(тип, ид):
        запрос(session, "PUT", f"/entity/{тип}/{ид}", body={"applicable": True})

    return ms_serial_fix.применить(план, правильный, снять=снять, записать=записать,
                                   провести=провести)


def _остаток(session, товар, *, запрос):
    """Сколько этого товара на складе. → число или None, если спросить не вышло.

    None и ноль — разные вещи: по нулю мы решаем, что карточка продана, а по «не знаем»
    решать нельзя, иначе проданной окажется та, про которую МойСклад просто не ответил."""
    href = (товар.get("meta") or {}).get("href") or ""
    if not href:
        return None
    try:
        строки = (запрос(session, "GET", "/report/stock/all",
                         params={"filter": f"product={href}", "limit": 10}) or {}).get("rows") or []
    except Exception:                                    # noqa: BLE001
        return None
    return sum(float(с.get("stock") or 0) for с in строки)


def _поля_товара(session, *, запрос, кэш) -> dict:
    """Доп. поля товара по именам (из метаданных МойСклада, тем же кэшем, что у приёмки)."""
    meta = кэш("product_meta", lambda: запрос(session, "GET", "/entity/product/metadata"))
    attrs = meta.get("attributes") or {}
    rows = attrs.get("rows") if isinstance(attrs, dict) else attrs
    if not rows and isinstance(attrs, dict):
        href = (attrs.get("meta") or {}).get("href")
        if href:
            rows = запрос(session, "GET", href).get("rows") or []
    return {(a.get("name") or "").strip(): a for a in (rows or [])}


def _справочник(session, row, *, запрос, кэш) -> list:
    cem = row.get("customEntityMeta") or {}
    href = cem.get("href") or (cem.get("meta") or {}).get("href") or ""
    if not href:
        return []
    # Ссылка справочника у МойСклада выглядит так:
    #     …/entity/customentity/<номер справочника>/metadata
    # то есть номер стоит ПЕРЕД словом «metadata», а не в конце. Брали последний кусок —
    # получалось «/entity/customentity/metadata», и МойСклад отвечал 404 на каждый
    # справочник (АКБ, Память, Статус, Комплектация, Способ приобретения, Цвет).
    части = [ч for ч in href.rstrip("/").split("/") if ч]
    cid = части[части.index("customentity") + 1] if "customentity" in части else части[-1]

    def загрузить():
        все, сдвиг = [], 0
        while True:
            кусок = запрос(session, "GET", f"/entity/customentity/{cid}",
                           params={"limit": 100, "offset": сдвиг}).get("rows") or []
            все += кусок
            if len(кусок) < 100 or сдвиг > 5000:
                return все
            сдвиг += 100
    return кэш(f"ce:{cid}", загрузить)


def посчитать(session, товар: dict, поля: dict, имеи, *, запрос, кэш, dict_aliases=None) -> dict:
    """Что изменится в карточке товара. Ничего не пишет.

    → {"изменения": [{"поле", "было", "станет"}], "attributes": [для PUT], "заметки": [...]}
    """
    from utils import ms_card_fields as карточка

    dict_aliases = dict_aliases or {}
    по_имени = _поля_товара(session, запрос=запрос, кэш=кэш)
    сейчас = {(a.get("name") or "").strip(): a.get("value") for a in (товар.get("attributes") or [])}
    изменения, attributes, заметки = [], [], []
    правка_товара = {}            # поля САМОГО товара: серийник, штрихкод

    def поле(*имена):
        return next((по_имени[n] for n in имена if n in по_имени), None)

    def поставить(имена, значение, кандидаты=None):
        """Одно поле: посчитать новое значение, сравнить с тем, что в карточке, запомнить."""
        имена = (имена,) if isinstance(имена, str) else tuple(имена)
        if значение in (None, ""):
            return
        row = поле(*имена)
        if row is None:
            return                                   # поля в МойСкладе нет — и обновлять нечего
        имя = (row.get("name") or имена[0]).strip()
        вид = (row.get("type") or "").lower()
        try:
            if вид == "boolean":
                новое = bool(значение) and значение != "Нет"
            elif вид == "long":
                новое = int(значение)
            elif вид == "double":
                новое = float(значение)
            elif вид == "link":
                новое = str(значение).strip()
                if not новое or len(новое) > карточка.ДЛИНА_СТРОКИ:
                    заметки.append(f"{имя}: ссылка не помещается в поле")
                    return
            elif вид == "time":
                новое = карточка.время_мойсклада(значение)
                if not новое:
                    заметки.append(f"{имя}: «{значение}» не похоже на дату — поле не тронуто")
                    return
            elif вид in ("string", "text"):
                if isinstance(значение, bool):
                    значение = "Да" if значение else "Нет"
                новое = карточка._обрезать(значение, карточка.ДЛИНА_СТРОКИ if вид == "string"
                                           else карточка.ДЛИНА_ТЕКСТА)
            else:                                    # справочник
                варианты = [str(x).strip() for x in (кандидаты or [значение]) if str(x or "").strip()]
                все = _справочник(session, row, запрос=запрос, кэш=кэш)
                нашли = next((v for вариант in варианты for v in все
                              if (v.get("name") or "").strip().casefold() == вариант.casefold()), None)
                if not нашли:
                    заметки.append(f"{имя}: в справочнике МойСклада нет значения «{варианты[0]}» — поле не тронуто")
                    return
                новое = {"meta": нашли["meta"], "name": (нашли.get("name") or "").strip()}
        except (TypeError, ValueError):
            заметки.append(f"{имя}: значение «{значение}» не подходит полю")
            return
        было, станет = _словами(сейчас.get(имя)), _словами(новое)
        if было.casefold() == станет.casefold():
            return
        if isinstance(новое, dict):
            новое = {"meta": новое["meta"]}
        attributes.append({"meta": row["meta"], "value": новое})
        изменения.append({"поле": имя, "было": было, "станет": станет})

    def заменить(имя_поля, значение):
        """Одно НАШЕ поле — записать значение или очистить. Пустое значит «очистить».

        Очистка в МойСкладе — это `value: null` (пустая строка так не работает: незаполненное
        поле в ответе API вообще отсутствует). Справочники (`customentity`) здесь не
        обрабатываются: у диагностики таких полей нет, а чужие справочники — «Статус»,
        «Цвет», «Комплектация», «Способ приобретения» — ведёт `поставить` выше и люди руками."""
        row = по_имени.get(имя_поля)
        if row is None:
            return                                   # поля в МойСкладе нет — заменять нечего
        вид = (row.get("type") or "").lower()
        пусто = значение is None or (isinstance(значение, str) and not значение.strip())
        новое = None
        if not пусто:
            try:
                if вид == "boolean":
                    новое = bool(значение) and значение != "Нет"
                elif вид == "long":
                    новое = int(значение)
                elif вид == "double":
                    новое = float(значение)
                elif вид == "time":
                    новое = карточка.время_мойсклада(значение) or None
                elif вид in ("string", "text", "link"):
                    предел = карточка.ДЛИНА_ТЕКСТА if вид == "text" else карточка.ДЛИНА_СТРОКИ
                    новое = карточка._обрезать(значение, предел)
                else:
                    # Справочник (23.11.2026): верификация IMEI стала не строкой, а выбором
                    # из трёх значений. Пишем так же, как чужие справочники, — ищем значение
                    # по имени; нет такого — поле не трогаем и говорим об этом.
                    все = _справочник(session, row, запрос=запрос, кэш=кэш)
                    нашли = next((v for v in все
                                  if (v.get("name") or "").strip().casefold()
                                  == str(значение).strip().casefold()), None)
                    if not нашли:
                        заметки.append(f"{имя_поля}: в справочнике МойСклада нет значения "
                                       f"«{значение}» — поле не тронуто")
                        return
                    # имя кладём рядом: по нему строка «было → станет» читается словом,
                    # а в саму запись уходит только ссылка (как в `поставить`)
                    новое = {"meta": нашли["meta"], "name": (нашли.get("name") or "").strip()}
            except (TypeError, ValueError):
                заметки.append(f"{имя_поля}: значение не подходит полю")
                return
        было = _словами(сейчас.get(имя_поля))
        станет = "" if новое is None else _словами(новое)
        if было.casefold() == станет.casefold():
            return                                   # и так совпадает — лишний PUT не нужен
        if isinstance(новое, dict):
            новое = {"meta": новое["meta"]}          # в МойСклад уходит только ссылка
        attributes.append({"meta": row["meta"], "value": новое})
        изменения.append({"поле": имя_поля, "было": было or "—",
                          "станет": станет or "— очищено"})

    # --- батарея: точный процент, а где его нет в справочнике (или с кабеля) — диапазон
    точно, акб = поля.get("akb_exact"), поля.get("akb")
    диапазон = (dict_aliases.get("АКБ") or {}).get(str(акб or "").strip(), акб)
    варианты_акб = ([f"{int(точно)}%"] if точно else []) + ([диапазон] if диапазон else [])
    поставить("АКБ", варианты_акб[0] if варианты_акб else None, варианты_акб)
    поставить("Цикл", поля.get("akb_cycles"))
    поставить("Память", str(поля.get("ddr") or "") or None)
    цвета = карточка._цвета(поля.get("color"))
    поставить("Цвет", цвета[0] if цвета else None, цвета)

    # --- SIM-лоток: галочка; прежний справочник «Sim слот» правим, только когда он ей противоречит
    лоток = карточка._лоток(поля.get("sim"))
    if лоток is not None:
        лоток_поле = поле(карточка.ПОЛЕ_ЛОТКА)
        if лоток_поле is not None and (лоток_поле.get("type") or "").lower() == "boolean":
            поставить(карточка.ПОЛЕ_ЛОТКА, "Да" if лоток else "Нет")
        слот = _словами(сейчас.get(карточка.ПОЛЕ_СЛОТА)).casefold()
        if лоток and слот == СЛОТ_БЕЗ_ЛОТКА.casefold():
            поставить(карточка.ПОЛЕ_СЛОТА, СЛОТ_С_ЛОТКОМ)
        elif not лоток and слот != СЛОТ_БЕЗ_ЛОТКА.casefold():
            поставить(карточка.ПОЛЕ_СЛОТА, СЛОТ_БЕЗ_ЛОТКА)

    panic = поля.get("panic_full")
    поставить("Panic full", None if panic is None else ("Да" if panic else "Нет"))

    # --- второй IMEI: тот из двух, которого ещё нет в «Imei 1»
    первый = re.sub(r"\D", "", _словами(сейчас.get(ПОЛЕ_IMEI_1)))
    второй = next((x for x in _имеи(имеи) if x != первый), None)
    if первый and второй:
        поставить(ПОЛЕ_IMEI_2, второй)

    # --- состояние: только «нормальное → был в ремонте», и только по находке кабеля
    имя_статуса = next((n for n in карточка.ПОЛЕ_СТАТУСА if n in по_имени), None)
    if поля.get("phone_status") == СТАТУС_РЕМОНТ and имя_статуса:
        текущий = _словами(сейчас.get(имя_статуса))
        if текущий.casefold() in СТАТУСЫ_НОРМЫ:
            старое = (dict_aliases.get("Ремонт статус") or {}).get(СТАТУС_РЕМОНТ)
            кандидаты = list(карточка.СТАТУСЫ[СТАТУС_РЕМОНТ]) + ([старое] if старое else [])
            поставить(карточка.ПОЛЕ_СТАТУСА, СТАТУС_РЕМОНТ, list(dict.fromkeys(кандидаты)))
        elif текущий.casefold() not in (x.casefold() for x in карточка.СТАТУСЫ[СТАТУС_РЕМОНТ]):
            заметки.append(f"Статус оставлен «{текущий}»: кабель нашёл замену детали, "
                           "она записана в «Отчёт диагностики»")

    # --- что не прошло проверку — той же строкой, что у новых товаров
    отчёт = карточка.краткий_отчёт(SimpleNamespace(
        comment_ocenka=поля.get("comment_ocenka"), diag_brief="", malfunction="", defects=""))
    поставить(карточка.ПОЛЕ_ОТЧЁТА, отчёт or None)
    поставить(карточка.ПОЛЕ_ЗАКЛЮЧЕНИЯ, str(поля.get("ссылка_чека") or "").strip() or None)
    # Галочка и дата диагностики (18.11.2026): здесь телефон точно читали кабелем — для этого
    # режим и сделан. Дату присылает касса; не прислала (касса прежней сборки) — ставим
    # только галочку, выдумывать дату нельзя.
    поставить(карточка.ПОЛЕ_ДИАГНОСТИКИ, True)
    поставить(карточка.ПОЛЕ_ДАТЫ_ДИАГНОСТИКИ, поля.get("когда_диагностика") or None)

    # --- ЗАМЕНА: поля, которыми владеет диагностика, перезаписываются целиком (18.11.2026)
    #
    # Владелец: «пусть он не дописывает, не корректирует. А все доп поля перезаполняет
    # заменой». Отличие от `поставить` выше принципиальное: там пустое значение означало
    # «кабель не прочитал — оставь как было», и в карточке оставалось прошлое значение,
    # иногда от ДРУГОГО телефона. Здесь пустое значение означает «очистить».
    #
    # PUT в МойСкладе дополняет, а не заменяет: поле, которое не упомянули в attributes,
    # остаётся как было. Поэтому «заменить всё» = перечислить каждое наше поле явно, со
    # значением или с `null`. Чужих полей (Kaspi, Halyk, скидка, артикул, бренд, способ
    # приобретения, комплектация, номер сделки) в словаре нет вовсе — замена до них не
    # дотянется, и ручную работу сотрудников мы не стираем.
    for имя_поля, значение in (поля.get("доп") or {}).items():
        заменить(имя_поля, значение)

    # Порядок для глаз сотрудника. С 18.11.2026 полей семьдесят три, а на экране кассы
    # помещается одиннадцать строк: без порядка он подтверждал бы запись, видя случайные
    # одиннадцать из шестидесяти. Наверх идёт то, что требует внимания:
    #   1) исправление — в поле было одно значение, станет другое (прошлый телефон, ошибка);
    #   2) очистка — значение было, а теперь его нет;
    #   3) заполнение пустого — проверять нечего, это просто новые данные.
    def важность(и):
        было, станет = str(и.get("было") or ""), str(и.get("станет") or "")
        if было and было != "—" and станет != "— очищено":
            return 0
        if станет == "— очищено":
            return 1
        return 2

    # --- серийный номер и штрихкод самого товара (19.11.2026)
    #
    # Это не доп. поля, а поля товара, и до сих пор режим их не трогал вовсе. Замерено на
    # боевом остатке (392 телефона): у 382 серийник знак в знак равен «Imei 1», у ОДНОГО там
    # стоит второй IMEI, у девяти — вообще не IMEI. Владелец: «если он не равен первому имей
    # то исправляет и его».
    #
    # Правим только когда кабель назвал IMEI: без него сравнивать не с чем. Штрихкод трогаем
    # осторожнее серийника — по нему ищут, и занятый чужим товаром штрихкод создаст двойника,
    # поэтому перед правкой проверяем, свободен ли он.
    план_серийника = {"можно": False, "почему": ""}
    первый = (_имеи(имеи) or [None])[0]
    if первый:
        вещи = [str(x).strip() for x in (товар.get("things") or []) if str(x or "").strip()]
        if вещи[:1] != [первый]:
            # Серийник в КАРТОЧКЕ не меняем: МойСклад такую запись молча не применяет —
            # вещь живёт в документе, которым её приняли (проверено на боевых карточках
            # 41132, 41917, 44212, 45134). Правим в самом документе: план составляем здесь,
            # а выполняется он только при записи, по кнопке (владелец, 23.11.2026).
            план_серийника = _план_серийника(
                session, товар, вещи[0] if вещи else "", первый, запрос=запрос)
            если_можно = план_серийника.get("можно")
            изменения.append({"поле": "Серийный номер", "было": (вещи[0] if вещи else "—"),
                              "станет": первый if если_можно else "— не выйдет"})
            заметки.append(ms_serial_fix.словами(план_серийника, первый)
                           if если_можно else
                           f"серийный номер ({вещи[0] if вещи else 'пусто'}) не равен IMEI 1 "
                           f"({первый}): {план_серийника.get('почему')}")
        шк = [b for b in (товар.get("barcodes") or []) if isinstance(b, dict)]
        свои = [str(v).strip() for b in шк for v in b.values() if str(v or "").strip()]
        if первый not in свои:
            занят = запрос(session, "GET", "/entity/product",
                           params={"filter": f"barcode={первый}", "limit": 2}).get("rows") or []
            чужие = [т for т in занят if str(т.get("id")) != str(товар.get("id"))]
            if чужие:
                заметки.append(f"штрихкод не равен IMEI 1, но такой уже у товара "
                               f"{чужие[0].get('code') or '?'} — не трогаю")
            else:
                изменения.append({"поле": "Штрихкод товара",
                                  "было": (свои[0] if свои else "—"), "станет": первый})
                # PUT заменяет список штрихкодов целиком — прочие сохраняем
                правка_товара["barcodes"] = ([{"code128": первый}]
                                             + [b for b in шк if первый not in b.values()])

    изменения.sort(key=важность)
    сколько = {0: 0, 1: 0, 2: 0}
    for и in изменения:
        сколько[важность(и)] += 1
    если_много = []
    if len(изменения) > ИЗМЕНЕНИЙ_НЕ_БОЛЬШЕ:
        если_много.append(f"изменений всего {len(изменения)}: исправлений {сколько[0]}, "
                          f"очисток {сколько[1]}, заполнений пустого {сколько[2]}")
    return {"изменения": изменения[:ИЗМЕНЕНИЙ_НЕ_БОЛЬШЕ], "attributes": attributes,
            "товар": правка_товара, "заметки": (если_много + заметки)[:10],
            "серийник": план_серийника}


def выполнить(session, посылка: dict, *, запрос, кэш, dict_aliases=None) -> dict:
    """Запрос кассы целиком: найти товар, посчитать изменения и — если просят — записать.

    `посылка["мойсклад"]["что"]`: «найти» — только показать; «записать» — записать, и только
    в тот товар, который сотруднику показывали (`товар` — его id): между показом и
    подтверждением под тем же IMEI не должен оказаться другой товар."""
    мс = посылка.get("мойсклад") or {}
    что = "записать" if мс.get("что") == "записать" else "найти"
    примечания = []
    товар, почему = найти(session, посылка.get("imei"), запрос=запрос, кэш=кэш,
                          модель=посылка.get("модель") or "", заметки=примечания)
    if товар is None:
        return {"что": что, "найден": False, "почему": почему}
    товар = запрос(session, "GET", f"/entity/product/{товар['id']}")       # свежая карточка целиком
    расчёт = посчитать(session, товар, посылка.get("поля") or {}, посылка.get("imei"),
                       запрос=запрос, кэш=кэш, dict_aliases=dict_aliases)
    ответ = {"что": что, "найден": True, "почему": "",
             "товар": {"id": str(товар.get("id") or ""), "код": str(товар.get("code") or ""),
                       "название": str(товар.get("name") or "")[:200],
                       "папка": str(товар.get("pathName") or "")[:200]},
             "изменения": расчёт["изменения"],
             "заметки": (примечания + расчёт["заметки"])[:10], "записано": False}
    if что != "записать":
        return ответ
    if str(мс.get("товар") or "") != ответ["товар"]["id"]:
        return {**ответ, "почему": "под этим IMEI теперь другой товар — проверьте телефон ещё раз"}
    if расчёт["attributes"] or расчёт.get("товар"):
        тело = dict(расчёт.get("товар") or {})
        if расчёт["attributes"]:
            тело["attributes"] = расчёт["attributes"]
        запрос(session, "PUT", f"/entity/product/{товар['id']}", body=тело)
        log.warning("МойСклад: обновлён товар %s (%s): %s", ответ["товар"]["код"], ответ["товар"]["id"],
                    "; ".join(f"{и['поле']}: «{и['было']}» → «{и['станет']}»" for и in расчёт["изменения"]))
    # Серийный номер — в документах, и только здесь, по кнопке: показ ничего не меняет.
    план = расчёт.get("серийник") or {}
    if план.get("можно"):
        первый = (_имеи(посылка.get("imei")) or [None])[0]
        итог = _поправить_серийник(session, план, первый, запрос=запрос)
        for строка in итог["сделано"]:
            log.warning("МойСклад: товар %s — %s", ответ["товар"]["код"], строка)
        if итог["беда"]:
            log.warning("МойСклад: товар %s — серийный номер не доправлен: %s",
                        ответ["товар"]["код"], итог["беда"])
            ответ["заметки"] = list(ответ["заметки"]) + [
                "серийный номер исправить не вышло: " + итог["беда"]
                + ". Проверьте документы в МойСкладе: "
                + "; ".join(итог["сделано"] or ["ничего не поменяли"])]
        else:
            ответ["заметки"] = list(ответ["заметки"]) + ["серийный номер исправлен в документах"]
    ответ["записано"] = True
    return ответ


