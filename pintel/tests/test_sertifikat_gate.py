# -*- coding: utf-8 -*-
"""Сертификат проверки отдаётся только после всех этапов, и отметки в нём есть.

Владелец, 19.11.2026: «Пусть заключение появляется только после прохождения всех этапов
тестов (через браузер и ручные), а то в заключении их нет!»

Беда была двойная. Первое: чек ждёт тест и проверки руками в «сделке», а страница на домене
собирала сделку только из `чек` — отметок там нет, и блок проверок выходил пустым, хотя на
бумаге он печатался. Второе: ссылка выдавалась сразу после чтения кабелем, то есть сертификат
можно было открыть до теста — и он выглядел бы как полная проверка.
"""
import importlib.util
import io
import os

import pytest

HERE = os.path.dirname(os.path.abspath(__file__))
ФАЙЛ = os.path.join(HERE, "..", "pintel_server", "routers", "web.py")
ТЕСТ_ПРОЙДЕН = {k: "ok" for k in ("sensor", "multitouch", "screen", "speaker", "mic",
                                  "camera_back", "camera_front")}
РУЧНАЯ_ПРОЙДЕНА = {k: True for k in ("keys", "vibro", "bio", "charge", "net", "glue",
                                     "apple", "mdm")}


@pytest.fixture(scope="module")
def ворота():
    """Две функции из web.py, без поднятия всего сервера: тут проверяется правило, а не FastAPI."""
    src = io.open(ФАЙЛ, encoding="utf-8").read()
    нач = src.index("def _чего_не_хватает_для_сертификата")
    кон = src.index('@router.get("/check/{token}"')
    ns = {}
    exec(compile(src[нач:кон], "web.py", "exec"), {"__builtins__": __builtins__}, ns)  # noqa: S102
    return ns


def test_everything_passed_opens_the_certificate(ворота):
    нет = ворота["_чего_не_хватает_для_сертификата"](
        {"тест_телефона": ТЕСТ_ПРОЙДЕН, "ручная_диагностика": РУЧНАЯ_ПРОЙДЕНА})
    assert нет == []


def test_the_phone_test_alone_is_not_enough(ворота):
    нет = ворота["_чего_не_хватает_для_сертификата"](
        {"тест_телефона": ТЕСТ_ПРОЙДЕН, "ручная_диагностика": {}})
    assert len(нет) == 1 and "проверки руками" in нет[0]
    assert "Герметик" in нет[0], "сотруднику надо назвать, чего именно не хватает"


def test_the_manual_checks_alone_are_not_enough(ворота):
    нет = ворота["_чего_не_хватает_для_сертификата"](
        {"тест_телефона": {"sensor": "ok"}, "ручная_диагностика": РУЧНАЯ_ПРОЙДЕНА})
    assert len(нет) == 1 and "тест на телефоне" in нет[0]


def test_a_failed_item_still_counts_as_passed_stage(ворота):
    """Этап пройден, даже если пункт НЕ прошёл: сертификат честно покажет сбой.

    Прятать сертификат телефона со сбоем нельзя — именно он и нужен покупателю, чтобы
    увидеть, что не работает. Запрет здесь про НЕПРОЙДЕННЫЙ этап, а не про плохой результат."""
    тест = {**ТЕСТ_ПРОЙДЕН, "speaker": "fail"}
    ручная = {**РУЧНАЯ_ПРОЙДЕНА, "glue": False}
    assert ворота["_чего_не_хватает_для_сертификата"](
        {"тест_телефона": тест, "ручная_диагностика": ручная}) == []


def test_a_skipped_test_counts_as_a_passed_stage(ворота):
    """Запечатанный телефон: тест пропущен с причиной — этап считается закрытым."""
    assert ворота["_чего_не_хватает_для_сертификата"](
        {"тест_пропущен": "запечатанный — коробку не вскрывали",
         "ручная_диагностика": РУЧНАЯ_ПРОЙДЕНА}) == []


def test_old_evaluations_keep_their_certificates(ворота):
    """Оценки прежних сборок отметок не присылали — их сертификаты не прячем.

    Ссылки на них уже у клиентов на руках, а задним числом проверку не пройти."""
    assert ворота["_чего_не_хватает_для_сертификата"]({}) == []
    assert ворота["_чего_не_хватает_для_сертификата"]({"паспорт": {"модель": "iPhone 13"}}) == []


def test_the_page_says_what_is_missing_without_blaming_anyone(ворота):
    стр = ворота["_сертификат_не_готов"](["тест на телефоне", "проверки руками (Герметик)"])
    assert "Проверка не закончена" in стр
    assert "тест на телефоне" in стр and "Герметик" in стр
    assert "ссылк" in стр.lower(), "клиенту надо сказать, что ссылка не изменится"
    # страницу видит и клиент: внутренних подробностей и упрёков там быть не должно
    for лишнее in ("сотрудник", "оценщик", "киоск", "traceback"):
        assert лишнее not in стр.lower()


def test_the_certificate_route_fills_the_marks_from_the_report():
    """Страница на домене обязана брать отметки из отчёта, иначе блок проверок пуст.

    Читаем исходник: поднимать сервер ради одной строки незачем, а правило должно быть
    закреплено — именно его отсутствие и было бедой."""
    src = io.open(ФАЙЛ, encoding="utf-8").read()
    нач = src.index('def public_check')
    тело = src[нач:нач + 3000]
    assert 'сделка.setdefault("тест", dict(rep.get("тест_телефона")' in тело
    assert 'сделка.setdefault("ручная", dict(rep.get("ручная_диагностика")' in тело
    assert "_чего_не_хватает_для_сертификата(rep)" in тело


def test_a_stage_the_build_does_not_report_is_not_demanded(ворота):
    """Этап требуем только если сборка кассы его присылает.

    Проверено на боевом 19.11.2026: у оценок 136 и 138 тест есть, анкеты нет — и страница
    отдавала 409. Это закрыло бы сертификаты ВСЕМ телефонам, пока парк касс не обновлён.
    Ключа в отчёте нет — значит на точке программа, которая этих отметок не знает."""
    f = ворота["_чего_не_хватает_для_сертификата"]
    # нынешняя сборка: тест присылает, анкету — нет
    assert f({"тест_телефона": ТЕСТ_ПРОЙДЕН}) == []
    нет = f({"тест_телефона": {"sensor": "ok"}})
    assert len(нет) == 1 and "тест на телефоне" in нет[0]
    # новая сборка: присылает оба, и оба спрашиваются
    assert f({"тест_телефона": ТЕСТ_ПРОЙДЕН, "ручная_диагностика": {}}) != []
