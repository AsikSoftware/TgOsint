# -*- coding: utf-8 -*-
"""История телефона по IMEI: что с этим аппаратом у нас уже было.

Зачем. Аппарат приходит к нам не впервые гораздо чаще, чем кажется: его оценивали на другой
точке, по нему оставляли заявку на сайте, его уже выкупали и продали. Сотрудник этого не
видел и называл цену с нуля — а клиент помнил прошлую, торговался по ней и знал, где дали
больше. Теперь всё, что мы про этот IMEI знаем, лежит у сотрудника на экране до того, как он
назовёт цену.

Три источника, каждый про своё:

* **сделки Оценки** — `devices` по `device_imeis` в её базе: когда, на какой точке, какая
  была батарея, какая автоцена и за сколько в итоге выкупили;
* **заявки с сайта** — Google Таблица «Pintel — заявки»: что клиент сказал о телефоне сам и
  какую цену ему назвали онлайн. Ссылка в `PINTEL_REQUESTS_SHEET_URL`; пусто — источник
  выключен и так и говорит;
* **наши проверки** — таблица `evaluations`: что показал кабель в прошлый раз.

Два правила, без которых это нельзя показывать сотруднику:

1. **Источник, который не ответил, говорит об этом словами.** «Истории нет» и «база Оценки не
   ответила» — разные вещи: во втором случае сотрудник обязан знать, что смотреть надо
   руками, а не считать, что аппарат у нас впервые.
2. **История ничего не решает за человека.** Она не меняет ни автоцену, ни состояние сделки —
   это подсказка у стойки.
"""
from __future__ import annotations

import csv
import io
import logging
import os
import re
import threading
import time

from sqlalchemy import select, text

from pintel_core.external import gsheet

from ..config import settings
from ..models import Evaluation

log = logging.getLogger("pintel.history")

# Сколько записей каждого вида отдаём. Это подсказка у стойки, а не отчёт: двадцать строк
# сотрудник всё равно не прочитает, пока клиент стоит рядом.
ПРЕДЕЛ = 8

# Заявки живут в Google, и спрашивать её на каждый телефон нельзя: у Sheets API квота, а
# заявки правят руками и редко. Пять минут — столько же держит прайс точки в боте.
КЭШ_СЕКУНД = 300

# Колонки таблицы заявок — по названиям в шапке, а не по номерам: колонку в неё вставят
# когда-нибудь посередине, и привязка к номерам сломалась бы молча.
ЗАЯВКА_ПОЛЯ = {"Дата": "дата", "Время": "время", "Заявка": "номер", "Имя": "имя",
               "Телефон": "телефон", "IMEI": "imei", "Модель": "модель", "Память": "память",
               "Оценка": "цена", "Внешний вид": "вид", "Не работает": "не_работает",
               "Ремонт": "ремонт", "Комплект": "комплект"}

# «когда» — отметка монотонных часов последнего чтения; None значит «не читали ни разу».
# Нулём это писать нельзя: монотонные часы считают от загрузки машины, и на только что
# поднятой машине ноль читается как «прочитано только что».
_кэш: dict = {"когда": None, "по_имеи": {}, "строк": 0, "беда": ""}
_замок = threading.Lock()


def только_цифры(значение) -> str:
    return re.sub(r"\D", "", str(значение or ""))


def _хвост_телефона(значение) -> str:
    """Последние четыре цифры: сотруднику нужно узнать, тот же это человек или другой, а не
    получить телефон клиента вторым экземпляром."""
    цифры = только_цифры(значение)
    return ("…" + цифры[-4:]) if len(цифры) >= 4 else ""


# ---------------------------------------------------------------- заявки с сайта

def _заявки_прочитать() -> tuple[dict, int, str]:
    """Таблицу заявок → {IMEI: [заявка, …]}, сколько строк, текст беды. Без исключений."""
    ссылка = settings.requests_sheet_url
    if not ссылка:
        return {}, 0, "заявки с сайта не подключены (PINTEL_REQUESTS_SHEET_URL пуст)"
    try:
        if os.path.isfile(gsheet.sa_path()):
            строки = gsheet.api_rows(ссылка, клетки="A1:T20000")
        else:
            # Лист заявок открыт по ссылке, и ключ для него не нужен — ровно так же сервер
            # читает и прайс, когда gservice.json на него не положили (gsheet.fetch_grid).
            строки = list(csv.reader(io.StringIO(gsheet.fetch_csv(ссылка))))
    except Exception as exc:                                     # noqa: BLE001 — Google падает сам по себе
        log.warning("заявки: таблица не прочиталась (%s)", exc)
        return {}, 0, f"таблица заявок не прочиталась: {str(exc)[:160]}"
    if not строки or len(строки) < 2:
        return {}, 0, "в таблице заявок нет строк"
    шапка = [str(x or "").strip() for x in строки[0]]
    место = {}
    for столбец, имя in ЗАЯВКА_ПОЛЯ.items():
        if столбец in шапка:
            место[имя] = шапка.index(столбец)
    if "imei" not in место:
        return {}, 0, "в таблице заявок нет колонки IMEI"
    по_имеи: dict = {}
    for строка in строки[1:]:
        def клетка(имя):
            i = место.get(имя)
            return str(строка[i]).strip() if (i is not None and i < len(строка)) else ""
        имеи = только_цифры(клетка("imei"))
        if len(имеи) < 14:
            continue
        по_имеи.setdefault(имеи[:14], []).append({
            "когда": (клетка("дата") + " " + клетка("время")).strip(),
            "номер": клетка("номер"),
            "имя": клетка("имя"),
            "телефон": _хвост_телефона(клетка("телефон")),
            "модель": (клетка("модель") + " " + клетка("память")).strip(),
            "цена": только_цифры(клетка("цена")) or "",
            "вид": клетка("вид"),
            "не_работает": клетка("не_работает"),
            "ремонт": клетка("ремонт"),
            "комплект": клетка("комплект"),
        })
    return по_имеи, len(строки) - 1, ""


def заявки(имеи) -> tuple[list, str]:
    """Заявки с сайта по этим IMEI (новые сверху). → (список, текст беды)."""
    with _замок:
        устарело = (_кэш["когда"] is None
                    or time.monotonic() - _кэш["когда"] > КЭШ_СЕКУНД)
        if устарело:
            по_имеи, строк, беда = _заявки_прочитать()
            # Прочитанное не выбрасываем: Google мог не ответить именно сейчас, а вчерашние
            # заявки всё ещё лучше, чем пустой угол. Беду при этом всё равно говорим.
            if по_имеи or not _кэш["по_имеи"]:
                _кэш.update({"по_имеи": по_имеи, "строк": строк})
            _кэш.update({"когда": time.monotonic(), "беда": беда})
        таблица, беда = _кэш["по_имеи"], _кэш["беда"]
    найдено = []
    for один in имеи:
        найдено += таблица.get(только_цифры(один)[:14], [])
    найдено.sort(key=lambda з: з.get("когда") or "", reverse=True)
    return найдено[:ПРЕДЕЛ], беда


# ---------------------------------------------------------------- сделки Оценки

ЗАПРОС_ОЦЕНКИ = text("""
    select d.id, d.created, coalesce(s.shop_name, '') as точка, d.model, d.ddr,
           coalesce(d.akb, '') as akb, d.akb_exact, d.price_grade_auto, d.price_grade_admin,
           d.price_buy, coalesce(st.status_name, '') as статус,
           coalesce(d.phone_status, '') as состояние, coalesce(d.trade_type, '') as вид
      from device_imeis i
      join devices d on d.id = i.device_id
      left join shops s on s.id = coalesce(d.shop_id_buy, d.shop_id_grade)
      left join statuses st on st.id = d.status_id
     where i.imei = any(:имеи)
     order by d.created desc
     limit :предел
""")


def сделки_оценки(имеи) -> tuple[list, str]:
    """Сделки Оценки по этим IMEI. → (список, текст беды).

    Один аппарат приходит в запрос двумя IMEI (слоты), и одна сделка в ответе может
    повториться — поэтому убираем повторы по id сделки, а не по IMEI.
    """
    if not settings.ocenka_enabled:
        return [], "база Оценки не подключена (PINTEL_OCENKA_DB_URL пуст)"
    from .ocenka_import import _ocenka_engine         # один пул на процесс, он уже есть
    try:
        with _ocenka_engine().connect() as c:
            строки = c.execute(ЗАПРОС_ОЦЕНКИ, {"имеи": list(имеи), "предел": ПРЕДЕЛ * 2}).all()
    except Exception as exc:                                     # noqa: BLE001
        log.warning("история: база Оценки не ответила (%s)", exc)
        return [], f"база Оценки не ответила: {type(exc).__name__}"
    видели, готово = set(), []
    for р in строки:
        if р.id in видели:
            continue
        видели.add(р.id)
        готово.append({
            "сделка": р.id,
            "когда": р.created.strftime("%d.%m.%Y") if р.created else "",
            "точка": р.точка,
            "модель": f"{р.model} {р.ddr} ГБ".strip(),
            "акб": (f"{р.akb_exact}%" if р.akb_exact else р.akb),
            "автоцена": р.price_grade_auto or р.price_grade_admin,
            "выкуп": р.price_buy,
            "статус": р.статус,
            "состояние": р.состояние,
            "вид": р.вид,
        })
    return готово[:ПРЕДЕЛ], ""


# ---------------------------------------------------------------- наши проверки

def наши_проверки(db, имеи, кроме=None) -> list:
    """Прошлые проверки этого аппарата у нас (кроме текущей)."""
    цифры = [только_цифры(x) for x in имеи if только_цифры(x)]
    if not цифры:
        return []
    запрос = (select(Evaluation).where(Evaluation.imei.in_(цифры))
              .order_by(Evaluation.created_at.desc()).limit(ПРЕДЕЛ + 1))
    готово = []
    for ev in db.scalars(запрос):
        if кроме and ev.id == кроме:
            continue
        готово.append({
            "оценка": ev.id,
            "номер": ev.number,
            "когда": ev.created_at.strftime("%d.%m.%Y %H:%M") if ev.created_at else ev.day,
            "модель": f"{ev.model_name or ''} {ev.capacity_gb or ''}".strip(),
            "акб": ev.battery_health,
            "циклы": ev.battery_cycles,
            "вердикт": ev.verdict,
            "цена": ev.price_offer,
            "итог": ev.final_price,
            "детали": ev.apple_summary,
        })
    return готово[:ПРЕДЕЛ]


# ---------------------------------------------------------------- всё вместе

def по_имеи(db, имеи, кроме=None) -> dict:
    """Вся история телефона одним словарём — ровно то, что киоск покажет в углу экрана."""
    чистые = []
    for один in имеи or ():
        ц = только_цифры(один)
        if len(ц) >= 14 and ц not in чистые:
            чистые.append(ц)
    if not чистые:
        return {"есть": False, "почему": ["IMEI не прочитался — искать нечего"],
                "оценки": [], "заявки": [], "наши": []}
    оценки, беда_оценки = сделки_оценки(чистые)
    заявки_, беда_заявок = заявки(чистые)
    наши = наши_проверки(db, чистые, кроме=кроме)
    почему = [x for x in (беда_оценки, беда_заявок) if x]
    return {"есть": bool(оценки or заявки_ or наши),
            "почему": почему,
            "оценки": оценки, "заявки": заявки_, "наши": наши}
