def _диагностические_поля():
    """(имя, тип) всех полей, которые завела диагностика — из того же списка, что и скрипт."""
    спец = importlib.util.spec_from_file_location(
        "ms_diag_fields", os.path.join(ПАПКА, "ms_diag_fields.py"))
    м = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(м)
    return м.ПОЛЯ


def карточка_со_всеми_полями():
    """Карточка, в которой есть и прежние поля, и все 73 новых — как на боевом с 18.11.2026."""
    поля, справочники = с_заключением_и_цветом()
    поля = list(поля) + [(и, т, "") for и, т in _диагностические_поля()]
    return поля, справочники


def test_the_names_we_create_are_exactly_the_names_we_fill():
    """Список полей в МойСкладе и то, что отдаёт касса, обязаны совпадать знак в знак.

    Поле ищется ПО ИМЕНИ: опечатка в одну букву — и значение молча не доедет, а в карточке
    останется прошлое. Ни в журнал, ни на экран это не попадёт, потому что поля
    необязательные. Поэтому сверяем списки целиком, в обе стороны."""
    from pintel_core.external import ms_update
    в_мойскладе = {и for и, _ in _диагностические_поля()}
    отдаёт_касса = set(ms_update.доп_поля({}).keys())
    assert отдаёт_касса - в_мойскладе == set(), "касса шлёт поля, которых в МойСкладе нет"
    assert в_мойскладе - отдаёт_касса == set(), "в МойСкладе есть поля, которых касса не заполняет"


def test_our_fields_are_replaced_and_foreign_ones_are_never_touched(м):
    """Замена: наше поле перезаписывается, даже если в нём уже что-то стоит; чужое — нет."""
