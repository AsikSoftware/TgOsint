# Пусто: владелец распорядился запрещать и цвет, и panic full — оба в `ПУНКТЫ`. Механизм
# оставлен: если какую-то величину решат не запрещать, а только снимать автоцену, её место здесь.
ЖЕЛАТЕЛЬНОЕ = ()

# Что приходит НЕ из чтения по кабелю. Запрет это не отменяет — сделку без цвета по-прежнему
# не создать, — но ПЕРЕЧИТЫВАТЬ ради этого телефон бессмысленно: цвет даёт база IMEI (её
# спрашивают позже, уже после чтения) или кнопка сотрудника, а в самом телефоне его на новых
# iOS нет вовсе — служба MobileGestalt закрыта и молчит на 92% эталонов.
#
# Цена этой мелочи: за 10 дней на точках 750 чтений и 1310 перечитываний, из них 650 раз цвет
# так и не прочитался. Телефон читали по три раза, клиент ждал втрое дольше, а на экране
# висело «не прочитано: цвет — читаем заново» (24.11.2026).
НЕ_ИЗ_КАБЕЛЯ = {"цвет", "сверка_деталей"}


def _сверка_закончена(rep) -> bool:
    """Сотрудник ответил по всем деталям, по которым ответа не было? Сверка не нужна — тоже
    «да»: у модели нет раздела, аппарат запечатан или Apple сказала всё сама."""
    from . import сверка_деталей as _с
    return (not _с.спрашивать_ли(rep)) or _с.закончена(rep, (rep or {}).get("сверка_сотрудником"))




def _пас(rep):
    return (rep or {}).get("паспорт") or {}


def _непусто(v) -> bool:
    return bool(str(v or "").strip())


def _цифры(v) -> str:
    return "".join(c for c in str(v or "") if c.isdigit())


def запечатанный(rep) -> bool:
    """Запечатанный аппарат кабелем не читают — список к нему не применяется."""
    rep = rep or {}
    return bool(rep.get("запечатанный") or (rep.get("sickw") or {}).get("запечатанный"))


def _проверить(rep, список, закрыто=()) -> list:
    if not rep or запечатанный(rep):
        return []
    закрыто = set(закрыто or ())
    нет = []
    for ключ, название, есть, зачем in список:
        if ключ in закрыто:
            continue                             # сотрудник закрыл это сам (цвет кнопкой)
        try:
            ладно = bool(есть(rep))
        except Exception:                                        # noqa: BLE001 — нет раздела вовсе
            ладно = False
        if not ладно:
            нет.append((ключ, название, зачем))
    return нет


def не_прочитано(rep, закрыто=(), только_кабель=False) -> list:
    """Чего из обязательного нет. → [(ключ, название, зачем)]. Пустой список — можно пускать.

    `закрыто` — ключи, которые сотрудник закрыл сам: сейчас это «цвет» (кнопка на экране).
    `только_кабель` — оставить лишь то, что даёт само чтение телефона: по этому списку
    решают, перечитывать ли аппарат, и повторять чтение ради цвета незачем (см. НЕ_ИЗ_КАБЕЛЯ).
    """
    нет = _проверить(rep, ПУНКТЫ, закрыто)
    return [п for п in нет if п[0] not in НЕ_ИЗ_КАБЕЛЯ] if только_кабель else нет


def желательного_нет(rep) -> list:
    """Чего нет из того, что не запрещает сделку, но снимает автоцену (сейчас — ничего)."""
    return _проверить(rep, ЖЕЛАТЕЛЬНОЕ)


def всё_прочитано(rep, закрыто=()) -> bool:
    return not не_прочитано(rep, закрыто)


def словами(rep, закрыто=()) -> str:
    """Короткая строка для экрана кассы и журнала точки."""
    нет = не_прочитано(rep, закрыто)
    if not нет:
        return ""
    return "не прочитано: " + ", ".join(название for _к, название, _з in нет)


def почему_не_пустить(rep, закрыто=()) -> str:
    """Фраза сотруднику: чего нет и что с этим делать.

    Совет разный, потому что причины разные: кабель виноват в одном, наша сборка — в другом,
    а цвет сотрудник закрывает сам. Советовать «замените кабель» там, где дело в программе,
    значит гонять человека по кругу."""
    нет = не_прочитано(rep, закрыто)
    if not нет:
        return ""
    ключи = {к for к, _н, _з in нет}
    пункты = ", ".join(название for _к, название, _з in нет)
    если_одно = len(нет) == 1
    начало = (f"Без {'этой величины' if если_одно else 'этих величин'} оценка будет "
              f"выдумкой, а {'её' if если_одно else 'их'} нет: {пункты}.")
    советы = []
    if ключи - {"цвет", "panic_full"}:
        советы.append("Нажмите «Проверить телефон заново»; не поможет — замените кабель или "
                      "переставьте его в другой порт.")
    if "цвет" in ключи:
        советы.append("Цвет выберите кнопкой на этом экране: база IMEI его не дала.")
    if "panic_full" in ключи:
        беда = str((rep.get("паника") or {}).get("ошибка") or "")
        советы.append("Ошибку Panic full читает сама программа — "
                      + ("обновите её на точке." if ("модул" in беда or "metadata" in беда)
                         else "переподключите кабель, а если повторится, обновите программу."))
    return начало + " " + " ".join(советы)
