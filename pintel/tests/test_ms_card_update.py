def товар(**поля):
    """Старый товар со склада: АКБ диапазоном, без циклов, цвета и заключения. `поля` — что
    уже записано в доп. полях (имя → значение словами)."""
    записано = {"АКБ": "86-90%", "Память": "128", "Sim слот": "Стандарт",
                "Статус": "Б/у телефон в нормальном состоянии", "Imei 1": ИМЕИ[0],
                "Комплектация": "Коробка", "Kaspi 12": 21834, **поля}
    справочные = {"АКБ", "Память", "Sim слот", "Статус", "Комплектация", "Цвет"}
    return {"id": "t-1", "code": "40117", "name": "026 Ip 13 128 Midnight", "pathName": "БУ телефоны/Apple/13 Серия/Ip 13",
            "meta": {"href": "https://api.moysklad.ru/api/remap/1.2/entity/product/t-1"},
            # серийник товара в МойСкладе — это первый IMEI (так его ставит автоприёмка);
            # в карточке со склада он бывает и вторым, и мусором — см. отдельную проверку ниже
            "barcodes": [{"code128": ИМЕИ[0]}], "things": [ИМЕИ[0]], "buyPrice": {"value": 15000000},
            "attributes": [{"name": k, "value": ({"name": v} if k in справочные else v)}
                           for k, v in записано.items() if v is not None]}


def склад(товары, карточка=None, документы=None):
    """Подменный МойСклад: метаданные и справочники как у настоящей карточки, товары — наши.
    → (запрос, кэш, журнал); в журнале всё, что ушло, вместе с телом записи.

    `карточка` — вид карточки: по умолчанию та, что была до 18.11.2026 (без галочки
    диагностики), чтобы прежние проверки говорили ровно о прежних полях.
    `документы` — движения телефона: приёмка и, если продан, продажа. Пусто — движений нет."""
    поля, справочники = (карточка or с_заключением_и_цветом)()
    документы = list(документы or [])
    журнал = []

    def запрос(session, метод, адрес, params=None, body=None):
        журнал.append((метод, адрес, body))
        if адрес == "/entity/product/metadata":
            # Ссылка справочника — как у настоящего МойСклада: номер стоит ПЕРЕД словом
            # «metadata». Подменный склад держит её в том же виде нарочно: пока здесь было
            # «справочник/<номер>», разбор ссылки читался неверно и тесты этого не видели,
            # а на точке 20.11.2026 все справочники отвечали 404.
            return {"attributes": {"rows": [
                {"name": n, "type": t, "meta": {"href": "поле/" + n},
                 **({"customEntityMeta": {
                     "href": f"https://api.moysklad.ru/api/remap/1.2/entity/customentity/{d}/metadata"}}
                    if d else {})}
                for n, t, d in поля]}}
        if адрес == "/report/turnover/byoperations":
            return {"rows": [{"operation": {"meta": {
                "type": д["тип"],
                "href": f"https://api.moysklad.ru/api/remap/1.2/entity/{д['тип']}/{д['id']}"}}}
                for д in документы]}
        if метод == "GET" and re.match(r"^/entity/(supply|enter|demand|retaildemand)/[^/]+$", адрес):
            ид = адрес.rsplit("/", 1)[-1]
            д = next(д for д in документы if д["id"] == ид)
            return {"id": д["id"], "name": д["номер"], "applicable": д["проведён"],
                    "positions": {"rows": [{"id": п["id"], "things": list(п["вещи"])}
                                           for п in д["позиции"]]}}
        if метод == "PUT" and re.match(r"^/entity/(supply|enter|demand|retaildemand)/[^/]+/positions/", адрес):
            return {"id": адрес.rsplit("/", 1)[-1]}
        if метод == "PUT" and re.match(r"^/entity/(supply|enter|demand|retaildemand)/[^/]+$", адрес):
            return {"id": адрес.rsplit("/", 1)[-1]}
        if адрес == "/report/stock/all":
            # остаток держим на самом товаре, ключом «остаток»: так тесту видно, какая
            # карточка продана, а какая лежит на складе
            ид = str((params or {}).get("filter", "")).rsplit("/", 1)[-1]
            т = next((t for t in товары if t["id"] == ид), None)
            return {"rows": [{"stock": (т or {}).get("остаток", 0)}] if т else []}
        if адрес.startswith("/entity/customentity/"):
            номер = адрес.rsplit("/", 1)[-1]
            if номер not in справочники:          # настоящий МойСклад отвечает на это 404
                raise AssertionError(f"нет такого справочника: {адрес}")
            return {"rows": [{"name": v, "meta": {"href": "значение/" + v}}
                             for v in справочники[номер]]}
        if адрес == "/entity/product" and метод == "GET":
            фильтр = params["filter"]
            ключ, значение = фильтр.split("=", 1)
            if ключ.startswith("поле/"):
                # поиск по доп. полю: так находятся телефоны с битым штрихкодом и двойниками
                имя_поля = ключ.split("/", 1)[1]
                return {"rows": [t for t in товары
                                 if any((a.get("name") or "").strip() == имя_поля
                                        and str(a.get("value")) == значение
                                        for a in (t.get("attributes") or []))]}
            return {"rows": [t for t in товары
                             if any(значение in b.values() for b in t.get("barcodes") or [])]}
        if адрес.startswith("/entity/product/") and метод == "GET":
            return next(t for t in товары if t["id"] == адрес.rsplit("/", 1)[-1])
        if адрес.startswith("/entity/product/") and метод == "PUT":
            return {"id": адрес.rsplit("/", 1)[-1]}
        raise AssertionError((метод, адрес))

    return запрос, (lambda ключ, загрузить: загрузить()), журнал


def посылка(что="найти", товар_id="", **поля):
    основа = {"akb": "86-90", "akb_exact": 88, "akb_cycles": 412, "ddr": 128, "color": "MIDNIGHT",
              "sim": "Стандарт", "panic_full": False, "phone_status": None,
              "comment_ocenka": "Детали: родные · Батарея: 88%, 412 циклов · Киоск 16/38 от 2026-11-17",
              "ссылка_чека": ССЫЛКА}
    основа.update(поля)
    return {"версия": 1, "код": "ABCD12", "imei": list(ИМЕИ), "поля": основа,
            "мойсклад": {"что": что, **({"товар": товар_id} if товар_id else {})}}


def выполнить(м, товары, п, карточка=None, документы=None):
    запрос, кэш, журнал = склад(товары, карточка, документы)
    return м.выполнить(None, п, запрос=запрос, кэш=кэш, dict_aliases=АЛИАСЫ), журнал


def пары(ответ):
    return {и["поле"]: (и["было"], и["станет"]) for и in ответ["изменения"]}


def test_the_product_is_found_by_imei_and_the_preview_writes_nothing(м):
    """«Найти»: товар ищется по IMEI (штрихкод), сотруднику показывается «было → станет», а в
    МойСклад при этом не уходит ни одной записи."""
    ответ, журнал = выполнить(м, [товар()], посылка())
    assert ответ["найден"] and ответ["товар"] == {"id": "t-1", "код": "40117", "название": "026 Ip 13 128 Midnight",
                                                 "папка": "БУ телефоны/Apple/13 Серия/Ip 13"}
    assert not ответ["записано"] and all(метод == "GET" for метод, _, _ in журнал)
    assert пары(ответ) == {"АКБ": ("86-90%", "88%"), "Цикл": ("", "412"), "Цвет": ("", "MIDNIGHT"),
                           "Sim Лоток": ("", "Да"), "Panic full": ("", "Нет"),
                           "Imei 2": ("", ИМЕИ[1]), "Заключение": ("", ССЫЛКА)}


def test_writing_sends_only_the_changed_fields_and_never_the_rest(м):
    """«Записать»: один запрос PUT, в нём только изменившиеся доп. поля. Названия, цен, папки,
    штрихкода и чужих полей (комплектация, рассрочки) в теле нет вовсе — МойСклад оставляет
    не названное как было."""
    ответ, журнал = выполнить(м, [товар()], посылка("записать", "t-1"))
    assert ответ["записано"] and ответ["найден"]
    записи = [(адрес, тело) for метод, адрес, тело in журнал if метод != "GET"]
    assert len(записи) == 1 and записи[0][0] == "/entity/product/t-1"
    тело = записи[0][1]
    assert set(тело) == {"attributes"}, "в запись ушло что-то кроме доп. полей"
    поля = {a["meta"]["href"].split("/", 1)[1]: a["value"] for a in тело["attributes"]}
    assert set(поля) == {"АКБ", "Цикл", "Цвет", "Sim Лоток", "Panic full", "Imei 2", "Заключение"}
    assert поля["АКБ"] == {"meta": {"href": "значение/88%"}} and поля["Цикл"] == 412
    assert поля["Sim Лоток"] is True and поля["Panic full"] is False and поля["Заключение"] == ССЫЛКА
    for чужое in ("Комплектация", "Kaspi 12", "Память", "Статус", "Sim слот", "Imei 1", "Способ приобретения"):
        assert чужое not in поля, чужое


