def _таблица(monkeypatch, строки, через_csv=False):
    """Таблица заявок в памяти. `через_csv` — как на сервере без gservice.json."""
    сервис = _сервис()
    monkeypatch.setattr(сервис.settings, "requests_sheet_url",
                        "https://docs.google.com/spreadsheets/d/КЛЮЧ/edit#gid=0")
    if через_csv:
        monkeypatch.setattr(сервис.gsheet, "sa_path", lambda: "/нет/такого/ключа.json")
        monkeypatch.setattr(сервис.gsheet, "fetch_csv", lambda url, timeout=30:
                            "\r\n".join(",".join(f'"{к}"' for к in р) for р in строки))
    else:
        monkeypatch.setattr(сервис.gsheet, "sa_path", lambda: __file__)   # «ключ есть»
        monkeypatch.setattr(сервис.gsheet, "api_rows", lambda url, клетки=None: строки)
    сервис._кэш.update({"когда": None, "по_имеи": {}, "строк": 0, "беда": ""})


def test_zayavki_chitayutsya_po_nazvaniyam_kolonok(monkeypatch):
    """Колонки берём по названиям в шапке. Вставят колонку посередине — привязка к номерам
    молча показывала бы сотруднику цену из соседней клетки."""
    сервис = _сервис()
    переставленная = [["Время", "Дата", "IMEI", "Заявка", "Оценка", "Телефон", "Имя"],
                      ["13:11", "19.10.2026", "351234560000019", "PT-0001", "549 500",
                       "+7 (700) 000-00-11", "Клиент"]]
    _таблица(monkeypatch, переставленная)
    найдено, беда = сервис.заявки(["351234560000019"])
    assert not беда and len(найдено) == 1
    assert найдено[0]["номер"] == "PT-0001" and найдено[0]["цена"] == "549500"
    assert найдено[0]["телефон"] == "…0011", "телефон клиента целиком на экране не нужен"


def test_imei_sravnivaetsya_po_14_tsifram(monkeypatch):
    """Контрольная (15-я) цифра у двух слотов разная, а аппарат один. Сравнивать надо по
    первым четырнадцати, иначе заявка по тому же телефону не найдётся."""
    сервис = _сервис()
