# -*- coding: utf-8 -*-
"""Прошлая проверка того же телефона: найти, взять готовой, назвать словами.

Зачем. Один и тот же аппарат оказывается у кассы второй раз за смену чаще, чем кажется:
сделку отменили, программа перезапустилась, клиент ушёл подумать и вернулся, сотрудник
переоформляет с нуля. Полное чтение по кабелю — это минуты: слепок, ожидание раздела Apple,
запрос к базе IMEI, реестр РФС. Повторять их ради того же самого ответа незачем, а клиент
стоит у стола.

Поэтому программа, увидев телефон, сначала смотрит: не проверяли ли его совсем недавно. Если
проверяли — берёт готовый отчёт и ведёт сотрудника дальше, к тесту на телефоне и медиа.

Чем это держится:

* **срок.** Чем старее отчёт, тем меньше он про телефон, который сейчас на столе: заряд,
  память и журнал сбоев живут своей жизнью. Окно короткое — по умолчанию 6 часов
  (`reuse_hours` в настройках точки; 0 выключает поиск совсем).
* **серийник.** Берём только отчёт этого самого аппарата: сверяем UDID (им киоск и
  называет телефон на кабеле), а у старых отчётов — серийный номер.
* **видимость.** Отчёт взят прошлый — это написано на экране, с временем проверки, и рядом
  стоит кнопка «Проверить заново». Молча старым отчётом не прикрываемся: ошибка в эту
  сторону стоит денег, а не минуты.

Чтение с диска — единственное, что здесь есть; к серверу и к телефону эта часть не ходит,
поэтому её целиком проверяют тесты.
"""
from __future__ import annotations

import glob
import os
from datetime import datetime, timedelta

ЧАСОВ = 6                                   # окно по умолчанию; настройка точки — `reuse_hours`
ИМЯ_ОТЧЁТА = "report.json"
ФОРМАТ_ПАПКИ = "%Y%m%d_%H%M%S"              # так их называет pintel_kiosk.worker


def _когда(путь: str) -> datetime:
    """Когда сделана проверка. Имя папки надёжнее даты файла: файл могли скопировать."""
    имя = os.path.basename(путь.rstrip(os.sep))
    try:
        return datetime.strptime(имя[:15], ФОРМАТ_ПАПКИ)
    except ValueError:
        return datetime.fromtimestamp(os.path.getmtime(os.path.join(путь, ИМЯ_ОТЧЁТА)))


def тот_же(отчёт: dict, серийник: str) -> bool:
    """Это отчёт того самого телефона? Сверяем UDID, а у старых отчётов — серийный номер.

    Имя папки содержит лишь первые 12 знаков UDID, и этого мало: совпадения по префиксу
    хватит, чтобы подсунуть в сделку чужой аппарат. Поэтому решает то, что внутри отчёта.
    """
    серийник = str(серийник or "").strip().casefold()
    if not серийник:
        return False
    пас = (отчёт or {}).get("паспорт") or {}
    свои = [str(пас.get(k) or "").strip().casefold() for k in ("udid", "серийник")]
    return серийник in [x for x in свои if x]


def словами(когда: datetime, сейчас: datetime | None = None) -> str:
    """«сегодня в 14:05, 40 минут назад» — для плашки на экране и для карточки оценщика."""
    сейчас = сейчас or datetime.now()
    минут = max(0, int((сейчас - когда).total_seconds() // 60))
    если = "сегодня" if когда.date() == сейчас.date() else f"{когда:%d.%m}"
    сколько = (f"{минут} мин назад" if минут < 60 else
               f"{минут // 60} ч {минут % 60} мин назад" if минут < 60 * 24 else
               f"{минут // (60 * 24)} дн назад")
    return f"{если} в {когда:%H:%M}, {сколько}"


def найти(папка: str, серийник: str, часов: float = ЧАСОВ, сейчас: datetime | None = None):
    """Самая свежая проверка этого телефона за последние `часов`. → словарь или None.

    `часов <= 0` — поиск выключен (настройка `reuse_hours = 0`): всегда читаем заново.
    """
    import json

    серийник = str(серийник or "").strip()
    if not (папка and серийник) or not часов or часов <= 0:
        return None
    сейчас = сейчас or datetime.now()
    порог = сейчас - timedelta(hours=float(часов))
    # Папки названы «время_серийник», поэтому сортировка по имени — это сортировка по
    # времени, и свежая находится с первой же подходящей.
    образец = os.path.join(папка, f"*_{серийник[:12]}", ИМЯ_ОТЧЁТА)
    for файл in sorted(glob.glob(образец), reverse=True):
        путь = os.path.dirname(файл)
        try:
            когда = _когда(путь)
        except OSError:
            continue
        if когда < порог or когда > сейчас + timedelta(minutes=5):
            # «из будущего» бывает после перевода часов на машине: такой отчёт не берём,
            # иначе он навсегда останется «свежим»
            continue
        try:
            with open(файл, encoding="utf-8") as f:
                отчёт = json.load(f)
        except (OSError, ValueError):
            continue
        if not isinstance(отчёт, dict) or not тот_же(отчёт, серийник):
            continue
        return {"путь": путь, "отчёт": отчёт, "когда": когда,
                "возраст_мин": max(0, int((сейчас - когда).total_seconds() // 60)),
                "словами": словами(когда, сейчас)}
    return None


def отметить(отчёт: dict, находка: dict) -> dict:
    """Отчёт, взятый прошлым, обязан сам про это говорить.

    Отметка едет и в сделку (комментарий оценщика собирается из отчёта), и на экран кассы:
    по ней видно, что телефон в этот раз кабелем не перечитывали, и когда читали.
    """
    out = dict(отчёт or {})
    когда = находка.get("когда")
    out["повторная_проверка"] = {
        "когда": когда.isoformat(timespec="seconds") if isinstance(когда, datetime) else None,
        "возраст_мин": int(находка.get("возраст_мин") or 0),
        "словами": str(находка.get("словами") or ""),
        "папка": os.path.basename(str(находка.get("путь") or "")),
    }
    return out
