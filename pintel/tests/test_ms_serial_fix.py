# -*- coding: utf-8 -*-
"""Серийник правится в документах, и только когда это безопасно.

Владелец, 23.11.2026: «чтобы исправить серийник телефона, надо менять его в документе приёмки
или оприходования», и отдельно — «проданные трогай». Здесь проверяется порядок действий:
снять проведение, исправить, провести обратно, причём у проданного телефона порядок обратный —
иначе МойСклад не даст провести продажу серийника, которого нет на складе.
"""
import importlib.util
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ФАЙЛ = os.path.join(HERE, "..", "deploy", "оценка_бот", "ms_serial_fix.py")
спец = importlib.util.spec_from_file_location("ms_serial_fix", ФАЙЛ)
м = importlib.util.module_from_spec(спец)
спец.loader.exec_module(м)

ПЛОХОЙ, ХОРОШИЙ = "357763868124688", "357763867612758"


def приход(номер="4092", вещи=(ПЛОХОЙ,), проведён=True):
    return {"тип": "supply", "id": "d-1", "номер": номер, "проведён": проведён,
            "позиции": [{"id": "p-1", "вещи": list(вещи)}]}


def продажа(номер="55", вещи=(ПЛОХОЙ,), проведён=True):
    return {"тип": "demand", "id": "d-2", "номер": номер, "проведён": проведён,
            "позиции": [{"id": "p-2", "вещи": list(вещи)}]}


def test_a_phone_in_stock_is_fixed_in_its_supply():
    план = м.разобрать([приход()], ПЛОХОЙ, ХОРОШИЙ)
    assert план["можно"] and len(план["правки"]) == 1
    assert план["правки"][0]["номер"] == "4092"
    assert "4092" in м.словами(план, ХОРОШИЙ) and ХОРОШИЙ in м.словами(план, ХОРОШИЙ)


def test_a_sold_phone_is_unposted_sale_first_and_posted_supply_first():
    """У проданного порядок обратный: снимаем с продажи, возвращаем с прихода.

    Иначе МойСклад откажет — отгрузить серийник, которого нет на складе, нельзя."""
    план = м.разобрать([приход(), продажа()], ПЛОХОЙ, ХОРОШИЙ)
    assert план["можно"] and len(план["правки"]) == 2
    assert [п["тип"] for п in план["порядок_снятия"]] == ["demand", "supply"]
    assert [п["тип"] for п in план["порядок_проведения"]] == ["supply", "demand"]


def test_the_order_is_kept_when_applying():
    ходы = []
    план = м.разобрать([приход(), продажа()], ПЛОХОЙ, ХОРОШИЙ)
    итог = м.применить(
        план, ХОРОШИЙ,
        снять=lambda т, i: ходы.append(("снять", т)),
        записать=lambda т, i, поз, вещи: ходы.append(("записать", т, tuple(вещи))),
        провести=lambda т, i: ходы.append(("провести", т)))
    assert итог["беда"] == ""
    assert ходы == [("снять", "demand"), ("снять", "supply"),
                    ("записать", "supply", (ХОРОШИЙ,)), ("записать", "demand", (ХОРОШИЙ,)),
                    ("провести", "supply"), ("провести", "demand")]


def test_an_unposted_document_is_not_posted_by_us():
    """Документ лежал непроведённым — таким и остаётся: проводить за человека не наше дело."""
    ходы = []
    план = м.разобрать([приход(проведён=False)], ПЛОХОЙ, ХОРОШИЙ)
    м.применить(план, ХОРОШИЙ,
                снять=lambda т, i: ходы.append(("снять", т)),
                записать=lambda т, i, поз, вещи: ходы.append(("записать", т)),
                провести=lambda т, i: ходы.append(("провести", т)))
    assert ходы == [("записать", "supply")], "ни снятия, ни проведения у непроведённого"


def test_other_serials_in_the_same_position_are_kept():
    """В позиции несколько вещей — меняем только нашу, остальные остаются на месте."""
    ходы = []
    д = приход(вещи=(ПЛОХОЙ, "111111111111111"))
    план = м.разобрать([д], ПЛОХОЙ, ХОРОШИЙ)
    м.применить(план, ХОРОШИЙ, снять=lambda *a: None,
                записать=lambda т, i, поз, вещи: ходы.append(tuple(вещи)),
                провести=lambda *a: None)
    assert ходы == [(ХОРОШИЙ, "111111111111111")]


def test_nothing_is_touched_when_the_case_is_unclear():
    """Три случая, в которых не трогаем ничего и говорим словами."""
    нет_документов = м.разобрать([], ПЛОХОЙ, ХОРОШИЙ)
    assert not нет_документов["можно"] and "нет документа" in нет_документов["почему"]

    много = м.разобрать([приход(), продажа(), продажа(номер="56")], ПЛОХОЙ, ХОРОШИЙ)
    assert not много["можно"] and "больше двух" in много["почему"]

    чужой = м.разобрать([приход(вещи=("999999999999999",))], ПЛОХОЙ, ХОРОШИЙ)
    assert not чужой["можно"] and "нет ни в одном документе" in чужой["почему"]

    только_расход = м.разобрать([продажа()], ПЛОХОЙ, ХОРОШИЙ)
    assert not только_расход["можно"] and "только в расходном" in только_расход["почему"]

    без_имei = м.разобрать([приход()], ПЛОХОЙ, "")
    assert not без_имei["можно"] and "не знаем правильный" in без_имei["почему"]


def test_a_failure_midway_is_reported_with_what_was_done():
    """Сорвалось посередине — говорим, что успели: документы остались непроведёнными,
    и молчать об этом нельзя, иначе остаток разойдётся незаметно."""
    план = м.разобрать([приход(), продажа()], ПЛОХОЙ, ХОРОШИЙ)

    def провести(тип, i):
        raise RuntimeError("HTTP 412 период закрыт")

    итог = м.применить(план, ХОРОШИЙ, снять=lambda *a: None,
                       записать=lambda *a: None, провести=провести)
    assert "период закрыт" in итог["беда"]
    assert any("снято проведение" in с for с in итог["сделано"])
