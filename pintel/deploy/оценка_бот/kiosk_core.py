# -*- coding: utf-8 -*-
"""Приём сделки от приложения на точке: разбор посылки, проверки, колонки devices.

Чистая часть обработчика — без aiogram и без базы. Так её можно прогнать тестами
(tests/test_kiosk_deal_core.py в репозитории приложения), и в самом обработчике не
остаётся логики, которую нельзя проверить до установки на сервер.

Посылка приходит JSON-файлом в чат: приложение не может писать в базу Оценки (порт
Postgres закрыт наружу), поэтому единственный канал — сам бот. Из посылки берём только
колонки из КОЛОНКИ: что бы в ней ни пришло, в devices попадёт лишь разрешённое, и имя
колонки никогда не склеивается из чужого текста.
"""
import json
import re

ВЕРСИЯ = 1
КОД = re.compile(r"^[A-Z0-9]{4,12}$")
# та же строка, что кладёт в кнопку приложение (pintel_core/external/ocenka_tg.py):
# разойдутся — нажатие не дойдёт ни до одного обработчика
ПРЕФИКС_КНОПКИ = "kiosk_deal_"

# staffs в Оценке: 1 — Администратор, 2 — Продавец, 3 — Клиент
АДМИН, ПРОДАВЕЦ, КЛИЕНТ = 1, 2, 3
ОЦЕНЩИКИ = (АДМИН, ПРОДАВЕЦ)

# Словарь phone_status самой Оценки (handlers/ocenka/flow.py, status_map). Те же четыре
# значения кладёт приложение на точке (pintel_core/external/ocenka.py) — расходиться им
# нельзя: по ним решается автоцена и по ним админ читает карточку.
СТАТУС_ЧИСТЫЙ = "Не был в ремонте"
СТАТУС_РЕМОНТ = "Ранее был в ремонте"
СТАТУС_ДЕФЕКТ = "Присутствует дефект"
СТАТУС_НОВЫЙ = "Прочее"              # её кнопка «Запечатанный (новый)»
# status_id в Оценке: 1 — автооценка показана клиенту, 2 — ждёт оценки администратора
СТАТУС_АВТО, СТАТУС_АДМИН = 1, 2
SIM_ВАРИАНТЫ = ("Dual sim", "E-sim", "Прочее", "Стандарт")

# ровно те колонки devices, что заполняет бот Оценки при создании сделки
КОЛОНКИ = ("model", "code_name", "ddr", "akb", "akb_exact", "color", "sim", "box", "cord",
           "panic_full", "phone_status", "price_grade_auto", "comment", "comment_ocenka")
# что добавляет сам обработчик, а не посылка. Список обязан совпадать с тем, что кладёт
# `_вставить` в kiosk_media.py: иначе sql_devices отвечает «не наши колонки» на каждое
# нажатие «Создать сделку». Сверяется тестом test_kiosk_deal_core.py.
СВОИ = ("status_id", "user_client", "user_grade", "shop_id_grade", "photo_phone", "video_phone",
        "active_user")
ЦЕЛЫЕ = ("ddr", "akb_exact", "price_grade_auto")
ФЛАГИ = ("box", "cord", "panic_full")
# длины — из models.py Оценки: обрезаем сами, иначе вставка падает на длинном тексте
ПРЕДЕЛЫ = {"model": 50, "code_name": 50, "akb": 50, "color": 40, "sim": 20,
           "phone_status": 100, "comment": 500, "comment_ocenka": 4000}


class ОшибкаПосылки(ValueError):
    """Человеческий текст, почему сделку создать нельзя."""


def _целое(v):
    if v is None or isinstance(v, bool):
        return None
    if isinstance(v, (int, float)):
        return int(v)
    s = str(v).strip().replace(" ", "")
    return int(s) if re.fullmatch(r"-?\d+", s) else None


def разобрать(сырое) -> dict:
    """Байты или текст файла → посылка. Всё непонятное — сразу отказ со словами."""
    if isinstance(сырое, (bytes, bytearray)):
        сырое = bytes(сырое).decode("utf-8", "replace")
    if isinstance(сырое, str):
        try:
            сырое = json.loads(сырое)
        except Exception as exc:                                 # noqa: BLE001
            raise ОшибкаПосылки(f"файл не читается как JSON: {exc}") from None
    if not isinstance(сырое, dict):
        raise ОшибкаПосылки("в файле не объект JSON")
    if _целое(сырое.get("версия")) != ВЕРСИЯ:
        raise ОшибкаПосылки(
            f"посылка версии {сырое.get('версия')!r}, а обработчик понимает {ВЕРСИЯ}: "
            "обновите программу на точке или этот файл на сервере")
    if not КОД.match(str(сырое.get("код") or "")):
        raise ОшибкаПосылки("в посылке нет кода")
    if not isinstance(сырое.get("сделка"), dict):
        raise ОшибкаПосылки("в посылке нет полей сделки")
    return сырое


def точка_сотрудника(staff_id, shop_id):
    """Какая точка у сделки по тому, кто сдавал медиа.

    Продавец закреплён за магазином — его магазин и есть точка сделки, спрашивать нечего.
    Администратор работает на разных точках, поэтому выбирает сам после загрузки медиа;
    так же поступаем с продавцом без магазина — догадываться тут нельзя.
    """
    return shop_id if (staff_id == ПРОДАВЕЦ and shop_id) else None


def проверить(посылка: dict, медиа) -> list:
    """Чего не хватает, чтобы сделка открылась у оценщика. Пустой список — можно создавать."""
    нет = []
    сд = посылка.get("сделка") or {}
    кл = посылка.get("клиент") or {}
    if not (медиа or {}).get("video"):
        # карточку Оценка открывает через InputMediaVideo(video_phone) без проверки на пусто
        нет.append("видео телефона — без него Оценка не открывает карточку сделки")
    if not (медиа or {}).get("shop_id"):
        нет.append("точка: выберите её в боте")
    if not сд.get("model"):
        нет.append("модель")
    if not _целое(сд.get("ddr")):
        нет.append("объём памяти")
    if not (кл.get("имя") and кл.get("телефон")):
        нет.append("имя и телефон клиента")
    if not [x for x in (посылка.get("imei") or []) if x]:
        нет.append("IMEI")
    нет += чего_нет_в_диагностике(посылка, медиа)
    return нет


def чего_нет_в_диагностике(посылка: dict, медиа) -> list:
    """Чего не хватает в ручной диагностике. Пустой список — пройдена (или не требуется).

    Кабель не видит того, что видно руками: разбитый тачскрин, глухой динамик, мёртвую
    кнопку, следы воды в лотке. Поэтому последний шаг сделки — отметки сотрудника по
    пунктам, и без них сделки нет вовсе.

    Запечатанный аппарат — исключение: коробку не вскрывают, проверять нечего. Отметку
    «не вскрывали» сверяем с самой сделкой: стоит она на б/у аппарате — это не исключение,
    а пропуск диагностики, и такую сделку мы не создаём.
    """
    диаг = диагностика_разобрать((медиа or {}).get("checks"))
    запечатанная = (посылка.get("сделка") or {}).get("phone_status") == СТАТУС_НОВЫЙ
    if запечатан(диаг) and not запечатанная:
        return ["ручная диагностика отмечена «коробку не вскрывали», а сделка на б/у аппарат: "
                "пройдите диагностику в боте"]
    if запечатанная:
        return []
    осталось = не_отмечено(диаг)
    if not осталось:
        return []
    хвост = f" и ещё {len(осталось) - 4}" if len(осталось) > 4 else ""
    return ["ручная диагностика: не отмечено " + ", ".join(осталось[:4]) + хвост]


def колонки(посылка: dict) -> dict:
    """Поля сделки → колонки devices. Лишнее из посылки не проходит вовсе."""
    сд = посылка.get("сделка") or {}
    поля = {}
    for k in КОЛОНКИ:
        v = сд.get(k)
        if k in ЦЕЛЫЕ:
            v = _целое(v)
        elif k in ФЛАГИ:
            v = None if v is None else bool(v)
        elif isinstance(v, str):
            v = v.strip()[:ПРЕДЕЛЫ.get(k, 200)] or None
        elif v is not None:
            v = str(v)[:ПРЕДЕЛЫ.get(k, 200)]
        поля[k] = v
    if поля.get("sim") not in SIM_ВАРИАНТЫ:
        поля["sim"] = "Прочее"
    return поля


def статус_id(поля: dict, диагностика=None, неполно=()) -> int:
    """То же правило, что у бота Оценки: цену сразу показываем только чистому аппарату с
    автоценой, иначе сделка уходит администратору на ручную оценку.

    Добавлено к её правилу два условия, и оба про доверие к проверке:

    * **ручная диагностика нашла поломку** — автоцены нет. Кабель её не видит: он не нажмёт
      кнопку, не послушает динамик и не посмотрит на следы воды в лотке.
    * **проверка неполная** (`неполно` — список из посылки) — цену называет человек. Это
      ровно те случаи, которые экран киоска показывает как «ПРОВЕРКА НЕПОЛНАЯ»: батарея не
      прочиталась, чёрный список не спросили, реестр молчит, часть узлов не ответила. Раньше
      такая сделка получала автоцену, то есть клиенту называлась цена по проверке, которой
      не было.
    """
    чисто = поля.get("phone_status") == СТАТУС_ЧИСТЫЙ
    if not (чисто and поля.get("price_grade_auto")):
        return СТАТУС_АДМИН
    if list(неполно or []) or плохие(диагностика):
        return СТАТУС_АДМИН
    return СТАТУС_АВТО


def имейки(посылка: dict) -> list:
    """[(imei, первый?)] без повторов: первым идёт основной."""
    список = [str(x).strip()[:20] for x in (посылка.get("imei") or []) if str(x or "").strip()]
    return [(imei, n == 0) for n, imei in enumerate(dict.fromkeys(список))]


def sql_devices(поля: dict) -> str:
    """INSERT по именам колонок. Имена — только из белого списка, значения — через bind."""
    лишние = set(поля) - set(КОЛОНКИ) - set(СВОИ)
    if лишние:
        raise ОшибкаПосылки("не наши колонки: " + ", ".join(sorted(лишние)))
    имена = [k for k in list(КОЛОНКИ) + list(СВОИ) if k in поля]
    return ("INSERT INTO devices (producer, online, " + ", ".join(имена) + ") "
            "VALUES ('Apple', false, " + ", ".join(":" + k for k in имена) + ") RETURNING id")


# ---------------------------------------------------------------- шаги приёма медиа

# Порядок важен дважды: в Оценке фото показываются в том порядке, в каком легли (первым —
# экран с IMEI), и по числу уже принятых фото бот понимает, какой шаг сейчас. Шаг считается
# по базе, а не держится в памяти бота: перезапуск бота не должен ронять приём на всех
# точках разом — строка в kiosk_media переживает его.
ЭТАПЫ_ФОТО = (
    "фото экрана с набранным <b>*#06#</b> — чтобы IMEI был виден на самом телефоне",
    "фото <b>лицевой</b> стороны — телефон целиком в кадре",
    "фото <b>задней</b> стороны",
)
ЭТАП_ВИДЕО = "<b>видео</b> телефона — без него сделка в Оценке не открывается"

ЖДЁМ_ФОТО, ЖДЁМ_ВИДЕО = "фото", "видео"


def сколько_фото(строка) -> int:
    """Фото копятся в одной колонке через «||», как в самой Оценке."""
    return len([x for x in str((строка or {}).get("photos") or "").split("||") if x])


def чего_не_хватает(строка) -> list:
    """Что ещё прислать, по порядку. Пусто — медиа собраны."""
    чего = list(ЭТАПЫ_ФОТО[сколько_фото(строка):])
    if not (строка or {}).get("video"):
        чего.append(ЭТАП_ВИДЕО)
    return чего


def что_ждём(строка):
    """Что принимаем прямо сейчас: ЖДЁМ_ФОТО, ЖДЁМ_ВИДЕО или None — медиа собраны.

    Порядок строгий, и принимается только своё. С точки пришла жалоба: на шаге «фото
    задней стороны» прислали видео, бот ответил «Видео принято. Теперь фото задней
    стороны» — и сотрудник решил, что видео уже учтено, хотя шаг видео был ещё впереди.
    Когда медиа собраны (None), принимается и то и другое: можно доложить фото дефекта
    или переснять видео."""
    осталось = чего_не_хватает(строка)
    if not осталось:
        return None
    return ЖДЁМ_ВИДЕО if осталось[0] == ЭТАП_ВИДЕО else ЖДЁМ_ФОТО


def не_то_прислали(строка, что: str) -> str:
    """Прислали не то, что нужно на этом шаге. → что ответить сотруднику.

    Главное в ответе — чего ждём, а не что получили: человек на точке держит в руках
    телефон клиента, ему нужно действие, а не отчёт."""
    если_видео = что == ЖДЁМ_ВИДЕО
    пришло, ждали = (ЖДЁМ_ВИДЕО, ЖДЁМ_ФОТО) if если_видео else (ЖДЁМ_ФОТО, ЖДЁМ_ВИДЕО)
    хвост = ("Видео — последним шагом, после фото." if если_видео
             else "Дополнительные фото можно прислать после видео.")
    return (f"❌ Нужно {ждали}, а пришло {пришло} — не принял.\n\n"
            f"Сейчас: {чего_не_хватает(строка)[0]}\n{хвост}")


def шаги_списком() -> str:
    return "\n".join(f"{n}. {ш}" for n, ш in enumerate(ЭТАПЫ_ФОТО + (ЭТАП_ВИДЕО,), 1))


# ---------------------------------------------------------------- ручная диагностика

# Что проверяет сотрудник РУКАМИ, последним шагом сделки. Кабель и базы IMEI не умеют
# ничего из этого списка: они читают прошивку и привязку модулей, а не то, слышно ли
# динамик и жива ли кнопка. Поэтому список закрытый и одинаковый для всех точек — чтобы
# оценщик в карточке видел не «осмотрено», а по пунктам.
#
# Два последних пункта — не поломки, а то, что кабель НЕ может подтвердить и о чём отчёт
# прямо говорит «проверить на телефоне»: раздел «Детали и обслуживание» (подлинность
# деталей подтверждает только Apple, и только с экрана) и «VPN и управление устройством»
# (корпоративный надзор по кабелю определяется не на всех моделях).
#
# Ключи ASCII и короткие: они едут в callback_data кнопки (64 байта на всё) и в колонку
# checks. Надписи — русские, их читает сотрудник.
ПУНКТЫ = (
    ("screen", "Экран", "изображение без полос, пятен и битых точек"),
    ("touch", "Касание", "отзывается по всей площади экрана"),
    ("cams", "Камеры", "передняя, задние и вспышка снимают"),
    ("sound", "Звук", "оба динамика и микрофон"),
    ("keys", "Кнопки", "питание, громкость, бесшумный режим"),
    ("vibro", "Вибрация", "Taptic отзывается"),
    ("bio", "Face ID", "разблокировка лицом или отпечатком"),
    ("charge", "Зарядка", "заряжается от кабеля"),
    ("net", "Связь", "SIM видна, сеть и Wi-Fi работают"),
    ("water", "Влага", "в лотке SIM нет следов воды"),
    ("apple", "Детали Apple", "Об этом устройстве → Детали и обслуживание: неизвестных деталей нет"),
    ("mdm", "Управление", "VPN и управление устройством: чужих профилей нет"),
)
КЛЮЧИ = tuple(k for k, _, _ in ПУНКТЫ)
КОРОТКО = {k: s for k, s, _ in ПУНКТЫ}
ПОДРОБНО = {k: d for k, _, d in ПУНКТЫ}
# Ключ тоже ASCII, и по той же причине: он едет в callback_data кнопки рядом с ключами
# пунктов, а кириллица в ней съедает по два байта на букву.
ЗАПЕЧАТАН = "sealed"                       # коробку не вскрывали — проверять нечего
# Пункт, провал которого значит не «видимый дефект», а «был в ремонте»: неизвестную деталь
# на экране телефона показывает сама Apple.
РЕМОНТНЫЕ_ПУНКТЫ = ("apple",)


def диагностика_разобрать(сырое) -> dict:
    """Колонка `checks` → отметки. Всё лишнее и непонятное отбрасываем молча: это наши же
    данные, но полежавшие в базе между версиями обработчика."""
    if isinstance(сырое, (bytes, bytearray)):
        сырое = bytes(сырое).decode("utf-8", "replace")
    if isinstance(сырое, str):
        try:
            сырое = json.loads(сырое or "{}")
        except Exception:                                        # noqa: BLE001
            return {}
    if not isinstance(сырое, dict):
        return {}
    из = {}
    for k, v in сырое.items():
        if k == ЗАПЕЧАТАН and v:
            из[ЗАПЕЧАТАН] = True
        elif k in КЛЮЧИ and isinstance(v, bool):
            из[k] = v
    return из


def диагностика_сохранить(отметки: dict) -> str:
    return json.dumps(диагностика_разобрать(отметки), ensure_ascii=False, sort_keys=True)


def диагностика_переключить(отметки: dict, ключ: str) -> dict:
    """Нажатие на пункт: не отмечено → работает → не работает → не отмечено.

    Третьего состояния «не проверял» нет намеренно: оно стало бы способом пропустить шаг.
    Нечем проверить (нет SIM, телефон не включается) — это «не работает», и сделка уходит
    на ручную оценку. Ошибка в эту сторону стоит оценки человеком, обратная — денег.
    """
    d = dict(диагностика_разобрать(отметки))
    if ключ == ЗАПЕЧАТАН:
        if d.get(ЗАПЕЧАТАН):
            return {}
        return {ЗАПЕЧАТАН: True}
    if ключ not in КЛЮЧИ:
        return d
    d.pop(ЗАПЕЧАТАН, None)                 # отмечают по пунктам — значит коробка вскрыта
    текущее = d.get(ключ)
    if текущее is None:
        d[ключ] = True
    elif текущее is True:
        d[ключ] = False
    else:
        d.pop(ключ, None)
    return d


def запечатан(отметки: dict) -> bool:
    return bool(диагностика_разобрать(отметки).get(ЗАПЕЧАТАН))


def не_отмечено(отметки: dict) -> list:
    """Пункты, по которым ответа ещё нет, — короткими надписями, в порядке списка."""
    d = диагностика_разобрать(отметки)
    if d.get(ЗАПЕЧАТАН):
        return []
    return [КОРОТКО[k] for k in КЛЮЧИ if not isinstance(d.get(k), bool)]


def плохие(отметки: dict) -> list:
    """Пункты, отмеченные «не работает» → [(ключ, надпись)]."""
    d = диагностика_разобрать(отметки)
    return [(k, КОРОТКО[k]) for k in КЛЮЧИ if d.get(k) is False]


def диагностика_готова(отметки: dict) -> bool:
    d = диагностика_разобрать(отметки)
    return bool(d.get(ЗАПЕЧАТАН)) or not не_отмечено(d)


def диагностика_словами(отметки: dict) -> str:
    """Отметки → одна строка для комментария оценщика. Пусто — диагностики не было."""
    d = диагностика_разобрать(отметки)
    if d.get(ЗАПЕЧАТАН):
        return "Ручная диагностика: коробку не вскрывали"
    плох = [имя for _, имя in плохие(d)]
    нет = не_отмечено(d)
    если_всё = len([k for k in КЛЮЧИ if isinstance(d.get(k), bool)])
    if not если_всё:
        return ""
    куски = [f"Ручная диагностика ({если_всё} из {len(КЛЮЧИ)})"]
    куски.append("НЕ РАБОТАЕТ: " + ", ".join(плох) if плох else "всё работает")
    if нет:
        куски.append("не отмечено: " + ", ".join(нет))
    return " · ".join(куски)


def применить_диагностику(поля: dict, отметки: dict, неполно=()) -> dict:
    """Отметки сотрудника и неполнота проверки → поля сделки.

    Найденная руками поломка обязана снимать автоцену: иначе ручная диагностика остаётся
    отчётом ни о чём. «Детали Apple» переводят аппарат в «Ранее был в ремонте» — неизвестную
    деталь показывает сама Apple; остальные пункты — в «Присутствует дефект». Состояние,
    которое и так не чистое, не переписываем: ремонт по журналу Apple — факт твёрже.
    """
    out = dict(поля)
    плох = плохие(отметки)
    if плох and out.get("phone_status") == СТАТУС_ЧИСТЫЙ:
        прочее = [k for k, _ in плох if k not in РЕМОНТНЫЕ_ПУНКТЫ]
        out["phone_status"] = СТАТУС_ДЕФЕКТ if прочее else СТАТУС_РЕМОНТ
    хвосты = [диагностика_словами(отметки)]
    if list(неполно or []):
        хвосты.append("ПРОВЕРКА НЕПОЛНАЯ: " + "; ".join(str(x) for x in неполно)[:600])
    хвост = " · ".join(x for x in хвосты if x)
    if хвост:
        было = str(out.get("comment_ocenka") or "").strip()
        out["comment_ocenka"] = ((было + " · " if было else "") + хвост)[:ПРЕДЕЛЫ["comment_ocenka"]]
    return out


def неполнота(посылка: dict) -> list:
    """Что в проверке осталось непрочитанным — из посылки, строками для оценщика.

    Сверку деталей на телефоне сюда НЕ кладём: её закрывает пункт «Детали Apple» ручной
    диагностики, то есть человек с телефоном в руках. Здесь только то, что закрыть нечем.
    """
    return [str(x)[:200] for x in (посылка.get("не_прочиталось") or []) if str(x or "").strip()][:6]
