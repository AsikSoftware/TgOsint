# -*- coding: utf-8 -*-
"""Повторы запросов к МойСкладу: что повторяем, а что нет.

Модуль лежит в `deploy/оценка_бот/ms_http.py` и ставится в `utils/` бота. Проверять его «на
тесте» нельзя по двум причинам: МойСклад у нас один на тест и боевое, и отказ 503 по заказу
не вызовешь. Поэтому здесь подменный МойСклад, который отказывает по сценарию.

Главное, что проверяем, — повтор НЕ создаёт двойников. За это отвечает одно правило:
ответа не было → повторяем только GET и PUT; сервер ответил 5xx → повторяем любой запрос,
потому что ответивший сервер запрос не выполнил.
"""
import importlib.util
import os

import pytest

HERE = os.path.dirname(os.path.abspath(__file__))
ФАЙЛ = os.path.join(HERE, "..", "deploy", "оценка_бот", "ms_http.py")


@pytest.fixture(scope="module")
def м():
    спец = importlib.util.spec_from_file_location("ms_http", ФАЙЛ)
    m = importlib.util.module_from_spec(спец)
    спец.loader.exec_module(m)
    return m


class Обрыв(Exception):
    """Сюда подставляется requests.exceptions.RequestException бота."""


class Ответ:
    def __init__(self, код, тело=None, headers=None, текст=""):
        self.status_code, self._тело = код, тело if тело is not None else {}
        self.headers, self.text = headers or {}, текст

    def json(self):
        if isinstance(self._тело, Exception):
            raise self._тело
        return self._тело


def склад(сценарий):
    """Подменный МойСклад: отдаёт ответы по списку. Исключение в списке — обрыв связи.

    → (отправить, попытки, сны, жду). `попытки` растёт на каждой отправке, `сны` — что ждали.
    """
    попытки, сны, пауза_до = [], [], []

    def отправить():
        попытки.append(len(попытки) + 1)
        шаг = сценарий[min(len(попытки) - 1, len(сценарий) - 1)]
        if isinstance(шаг, Exception):
            raise шаг
        return шаг

    def спать(сек):
        сны.append(сек)

    def перед():
        пауза_до.append(len(попытки))

    return отправить, попытки, сны, пауза_до, спать, перед


def позвать(м, сценарий, метод="GET", адрес="/entity/product"):
    отправить, попытки, сны, пауза_до, спать, перед = склад(сценарий)
    итог = м.запросить(отправить, метод, адрес, обрыв=Обрыв, перед=перед, спать=спать)
    return итог, попытки, сны, пауза_до


def test_503_повторяется_и_запрос_доходит(м):
    """Ровно та беда, что случилась 18.11.2026 в 12:27: справочник отдал 503.

    Прежний код на этом сдавался, и карточка товара уезжала без «Статуса». Теперь — повтор."""
    итог, попытки, сны, _ = позвать(м, [Ответ(503), Ответ(200, {"rows": [{"name": "Плата"}]})])
    assert итог == {"rows": [{"name": "Плата"}]}
    assert len(попытки) == 2, "после 503 запрос должен уйти второй раз"
    assert len(сны) == 1 and 0 < сны[0] < 2, "пауза между попытками короткая"


def test_повторы_не_бесконечны_и_отказ_виден_прежним_текстом(м):
    """Сервер лежит — поднимаем наружу, и текст прежний: его читает человек."""
    with pytest.raises(RuntimeError) as беда:
        позвать(м, [Ответ(503, {"errors": [{"error": "Service Unavailable"}]})])
    текст = str(беда.value)
    assert текст.startswith("HTTP 503 GET /entity/product"), текст
    assert "Service Unavailable" in текст, "тело отказа должно остаться в тексте"
    assert not isinstance(беда.value, м.СвязьНеВышла), "сервер ответил — это не обрыв связи"


def test_число_попыток_при_отказе_сервера(м):
    отправить, попытки, сны, _, спать, перед = склад([Ответ(502)])
    with pytest.raises(RuntimeError):
        м.запросить(отправить, "GET", "/x", обрыв=Обрыв, перед=перед, спать=спать)
    assert len(попытки) == м.ОТКАЗ_ПОПЫТОК
    assert len(сны) == м.ОТКАЗ_ПОПЫТОК - 1, "паузы между попытками, а не после последней"
    assert сны == sorted(сны), "пауза удваивается, а не стоит на месте"


def test_запись_повторяется_когда_сервер_ответил_отказом(м):
    """POST при 5xx повторяем: ответивший сервер запрос не выполнил, двойника не будет."""
    итог, попытки, _, _ = позвать(м, [Ответ(503), Ответ(503), Ответ(200, {"id": "7"})],
                                  метод="POST", адрес="/entity/supply")
    assert итог == {"id": "7"}
    assert len(попытки) == 3


def test_запись_после_обрыва_связи_не_повторяется(м):
    """Ответа не было — неизвестно, создался ли документ. Повтор завёл бы вторую приёмку."""
    отправить, попытки, сны, _, спать, перед = склад([Обрыв("соединение разорвано")])
    with pytest.raises(м.СвязьНеВышла) as беда:
        м.запросить(отправить, "POST", "/entity/supply", обрыв=Обрыв, перед=перед, спать=спать)
    assert len(попытки) == 1, "POST после обрыва уходить второй раз не должен"
    assert not сны
    текст = str(беда.value)
    assert "повторять нельзя" in текст and "прошёл ли он" in текст, текст


def test_чтение_после_обрыва_связи_повторяется(м):
    """GET повторить безопасно: тот же запрос даёт тот же итог."""
    итог, попытки, сны, _ = позвать(м, [Обрыв("таймаут"), Обрыв("таймаут"), Ответ(200, {"ok": 1})])
    assert итог == {"ok": 1}
    assert len(попытки) == 3 and len(сны) == 2


def test_обрыв_связи_на_чтении_тоже_не_вечен(м):
    отправить, попытки, _, _, спать, перед = склад([Обрыв("таймаут")])
    with pytest.raises(м.СвязьНеВышла) as беда:
        м.запросить(отправить, "GET", "/entity/product", обрыв=Обрыв, перед=перед, спать=спать)
    assert len(попытки) == м.ОТКАЗ_ПОПЫТОК
    assert "не вышла за" in str(беда.value)


def test_put_после_обрыва_повторяется(м):
    """PUT — тоже безопасный: кладём то же тело в тот же товар."""
    итог, попытки, _, _ = позвать(м, [Обрыв("сброс"), Ответ(200, {"id": "1"})],
                                  метод="PUT", адрес="/entity/product/1")
    assert итог == {"id": "1"} and len(попытки) == 2


def test_429_слушает_retry_after(м):
    """Лимит запросов — просьба подождать, и сервер говорит, сколько."""
    итог, попытки, сны, _ = позвать(м, [Ответ(429, headers={"Retry-After": "3"}), Ответ(200, {"ok": 2})])
    assert итог == {"ok": 2} and len(попытки) == 2
    assert 3.0 <= сны[0] < 3.3, f"ждали {сны[0]}, а сервер просил 3 с"


def test_429_без_retry_after_считает_паузу_сам(м):
    итог, _, сны, _ = позвать(м, [Ответ(429), Ответ(429, headers={"Retry-After": "мусор"}),
                                  Ответ(200, {"ok": 3})])
    assert итог == {"ok": 3}
    assert len(сны) == 2 and all(с > 0 for с in сны), сны


def test_429_и_5xx_считаются_отдельно(м):
    """Лимит и отказ сервера не должны съедать попытки друг у друга."""
    сценарий = [Ответ(429), Ответ(503), Ответ(429), Ответ(503), Ответ(200, {"ok": 4})]
    итог, попытки, _, _ = позвать(м, сценарий)
    assert итог == {"ok": 4} and len(попытки) == 5


def test_ошибку_в_запросе_не_повторяем(м):
    """404 и 412 — наша вина, повтор ничего не изменит, только задержит сотрудника."""
    for код in (400, 401, 403, 404, 412):
        отправить, попытки, сны, _, спать, перед = склад([Ответ(код, {"errors": [{"code": 1034}]})])
        with pytest.raises(RuntimeError) as беда:
            м.запросить(отправить, "GET", "/entity/product", обрыв=Обрыв, перед=перед, спать=спать)
        assert len(попытки) == 1, f"{код} не повторяем"
        assert not сны
        assert f"HTTP {код}" in str(беда.value)


def test_204_отдаёт_ничего(м):
    итог, попытки, _, _ = позвать(м, [Ответ(204)], метод="DELETE", адрес="/entity/product/1")
    assert итог is None and len(попытки) == 1


def test_не_json_в_отказе_не_роняет_разбор(м):
    """МойСклад под нагрузкой отдаёт HTML от балансировщика — текст должен уцелеть."""
    отказ = Ответ(503, ValueError("not json"), текст="<html>502 Bad Gateway</html>")
    отправить, _, _, _, спать, перед = склад([отказ])
    with pytest.raises(RuntimeError) as беда:
        м.запросить(отправить, "GET", "/x", обрыв=Обрыв, перед=перед, спать=спать)
    assert "Bad Gateway" in str(беда.value)


def test_пауза_между_запросами_перед_каждой_попыткой(м):
    """`перед` — это троттлинг бота: без него повторы сами упрутся в лимит 429."""
    _, попытки, _, пауза_до = позвать(м, [Ответ(503), Ответ(503), Ответ(200, {})])
    assert len(пауза_до) == len(попытки) == 3


def test_успех_с_первого_раза_не_ждёт_и_не_повторяет(м):
    итог, попытки, сны, _ = позвать(м, [Ответ(200, {"rows": []})])
    assert итог == {"rows": []} and len(попытки) == 1 and not сны
