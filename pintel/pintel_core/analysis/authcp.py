# -*- coding: utf-8 -*-
"""Проверка подлинности Apple — по кабелю, без экрана телефона.

Зачем. До 24.11.2026 вердикт Apple о деталях мы брали ТОЛЬКО из журнала телефона, а его
телефон печатает лишь тогда, когда человек зайдёт в Настройки → Основные → Об этом
устройстве. Не зашёл — шаг «история Apple» висел без конца. 24.11.2026 так встал iPhone 14
(iOS 16.5.1) на кабеле: журнал по теме телефон написал, вердикта в нём не было, и касса
ждала вечно.

Причина оказалась не в телефоне. Тот же вердикт телефон держит в своём IORegistry и
оттуда же его и читает — его демон пишет об этом прямым текстом:

    mobilerepaird[215]: [Battery][[-[MRBaseComponentHandler checkInAndHandleAuthStatus]]
                         IOREG Auth Component Trusted]

(эталоны iPhone 11 на iOS 26.6.2 и iPhone 17 Pro на iOS 27.2; те же строки есть по
TouchController, NFC, Wifi, Baseband). По кабелю этот узел читается за 0,04 с и отдаёт ровно
те поля, что телефон печатает словарём «AuthCP Components»:

    AuthPassed, AuthFullPass, isTrusted, isTrustedForUI, authError/authErrorDescription,
    FdrValidationStatus, InternalComponent

Чей это сопроцессор. Запрос по имени отдаёт ПЕРВЫЙ подходящий узел, а узлов бывает
несколько: у аккумулятора (AppleSmartBattery/AppleBatteryAuth), у дисплея и платы на новых
моделях (mogul-display, mogul-mlb), у шины аксессуаров (roswell, Port-Lightning). Во всех
43 картах узлов, снятых с живых аппаратов (11 поколений, iOS 17–27), первым в обходе стоит
узел АККУМУЛЯТОРА — поэтому чтение по имени `AppleAuthCPRelay` это проверка аккумулятора.
Чтобы случайный узел аксессуара не выдали за аккумулятор, узлы с полями `Accessory…` и
`IOAccessoryIDBusTransportInternalAuth` (разъём, шина AID) мы в вердикт по аккумулятору не
берём вовсе.

Что этот канал НЕ делает. Он не отвечает за экран, камеры и Face ID: их сопроцессоры по
кабелю так не достать (у iPhone 13–15 их нет вовсе, у 16 и новее они стоят в обходе после
аккумулятора). Поэтому «Apple подтвердила весь аппарат» по одному этому чтению не выдаётся:
подтверждение по аккумулятору — да, зелёный на всё — нет.
"""

# Узел сопроцессора аккумулятора: имя одно на всех моделях.
УЗЕЛ = "AppleAuthCPRelay"
# Узлы шины аксессуаров — внутренний модуль разъёма и док. Их читаем, кладём в слепок и
# показываем сотруднику, но за деталь, которую мы оцениваем, не выдаём: живого аппарата с
# НЕподтверждённым разъёмом у нас ещё не было, а вердикт без эталона мы не ставим.
УЗЛЫ_АКСЕССУАРОВ = ("AppleAuthCPAID", "AppleAuthCPDock")
# Поля, которые кладём в отчёт и в эталон: по ним разбираемся, когда вердикт разойдётся
# с экраном телефона.
ПОЛЯ = ("AuthPassed", "AuthFullPass", "isTrusted", "isTrustedForUI", "authError",
        "authErrorDescription", "FdrValidationStatus", "InternalComponent")


def _да(v):
    """Телефон отдаёт флаг то булевым, то числом, то строкой. → True/False/None."""
    if v is None:
        return None
    if isinstance(v, bool):
        return v
    if isinstance(v, (int, float)):
        return bool(v)
    s = str(v).strip().lower()
    if s in ("1", "true", "yes", "pass"):
        return True
    if s in ("0", "false", "no", "fail"):
        return False
    return None


def аксессуар(узел) -> bool:
    """Это сопроцессор аксессуара (разъём, док, кабель), а не внутренней детали?"""
    if not isinstance(узел, dict):
        return False
    return (any(str(k).startswith("Accessory") for k in узел)
            or _да(узел.get("IOAccessoryIDBusTransportInternalAuth")) is True
            or _да(узел.get("IsInductiveTransport")) is True)


def прочитать(узел) -> dict:
    """Один узел AuthCP → {доверена, почему, поля}. Непонятный узел → доверена None.

    доверена True  — Apple признала деталь подлинной (подпись сошлась);
             False — не признала: это замена или неоригинал;
             None  — узел не отдался или сказал не всё, вердикта нет.
    """
    пусто = {"доверена": None, "почему": "", "поля": {}}
    if not isinstance(узел, dict) or not узел:
        return {**пусто, "почему": "телефон не отдал узел проверки подлинности"}
    поля = {k: узел[k] for k in ПОЛЯ if k in узел}
    доверие = _да(узел.get("isTrusted"))
    подпись = _да(узел.get("AuthPassed"))
    ошибка = узел.get("authError")
    словами = str(узел.get("authErrorDescription") or "").strip()
    # Узел без обоих главных полей — это не отказ, а «не прочиталось»: вердикта не ставим.
    if доверие is None and подпись is None:
        return {**пусто, "поля": поля, "почему": "в узле нет ни isTrusted, ни AuthPassed"}
    плохо = (доверие is False) or (подпись is False)
    try:
        плохо = плохо or (ошибка is not None and int(ошибка) != 0)
    except (TypeError, ValueError):
        pass
    if плохо:
        причина = словами if словами and словами.lower() != "authsuccess" else "подпись Apple не сошлась"
        return {"доверена": False, "почему": причина, "поля": поля}
    # Полным проходом Apple считает AuthFullPass; его отсутствие вердикт не отменяет —
    # на живых аппаратах он всегда шёл рядом с AuthPassed.
    return {"доверена": True, "почему": словами or "подпись Apple сошлась", "поля": поля}


def разобрать(nodes) -> dict:
    """Узлы слепка → {"аккумулятор": {...}, "аксессуары": [...], "прочитано": n}.

    Ничего не спрашивает у телефона: работает по уже снятому слепку, поэтому тот же вердикт
    получается и при пересчёте отчёта из архива.
    """
    nodes = nodes or {}
    итог = {"аккумулятор": {"доверена": None, "почему": "", "поля": {}}, "аксессуары": [], "прочитано": 0}
    узел = nodes.get(УЗЕЛ)
    if аксессуар(узел):
        # Первым подвернулся узел аксессуара — за аккумулятор его не выдаём.
        итог["аккумулятор"] = {"доверена": None, "поля": {},
                               "почему": "первым ответил сопроцессор аксессуара, а не аккумулятора"}
    else:
        итог["аккумулятор"] = прочитать(узел)
        if итог["аккумулятор"]["доверена"] is not None:
            итог["прочитано"] += 1
    for имя in УЗЛЫ_АКСЕССУАРОВ:
        у = nodes.get(имя)
        if not isinstance(у, dict) or not у:
            continue
        чтение = прочитать(у)
        if чтение["доверена"] is None:
            continue
        итог["аксессуары"].append({"узел": имя, **чтение})
    return итог


def словами(итог) -> str:
    """Короткая строка для экрана кассы и журнала точки. Коротко — потому что на экране она
    стоит рядом с подписью шага, а длинная подпись там обрезается."""
    бат = (итог or {}).get("аккумулятор") or {}
    if бат.get("доверена") is True:
        return "аккумулятор подтвердила Apple"
    if бат.get("доверена") is False:
        return "аккумулятор Apple не признала: " + (бат.get("почему") or "подпись не сошлась")
    return ""
