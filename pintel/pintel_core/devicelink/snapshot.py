_УБОРКА = set()            # ссылки на задачи уборки: без них в журнал летит «Task was destroyed»


def _прибрать_потом(корутина) -> None:
    """Закрыть то, чего уже никто не ждёт, и не оставить за собой висящую задачу."""
    задача = asyncio.ensure_future(корутина)
    _УБОРКА.add(задача)
    задача.add_done_callback(_УБОРКА.discard)


def _закрыть_когда_откроется(задача) -> None:
    """Соединение, которое открылось, когда его уже не ждали, — закрыть."""
    if задача.cancelled() or задача.exception() is not None:
        return
    _прибрать_потом(_закрыть_соединение(задача.result()))


async def _открыть_сбоку(соединить, ждать=ЖДАТЬ_СОЕДИНЕНИЕ, копилка=None):
    """Ещё одно соединение с тем же телефоном, не дольше `ждать`. → (соединение, почему нет).

    Открытие НЕ отменяем: отмена оставляет за собой открытый сокет usbmux — в
    pymobiledevice3 уборка стоит под `except Exception`, а отмена ею не является. Не успело —
    пусть откроется само и само закроется (`_закрыть_когда_откроется`)."""
    задача = asyncio.ensure_future(соединить())
    готово, _ = await asyncio.wait({задача}, timeout=ждать)
    if not готово:
        задача.add_done_callback(_закрыть_когда_откроется)
        return None, f"соединение не открылось за {ждать:g} с"
    if задача.cancelled():
        return None, "открытие соединения отменено"
    беда = задача.exception()
    if беда is not None:
        return None, f"{type(беда).__name__}: {str(беда)[:120]}"
    соединение = задача.result()
    if копилка is not None:
        копилка.add(соединение)
    return соединение, ""


async def _закрыть_соединение(соединение) -> None:
    if соединение is None:
        return
    try:
        итог = соединение.close()
        if asyncio.iscoroutine(итог):
            await asyncio.wait_for(итог, 3)
    except Exception:                                             # noqa: BLE001
        pass


async def _снять_задачу(задача) -> None:
    """Отменить вопрос и ДОЖДАТЬСЯ его. Без ожидания задача остаётся висеть, а её исключение
    никто не забирает — в журнал кассы летит «exception was never retrieved»."""
    if задача.done():
        if not задача.cancelled():
            задача.exception()                   # забрать, чтобы не ругался сборщик мусора
        return
    задача.cancel()
    try:
        await задача
    except BaseException:                                         # noqa: BLE001
        pass


class СборДоменов:
    """Собирает ВСЕ домены телефона и ничего не теряет, но и не держит проверку.

    Как это было: домены читались по очереди, на том же соединении, которым читается весь
    слепок, и без предела ожидания. Один вопрос, который телефон обдумывал 195 секунд, вешал
    всю проверку — сотрудник выдёргивал кабель, и аппарат оставался непрочитанным вовсе.

    Как теперь: вопросы задаются на отдельных («боковых») соединениях lockdown, по
    `ПОТОКОВ_ДОМЕНОВ` сразу, и у каждого вопроса есть предел. Не ответил за `ЖДАТЬ_ДОМЕН` —
    вопрос не бросается: он остаётся обдумываться на своём соединении (`ПАРКОВОК` таких мест),
    а остальные домены спрашиваются дальше на новом соединении. Ответ пришёл позже — он
    попадает в слепок при следующем `собрать`; а `собрать` касса зовёт и в конце проверки, и
    после того, как отчёт уже показан: телефон всё это время на кабеле.

    Почему своё соединение на вопрос, а не отмена: брошенный ответ, который придёт позже,
    был бы прочитан как ответ на СЛЕДУЮЩИЙ вопрос по тому же соединению — в слепок попали бы
    чужие данные. Это хуже, чем ждать.

    Что не вышло вовсе (ошибка связи, телефон отказал) — спрашивается заново,
    `ПОПЫТОК_ДОМЕНА` раз. И только если и это не помогло, в слепке остаётся запись, почему.
    """

    def __init__(self, соединить, *, жив=None, log=None):
        self._соединить = соединить
        self._жив = жив
        self._log = log or (lambda *a: None)
        self.ответы = {}                 # домен → ответ (бывает пустой: «такого на этой iOS нет»)
        self.ошибки = {}                 # домен → почему в последний раз не вышло
        self.сдались = set()             # домены, которые больше не спрашиваем
        self.время = {}                  # домен → за сколько пришёл ответ, с
        self._очередь = collections.deque()
        self._все = []
        self._попытки = {}
        self._парк = {}                  # домен → (задача, соединение, начато)
        self._рабочие = []
        self._соединения = set()         # все открытые нами — чтобы закрыть любой ценой
        self._беда_соединения = ""
        self._начато = None
        self._отмечено = set()
        self._жалобы = set()             # что мы записали в «не прочиталось»
        self._закрыто = False

    # ---------------------------------------------------------------- наружу

    def начать(self, домены) -> None:
        """Поставить все вопросы в очередь и начать спрашивать. Нужные Оценке — первыми."""
        if self._все:
            return                                   # уже начали
        self._начато = time.monotonic()
        порядок = ([d for d in домены if d in ЧИТАЕМЫЕ_ДОМЕНЫ]
                   + [d for d in домены if d not in ЧИТАЕМЫЕ_ДОМЕНЫ])
        self._все = list(dict.fromkeys(порядок))
        self._очередь.extend(self._все)
        self._поднять()

    def осталось(self) -> list:
        """Домены, по которым ответа ещё нет, а мы ещё не сдались."""
        return [d for d in self._все if d not in self.ответы and d not in self.сдались]

    def без_соединений(self) -> bool:
        """Второго соединения телефон не дал ни разу — спрашивать нечем."""
        return bool(self._беда_соединения) and not self.ответы and not self._соединения

    def забыть(self) -> None:
        """Домены собраны другим путём: эта очередь больше не нужна."""
        self._все, self._отмечено = [], set()
        self._очередь.clear()

    def __len__(self):
        return len(self.осталось())

    def собранное(self) -> dict:
        """Непустые ответы — как раздел `domains` слепка."""
        return {d: v for d, v in self.ответы.items() if v}

    async def собрать(self, snap=None, ждать: float = 0.0) -> list:
        """Забрать всё, что телефон успел ответить, и доспросить остальное.

        `ждать` — сколько секунд готовы ждать остаток (0 — только то, что уже пришло).
        Зовётся сколько угодно раз. → какие домены пришли за этот раз."""
        до = time.monotonic() + max(0.0, float(ждать))
        пришли = []
        while True:
            пришли += await self._подобрать()
            if snap is not None:
                self._вложить(snap)
            if not self.осталось() or not self._идём():
                break
            остаток = до - time.monotonic()
            if остаток <= 0:
                break
            self._поднять()                          # есть что доспросить, а рабочих нет
            await self._подождать(min(0.5, остаток))
        if snap is not None:
            self._вложить(snap)
        return пришли

    def итог(self, snap: dict) -> None:
        """Последнее слово о том, чего телефон так и не сказал.

        Решающее для сделки (`РЕШАЮЩИЕ_ДОМЕНЫ`) — в «не прочиталось»: проверка неполная,
        автоцены нет, сомнение не бывает зелёным. Остальное — отметкой в слепке: о самом
        телефоне оно ничего не говорит, и держать из-за него сделку не за что. Зовётся
        сколько угодно раз: поздний ответ снимает прежнюю жалобу."""
        кач = snap.setdefault("quality", {})
        не_прочиталось = кач.setdefault("не_прочиталось", {})
        for ключ in self._жалобы:
            не_прочиталось.pop(ключ, None)
        self._жалобы.clear()
        без_ответа = {}
        for dom in self._все:
            if dom in self.ответы:
                continue
            сек = round(time.monotonic() - (self._начато or time.monotonic()))
            почему = self.ошибки.get(dom) or f"{НЕ_ОТВЕТИЛ} {сек} с"
            без_ответа[dom] = почему
            if dom in РЕШАЮЩИЕ_ДОМЕНЫ:
                не_прочиталось[dom] = почему
                self._жалобы.add(dom)
        if без_ответа:
            кач["домены_без_ответа"] = без_ответа
        else:
            кач.pop("домены_без_ответа", None)
        if not не_прочиталось:
            кач.pop("не_прочиталось", None)

    async def закрыть(self) -> None:
        """Больше не ждём: снимаем вопросы и закрываем все свои соединения."""
        self._закрыто = True
        задачи = list(self._рабочие) + [з for з, _с, _н in self._парк.values()]
        for задача in задачи:
            if not задача.done():
                задача.cancel()
        for задача in задачи:                    # дождаться ДО закрытия соединений
            try:
                await задача
            except BaseException:                                 # noqa: BLE001
                pass
        self._рабочие, self._парк = [], {}
        for соединение in list(self._соединения):
            await self._закрыть(соединение)
        self._соединения.clear()
        self._очередь.clear()

    # ---------------------------------------------------------------- внутри

    def _идём(self) -> bool:
        if self._закрыто:
            return False
        return self._жив is None or bool(self._жив())

    def _поднять(self) -> None:
        """Поднять рабочих под то, что лежит в очереди (не больше `ПОТОКОВ_ДОМЕНОВ`)."""
        if not self._идём():
            return
        self._рабочие = [з for з in self._рабочие if not з.done()]
        надо = min(ПОТОКОВ_ДОМЕНОВ, len(self._очередь)) - len(self._рабочие)
        for _ in range(max(0, надо)):
            self._рабочие.append(asyncio.ensure_future(self._рабочий()))

    async def _рабочий(self) -> None:
        """Берёт вопросы из очереди, пока они есть. Из него наружу ничего не вылетает:
        исключение в этой задаче никто не ждёт, и в журнале кассы оно выглядело бы крашем."""
        try:
            await self._работа()
        except asyncio.CancelledError:
            raise
        except Exception as e:                                    # noqa: BLE001
            self._log(f"сбор доменов: рабочий остановился ({type(e).__name__}: {str(e)[:120]})")

    async def _работа(self) -> None:
        соединение, подряд = None, 0
        try:
            while self._идём() and self._очередь:
                if соединение is None:
                    соединение, почему = await self._открыть()
                    if соединение is None:
                        подряд += 1
                        self._беда_соединения = почему
                        if подряд >= 3:
                            return                   # сдаётся этот рабочий, остальные живы
                        await asyncio.sleep(1.0)
                        continue
                    подряд = 0
                dom = self._очередь.popleft()
                начато = time.monotonic()
                задача = asyncio.ensure_future(соединение.get_value(domain=dom))
                try:
                    готово, _ = await asyncio.wait({задача}, timeout=ЖДАТЬ_ДОМЕН)
                except asyncio.CancelledError:
                    # порядок несущий: отменить вопрос, ДОЖДАТЬСЯ его и только потом закрывать
                    # соединение. Закрыть под висящим вопросом — значит, что библиотека сочтёт
                    # это обрывом связи, переподключится и задаст тот же вопрос заново.
                    await _снять_задачу(задача)
                    raise
                if not готово:
                    # телефон обдумывает ответ — пусть обдумывает на своём соединении, а мы
                    # берём новое и спрашиваем дальше. Ответ подберём позже.
                    await self._припарковать(dom, задача, соединение, начато)
                    соединение = None
                    continue
                if not self._забрать(dom, задача, начато):
                    # Ответ не состоялся. Соединение могло умереть вместе с ним — закрываем и
                    # берём новое, а домен спрашиваем заново: сорвавшийся вопрос — не потеря.
                    await self._закрыть(соединение)
                    соединение = None
                    if not self._ещё_раз(dom):
                        self._не_вышло(dom, self.ошибки.get(dom) or "ответа нет")
        finally:
            if соединение is not None:
                try:
                    await self._закрыть(соединение)
                except BaseException:                             # noqa: BLE001
                    pass                                          # добьёт `закрыть`

    async def _открыть(self):
        """Ещё одно соединение с тем же телефоном. → (соединение, почему нет)."""
        return await _открыть_сбоку(self._соединить, копилка=self._соединения)

    async def _закрыть(self, соединение) -> None:
        self._соединения.discard(соединение)
        await _закрыть_соединение(соединение)

    async def _припарковать(self, dom, задача, соединение, начато) -> None:
        """Отложить обдумываемый вопрос вместе с его соединением."""
        while len(self._парк) >= ПАРКОВОК:
            давний = min(self._парк, key=lambda d: self._парк[d][2])
            await self._снять(давний)
        self._парк[dom] = (задача, соединение, начато)

    async def _снять(self, dom) -> None:
        """Мест в парковке нет: самый давний вопрос снимаем и ставим в очередь заново."""
        задача, соединение, начато = self._парк.pop(dom)
        пришёл = задача.done() and self._забрать(dom, задача, начато)
        if not задача.done():
            await _снять_задачу(задача)          # отменить и дождаться — и только потом закрыть
        await self._закрыть(соединение)
        if not пришёл and not self._ещё_раз(dom):
            сек = round(time.monotonic() - начато)
            self._не_вышло(dom, f"{НЕ_ОТВЕТИЛ} {сек} с")

    async def _подобрать(self) -> list:
        """Ответы на обдуманные вопросы — к себе. → какие пришли."""
        пришли = []
        for dom in [d for d, (з, _с, _н) in self._парк.items() if з.done()]:
            что = self._парк.pop(dom, None)
            if что is None:
                continue                         # забрал тот, кто позвал `собрать` рядом
            задача, соединение, начато = что
            if self._забрать(dom, задача, начато):
                пришли.append(dom)
            elif not self._ещё_раз(dom):
                self._не_вышло(dom, self.ошибки.get(dom) or "ответа нет")
            await self._закрыть(соединение)
        return пришли

    def _забрать(self, dom, задача, начато) -> bool:
        """Законченная задача → ответ. → пришёл ли ответ (пусто — тоже ответ)."""
        if задача.cancelled():
            return False
        беда = задача.exception()
        if беда is not None:
            self.ошибки[dom] = f"{type(беда).__name__}: {str(беда)[:120]}"
            return False
        self.ответы[dom] = задача.result()
        self.время[dom] = round(time.monotonic() - начато, 2)
        self.ошибки.pop(dom, None)
        self.сдались.discard(dom)
        return True

    def _ещё_раз(self, dom) -> bool:
        """Спросить домен заново, если попытки не кончились. → будем ли спрашивать."""
        n = self._попытки.get(dom, 0) + 1
        self._попытки[dom] = n
        if n >= ПОПЫТОК_ДОМЕНА or self._закрыто:
            return False
        self._очередь.append(dom)                    # в конец: остальные домены вперёд
        self._поднять()
        return True

    def _не_вышло(self, dom, почему) -> None:
        self.ошибки[dom] = почему
        self.сдались.add(dom)
        self._log(f"сбор доменов: {dom} — {почему}")

    async def _подождать(self, сколько) -> None:
        ждём = {з for з, _с, _н in self._парк.values() if not з.done()}
        ждём |= {з for з in self._рабочие if not з.done()}
        if not ждём:
            await asyncio.sleep(сколько)
            return
        await asyncio.wait(ждём, timeout=сколько, return_when=asyncio.FIRST_COMPLETED)

    def _вложить(self, snap: dict) -> None:
        """Ответы — в слепок. Зовётся много раз, поэтому ничего не портит и не дублирует."""
        кач = snap.setdefault("quality", {})
        домены = snap.setdefault("domains", {})
        for dom, v in self.ответы.items():
            if v:
                домены[dom] = v
            if dom in self._отмечено:
                continue
            self._отмечено.add(dom)
            сек = self.время.get(dom)
            if сек is not None and сек >= 1.0:
                # какой именно домен телефон отдавал долго — раньше знали только сумму по всем
                кач.setdefault("медленные_домены", {})[dom] = round(сек, 1)
            if self._начато is not None and сек is not None and time.monotonic() - self._начато > сек + 1.0:
                кач.setdefault("поздние_домены", {})[dom] = round(time.monotonic() - self._начато, 1)
        ждут = {d: round(time.monotonic() - (self._начато or time.monotonic()), 1)
                for d in self.осталось()}
        if ждут:
            кач["ждём_домены"] = ждут
        else:
            кач.pop("ждём_домены", None)
        if self._беда_соединения:
            кач["боковое_соединение"] = self._беда_соединения


async def спросить_в_стороне(соединить, домен=None, ключ=None, ждать=ЖДАТЬ_ДОМЕН):
    """Один вопрос телефону на своём соединении и не дольше `ждать` секунд.
    → (ответ, почему нет): ответ None и причина словами, если не дождались или не вышло."""
    соединение, почему = await _открыть_сбоку(соединить)
    if соединение is None:
        return None, почему
    try:
        что = {k: v for k, v in (("domain", домен), ("key", ключ)) if v}
        return await asyncio.wait_for(соединение.get_value(**что), ждать), ""
    except asyncio.TimeoutError:
        return None, f"{НЕ_ОТВЕТИЛ} {ждать:g} с"
    except Exception as e:                                        # noqa: BLE001
        return None, f"{type(e).__name__}: {str(e)[:120]}"
    finally:
        await _закрыть_соединение(соединение)


async def _читать_домены_подряд(ld, quality, связь, ждать=None):
    """Домены по очереди, на общем соединении — так читалось до 17.11.2026.

    Остаётся на два случая: подставной телефон в тестах (`ждать=None` — без предела, как
    раньше) и живой телефон, к которому не вышло открыть второе соединение. Во втором случае
    предел есть, и дальше читать по этому соединению НЕЛЬЗЯ: брошенный ответ придёт позже и
    будет прочитан как ответ на следующий вопрос — в слепок попали бы чужие данные. Поэтому
    `СвязьПропала`: чтение начнётся заново, с новым соединением (`worker._прочитать_телефон`,
    до ЧТЕНИЙ раз)."""
    domains, медленные = {}, {}
    for dom in DOMAINS:
        if dom == ДОМЕН_ДИСКА:
            continue                             # про память — отдельно и не дожидаясь, см. ниже
        связь.проверить()
        t_dom = time.monotonic()
        try:
            if ждать:
                v = await asyncio.wait_for(ld.get_value(domain=dom), ждать)
            else:
                v = await ld.get_value(domain=dom)
            связь.удалось()
            if v:
                domains[dom] = v
        except asyncio.TimeoutError:
            raise СвязьПропала(f"{dom}: {НЕ_ОТВЕТИЛ} {ждать:g} с, а второго соединения нет") from None
        except Exception as e:                   # noqa: BLE001
            почему = f"{type(e).__name__}: {e}"
            # правило о неполноте одно на оба пути чтения: см. РЕШАЮЩИЕ_ДОМЕНЫ
            if dom in РЕШАЮЩИЕ_ДОМЕНЫ:
                quality["не_прочиталось"][dom] = почему
            else:
                quality.setdefault("домены_без_ответа", {})[dom] = почему
            await связь.сорвалось(dom, почему)
        if time.monotonic() - t_dom >= 1.0:
            медленные[dom] = round(time.monotonic() - t_dom, 1)
    if медленные:
        quality["медленные_домены"] = медленные
    return domains


class ЧтениеДиска:
    """Ответ телефона про память, который читается в стороне от основного слепка.

    `соединить` — корутина без аргументов, дающая СВОЁ соединение lockdown с тем же
    телефоном. Своё — потому что телефон может считать ответ минутами, а бросить ждать ответ
    на общем соединении нельзя: он придёт позже и будет прочитан как ответ на следующий
    вопрос. Своё соединение просто закрывают."""

    def __init__(self, соединить):
        """Чтение начинается сразу, в стороне; забирают его через `вложить`."""
        self._соединить, self._соединение = соединить, None
        self.начато, self.готово_за, self.ответ, self.беда = time.monotonic(), None, None, ""
        self._задача = asyncio.ensure_future(self._читать())

    async def _читать(self):
        try:
            # соединение открываем общим путём: отмена на этом шаге не оставит за собой
            # открытый сокет, а не успевшее открыться закроется само
            self._соединение, почему = await _открыть_сбоку(self._соединить)
            if self._соединение is None:
                self.беда = почему
                return None
            self.ответ = await self._соединение.get_value(domain=ДОМЕН_ДИСКА) or None
            self.готово_за = round(time.monotonic() - self.начато, 2)
        except asyncio.CancelledError:
            raise
        except Exception as e:                                    # noqa: BLE001
            self.беда = f"{type(e).__name__}: {str(e)[:120]}"
        return self.ответ

    async def вложить(self, snap: dict, ждать: float = 0.0) -> bool:
        """Положить ответ в слепок, если он пришёл или придёт за `ждать` секунд. → пришёл ли.

        Не пришёл — в `quality` остаётся, сколько ждали: отчёт скажет, что объём взят с
        контроллера и с диском не сверен."""
        if not self._задача.done() and ждать > 0:
            await asyncio.wait({self._задача}, timeout=ждать)
        кач = snap.setdefault("quality", {})
        if self._задача.done() and self.ответ:
            snap.setdefault("domains", {})[ДОМЕН_ДИСКА] = self.ответ
            кач.setdefault("время_с", {})["диск"] = self.готово_за
            кач.pop("память_не_дождались_с", None)
            if self.ответ.get("NANDInfo"):
                nv_fw = txt(deep((snap.get("nodes") or {}).get("nvme") or {}, "Firmware Revision"))
                snap["nand_summary"] = nand.summarize(self.ответ["NANDInfo"], nv_fw)
            return True
        кач["память_не_дождались_с"] = round(time.monotonic() - self.начато, 1)
        if self.беда:
            кач["память_беда"] = self.беда
        return False

    async def закрыть(self):
        """Больше не ждём: бросаем чтение и закрываем его соединение."""
        if not self._задача.done():
            self._задача.cancel()
            try:
                await self._задача
            except BaseException:                                 # noqa: BLE001
                pass
        if self._соединение is not None:
            await _закрыть_соединение(self._соединение)
            self._соединение = None


async def collect(ld, diag, log=lambda *a: None, жив=None, память=True, соединить=None, сбор=None):
    """Слепок телефона. `жив()` — не отменили ли чтение. `память=False` — про память не
    спрашивать вовсе: касса делает это сама, в конце проверки (`ЧтениеДиска`). Иначе (доктор,
    тесты) память читается здесь же — один раз и последней.

    `соединить` — корутина, дающая ещё одно соединение с тем же телефоном. С ней все домены
    собираются в фоне и с пределом на каждый вопрос (`СборДоменов`), а слепок их не ждёт:
    что не успело прийти — приходит позже и вкладывается в слепок. `сбор` — уже созданный
    сборщик: касса держит его до конца проверки и дособирает остаток сама.

    Бросает `СвязьПропала`, если соединение оборвалось, и `Остановлено`, если отменили."""
    t0 = time.monotonic()
    quality = {"повторы": {}, "не_прочиталось": {}, "устарело": [], "время_с": {}}

    async def проба():
        # то же, чем `open_diagnostics` проверяет готовность: узел батареи есть у любого iPhone
        return bool(await diag.ioregistry(name="AppleSmartBattery")) and bool(await ld.get_value(key="ProductType"))
    связь = _Связь(проба, жив)

    log("паспорт…")
    root = await _retry(lambda: ld.get_value(), "root", quality, связь=связь, ждать=ЖДАТЬ_ОТВЕТА) or {}
    quality["время_с"]["паспорт"] = round(time.monotonic() - t0, 2)

    log("домены…")
    t = time.monotonic()
    # Домены собираются в стороне и все до единого: ни один вопрос не держит чтение, а тот,
    # что телефон обдумывает, догоняет слепок позже (`СборДоменов`). Перезапрос сорвавшегося
    # вопроса — там же: прежде одного моргнувшего USB хватало, чтобы «Найти iPhone» стал
    # «не определился», хотя телефон всё это время лежал на кабеле.
    свой_сбор = None
    if сбор is None and соединить is not None:
        сбор = свой_сбор = СборДоменов(соединить, жив=жив, log=log)
    if сбор is not None:
        сбор.начать([d for d in DOMAINS if d != ДОМЕН_ДИСКА])
        await сбор.собрать(ждать=ЖДАТЬ_ДОМЕНЫ_В_СЛЕПКЕ)
        domains = сбор.собранное()
        if not domains and сбор.без_соединений():
            # второго соединения телефон не даёт вовсе — собираем по общему, с пределом:
            # данные нужны все, а не «сколько получилось»
            log("домены по общему соединению…")
            quality["боковое_соединение_нет"] = True
            domains = await _читать_домены_подряд(ld, quality, связь, ждать=ЖДАТЬ_ДОМЕН)
            сбор.забыть()
    else:
        domains = await _читать_домены_подряд(ld, quality, связь)
    quality["время_с"]["домены"] = round(time.monotonic() - t, 2)

    log("карта узлов…")
    t = time.monotonic()
    tree = await _retry(lambda: diag.ioregistry(plane="IOService"), "ioreg:IOService", quality, связь=связь,
                        ждать=ЖДАТЬ_ОТВЕТА)
    names = collect_entry_names(tree) if tree else set()
    quality["время_с"]["карта"] = round(time.monotonic() - t, 2)
    quality["узлов_в_карте"] = len(names)

    # Дерево устройств целиком: все *-serial-num, device-colors, wifi-module-sn
    # любой модели попадают в слепок, даже если мы о них ещё не знаем.
    log("дерево устройств…")
    t = time.monotonic()
    dtree = await _retry(lambda: diag.ioregistry(plane="IODeviceTree"), "ioreg:IODeviceTree", quality, tries=2,
                         ждать=ЖДАТЬ_ОТВЕТА,
                         связь=связь)
    quality["время_с"]["дерево"] = round(time.monotonic() - t, 2)
    names_all = set(names) | (collect_entry_names(dtree) if dtree else set())

    cam_names = pick_names(names, CAMERA_RE, CAMERA_FALLBACK)
    nvme_names = pick_names(names, NVME_RE, NVME_FALLBACK)

    log("узлы…")
    t = time.monotonic()
    nodes = {}
    quality["нет_в_карте"] = []
    for name in FIXED_NODES:
        # Драйверных узлов, которых нет в карте телефона, не ждём по 5 секунд:
        # у iPhone 17 Pro нет AIDBus (USB-C) — это не сбой чтения, а устройство другое.
        if names_all and name[0].isupper() and name not in names_all:
            nodes[name] = None
            quality["нет_в_карте"].append(name)
            continue
        nodes[name] = await _retry(lambda n=name: diag.ioregistry(name=n), name, quality, связь=связь,
                                   ждать=ЖДАТЬ_ОТВЕТА)
    nodes["prox"] = None
    for n in pick_names(names_all, PROX_RE, PROX_FALLBACK):
        if names_all and n not in names_all:
            continue
        v = await _retry(lambda n=n: diag.ioregistry(name=n), n, quality, tries=2, связь=связь,
                         ждать=ЖДАТЬ_ОТВЕТА)
        if v:
            nodes["prox"] = v
            quality["prox_узел"] = n
            break
    for key, cands in (("camera", cam_names), ("nvme", nvme_names)):
        nodes[key] = None
        for n in cands:
            v = await _retry(lambda n=n: diag.ioregistry(name=n), n, quality, tries=2, связь=связь,
                         ждать=ЖДАТЬ_ОТВЕТА)
            if v:
                nodes[key] = v
                quality[f"{key}_узел"] = n
                break
    async def узел_по_возможности(что):
        """Узел, которого у модели может не быть: нет — не беда. А вот молчание телефона —
        беда: ответ брошен, соединение диагностики библиотека закрыла, и дальше по нему
        прочитается только пустота. Поэтому `СвязьПропала` и чтение заново."""
        try:
            return await asyncio.wait_for(что, ЖДАТЬ_ОТВЕТА)
        except asyncio.TimeoutError:
            raise СвязьПропала(f"узел: {НЕ_ОТВЕТИЛ} {ЖДАТЬ_ОТВЕТА:g} с") from None
        except Exception:                                         # noqa: BLE001
            return None

    # узлы «по возможности» — одна попытка, отсутствие не считается ошибкой чтения
    for key, (rx, fallback) in OPTIONAL_NODES.items():
        nodes[key] = None
        for n in pick_names(names_all, rx, fallback):
            if names_all and n not in names_all:
                continue
            v = await узел_по_возможности(diag.ioregistry(name=n))
            if v:
                nodes[key] = v
                quality[f"{key}_узел"] = n
                break
    for key, cls in OPTIONAL_CLASSES.items():
        nodes[key] = await узел_по_возможности(diag.ioregistry(ioclass=cls)) or None
    quality["время_с"]["узлы"] = round(time.monotonic() - t, 2)

    # MobileGestalt — лучшим доступным каналом: diagnostics до iOS 17.4, а на 17.4+
    # через userspace-туннель CoreDevice (без прав администратора; тот же канал, что у
    # 3uTools). Печать деталей, серийники модулей, цвета корпуса — без действий клиента.
    связь.проверить()
    log("MobileGestalt…")
    t = time.monotonic()
    serial = txt((root or {}).get("UniqueDeviceID")) or None
    try:
        mg_res = await mg_mod.read(diag, serial=serial)
    except Exception as e:                                        # noqa: BLE001
        mg_res = {"значения": {}, "канал": "нет", "ошибка": f"{type(e).__name__}: {str(e)[:160]}"}
    mg = dict(mg_res.get("значения") or {})
    if not mg:
        mg = {"недоступен": mg_res.get("ошибка") or "пусто"}
    mg["_канал"] = mg_res.get("канал")
    if mg_res.get("device_info"):
        mg["_device_info"] = mg_res["device_info"]
    if mg_res.get("диагностика"):
        # туннель поднялся, а службы нет: кладём в слепок, что телефон предлагает вместо неё
        mg["_диагностика"] = mg_res["диагностика"]
    quality["mobilegestalt_канал"] = mg_res.get("канал")
    quality["время_с"]["mobilegestalt"] = round(time.monotonic() - t, 2)

    связь.проверить()
    # Джейлбрейк, panic full и профили — на СВОЁМ соединении, если его дают. У каждой пробы
    # свой предел (20, 25 и 12 с), но истёкший предел означает брошенный запрос, а после него
    # соединение непригодно: библиотека закрывает его, а по основному соединению ещё работает
    # слушатель журнала — там бы молча потерялись записи Apple и процент батареи.
    пробное, почему_нет = (await _открыть_сбоку(соединить)) if соединить is not None else (None, "")
    if пробное is None and почему_нет:
        quality["пробное_соединение"] = почему_нет
    на_пробы = пробное or ld
    try:
        связь.проверить()
        log("джейлбрейк…")
        t = time.monotonic()
        jb = await jailbreak.probe(на_пробы)
        quality["время_с"]["джейлбрейк"] = round(time.monotonic() - t, 2)

        связь.проверить()
        log("panic full…")
        t = time.monotonic()
        pan = await panic.probe(на_пробы)
        quality["время_с"]["паника"] = round(time.monotonic() - t, 2)

        связь.проверить()
        log("профили и надзор…")
        t = time.monotonic()
        mdm_info = await mdm.probe(на_пробы)
        quality["время_с"]["mdm"] = round(time.monotonic() - t, 2)
    finally:
        if пробное is not None:
            await _закрыть_соединение(пробное)

    связь.проверить()
    nand_summary = {}
    if память:
        log("память…")
        t = time.monotonic()
        if соединить is not None:
            # своё соединение и предел: память телефон считает когда как (до минут)
            диск = ЧтениеДиска(соединить)
            try:
                частично = {"domains": domains, "nodes": nodes, "quality": quality}
                if await диск.вложить(частично, ждать=ЖДАТЬ_ПАМЯТЬ_ЗДЕСЬ):
                    nand_summary = частично.get("nand_summary") or {}
            finally:
                await диск.закрыть()
        else:
            disk = await _retry(lambda: ld.get_value(domain=ДОМЕН_ДИСКА), ДОМЕН_ДИСКА, quality, tries=2,
                                ждать=ЖДАТЬ_ПАМЯТЬ_ЗДЕСЬ,
                                delays=(0.8, 2.0), связь=связь) or {}
            if disk:
                domains[ДОМЕН_ДИСКА] = disk
            quality["время_с"]["диск"] = round(time.monotonic() - t, 2)
            # NANDInfo: разбор и сверка прошивки с NVMe-контроллером
            if disk.get("NANDInfo"):
                nand_summary = nand.summarize(disk["NANDInfo"], txt(deep(nodes.get("nvme") or {}, "Firmware Revision")))

    quality["время_с"]["всего"] = round(time.monotonic() - t0, 2)
    snap = {
        "snapshot_version": SNAPSHOT_VERSION,
        "когда": datetime.now().isoformat(timespec="seconds"),
        "root": root,
        "domains": domains,
        "node_names": sorted(names),
        "nodes": nodes,
        "ioreg_planes": {"IOService": tree, "IODeviceTree": dtree},
        "mobilegestalt": mg,
        "jailbreak": jb,
        "panic": pan,
        "mdm": mdm_info,
        "nand_summary": nand_summary,
        "quality": quality,
    }
    if сбор is not None:
        # то, что уже пришло, — в слепок; остальное догонит позже
        await сбор.собрать(snap)
        if свой_сбор is not None:
            # сборщик наш (доктор, тесты): никто за нас остаток не доберёт
            await сбор.собрать(snap, ждать=ЖДАТЬ_ОСТАТОК)
            сбор.итог(snap)
            await сбор.закрыть()
    return snap
