def test_status_changes_only_from_normal_to_repaired(м):
    """Кабель нашёл заменённую деталь: «нормальное состояние» становится «Телефон был в
    ремонте», а находка ложится в «Отчёт диагностики». «Есть видимые дефекты» не трогаем —
    кабель не видит корпус; и без находки статус не меняется никогда."""
    ремонт = dict(phone_status="Ранее был в ремонте",
                  comment_ocenka="Состояние: Б/у → изменено: по кабелю: Экран — не подтверждена · "
                                 "Детали: замена · Киоск 16/38 от 2026-11-17")
    ответ, _ = выполнить(м, [товар()], посылка(**ремонт))
    изменения = пары(ответ)
    assert изменения["Статус"] == ("Б/у телефон в нормальном состоянии", "Телефон был в ремонте")
    assert "Экран" in изменения["Отчёт диагностики"][1] and изменения["Отчёт диагностики"][0] == ""

    с_дефектом, _ = выполнить(м, [товар(**{"Статус": "Есть видимые дефекты"})], посылка(**ремонт))
    assert "Статус" not in пары(с_дефектом) and "Отчёт диагностики" in пары(с_дефектом)
    assert any("Статус оставлен" in з for з in с_дефектом["заметки"])

    чистый, _ = выполнить(м, [товар(**{"Статус": "Телефон был в ремонте"})], посылка())
    assert "Статус" not in пары(чистый), "чистый кабель состояние товара не улучшает"


