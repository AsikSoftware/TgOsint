def склад(поля, справочники):
    """Подменный МойСклад: метаданные товара и справочники. → (запрос, кэш, журнал)."""
    журнал = []

    def запрос(session, метод, адрес, params=None, body=None):
        журнал.append((метод, адрес))
        assert метод == "GET", "при сборке полей в МойСклад ничего не пишем"
        if адрес == "/entity/product/metadata":
            return {"attributes": {"rows": [
                {"name": n, "type": t, "meta": {"href": "поле/" + n},
                 **({"customEntityMeta": {"href": "справочник/" + d}} if d else {})}
                for n, t, d in поля]}}
        if адрес.startswith("/entity/customentity/"):
            return {"rows": [{"name": v, "meta": {"href": "значение/" + v}}
                             for v in справочники[адрес.rsplit("/", 1)[-1]]]}
        raise AssertionError(адрес)

    return запрос, (lambda ключ, загрузить: загрузить()), журнал


def сделка(**замены):
    d = dict(id=16487, akb="75-79", akb_exact=79, akb_cycles=1719, ddr=128, sim="Стандарт",
             phone_status="Не был в ремонте", box=True, cord=False, color="BLACK",
             panic_full=False, sim_free=True, trade_type="Выкуп", defects="", malfunction=None,
             comment_ocenka="")
    d.update(замены)
    return types.SimpleNamespace(**d)


def собрать(м, поля, справочники, device):
    запрос, кэш, _ = склад(поля, справочники)
    out, skipped = м.поля_товара(None, device, запрос=запрос, кэш=кэш,
                                 pick_imeis=lambda d: ["356789012345678", "356789012345686"],
                                 defect_fields=ДЕФЕКТЫ,
                                 defect_set=lambda d: {x.strip() for x in (d.defects or "").split(",") if x.strip()},
                                 dict_aliases=АЛИАСЫ)
    значения = {}
    for a in out:
        v = a["value"]
        значения[a["meta"]["href"].split("/", 1)[1]] = (
            v["meta"]["href"].split("/", 1)[1] if isinstance(v, dict) else v)
    return значения, skipped


def test_the_old_card_is_filled_exactly_as_before(м):
    """Пока в МойСкладе ничего не меняли — на карточку ложится ровно то же, что и раньше,
    плюс «Цикл»: поле было, но бот его не заполнял."""
    поля, skipped = собрать(м, ПОЛЯ_ДО, СПРАВОЧНИКИ_ДО, сделка())
    assert поля == {
        "Imei 1": "356789012345678", "Imei 2": "356789012345686",
        "АКБ": "75-79%",                        # точных процентов в справочнике ещё нет
        "Цикл": 1719, "Память": "128", "Sim слот": "Стандарт",
        "Ремонт статус": "Не был в ремонте", "Комплектация": "Коробка",
        "Способ приобретения": "Выкуп",
        "Не работает": False, "Глубокие царапины": False, "Сколы": False, "Пятна на экране": False,
    }
    assert skipped == [], "новых полей ещё нет — молчим о них, админа не пугаем"


def test_the_renamed_card_gets_the_same_deal_under_the_new_names(м):
    """После правок владельца та же сделка ложится под новыми именами: точный процент,
    «Статус» словами кнопки бота, галочка «Sim Лоток» — и ничего не пропущено."""
    новые, спр = после_переименования()
    поля, skipped = собрать(м, новые, спр, сделка())
    assert поля["АКБ"] == "79%"
    assert поля["Статус"] == "Б/у телефон в нормальном состоянии"
    assert поля["Sim Лоток"] is True and поля["Sim слот"] == "Стандарт"
    assert поля["Цвет"] == "BLACK" and поля["Panic full"] is False
    assert поля["Сим без ограничений"] is True and поля["Номер сделки"] == 16487
    assert поля["Цикл"] == 1719 and isinstance(поля["Цикл"], int), "числовому полю — число"
    assert "Отчёт диагностики" not in поля, "чистому аппарату отчёт о поломках не нужен"
    assert "Ремонт статус" not in поля and skipped == []


@pytest.mark.parametrize("в_боте,по_новому,по_старому", [
    ("Не был в ремонте", "Б/у телефон в нормальном состоянии", "Не был в ремонте"),
    ("Ранее был в ремонте", "Телефон был в ремонте", "Ранее был ремонт"),
    ("Присутствует дефект", "Есть видимые дефекты", "Присутствует дефект"),
    ("Прочее", "Запечатанный (новый)", "Прочее"),
])
def test_every_condition_of_the_bot_lands_before_and_after_the_rename(м, в_боте, по_новому, по_старому):
    """Четыре кнопки состояния бота — четыре значения справочника, и каждое находится и по
    прежнему имени, и по новому. Имя поля и имена значений переименовывают в МойСкладе не
    одной кнопкой: между ними код обязан пережить и «поле уже Статус, значения ещё старые»."""
    до, _ = собрать(м, ПОЛЯ_ДО, СПРАВОЧНИКИ_ДО, сделка(phone_status=в_боте))
    assert до["Ремонт статус"] == по_старому
    новые, спр = после_переименования()
    после, skipped = собрать(м, новые, спр, сделка(phone_status=в_боте))
    assert после["Статус"] == по_новому and not [s for s in skipped if "Статус" in s]
    # поле уже переименовано, значения — ещё нет
    между, skipped = собрать(м, новые, {**спр, "rem": СПРАВОЧНИКИ_ДО["rem"]}, сделка(phone_status=в_боте))
    assert между["Статус"] == по_старому and not [s for s in skipped if "Статус" in s]


def test_the_exact_percent_falls_back_to_the_range_and_never_drops_the_field(м):
    """Точного значения в справочнике может не быть (45 % никто не заводил), а у старых
    сделок нет и самого процента. Тогда на карточке диапазон, как раньше, — но не пусто."""
    новые, спр = после_переименования()
    assert собрать(м, новые, спр, сделка(akb="0-74", akb_exact=45))[0]["АКБ"] == "<74%"
    assert собрать(м, новые, спр, сделка(akb="91-95", akb_exact=None))[0]["АКБ"] == "91-95%"
    assert собрать(м, новые, спр, сделка(akb="100", akb_exact=100))[0]["АКБ"] == "100%"
    поля, skipped = собрать(м, новые, спр, сделка(akb=None, akb_exact=None))
    assert "АКБ" not in поля and skipped == []


def test_the_sim_tray_is_a_tick_and_unknown_is_left_alone(м):
    """Лоток есть — галочка, лотка нет — снятая галочка. «Прочее» из старых сделок — не
    знаем: галочку не трогаем, а не ставим «нет»."""
    новые, спр = после_переименования()
    assert собрать(м, новые, спр, сделка(sim="E-sim"))[0]["Sim Лоток"] is False
    assert собрать(м, новые, спр, сделка(sim="Dual sim"))[0]["Sim Лоток"] is True
    прочее, _ = собрать(м, новые, спр, сделка(sim="Прочее"))
    assert "Sim Лоток" not in прочее and прочее["Sim слот"] == "Прочее"
    # прежний справочник убрали совсем — остаётся одна галочка, и это не «пропущено»
    без_слота = [x for x in новые if x[0] != "Sim слот"]
    поля, skipped = собрать(м, без_слота, спр, сделка(sim="E-sim"))
    assert поля["Sim Лоток"] is False and "Sim слот" not in поля and skipped == []


def test_cycles_zero_is_a_value_and_absent_cycles_leave_the_field_alone(м):
    """Ноль циклов — это значение (новая батарея), а не пусто. У сделок из бота без циклов
    поле не трогаем: на карточке могло стоять число, вписанное руками."""
    assert собрать(м, ПОЛЯ_ДО, СПРАВОЧНИКИ_ДО, сделка(akb_cycles=0))[0]["Цикл"] == 0
    assert "Цикл" not in собрать(м, ПОЛЯ_ДО, СПРАВОЧНИКИ_ДО, сделка(akb_cycles=None))[0]


