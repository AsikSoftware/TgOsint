# -*- coding: utf-8 -*-
"""Запрос к МойСкладу с повторами — там и только там, где повтор безопасен.

Зачем. Прежний `_ms_request` бота повторял запрос ровно при одном отказе: 429 (упёрлись в
лимит запросов). Всё остальное — 500, 502, 503, 504 и обрыв связи — падало с первого раза,
и каждый такой отказ стоил данных:

* 18.11.2026, 12:27 Алматы: МойСклад ответил `503` на чтение справочника «Статус», и
  автоприёмка завела карточку товара БЕЗ состояния. В журнале — одна строка
  «доп. поле Статус пропущено», сотруднику ничего, карточка так и осталась неполной;
* тот же отказ на записи (`POST /entity/supply`) рвёт приёмку целиком, а не одно поле;
* приход из Excel показывает отказ человеку и просит загрузить файл заново.

Политика повтора. Повторять «всё подряд» нельзя: ответа может не быть, а запись — пройти,
и тогда повтор заведёт второй документ. Поэтому:

* **429** — как было: пауза по `Retry-After`, иначе удвоение. Это не беда, а просьба подождать.
* **5xx** (сервер ОТВЕТИЛ отказом) — повторяем любой запрос, включая POST: раз сервер успел
  ответить «не могу», значит он запрос не выполнил.
* **обрыв связи** (ответа нет вовсе: таймаут, разорванное соединение) — повторяем только
  GET и PUT. Их повтор даёт тот же итог. POST после обрыва НЕ повторяем: неизвестно,
  создался документ или нет, и повтор рискует завести двойника. Такой отказ поднимаем
  наружу с отдельным текстом — чтобы в журнале было видно, что проверять руками.

Паузы небольшие: отказы МойСклада короткие, а на другом конце ждёт сотрудник у кассы.
Текст исключения оставлен прежним («HTTP <код> <метод> <адрес>» и тело ответа): его видит
человек в приходе из Excel, и на него смотрят глазами в журнале.

Модуль нарочно не знает ни про `requests`, ни про настройки бота: отправку, паузу и журнал
передают снаружи. Поэтому его можно проверить тестами без сети — tests/test_ms_http.py.
"""
import json
import random
import time

# Повторы при 429 — как в прежнем коде бота.
ЛИМИТ_ПОПЫТОК = 5
ЛИМИТ_ПАУЗА = 1.0
# Повторы при 5xx и обрыве связи: 4 попытки, пауза 0.7 → 1.4 → 2.8 с.
ОТКАЗ_ПОПЫТОК = 4
ОТКАЗ_ПАУЗА = 0.7
# Коды, которые считаем временной бедой сервера. 507/509 — предел места и трафика у МойСклада:
# они тоже проходят сами.
ОТКАЗ_КОДЫ = (500, 502, 503, 504, 507, 509)
# Разброс, чтобы два потока бота не стучались в одну и ту же миллисекунду.
РАЗБРОС = 0.25
# Какие запросы можно повторить, когда ответа не было вовсе.
БЕЗОПАСНЫЕ = ("GET", "PUT", "HEAD", "OPTIONS", "DELETE")


class СвязьНеВышла(RuntimeError):
    """Ответа не было, и повторять нельзя: неизвестно, прошла ли запись."""


def _пауза(номер: int, база: float) -> float:
    """Удвоение от номера попытки (1 → база, 2 → 2×база, …) плюс разброс."""
    return база * (2 ** max(0, номер - 1)) + random.uniform(0, РАЗБРОС)


def _сколько_ждать(ответ, номер: int) -> float:
    """Пауза при 429: сначала слушаем `Retry-After` сервера, потом считаем сами."""
    сказано = None
    try:
        сказано = (getattr(ответ, "headers", None) or {}).get("Retry-After")
    except Exception:                                            # noqa: BLE001 — заголовков нет
        сказано = None
    try:
        if сказано is not None:
            return float(сказано) + random.uniform(0, РАЗБРОС)
    except (TypeError, ValueError):
        pass
    return _пауза(номер, ЛИМИТ_ПАУЗА)


def _тело(ответ) -> str:
    """Тело отказа для текста исключения — так же, как писал прежний код."""
    try:
        payload = ответ.json()
    except Exception:                                            # noqa: BLE001 — не JSON
        payload = {"text": getattr(ответ, "text", "")}
    try:
        return json.dumps(payload, ensure_ascii=False, indent=2)
    except (TypeError, ValueError):
        return str(payload)


def запросить(отправить, метод: str, адрес: str, *, обрыв=Exception, перед=None,
              журнал=None, спать=None):
    """Запрос с повторами. → разобранный JSON, или None при 204.

    `отправить` — функция без доводов, делающая один запрос и возвращающая ответ вида
    `requests.Response` (нужны `status_code`, `json()`, `text`, `headers`).
    `обрыв` — класс (или кортеж классов) исключений «ответа не было»: для бота это
    `requests.exceptions.RequestException`.
    `перед` — что сделать перед каждой попыткой (у бота — пауза между запросами).
    `журнал` — объект с `warning`; `спать` — чем ждать (в тестах подменяется).

    Поднимает `СвязьНеВышла`, если ответа не было и повторять небезопасно, и `RuntimeError`
    с прежним текстом «HTTP <код> …» на любом другом отказе.
    """
    спать = спать or time.sleep
    можно_повторять = str(метод or "").upper() in БЕЗОПАСНЫЕ
    отказов, лимитов = 0, 0

    while True:
        if перед is not None:
            перед()
        try:
            ответ = отправить()
        except обрыв as e:
            # Ответа нет. Повторяем только то, что от повтора не испортится.
            отказов += 1
            if not можно_повторять:
                raise СвязьНеВышла(
                    f"связь с МойСкладом оборвалась: {метод} {адрес}: {e}. "
                    "Запрос изменяющий, повторять нельзя — проверьте в МойСкладе, прошёл ли он"
                ) from e
            if отказов >= ОТКАЗ_ПОПЫТОК:
                raise СвязьНеВышла(
                    f"связь с МойСкладом не вышла за {отказов} попыток: {метод} {адрес}: {e}"
                ) from e
            ждать = _пауза(отказов, ОТКАЗ_ПАУЗА)
            if журнал is not None:
                журнал.warning("МойСклад: связь оборвалась (%s), пауза %.1f c (попытка %s) — %s %s",
                               type(e).__name__, ждать, отказов, метод, адрес)
            спать(ждать)
            continue

        код = getattr(ответ, "status_code", 0)

        if код == 429:
            лимитов += 1
            if лимитов < ЛИМИТ_ПОПЫТОК:
                ждать = _сколько_ждать(ответ, лимитов)
                if журнал is not None:
                    журнал.warning("МойСклад 429, пауза %.1f c (попытка %s)", ждать, лимитов)
                спать(ждать)
                continue

        elif код in ОТКАЗ_КОДЫ:
            # Сервер ответил «не могу» — значит запрос он не выполнил, и повтор безопасен
            # даже для POST.
            отказов += 1
            if отказов < ОТКАЗ_ПОПЫТОК:
                ждать = _пауза(отказов, ОТКАЗ_ПАУЗА)
                if журнал is not None:
                    журнал.warning("МойСклад %s, пауза %.1f c (попытка %s) — %s %s",
                                   код, ждать, отказов, метод, адрес)
                спать(ждать)
                continue

        if код >= 400:
            raise RuntimeError(f"HTTP {код} {метод} {адрес}\n{_тело(ответ)}")
        return None if код == 204 else ответ.json()
