# -*- coding: utf-8 -*-
"""Бот Оценки: осечка доставки больше не снимает доступ к боту.

    python3.13 active_on_send_patch.py <каталог бота> --check    # только проверить, ляжет ли
    python3.13 active_on_send_patch.py <каталог бота>            # поставить

Что было. Рассылка администраторам (`utils/utils.py`) при ответе Телеграма «бот заблокирован
пользователем» ставила человеку `active = false`. Это не пометка о недоставке, а доступ ко
всему боту: дальше на каждый /start приходит «Вы заблокированы, свяжитесь с администрацией».

24.11.2026 так заперло троих администраторов — Сергея (3 октября), Ибу (2 ноября) и Жандоса
(сегодня, 10:17 по Алматы). Человек при этом бота не блокировал: Телеграм отвечает тем же
отказом, когда чат удалили или перезашли с другого устройства.

Ровно это владелец уже ловил в Pay: флаг доступа — не признак доставки. Поэтому отказ теперь
только пишется в журнал, а доступ не трогается. Кому закрыть вход — решает администратор в
меню бота, и только он.

Замена обязана лечь ровно один раз, иначе скрипт останавливается, ничего не записав.
Рядом кладётся копия `<файл>.bak_<дата>`.
"""
import datetime
import io
import sys

root = sys.argv[1].rstrip("/")
ТОЛЬКО_ПРОВЕРКА = "--check" in sys.argv
ФАЙЛ = "/utils/utils.py"

СТАРОЕ = '''            if isinstance(result, TelegramForbiddenError):
                from database.database import AsyncOrm

                try:
                    await AsyncOrm.change_active_user(int(chat_id), active=False)
                    logging.warning(
                        "Админ %s деактивирован: бот заблокирован пользователем",
                        chat_id,
                    )
                except Exception as deactivate_error:
                    logging.error(
                        "Не удалось деактивировать админа %s после блокировки бота: %s",
                        chat_id,
                        deactivate_error,
                        exc_info=(
                            type(deactivate_error),
                            deactivate_error,
                            deactivate_error.__traceback__,
                        ),
                    )
                continue
'''

НОВОЕ = '''            if isinstance(result, TelegramForbiddenError):
                # Доступ к боту и доставка сообщения — разные вещи. Телеграм отвечает «бот
                # заблокирован пользователем» и когда человек удалил чат, и когда перезашёл
                # с другого устройства. Снимать за это доступ нельзя: человек потом жмёт
                # /start и упирается в «Вы заблокированы» — 24.11.2026 так заперло троих
                # администраторов. Кому закрыть вход, решает администратор в меню бота.
                logging.warning(
                    "Сообщение админу %s не доставлено: бот заблокирован пользователем "
                    "(доступ не трогаем)",
                    chat_id,
                )
                continue
'''

текст = io.open(root + ФАЙЛ, encoding="utf-8").read()
if "доступ не трогаем" in текст:
    sys.exit("уже стоит: осечка доставки доступ не снимает — ничего не делаю")
if текст.count(СТАРОЕ) != 1:
    sys.exit(f"СТОП, ничего не записано: замена должна лечь 1 раз, "
             f"а легла бы {текст.count(СТАРОЕ)}")
новый = текст.replace(СТАРОЕ, НОВОЕ)
compile(новый, root + ФАЙЛ, "exec")
if ТОЛЬКО_ПРОВЕРКА:
    print("проверка: замена ложится")
    sys.exit(0)
метка = datetime.datetime.now().strftime("%Y-%m-%d_%H%M")
with open(root + ФАЙЛ, "rb") as f:
    прежнее = f.read()
with open(root + ФАЙЛ + ".bak_" + метка, "wb") as f:
    f.write(прежнее)
io.open(root + ФАЙЛ, "w", encoding="utf-8", newline="\n").write(новый)
print("записан", ФАЙЛ, "(копия .bak_" + метка + ")")
print("дальше: проверить импорт (python3 -c 'from utils import utils') и перезапустить бота")
