def test_states_are_her_four_buttons_in_her_order():
    """Сотрудник выбирает то же, что продавец в боте, — и в том же порядке."""
    assert [к for к, _ in ocenka.СОСТОЯНИЯ.values()] == [
        "📦 Запечатанный (новый)", "🛠️ Телефон был в ремонте",
        "📲 Есть видимые дефекты", "📱 Б/у телефон в нормальном состоянии"]
    assert [с for _, с in ocenka.СОСТОЯНИЯ.values()] == [
        "Прочее", "Ранее был в ремонте", "Присутствует дефект", "Не был в ремонте"]
    assert ocenka.состояние_словами("норма").endswith("в нормальном состоянии")
    assert ocenka.состояние_словами("чушь") == ""


ЧИСТЫЙ = {"детали_вердикт": {"итог": "родные"}, "батарея": {"подделка": []}, "стоп": [],
          "паника": {"panic_full": False}}
ЗАМЕНА = {**ЧИСТЫЙ, "детали_вердикт": {"итог": "замена", "детали": [
    {"деталь": "Экран", "статус": "bad", "почему": "серийник панели не привязан к плате", "источник": "кабель"}]}}


@pytest.mark.parametrize("состояние,rep,ждём,причина_есть", [
    ("норма", ЧИСТЫЙ, "Не был в ремонте", False),                # чистый остаётся чистым → автоцена
    ("норма", ЗАМЕНА, "Ранее был в ремонте", True),
    ("норма", {**ЧИСТЫЙ, "детали_вердикт": {"итог": "ремонт", "детали": []}}, "Ранее был в ремонте", True),
    ("норма", {**ЧИСТЫЙ, "батарея": {"подделка": ["заявляет 3614 мА·ч при заводских 3208"]}},
     "Ранее был в ремонте", True),
    ("норма", {**ЧИСТЫЙ, "стоп": ["аппарат под корпоративным надзором (MDM) — перепродать нельзя"]},
     "Присутствует дефект", True),
    ("норма", {**ЧИСТЫЙ, "паника": {"panic_full": True}}, "Присутствует дефект", True),
    ("норма", {**ЧИСТЫЙ, "детали_вердикт": {"итог": "неполно"}}, "Не был в ремонте", False),  # нет данных ≠ вердикт
    ("ремонт", ЧИСТЫЙ, "Ранее был в ремонте", False),             # сотрудник видел глазами — кабель не спорит
    ("дефект", ЧИСТЫЙ, "Присутствует дефект", False),
    ("новый", {}, "Прочее", False),
    ("чушь", ЧИСТЫЙ, None, False),
])
def test_cable_reclassifies_only_the_normal_used_phone(состояние, rep, ждём, причина_есть):
    """Автоцену Оценка даёт только при «Не был в ремонте», поэтому «б/у в норме» обязан
    пройти кабель: замена → ремонт, другой стоп → дефект. Остальные кнопки кабель не меняет."""
    статус, почему = ocenka.переклассифицировать(состояние, rep)
    assert статус == ждём and bool(почему) == причина_есть


def test_reclassification_names_the_channel_and_the_part():
    """Оценщик сверяет причину с экраном телефона: «по кабелю: Экран — …», а не безликое
    «по данным Apple»."""
    _, почему = ocenka.переклассифицировать("норма", ЗАМЕНА)
    assert "по кабелю" in почему and "Экран" in почему
    _, почему = ocenka.переклассифицировать("норма", {**ЧИСТЫЙ, "батарея": {"подделка": ["заявляет 3614 мА·ч"]}})
    assert почему.startswith("по кабелю: аккумулятор")


def test_payload_carries_state_reclassification_and_registry_for_the_card():
    """Карточка в группе печатает то, что уйдёт в сделку, — и то, что сотрудник выбрал,
    и что с этим сделал кабель, и что сказал реестр. Бот эти ключи не читает."""
    рфс = [{"imei": "350585886690250", "verdict": "verified", "ok": True, "deadline": None},
           {"imei": "350585881725184", "verdict": "not_verified", "ok": True, "deadline": "31.12.2026"}]
    данные = {"модель": "iPhone 14 Pro", "память": 256, "имя_клиента": "Зама", "акб": 86,
              "телефон_клиента": "+77058837953", "imei": "350585886690250",
              "состояние": "норма", "переклассификация": "по кабелю: Экран — не привязан",
              "статус_ремонта": "Ранее был в ремонте", "рфс": рфс}
    п = ocenka.посылка(данные, "7KQ4M")
    assert п["состояние"] == "📱 Б/у телефон в нормальном состоянии"
    assert п["переклассификация"].startswith("по кабелю")
    assert п["сделка"]["phone_status"] == "Ранее был в ремонте"
    assert п["рфс"][1] == {"imei": "350585881725184", "вердикт": "not_verified",
                          "статус": "не верифицирован (временный доступ до 31.12.2026)"}
    assert "состояние" not in ocenka.посылка({**данные, "состояние": None, "рфс": None}, "7KQ4M")


def test_locks_include_a_blocked_imei_but_not_an_unverified_one():
    """Блокировка в реестре — замок. Не верифицирован — не замок, а срок: он идёт отдельной
    строкой в карточке и комментарии."""
    заблок = {"imei": "350585886690250", "verdict": "blocked", "ok": True}
    невер = {"imei": "350585881725184", "verdict": "not_verified", "ok": True, "deadline": "31.12.2026"}
    assert ocenka.замки({"рфс": [заблок, невер]}) == ["РФС: 350585886690250 ЗАБЛОКИРОВАН"]
    txt = ocenka.комментарий_оценщика({"рфс": [заблок, невер]}, состояние="📱 Б/у", почему="по кабелю: Экран")
    assert txt.startswith("Состояние: 📱 Б/у → изменено: по кабелю: Экран")
    assert "РФС: 350585886690250 — ЗАБЛОКИРОВАН; 350585881725184 — не верифицирован (временный доступ до 31.12.2026)" in txt


