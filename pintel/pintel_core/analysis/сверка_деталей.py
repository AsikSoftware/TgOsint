# -*- coding: utf-8 -*-
"""Сверка деталей с экрана телефона: спрашиваем сотрудника по КАЖДОЙ детали.

Владелец, 24.11.2026: «не прочитанные по деталям с открытого раздела спрашивать по каждой
детали — один большой блок на передний план, пока не ответит, не пройдёт».

Зачем именно так. Подлинность деталей подтверждает только Apple и только с экрана телефона:
по кабелю её не отдаёт никто, а в журнал телефон пишет вердикт не на всех iOS. На 659
эталонах с точек подтверждения Apple нет у 16% аппаратов, и почти все они — iPhone на
iOS 16 и 17, где раздел открыт, а вердикта в журнале нет вовсе. Такой телефон уходил в
отчёт со строкой «подлинность деталей не подтверждена» — то есть проверка заканчивалась
ничем, хотя ответ был на экране, в руках у сотрудника.

Спрашиваем ТОЛЬКО то, на что ответа нет. Деталь, по которой Apple уже высказалась (журнал,
сверка с печатью, проверка подлинности), сотруднику не показывается: лишний вопрос — это
способ получить случайный ответ.

Ответ сотрудника — это слова Apple, прочитанные человеком, поэтому он и закрывает дыру, и
ложится в эталон как правда, по которой потом проверяется наш разбор. Ошибиться он может,
и поэтому ответ НЕ отменяет то, что нашёл кабель: «замена» по привязке модулей останется
заменой, даже если на экране написано «оригинальная».
"""
from .capabilities import has_face_id
from .parts import APPLE_PART_ORDER, APPLE_STATES

# Что бывает написано напротив детали, в порядке частоты на живых аппаратах. Первым —
# «в списке нет»: у чистого телефона раздел пуст, и это самый частый ответ.
ОТВЕТЫ = ("absent", "genuine", "unknown", "used", "serviced", "unverified", "finish")


def _пас(rep):
    return (rep or {}).get("паспорт") or {}


def спрашивать_ли(rep) -> bool:
    """Нужна ли сверка этому аппарату вообще."""
    rep = rep or {}
    if rep.get("запечатанный") or (rep.get("sickw") or {}).get("запечатанный"):
        return False                                   # коробку не вскрывали
    if rep.get("apple_история_статус") == "не поддерживается":
        return False                                   # у модели раздела нет вовсе
    return bool(детали(rep))


def детали(rep) -> list:
    """По каким деталям ответа нет. → [(ключ, имя)] в порядке таблицы Apple.

    Деталь считается отвеченной, если про неё сказала сама Apple: запись в журнале,
    сверка с заводской печатью или проверка подлинности компонентов."""
    rep = rep or {}
    если_сказала = set(rep.get("apple_история") or {})
    комп = ((rep.get("качество_чтения") or {}).get("компоненты")
            or (rep.get("apple_компоненты") or {}))
    если_сказала |= {k for k, v in (комп.get("доверие") or {}).items()
                     if isinstance(v, dict) and "AuthPassed" in v}
    face = has_face_id(_пас(rep).get("код_модели"))
    out = []
    for ключ, имя in APPLE_PART_ORDER:
        if ключ in если_сказала:
            continue
        if ключ == "FaceID" and face is False:
            continue                                   # у этой модели его нет
        out.append((ключ, имя))
    return out


def не_отвечено(rep, ответы) -> list:
    """Чего сотрудник ещё не отметил. Пусто — сверка закончена."""
    ответы = {k: v for k, v in (ответы or {}).items() if v in APPLE_STATES}
    return [(к, и) for к, и in детали(rep) if к not in ответы]


def закончена(rep, ответы) -> bool:
    return not не_отвечено(rep, ответы)


def вердикты(ответы) -> dict:
    """Ответы сотрудника → {деталь: (статус, словами)} для вердикта по деталям.

    «В списке нет» статуса не даёт: Apple про эту деталь ничего не пишет, и сам по себе
    это не зелёный — зелёный складывается из него и чистого кабеля."""
    out = {}
    for ключ, ответ in (ответы or {}).items():
        если = APPLE_STATES.get(ответ)
        if если is None:
            continue
        название, _подсказка, статус = если
        if статус:
            out[ключ] = (статус, f"сотрудник сверил с экраном телефона: {название.lower()}")
    return out


def словами(rep, ответы) -> str:
    """Строка для отчёта и карточки: что сотрудник увидел на экране телефона."""
    ответы = {k: v for k, v in (ответы or {}).items() if v in APPLE_STATES}
    if not ответы:
        return ""
    имена = dict(APPLE_PART_ORDER)
    плохие = [f"{имена.get(к, к)} — {APPLE_STATES[о][0].lower()}"
              for к, о in ответы.items() if APPLE_STATES[о][2] in ("bad", "used", "repaired")]
    if плохие:
        return "сотрудник сверил с экраном телефона: " + "; ".join(плохие)
    return (f"сотрудник сверил с экраном телефона: {len(ответы)} деталей, "
            "замен и ремонтов Apple не показывает")
