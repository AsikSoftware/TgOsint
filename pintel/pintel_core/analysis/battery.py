# -*- coding: utf-8 -*-
"""Батарея из узла AppleSmartBattery.

**Процент здоровья телефон называет сам.** `powerd` печатает его в журнал каждые 10–20
секунд строкой «Updated battery health (… maxCap=79 cycleCount=1064)», без всяких открытых
экранов, и это ровно то число, что стоит в «Максимальной ёмкости» (сверено на живых
аппаратах 11.11.2026). Его и берём — приходит оно из слушателя журнала (`repair_history`).

Считать самим приходится, только когда телефон за время проверки своего числа не назвал.
Тогда берём минимальную за жизнь ёмкость (NCCMin), а не текущую NominalChargeCapacity: она
ближе к экрану (на живых аппаратах экран 77 против наших 79 и 69 против 72, NCCMin давал 77
и 68). Где NCCMin не отдают — а iOS 27 его не отдаёт вовсе — остаётся расчёт по текущей
ёмкости, и он завышает на процент-два. Поэтому отчёт всегда говорит, откуда взято число.

MaxCapacity — НЕ процент здоровья, а константа шкалы (100 даже на убитой батарее).
В новых iOS (26/27) ёмкости переехали во вложенный словарь BatteryData — deep() достаёт их
на любой глубине.
"""
from ..devicelink.nodes import deep, num, txt

# Отпечаток батареи по модели: заводская ёмкость одна на модель
# (iPhone13,2 = 2798, а не рекламные 2815).
# Порог подделки 1.03 обоснован сверкой с вердиктом Apple на шести аппаратах.


def analyze(node, телефон=None):
    """`телефон` — что сказал сам аппарат (meta слушателя, ключ «батарея_телефона»)."""
    b = node or {}
    design = num(deep(b, "DesignCapacity"))
    nominal = num(deep(b, "NominalChargeCapacity")) or num(deep(b, "AppleRawMaxCapacity"))
    # Минимум за жизнь: лежит в BatteryData.LifetimeData, у разных iOS на разной глубине.
    минимум = num(deep(b, "NCCMin"))
    сырые_циклы = deep(b, "CycleCount")
    cycles = num(сырые_циклы)
    op_h = num(deep(b, "TotalOperatingTime"))
    tmax = num(deep(b, "MaximumTemperature")) // 10
    serial = txt(deep(b, "Serial"))
    disconnects = num(deep(b, "BatteryCellDisconnectCount"))
    health = текущее = None
    основание = ""
    if design and nominal:
        текущее = min(round(nominal * 100 / design), 100)
        # NCCMin берём только когда он действительно минимум и в разумных пределах: на одном
        # аппарате он пришёл больше заводской ёмкости, и доверять ему вслепую нельзя.
        по_экрану = минимум if (минимум and 0.4 * design <= минимум <= nominal) else None
        health = min(round((по_экрану or nominal) * 100 / design), 100)
        основание = "минимум за жизнь" if по_экрану else "текущая ёмкость (завышает)"

    # Что сказал сам телефон — главнее всего, что мы можем посчитать.
    сам = (телефон or {}).get("процент")
    if isinstance(сам, int) and 1 <= сам <= 200:
        health = min(сам, 100)                   # выше ста телефон и сам не рисует
        основание = "сказал сам телефон"

    flags, doubts = [], []
    if design and nominal:
        r = nominal / design
        if r > 1.08:
            flags.append(f"заявляет {nominal} мА·ч при заводских {design} (+{(r-1)*100:.0f}%) — для родной физически невозможно")
        elif r > 1.03:
            flags.append(f"заявляет {nominal} мА·ч при заводских {design} (+{(r-1)*100:.0f}%) — выше заводской, у родной так не бывает")
        elif r < 0.45:
            flags.append(f"заявляет {nominal} мА·ч при заводских {design} — ниже рабочего предела")
    years = round(op_h / 8760, 1) if op_h else None
    if сырые_циклы is not None and cycles == 0 and years and years > 0.25:
        flags.append(f"ноль циклов при наработке {years} года — пак новее аппарата")
    if disconnects:
        doubts.append(f"шлейф батареи снимали {disconnects} раз(а) — аппарат вскрывали")
    циклы_телефона = (телефон or {}).get("циклы")
    if циклы_телефона and cycles and abs(циклы_телефона - cycles) > 5:
        # Узел и журнал читаются из одного места, и разойтись им не с чего. Разошлись —
        # значит одно из чтений протухло, и молчать об этом нельзя: по циклам идёт самая
        # дорогая колонка прайса.
        doubts.append(f"циклы расходятся: по узлу {cycles}, телефон говорит {циклы_телефона}")

    return {
        # «Есть данные» — это есть ЦИФРЫ, а не «узел не пустой». Узел без DesignCapacity и
        # NominalChargeCapacity (так бывает, когда Apple переносит ключи, и так было в iOS 26)
        # не даёт ни здоровья, ни проверки на подделку — значит батарея не прочитана, и отчёт
        # обязан сказать это, а не молча объявить ёмкость «в норме заводской».
        "есть_данные": bool(design and nominal),
        "узел_есть": bool(b),
        "здоровье_%": health,
        # По какой ёмкости посчитали и что дала бы текущая: если на точке скажут, что число
        # опять расходится с экраном телефона, разбирать это надо по сохранённой оценке, а не
        # на словах.
        "здоровье_основание": основание,
        # Что телефон сказал сам и что вышло бы у нас — рядом: по ним разбирают спор у
        # стойки, не гадая, какое число откуда.
        "здоровье_по_телефону_%": (телефон or {}).get("процент"),
        "обслуживание_флаг": (телефон or {}).get("состояние"),
        "здоровье_текущее_%": текущее,
        "минимум_мАч": минимум or None,
        "ёмкость_мАч": nominal or None,
        "заводская_мАч": design or None,
        # ноль циклов — самая дорогая колонка прайса Оценки («100 (0-30)»). Отсутствие
        # ключа ею быть не должно.
        "циклы": cycles if сырые_циклы is not None else None,
        "наработка_лет": years,
        "макс_температура": tmax if 0 < tmax <= 90 else None,
        "серийник": serial,
        "снятий_шлейфа": disconnects,
        "заряд_%": num(deep(b, "CurrentCapacity")) or None,
        "подделка": flags,
        "сомнения": doubts,
    }
