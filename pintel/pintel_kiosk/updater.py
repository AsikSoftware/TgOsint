# -*- coding: utf-8 -*-
"""Обновление программы по интернету: ездить по точкам с флешкой никто не станет.

Сборки уже лежат в релизах GitHub — туда их кладёт сама сборка. Программа спрашивает у
GitHub последний релиз, сравнивает его тег со своим и, если он другой, скачивает архив,
распаковывает рядом и подменяет папку.

Подменить работающий exe на месте Windows не даёт, поэтому замену делает маленький .cmd:
он ждёт, пока программа закроется, переносит новую папку поверх старой и запускает её
снова. Старая версия при этом остаётся рядом — если новая не поднимется, откатиться
можно руками, ничего не потеряв.

На маке то же самое делает .sh, и отличий два. Программа на маке — это весь .app, а не
папка с exe: подменять надо его целиком. И ждать закрытия приходится по номеру процесса, а
не по имени: имя на маке совпадает со чем угодно, а номер принадлежит ровно той программе,
которая запросила обновление. Архив в релизе у каждой системы свой, и выбирает его сама
программа (`архив_этой_системы`) — windows-сборку маку не поставить.

Обновление ставится САМО: программа спрашивает GitHub каждые 15 минут и, найдя новую
сборку, больше не берёт новую работу, а подменяется в первую же свободную минуту — ждать
перезапуска или нажатия кнопки нельзя, на точке касса работает неделями без перезапуска, и
так исправленная ошибка жила на части точек (владелец, 25.11.2026). Посреди сделки подмена
не делается: телефон клиента уже на кабеле. Кнопка на экране ожидания осталась на один
случай — обновление сорвалось, и сотрудник повторяет его руками.
"""
from __future__ import annotations

import json
import logging
import os
import re
import shutil
import subprocess
import sys
import zipfile

from . import __version__

log = logging.getLogger("pintel.update")

API = "https://api.github.com"
ТЕГ_ФАЙЛ = "build_info.json"          # кладёт сборка: из какого релиза собран этот exe


def архив_этой_системы(из_настроек: str = "") -> str:
    """Имя архива в релизе для ЭТОЙ машины.

    Касс теперь две породы — Windows и мак, — а настройка на сервере одна на все точки.
    Поставить маку windows-архив нельзя, поэтому имя выбирает сама программа, а настройка
    остаётся только для случая, которого мы не предусмотрели.

    Мак на старом процессоре Intel своей сборки пока не имеет: он попросит её по имени, не
    найдёт в релизе и честно напишет в журнал «в релизе нет нужного архива» — работать это
    не мешает, а появится нужда, добавим ещё одну работу сборки."""
    if sys.platform == "win32":
        return "pintel-kiosk_Windows_x64.zip"
    if sys.platform == "darwin":
        import platform
        машина = "arm64" if platform.machine() in ("arm64", "aarch64") else "x86_64"
        return f"pintel-kiosk_macOS_{машина}.zip"
    return из_настроек or ""


def папка_программы(рядом_с_exe: str) -> str:
    """Что именно подменяет обновление.

    На Windows программа — это папка с exe. На маке программа — это весь .app, а exe лежит
    внутри него (Contents/MacOS): подменить только внутреннюю папку значит оставить
    половину прошлой версии и сломать саму программу."""
    if sys.platform != "darwin":
        return рядом_с_exe
    часть = рядом_с_exe.rstrip("/")
    while часть and часть != os.path.dirname(часть):
        if часть.endswith(".app"):
            return часть
        часть = os.path.dirname(часть)
    return рядом_с_exe


def свой_тег() -> str:
    """Тег релиза, из которого собрана эта программа. Пусто — запущено из исходников."""
    for папка in (os.path.dirname(os.path.abspath(sys.executable if getattr(sys, "frozen", False)
                                                  else __file__)),
                  os.path.dirname(os.path.abspath(__file__))):
        путь = os.path.join(папка, ТЕГ_ФАЙЛ)
        if os.path.isfile(путь):
            try:
                with open(путь, encoding="utf-8-sig") as f:   # на Windows бывает BOM
                    return str(json.load(f).get("тег") or "")
            except Exception:                                    # noqa: BLE001
                return ""
    return ""


def _номер(тег: str):
    """«doctor-48» → 48. Не наш формат → None."""
    м = re.fullmatch(r"[A-Za-z._-]*?(\d+)", (тег or "").strip())
    return int(м.group(1)) if м else None


def разобрать_релиз(релиз: dict, имя_архива: str, свой: str) -> dict:
    """Ответ GitHub → что с ним делать. Отдельно от сети, чтобы проверялось тестами."""
    тег = str((релиз or {}).get("tag_name") or "")
    активы = [a for a in ((релиз or {}).get("assets") or [])
              if str(a.get("name") or "") == имя_архива]
    if not тег or not активы:
        return {"есть": False, "тег": тег, "почему": "в релизе нет нужного архива"}
    if not свой:
        # запущено из исходников или сборка без метки — сами не обновляемся
        return {"есть": False, "тег": тег, "почему": "сборка без метки релиза"}
    if тег == свой:
        return {"есть": False, "тег": тег, "почему": "уже последняя"}
    # Только ВПЕРЁД. Если плохой релиз удалить (обычный способ откатиться), GitHub отдаст
    # в «latest» предыдущий — и касса на точке молча съехала бы на старую сборку, да ещё
    # и предлагала бы это снова и снова. Поэтому сравниваем номера, а не просто теги.
    нов, стар = _номер(тег), _номер(свой)
    if нов is None or стар is None:
        return {"есть": False, "тег": тег,
                "почему": f"тег релиза «{тег}» не сравнить с «{свой}» — обновите вручную"}
    if нов <= стар:
        return {"есть": False, "тег": тег,
                "почему": f"на точке сборка свежее релиза ({свой} против {тег})"}
    актив = активы[0]
    return {"есть": True, "тег": тег, "почему": "",
            "url": актив.get("url"), "размер": int(актив.get("size") or 0),
            "имя": актив.get("name"), "описание": str((релиз or {}).get("name") or тег)}


def проверить(репозиторий: str, токен: str, имя_архива: str, свой: str = "",
              таймаут: float = 20.0) -> dict:
    """Спросить у GitHub последний релиз. Сети нет — просто «нет обновления»."""
    import httpx
    if not репозиторий:
        return {"есть": False, "почему": "обновление не настроено"}
    # Токен нужен только закрытому репозиторию. Точка без токена в настройках молча не
    # обновлялась никогда — а релизы лежат на виду, и спросить их можно без ключа.
    заголовки = {"Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28"}
    if токен:
        заголовки["Authorization"] = f"Bearer {токен}"
    try:
        r = httpx.get(f"{API}/repos/{репозиторий}/releases/latest", headers=заголовки,
                      timeout=таймаут)
        if r.status_code >= 400:
            return {"есть": False, "почему": f"GitHub ответил {r.status_code}"}
        релиз = r.json()
    except Exception as exc:                                     # noqa: BLE001
        return {"есть": False, "почему": f"нет связи: {type(exc).__name__}"}
    return разобрать_релиз(релиз, имя_архива, свой or свой_тег())


def скачать(url: str, токен: str, куда: str, таймаут: float = 600.0) -> str:
    """Архив релиза → файл на диске. → путь."""
    import httpx
    os.makedirs(os.path.dirname(куда), exist_ok=True)
    временный = куда + ".part"
    заголовки = {"Accept": "application/octet-stream"}
    if токен:
        заголовки["Authorization"] = f"Bearer {токен}"
    with httpx.stream("GET", url, headers=заголовки, timeout=таймаут,
                      follow_redirects=True) as r:
        r.raise_for_status()
        with open(временный, "wb") as f:
            for кусок in r.iter_bytes(1 << 20):
                f.write(кусок)
    os.replace(временный, куда)
    return куда


def распаковать(архив: str, куда: str) -> str:
    """Архив → папка с программой. → путь к папке, в которой лежит exe."""
    if os.path.isdir(куда):
        shutil.rmtree(куда, ignore_errors=True)
    os.makedirs(куда, exist_ok=True)
    with zipfile.ZipFile(архив) as z:
        for имя in z.namelist():                                 # не даём архиву вылезти из папки
            цель = os.path.normpath(os.path.join(куда, имя))
            if not цель.startswith(os.path.normpath(куда)):
                raise RuntimeError(f"архив пытается записать мимо папки: {имя}")
        if sys.platform == "darwin":
            # На маке распаковываем ditto, а не питоном. Внутри .app есть ссылки (в рамках Qt
            # это Versions/Current) и право на запуск у самой программы — `zipfile` теряет и
            # то, и другое: ссылки становятся текстовыми файлами, программа перестаёт быть
            # исполняемой, и касса после первого же самообновления не запускается вовсе.
            # Поймано на живой машине 26.11.2026: обновилась и умерла.
            subprocess.check_call(["/usr/bin/ditto", "-x", "-k", архив, куда])
        else:
            z.extractall(куда)
    if sys.platform == "darwin":
        for корень, папки, _файлы in os.walk(куда):
            for имя in sorted(папки):
                if имя.endswith(".app"):
                    return os.path.join(корень, имя)
        raise RuntimeError("в архиве нет программы для мака (.app)")
    for корень, _, файлы in os.walk(куда):
        if any(f.lower() == "pintel-kiosk.exe" for f in файлы):
            return корень
    raise RuntimeError("в архиве нет pintel-kiosk.exe")


def перенести_своё(установлена: str, новая: str) -> list:
    """Что на точке положили рядом с exe — в новую папку, до подмены.

    Подмена уносит старую папку целиком. Токен точки и настройки обновления не боятся —
    они лежат рядом с данными, — но на точке могли положить сюда что-то своё.

    Правило простое и не требует списка имён: всё, чего в новой сборке НЕТ, — это чужое,
    положенное на точке, и оно переезжает. Берём только файлы рядом с exe: внутрь
    _internal не лезем, иначе обновление тащило бы за собой библиотеки от прошлой версии.
    → имена перенесённого."""
    перенесли = []
    if sys.platform == "darwin":
        # Внутрь .app на точке ничего не кладут, да и нельзя: подпись программы это ломает.
        # Токен точки и настройки лежат в папке данных, а её обновление не трогает.
        return перенесли
    if not (os.path.isdir(установлена) and os.path.isdir(новая)):
        return перенесли
    for имя in sorted(os.listdir(установлена)):
        откуда = os.path.join(установлена, имя)
        куда = os.path.join(новая, имя)
        if not os.path.isfile(откуда) or os.path.exists(куда):
            continue
        try:
            shutil.copy2(откуда, куда)
            перенесли.append(имя)
        except OSError as exc:
            log.warning("обновление: не перенёс %s (%s)", имя, exc)
    if перенесли:
        log.info("обновление: перенесены настройки точки: %s", ", ".join(перенесли))
    return перенесли


def сценарий(новая: str, установлена: str, exe: str) -> str:
    """Текст .cmd, который подменяет папку, пока программа закрыта.

    robocopy /MIR переносит новую папку поверх старой; старая уезжает в .bak рядом —
    если новая версия не поднимется, вернуть прежнюю можно руками.
    """
    резерв = установлена.rstrip("\\/") + ".bak"
    return (
        "@echo off\r\n"
        "chcp 65001 >nul\r\n"
        "echo Обновление Pintel Diagnostics...\r\n"
        ":ожидание\r\n"
        "timeout /t 2 /nobreak >nul\r\n"
        f'tasklist /fi "imagename eq {os.path.basename(exe)}" | find /i "{os.path.basename(exe)}" >nul '
        "&& goto ожидание\r\n"
        f'if exist "{резерв}" rmdir /s /q "{резерв}"\r\n'
        f'robocopy "{установлена}" "{резерв}" /E /MOVE /NFL /NDL /NJH /NJS /NC /NS >nul\r\n'
        f'robocopy "{новая}" "{установлена}" /E /NFL /NDL /NJH /NJS /NC /NS >nul\r\n'
        f'if not exist "{exe}" robocopy "{резерв}" "{установлена}" /E /MOVE /NFL /NDL /NJH /NJS '
        "/NC /NS >nul\r\n"
        f'start "" "{exe}"\r\n'
    )


def сценарий_мак(новая: str, установлена: str, pid: int) -> str:
    """Текст .sh, который подменяет .app, пока программа закрыта.

    Ждём не по имени процесса, а по его номеру: имя может совпасть с чем угодно, а номер
    принадлежит ровно той программе, которая запросила обновление.

    Старая программа уезжает в .bak рядом — не поднялась новая, вернуть прежнюю можно
    руками, ничего не потеряв. Обратно программу запускает `open`: так мак запускает её
    как настоящую программу, со своим значком и без окна терминала.
    """
    резерв = установлена.rstrip("/") + ".bak"
    # Программа внутри .app: по ней и проверяем, что подмена удалась. Проверять «папка на
    # месте» мало — папка остаётся и от испорченной сборки, а запускать нечего.
    внутри = os.path.join(установлена, "Contents", "MacOS",
                          os.path.basename(установлена.rstrip("/"))[:-len(".app")]
                          if установлена.rstrip("/").endswith(".app")
                          else "pintel-kiosk")
    return (
        "#!/bin/sh\n"
        "# Подмена программы Pintel: запущено самой кассой, закрывать не нужно\n"
        f"while kill -0 {int(pid)} 2>/dev/null; do sleep 1; done\n"
        "sleep 1\n"
        f'rm -rf "{резерв}"\n'
        f'mv "{установлена}" "{резерв}" 2>/dev/null\n'
        f'cp -R "{новая}" "{установлена}"\n'
        f'xattr -dr com.apple.quarantine "{установлена}" 2>/dev/null\n'
        f'if [ ! -x "{внутри}" ]; then\n'
        f'  rm -rf "{установлена}"\n'
        f'  mv "{резерв}" "{установлена}"\n'
        "fi\n"
        f'open "{установлена}"\n'
    )


def применить(новая: str, установлена: str, exe: str, папка_сценария: str) -> str:
    """Запустить подмену и вернуть путь к сценарию. Программу после этого надо закрыть."""
    os.makedirs(папка_сценария, exist_ok=True)
    if sys.platform == "darwin":
        путь = os.path.join(папка_сценария, "обновить.sh")
        with open(путь, "w", encoding="utf-8") as f:
            f.write(сценарий_мак(новая, установлена, os.getpid()))
        os.chmod(путь, 0o755)
        # start_new_session: сценарий переживает закрытие программы. Без этого мак убьёт его
        # вместе с той, которая его запустила, — и обновление не состоится вовсе.
        subprocess.Popen(["/bin/sh", путь], close_fds=True, start_new_session=True)
        return путь
    путь = os.path.join(папка_сценария, "обновить.cmd")
    with open(путь, "w", encoding="utf-8") as f:
        f.write(сценарий(новая, установлена, exe))
    if sys.platform == "win32":
        subprocess.Popen(["cmd", "/c", путь], close_fds=True,
                         creationflags=getattr(subprocess, "CREATE_NEW_CONSOLE", 0))
    else:                                    # на Linux сценарий только пишется — проверить им нечего
        log.info("обновление: сценарий готов, но подмена — только под Windows: %s", путь)
    return путь


def версия_словами(тег: str = "") -> str:
    номер = re.sub(r"\D", "", тег or "")
    return f"{__version__} (сборка {номер})" if номер else __version__
