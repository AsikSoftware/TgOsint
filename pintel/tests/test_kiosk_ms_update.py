def _проверки_сделаны(окно, нажать=True):
    """Пройти тест, отметить все восемь пунктов и сказать «Проверки закончены».

    Проверки в режиме обновления обязательные (18.11.2026): запись заменяет поля целиком, и
    пропуск проверок означал бы не освежение данных, а их стирание. Третий шаг при этом
    открывает САМ сотрудник кнопкой (24.11.2026) — восьмая отметка его не открывает."""
    from pintel_core import phonetest
    from pintel_core.external import ocenka_media
    окно.s_ms.set_тест({к: phonetest.ОК for к in phonetest.КЛЮЧИ})
    for ключ in ocenka_media.КЛЮЧИ:
        окно.s_ms.отметить(ключ)
    if нажать:
        окно.s_ms.b_проверки.click()


def test_the_same_phone_can_be_read_again_without_unplugging(окно):
    """Кнопка «Заново»: тот же аппарат читается с начала, кабель не трогают.

    Отдельная кнопка нужна потому, что «Следующий телефон» ждёт отключения кабеля, а после
    третьего шага отметки заперты — поправить их можно только перечитав телефон."""
    from pintel_kiosk import ui_update
    _до_телефона(окно)
    _прочитан(окно)
    _проверки_сделаны(окно)
    _ответ(окно)
    assert окно.s_ms.состояние == "найден" and окно._мс_этап == ui_update.ЭТАП_ИЗМЕНЕНИЯ
    было_чтений = len(окно.читали)

    # пока запись уходит в МойСклад, перечитывать нельзя: карточка в этот момент меняется
    окно._мс_что, окно._мс_запрос = ms_update.ЗАПИСАТЬ, "в-полёте"
    окно.s_ms.b_заново.click()
    assert len(окно.читали) == было_чтений, "перечитали телефон посреди записи"
    окно._мс_что, окно._мс_запрос = "", ""

    окно.s_ms.b_заново.click()
    assert len(окно.читали) == было_чтений + 1, "телефон не стали читать заново"
    # чтение началось сразу, отключать кабель никто не просил (это и есть «Заново»)
    assert окно.state == "ms_scan" and окно._мс_этап == ui_update.ЭТАП_ДИАГНОСТИКА
    assert окно._мс_товар == {} and окно.s_ms.ручная == {} and окно.s_ms.тест == {}


def test_the_last_mark_does_not_create_the_certificate_by_itself(окно):
    """Заключение создаёт сотрудник, а не восьмая отметка.

    Владелец, 24.11.2026: «человек не успевает последний блок поставить отказ — уже сразу
    формируется заключение». Так и было: последняя отметка открывала третий шаг в ту же
    секунду, и поправить ответ было нельзя — сертификат уже ушёл на сервер с прежним.
    Отметка переключается ⬜ → ✅ → ❌, то есть промахнуться на ней — обычное дело."""
    from pintel_core.external import ocenka_media
    from pintel_kiosk import ui_update
    _до_телефона(окно)
    _прочитан(окно)
    _проверки_сделаны(окно, нажать=False)
    assert окно.запросы == [] and окно.заливки == [], "заключение создалось само, без кнопки"
    assert окно._мс_этап == ui_update.ЭТАП_ПРОВЕРКИ
    assert окно.s_ms.b_проверки.isEnabled(), "кнопка перехода не ожила, хотя всё отмечено"

    # сотрудник передумал по последнему пункту — и это ещё можно
    последний = ocenka_media.КЛЮЧИ[-1]
    окно.s_ms.отметить(последний)
    assert окно.s_ms.ручная.get(последний) is False, "отказ по последнему пункту не поставился"
    assert окно.запросы == [] and окно._мс_этап == ui_update.ЭТАП_ПРОВЕРКИ

    окно.s_ms.b_проверки.click()
    assert окно._мс_этап == ui_update.ЭТАП_ИЗМЕНЕНИЯ
    assert окно.заливки and окно.заливки[-1]["report"]["ручная_диагностика"][последний] is False, \
        "в заключение уехал прежний ответ, а не исправленный"


def test_the_product_is_looked_up_while_the_phone_is_still_being_read(окно):
    """Товар в МойСкладе ищется параллельно диагностике и проверкам.

    Владелец, 24.11.2026: «пусть пока читается телефон, проходится диагностика, тесты —
    софт параллельно чекает МойСклад». IMEI известен через секунды, а диагностика идёт ещё
    около минуты: журнал Apple, база IMEI, реестр. Выигрыш не только во времени — если
    карточки по этому IMEI нет или их две, сотрудник узнаёт это сразу, а не после трёх
    минут проверок. Сам блок товара при этом закрыт: «станет» без теста и отметок считать
    нельзя (решение владельца 19.11.2026)."""
    from pintel_kiosk import ui_update
    _до_телефона(окно)
    окно.on_tick("READY", "", 1)
    assert окно.state == "ms_scan"

    окно._мс_паспорт(_отчёт())                       # поток проверки: паспорт готов, IMEI есть
    assert len(окно.запросы) == 1 and окно.запросы[0]["мойсклад"] == {"что": "найти"}
    assert "Ищем товар" in окно.s_ms.товар_занавес.text()
    assert окно._мс_этап == ui_update.ЭТАП_ДИАГНОСТИКА

    _ответ(окно)
    assert окно._мс_товар.get("код") == "40117"
    assert "Товар найден: 40117" in окно.s_ms.товар_занавес.text()
    assert окно.s_ms.состояние != "найден", "блок товара открылся раньше третьего шага"

    # дальше обычный порядок: телефон дочитан, проверки, кнопка — и только теперь заключение
    _прочитан(окно)
    _проверки_сделаны(окно)
    assert len(окно.запросы) == 2, "после проверок товар не спросили заново"
    assert окно.запросы[1]["поля"]["ссылка_чека"] == ССЫЛКА
    # и товар во втором вопросе уже назван: искать его заново боту не надо
    assert окно.запросы[1]["мойсклад"] == {"что": "найти", "товар": "t-1"}


