# -*- coding: utf-8 -*-
"""Что уже дошло в бота по коду обмена: фото, видео, ручная диагностика.

Зачем это серверу. Программа на точке показывает QR, сотрудник шлёт боту фото и видео, и
до этой версии касса не знала о них ничего: кнопка «Отправить в Оценку» нажималась и без
медиа, а отказ прилетал позже, уже от бота, когда карточка висела в рабочей группе. Теперь
касса спрашивает сервер, а сервер смотрит в базу Оценки — он стоит на том же VPS и уже
читает её (магазины, импорт оценок).

Наружу отдаём только счётчики и названия непройденных пунктов: `file_id` медиа, чат и
сотрудник остаются в базе Оценки. Строки по коду ещё нет (сотрудник не открывал ссылку) —
это не ошибка, а «ничего не прислали».
"""
from __future__ import annotations

import json
import logging
import re

from sqlalchemy import text

from pintel_core.external import ocenka_media as общее

log = logging.getLogger("pintel.ocenka")

КОД = re.compile(r"^[A-Za-z0-9]{4,16}$")


def _отметки(сырое) -> dict:
    """Колонка `checks` → словарь. Непонятное — пустой словарь: это наши же данные, но
    полежавшие в базе между версиями обработчика."""
    if isinstance(сырое, (bytes, bytearray)):
        сырое = bytes(сырое).decode("utf-8", "replace")
    if isinstance(сырое, str):
        try:
            сырое = json.loads(сырое or "{}")
        except Exception:                                        # noqa: BLE001
            return {}
    return сырое if isinstance(сырое, dict) else {}


def состояние(код: str) -> dict:
    """Код обмена → что по нему уже есть у бота.

    `известно: False` значит ровно одно — сервер не смог посмотреть (связи с базой Оценки
    нет или она не настроена). Это не «медиа нет»: разницу обязана видеть и касса, иначе
    она либо остановит работу на ровном месте, либо назовёт собранным то, чего не видела.
    """
    код = str(код or "").strip()
    if not КОД.match(код):
        return {"известно": False, "почему": "код обмена не похож на код"}
    from .ocenka_import import _ocenka_engine
    try:
        движок = _ocenka_engine()
        with движок.connect() as conn:
            строка = conn.execute(text(
                "SELECT photos, video, checks, done, device_id FROM kiosk_media "
                "WHERE code = :c"), {"c": код}).mappings().first()
    except Exception as exc:                                     # noqa: BLE001 — молчать нельзя
        log.warning("медиа %s: базу Оценки не спросить: %s", код, exc)
        return {"известно": False, "почему": "касса не видит базу Оценки"}
    if строка is None:
        # Строку заводит сам бот, когда сотрудник открывает ссылку из QR. Её нет — значит
        # ссылку ещё не открывали, и это нормальное начало сделки, а не сбой.
        return {"известно": True, "начали": False, "фото": 0, "видео": False,
                "не_отмечено": list(общее.не_отмечено({})), "готово": False, "сделка": None}
    фото = len([x for x in str(строка["photos"] or "").split("||") if x])
    отметки = _отметки(строка["checks"])
    не_отмечено = list(общее.не_отмечено(отметки))
    видео = bool(строка["video"])
    готово = фото >= общее.НУЖНО_ФОТО and видео and not не_отмечено
    return {"известно": True, "начали": True, "фото": фото, "видео": видео,
            "не_отмечено": не_отмечено, "готово": готово,
            "сделка": строка["device_id"]}
