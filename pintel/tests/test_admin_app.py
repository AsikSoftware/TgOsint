"""Административная программа: связь с сервером, хранение токена, экраны.

Главное, что здесь проверяется, — не кнопки, а два обещания:

* программа НИЧЕГО не считает сама. Число на экране владельца и число в выгрузке обязаны
  совпадать, а совпадают они только если считаются в одном месте — на сервере;
* пусто остаётся пустым. Ноль вместо «не знаем» на экране владельца это ложь, по которой
  принимают решения.
"""
import os
