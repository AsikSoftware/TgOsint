def _сохранить_csv(имя: str, колонки, строки) -> str:
    """Файл в «Загрузки». Разделитель — точка с запятой, кодировка с меткой: иначе Excel
    открывает кириллицу кракозябрами, и человек решает, что программа сломана."""
    import csv
    import os
    from datetime import datetime

    папка = os.path.expanduser("~/Downloads")
    os.makedirs(папка, exist_ok=True)
    путь = os.path.join(папка, f"pintel_{имя}_{datetime.now():%Y-%m-%d}.csv")
    with open(путь, "w", encoding="utf-8-sig", newline="") as f:
        писарь = csv.writer(f, delimiter=";")
        писарь.writerow(колонки)
        писарь.writerows(строки)
    return путь
