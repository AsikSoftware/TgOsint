    """То же, с настоящим доступом бота к МойСкладу. Блокирующее — звать из отдельного потока."""
    from utils import ms_auto_supply as мс

    session = мс._make_session(мс.settings.API_KEY_SKLAD)
    return выполнить(session, посылка, запрос=мс._ms_request, кэш=мс._cached,
                     dict_aliases=getattr(мс, "DICT_ALIASES", None))
