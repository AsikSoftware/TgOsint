def test_an_export_lands_in_downloads_as_a_readable_file(приложение, tmp_path, monkeypatch):
    """Выгрузка кладётся файлом, который Excel откроет без кракозябр."""
    from pintel_admin import app as модуль
    monkeypatch.setattr(os.path, "expanduser", lambda п: str(tmp_path) if п == "~/Downloads" else п)
    путь = модуль._сохранить_csv("люди", *модуль._csv_люди(
        [{"имя": "Данияр К.", "точка": "16/38", "роль_словами": "Кассир", "проверок_за_месяц": 187,
          "выкупов_за_месяц": 71, "выдано_за_месяц": 11_200_000, "доступ": True}]))
    содержимое = open(путь, encoding="utf-8-sig").read()
    assert "Данияр К." in содержимое and ";" in содержимое
    assert содержимое.startswith("имя;точка")
