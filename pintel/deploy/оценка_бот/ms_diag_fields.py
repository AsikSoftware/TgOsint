def ключ_из_env(путь):
    for строка in open(путь, encoding="utf-8"):
        строка = строка.strip()
        if строка.startswith("API_KEY_SKLAD"):
            return строка.split("=", 1)[1].strip().strip('"').strip("'")
    sys.exit(f"в {путь} нет API_KEY_SKLAD")


def запрос(ключ, метод, путь, тело=None):
    данные = json.dumps(тело).encode() if тело is not None else None
    # Набор заголовков ровно как в ms_card_setup.py: без «Accept-Encoding: gzip» тот же
    # запрос получает от их nginx 415 Unsupported Media Type (проверено 18.11.2026).
    req = urllib.request.Request(BASE + путь, data=данные, method=метод, headers={
        "Authorization": "Bearer " + ключ, "Accept-Encoding": "gzip",
        "Accept": "application/json;charset=utf-8", "Content-Type": "application/json"})
    # повтор при 503 и прочих временных отказах: МойСклад отдаёт их часто (18.11.2026)
    import time
    for попытка in range(4):
        try:
            with urllib.request.urlopen(req, timeout=60) as о:
                тело_ответа = о.read()
                if о.headers.get("Content-Encoding") == "gzip":
                    import gzip
                    тело_ответа = gzip.decompress(тело_ответа)
                return json.loads(тело_ответа) if тело_ответа else {}
        except urllib.error.HTTPError as e:
            if e.code in (429, 500, 502, 503, 504) and попытка < 3:
                пауза = 0.7 * (2 ** попытка)
                print(f"   МойСклад {e.code}, пауза {пауза:.1f} c")
                time.sleep(пауза)
                continue
            sys.exit(f"HTTP {e.code} {метод} {путь}: {e.read()[:300]!r}")
        except urllib.error.URLError as e:
            if попытка < 3:
                time.sleep(0.7 * (2 ** попытка))
                continue
            sys.exit(f"связь с МойСкладом не вышла: {e}")


def поля_товара(ключ):
    мета = запрос(ключ, "GET", "/entity/product/metadata")
    атр = мета.get("attributes") or {}
    строки = атр.get("rows") if isinstance(атр, dict) else атр
    if not строки and isinstance(атр, dict):
        href = (атр.get("meta") or {}).get("href") or ""
        if href:
            строки = запрос(ключ, "GET", href[len(BASE):]).get("rows") or []
    return [((a.get("name") or "").strip(), (a.get("type") or "")) for a in (строки or [])]


