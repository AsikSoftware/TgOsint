# -*- coding: utf-8 -*-
"""Свой прайс у точки: ссылка на вкладку лежит в `shops.price_url`.

Зачем. Цена выкупа на разных точках разная: аренда, поток, конкуренты через дорогу. До
этого прайс был один на всю сеть — одна вкладка Google Таблицы, зашитая в настройках бота
(`GOOGLE_SHEETS_SPREADSHEET_ID` + `SHEET_GID`), и отличить точку было нечем.

Как устроено теперь:

* у магазина в `shops` появилась колонка `price_url` — ссылка на **вкладку той же таблицы**
  (`.../spreadsheets/d/<ключ>/edit#gid=<номер>`). Пусто — значит у точки своего прайса нет
  и считаем по общему, как раньше;
* точку сделки берём из неё самой: `devices.shop_id_grade` проставлен до расчёта цены и у
  продавца (из его магазина), и у кассы (приходит в посылке);
* формат вкладки тот же, что у общего прайса: `Марка | Модель | Память`, дальше колонки по
  диапазонам АКБ. Её и копируют, меняя числа.

Главное правило: **свой прайс есть, а строки в нём нет — автоцены нет вовсе.** На общий
прайс в этом случае не падаем: цена из чужого списка хуже, чем ручная оценка. По той же
причине сюда попадает и недоступная таблица (сеть, квоты Google): молча подставить общую
цену — значит назвать клиенту число, которого в прайсе этой точки нет.

Модуль лежит в `handlers/` рядом с `kiosk_media.py` и `kiosk_core.py`; сам прайс читает
`utils/google_price.py`, оттуда же берётся и раскладка колонок по АКБ — чтобы две части
не разошлись в том, какая колонка что значит.
"""
import logging
import re
import time

log = logging.getLogger(__name__)

# Ссылка на вкладку: ключ документа и номер вкладки. Разбираем оба, потому что в адресной
# строке Google номер вкладки стоит после решётки, а при копировании «ссылки на лист» —
# после вопросительного знака.
КЛЮЧ_ТАБЛИЦЫ = re.compile(r"/spreadsheets/d/([A-Za-z0-9_-]{20,})")
НОМЕР_ВКЛАДКИ = re.compile(r"[#&?]gid=(\d+)")

# Сколько держим прочитанную вкладку. Раньше прайс читался один раз на всю жизнь процесса и
# сбрасывался кнопкой админа; с вкладкой на каждую точку забытый сброс означал бы, что
# правка цен не доезжает до половины сети. Пять минут — компромисс: цены правят руками и
# редко, а Google за это время не спросят больше одного раза на точку.
КЭШ_СЕКУНД = 300

_кэш: dict = {}


def сбросить_кэш() -> None:
    """Забыть прочитанные вкладки. Зовётся из `reset_price_cache` бота — кнопкой админа."""
    _кэш.clear()


def разобрать_ссылку(ссылка):
    """Ссылка на вкладку → (ключ таблицы, номер вкладки или None). Не ссылка → None.

    Номера вкладки может не быть: тогда берём первый лист документа — так ведёт себя и сам
    Google, когда открываешь таблицу без якоря.
    """
    текст = str(ссылка or "").strip()
    если_ключ = КЛЮЧ_ТАБЛИЦЫ.search(текст)
    if not если_ключ:
        return None
    если_вкладка = НОМЕР_ВКЛАДКИ.search(текст)
    return если_ключ.group(1), (int(если_вкладка.group(1)) if если_вкладка else None)


def цена_в_таблице(значения, колонка_акб: int, марка, модель, память):
    """Строки вкладки → цена или None. Те же правила, что у общего прайса.

    Первая строка — шапка. Сравниваем марку, модель и память без учёта регистра и
    пробелов по краям; пустая клетка цены — это «цены нет», а не ноль.
    """
    if колонка_акб is None or not значения or len(значения) < 2:
        return None
    марка_н = str(марка or "").strip().lower()
    модель_н = str(модель or "").strip().lower()
    память_н = str(память or "").strip().lower()
    if not (марка_н and модель_н and память_н):
        return None
    for строка in значения[1:]:
        if len(строка) < 3:
            continue
        if (строка[0].strip().lower() == марка_н and строка[1].strip().lower() == модель_н
                and строка[2].strip().lower() == память_н):
            if len(строка) <= колонка_акб:
                return None
            сырое = строка[колонка_акб].strip()
            if not сырое:
                return None
            try:
                return int(сырое.replace(" ", "").replace("\xa0", "").replace(",", ""))
            except ValueError:
                return None
    return None


async def ссылка_точки(shop_id) -> str:
    """`shops.price_url` этой точки. Нет точки, нет колонки, пусто — пустая строка.

    Колонки `price_url` может не быть вовсе: её добавляют руками (`ALTER TABLE`), а схему
    Оценка создаёт через `create_all`, который колонок не досоздаёт. Пока её нет, всё
    работает по-старому, а не падает."""
    if not shop_id:
        return ""
    from sqlalchemy import text
    from database.engine import async_session_factory
    try:
        async with async_session_factory() as session:
            строка = (await session.execute(
                text("SELECT price_url FROM shops WHERE id = :i"), {"i": int(shop_id)})).scalar()
        return str(строка or "").strip()
    except Exception as exc:                                     # noqa: BLE001
        log.warning("прайс точки %s: колонку не прочитать (%s)", shop_id, exc)
        return ""


def _вкладка(ключ: str, номер):
    """Строки вкладки из Google. Синхронно: зовётся в отдельном потоке."""
    свежесть, значения = _кэш.get((ключ, номер), (0.0, None))
    if значения is not None and time.monotonic() - свежесть < КЭШ_СЕКУНД:
        return значения
    from utils.google_price import _get_client
    книга = _get_client().open_by_key(ключ)
    лист = книга.get_worksheet_by_id(номер) if номер is not None else книга.get_worksheet(0)
    значения = лист.get_all_values() or []
    _кэш[(ключ, номер)] = (time.monotonic(), значения)
    return значения


async def по_точке(device):
    """Цена по прайсу точки сделки. → (свой прайс есть?, цена).

    `(False, None)` — у точки своего прайса нет, считайте по общему, как раньше.
    `(True, 12345)` — цена из её вкладки.
    `(True, None)` — прайс у точки есть, а цены в нём нет (или вкладка не прочиталась):
    автоцены у такой сделки быть не должно, и общий прайс сюда не подставляется.
    """
    import asyncio

    ссылка = await ссылка_точки(getattr(device, "shop_id_grade", None))
    if not ссылка:
        return False, None
    разобрано = разобрать_ссылку(ссылка)
    if not разобрано:
        log.warning("прайс точки %s: это не ссылка на таблицу", getattr(device, "shop_id_grade", None))
        return True, None
    ключ, номер = разобрано
    from utils.google_price import AKB_COL_INDEX_BY_STATE
    колонка = AKB_COL_INDEX_BY_STATE.get(device.akb)
    try:
        значения = await asyncio.to_thread(_вкладка, ключ, номер)
    except Exception as exc:                                     # noqa: BLE001 — цена не повод терять сделку
        log.warning("прайс точки %s: вкладка не прочиталась (%s)",
                    getattr(device, "shop_id_grade", None), exc)
        return True, None
    цена = цена_в_таблице(значения, колонка, device.producer, device.model, device.ddr)
    if цена is None:
        log.info("прайс точки %s: нет строки %s %s %s ГБ (%s) — автоцены не будет",
                 device.shop_id_grade, device.producer, device.model, device.ddr, device.akb)
    return True, цена
