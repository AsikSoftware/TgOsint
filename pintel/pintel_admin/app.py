class Список(Раздел):
    """Раздел-таблица общего вида: колонки и правило, как ответ сервера становится строками.

    Одиннадцать почти одинаковых классов были бы одиннадцатью местами, где можно по-разному
    округлить и по-разному назвать колонку. Здесь правило одно, а различия — в одной строке
    на раздел."""

    def __init__(self, заголовок, подпись, колонки, строки_из, подпись_из=None, цвет=None,
                 плитки=()):
        super().__init__(заголовок, подпись)
        self._строки_из, self._подпись_из, self._цвет = строки_из, подпись_из, цвет
        self.плитки, self._вид_плитки = {}, {}
        if плитки:
            ряд = QHBoxLayout()
            ряд.setSpacing(12)
            for пункт in плитки:
                ключ, подписькп = пункт[0], пункт[1]
                п = Плитка(подписькп)
                self.плитки[ключ] = п
                self._вид_плитки[ключ] = пункт[2] if len(пункт) > 2 else None
                ряд.addWidget(п)
            обёртка = QWidget()
            обёртка.setLayout(ряд)
            self.корень.addWidget(обёртка)
        карта = Карта("")
        self.таблица = таблица(колонки)
        карта.добавить(self.таблица)
        self.корень.addWidget(карта, 1)
        self.оговорка = надпись("", "muted", перенос=True)
        self.корень.addWidget(self.оговорка)

    def показать(self, данные):
        if self._подпись_из:
            self.подпись.setText(self._подпись_из(данные) or "")
        for ключ, плитка in self.плитки.items():
            значение = данные.get(ключ) if isinstance(данные, dict) else None
            вид = self._вид_плитки.get(ключ)
            плитка.показать(вид(значение) if вид and значение is not None else значение)
        заполнить(self.таблица, self._строки_из(данные), цвет_строки=self._цвет)
        словами = (данные.get("оговорка") if isinstance(данные, dict) else "") or ""
        self.оговорка.setText(словами)
        self.оговорка.setVisible(bool(словами))


