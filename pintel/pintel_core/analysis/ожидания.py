# -*- coding: utf-8 -*-
"""Дыры в чтении: чего у ЭТОГО телефона не хватает из того, что у таких же читается.

Владелец, 18.11.2026: «Те которые не прочитали хотя могли — мы должны заставлять читать. Без
него не давать оценку».

Смысл модуля — отличить дыру от особенности. Пустое поле бывает трёх сортов:

  * **особенность** — у этой модели или на этой iOS такого не бывает вовсе. Taptic
    отсутствует на части моделей, макс. температура батареи исчезла на iOS 27 (0 чтений из
    26), сверка датчика приближения мертва с iPhone 15 (0 из 64). Требовать нельзя;
  * **правда про телефон** — прочитали, и данных нет: журнал Apple пуст, потому что ремонтов
    не было. Тоже не дыра;
  * **дыра** — могли прочитать, но не прочитали: рвалась связь, не открыли раздел Apple. Вот
    это опасно, потому что выглядит как «всё хорошо».

Отличает их только сравнение с такими же телефонами, и оно посчитано в
`ожидания_данные.ТАБЛИЦА`: величина попала в ожидания группы «модель × поколение iOS», только
если пришла во ВСЕХ её чтениях (и чтений было не меньше четырёх).

Чего таблица не умеет — ловить систематическую дыру, когда величину не читает НИКТО: для
статистики это выглядит нормой модели. Так «Деталь: Телефото камера» пустовала у всех
Pro-моделей из-за расхождения в имени сигнала. Такие дыры ловит не этот модуль, а тест
`tests/test_ozhidaniya.py`, где записано, что у модели есть физически.

Цена ошибки несимметрична, и поэтому правило строгое в одну сторону: группы нет в таблице
(новая модель, новая iOS) — ожиданий не предъявляем вовсе. Лучше пропустить дыру на
незнакомом аппарате, чем остановить выкуп на всех.
"""
import re

from .ожидания_данные import ПОСЧИТАНО_ПО, ТАБЛИЦА  # noqa: F401 — ПОСЧИТАНО_ПО для отчёта


def поколение(ios) -> str:
    """iOS 17.4.1 → «17»."""
    m = re.match(r"\s*(\d+)", str(ios or ""))
    return m.group(1) if m else "?"


def ждём(модель: str, ios: str) -> tuple:
    """Что обязано прочитаться у этой модели на этой iOS. Группы нет — пустой кортеж."""
    return ТАБЛИЦА.get((str(модель or "").strip(), поколение(ios)), ())


def дыры(поля: dict, модель: str, ios: str) -> list:
    """Величины, которые у таких телефонов читаются всегда, а у этого не прочитались.

    `поля` — словарь доп. полей из `pintel_core.external.ms_update.доп_поля`: имя → значение,
    где `None` значит «не прочиталось». Возвращаем имена по порядку таблицы, чтобы отчёт и
    журнал не плясали от запуска к запуску.
    """
    пусто = {и for и, з in (поля or {}).items() if з is None or з == ""}
    return [и for и in ждём(модель, ios) if и in пусто]


# Откуда берётся величина — от этого зависит, что советовать сотруднику. Проверено на
# «исключи себя» по 70 чтениям: гейт срабатывает в 7% случаев, и в большинстве — не из-за
# телефона, а из-за внешней базы (верификация IMEI, чёрный список, гарантия, блокировка
# оператора). Советовать там «переподключите кабель» бессмысленно: нужно переспросить базу.
ВНЕШНЯЯ_БАЗА = frozenset({
    "Верификация IMEI 1", "Верификация IMEI 2", "Замок: чёрный список",
    "Замок: блокировка оператора", "Гарантия Apple до", "Дата первой покупки",
})


def по_источнику(дыр: list) -> dict:
    """Дыры врозь: что перечитывать кабелем, а что переспрашивать у внешней базы."""
    кабель = [и for и in дыр if и not in ВНЕШНЯЯ_БАЗА]
    база = [и for и in дыр if и in ВНЕШНЯЯ_БАЗА]
    return {"кабель": кабель, "база": база}


def словами(дыр: list) -> str:
    """Строка для карточки товара и для журнала точки."""
    if not дыр:
        return ""
    return f"не прочитано ({len(дыр)}): " + ", ".join(дыр)


def почему_к_человеку(дыр: list) -> str:
    """Что сказать сотруднику, когда автоцены не будет. Пусто — цена считается как обычно.

    Совет зависит от источника: телефон перечитывают кабелем, внешнюю базу переспрашивают.
    Перепутать нельзя — сотрудник будет дёргать кабель там, где это не поможет."""
    if not дыр:
        return ""
    врозь = по_источнику(дыр)
    части = []
    if врозь["кабель"]:
        части.append(f"телефон не отдал: {', '.join(врозь['кабель'][:3])}"
                     + (f" и ещё {len(врозь['кабель']) - 3}" if len(врозь["кабель"]) > 3 else "")
                     + " — переподключите кабель и перечитайте")
    if врозь["база"]:
        части.append(f"внешняя база не ответила: {', '.join(врозь['база'][:3])}"
                     + (f" и ещё {len(врозь['база']) - 3}" if len(врозь["база"]) > 3 else "")
                     + " — кабель тут не поможет, нажмите «Спросить снова»")
    return "; ".join(части) + ". Если не вышло — оценит человек."
