def test_nothing_known_stays_a_dash_not_a_zero(приложение):
    """Пустая плитка показывает прочерк, а не ноль."""
    п = ui.Плитка("выдано клиентам")
    п.показать(None)
    assert п.значение.text() == "—"
    п.показать(3_240_000)
    assert "3 240 000" in п.значение.text()
    assert ui.деньги(None) == "—" and ui.миллионы(None) == "—"


