# -*- coding: utf-8 -*-
"""Что обязано быть прочитано, иначе сделку не пускаем.

Решение владельца (17.11.2026): «надо составить список вещей, которые надо прочитать, и без
них не пускать». Смысл простой: цена и решение о выкупе строятся на нескольких величинах, и
если какой-то из них нет, оценка — выдумка. Лучше перечитать телефон или отдать его оценщику,
чем назвать клиенту число, взятое из воздуха.

Список составлен не на глаз, а по боевым оценкам (81 проверка за месяц, из них 20 последних —
на нынешней сборке): каждый пункт ниже читается в 100% случаев. То есть запрет не остановит
работу — он сработает только там, где и правда что-то сломалось: кабель, разъём, служба Apple.

Список двухуровневый, и это не осторожность, а разделение ответственности:

  • `ПУНКТЫ` — **запрет**. Величины, которые зависят только от телефона и читаются по кабелю
    всегда. Нет хотя бы одной — касса не даёт создать сделку, потому что цена была бы
    выдумкой. Сотрудник перечитывает телефон или меняет кабель;
  • `ЖЕЛАТЕЛЬНОЕ` — **автоцены нет, оценивает человек**. Сюда идёт то, что зависит не только
    от телефона: наша сборка (panic full читается модулем pymobiledevice3 — однажды он
    отвалился из-за недостающих метаданных pyimg4) и внешние базы (цвет, чёрный список).
    Останавливать точку из-за своей же ошибки нельзя, но и молча ставить цену — тоже.

Чего в списке СОЗНАТЕЛЬНО нет и почему:
  • MobileGestalt (печать Apple) — на нынешних iOS телефон эту службу не предлагает вовсе:
    0 из 20 последних проверок. Требовать нельзя, подлинность подтверждается привязкой
    модулей по IORegistry и журналом Apple;
  • сверка объёма с диском — объём и так известен с контроллера NVMe, а ответ про занятое
    место телефон считает на ходу и иногда минутами;
  • цвет и чёрный список — это внешняя база IMEI, а не кабель: цвет сотрудник выбирает
    кнопкой, непроверенный чёрный список и так снимает автоцену;
  • циклы батареи — читаются всегда, но на цену не влияют: прайс считает по проценту;
  • panic full — читается модулем нашей сборки, а не самим телефоном: он в `ЖЕЛАТЕЛЬНОЕ`;
  • журнал Apple — зависит от того, откроет ли клиент раздел на телефоне. Его закрывает
    сверка деталей сотрудником, и она уже обязательна отдельно.

Запечатанный аппарат (коробку не вскрывали) проверяется не кабелем, а по базе IMEI — на него
этот список не распространяется.
"""

# (ключ, что это для человека, как достать из отчёта, зачем нужно)
ПУНКТЫ = (
    ("модель", "модель телефона",
     lambda rep: _непусто(_пас(rep).get("модель")) and "не в справочнике" not in str(_пас(rep).get("модель")),
     "без неё нет ни цены, ни товара"),
    ("imei", "IMEI",
     lambda rep: len(_цифры(_пас(rep).get("imei"))) == 15,
     "по нему телефон числится в МойСкладе, РФС и базе IMEI"),
    ("серийник", "серийный номер",
     lambda rep: len(str(_пас(rep).get("серийник") or "").strip()) >= 8,
     "по нему сверяются детали и прошлые проверки"),
    ("память", "объём памяти",
     lambda rep: (rep.get("память") or {}).get("объём_гб") is not None,
     "это строка прайса"),
    ("батарея", "здоровье батареи",
     lambda rep: (rep.get("батарея") or {}).get("здоровье_%") is not None,
     "это колонка прайса"),
    ("найти_iphone", "«Найти iPhone»",
     lambda rep: (rep.get("правовой") or {}).get("найти_iphone") in ("включён", "выключен"),
     "с включённым замком телефон выкупать нельзя"),
    ("активация", "состояние активации",
     lambda rep: _непусто((rep.get("правовой") or {}).get("активация")),
     "неактивированный аппарат — отдельный разговор"),
    ("детали", "вердикт по деталям",
     lambda rep: _непусто((rep.get("детали_вердикт") or {}).get("итог")),
     "от подлинности деталей зависит статус и цена"),
)

# Без этого сделка создаётся, но автоцены не будет: оценит человек. Зависит не только от
# телефона — от нашей сборки и от внешних баз, и останавливать точку из-за них нельзя.
ЖЕЛАТЕЛЬНОЕ = (
    ("panic_full", "ошибка Panic full",
     lambda rep: bool((rep.get("паника") or {}).get("проверено")),
     "это вопрос, который Оценка задаёт по каждому телефону"),
)
# Цвета и чёрного списка здесь нет сознательно: про них отчёт говорит и так. Непроверенный
# чёрный список кладёт строку в «не прочиталось» сама касса (quality['не_проверено']), а цвет,
# которого не дала база, выбирает сотрудник кнопкой — без него сделку не отправить.


def _пас(rep):
    return (rep or {}).get("паспорт") or {}


def _непусто(v) -> bool:
    return bool(str(v or "").strip())


def _цифры(v) -> str:
    return "".join(c for c in str(v or "") if c.isdigit())


def запечатанный(rep) -> bool:
    """Запечатанный аппарат кабелем не читают — список к нему не применяется."""
    rep = rep or {}
    return bool(rep.get("запечатанный") or (rep.get("sickw") or {}).get("запечатанный"))


def _проверить(rep, список) -> list:
    if not rep or запечатанный(rep):
        return []
    нет = []
    for ключ, название, есть, зачем in список:
        try:
            ладно = bool(есть(rep))
        except Exception:                                        # noqa: BLE001 — нет раздела вовсе
            ладно = False
        if not ладно:
            нет.append((ключ, название, зачем))
    return нет


def не_прочитано(rep) -> list:
    """Чего из обязательного нет. → [(ключ, название, зачем)]. Пустой список — можно пускать."""
    return _проверить(rep, ПУНКТЫ)


def желательного_нет(rep) -> list:
    """Чего нет из того, что не запрещает сделку, но снимает автоцену."""
    return _проверить(rep, ЖЕЛАТЕЛЬНОЕ)


def всё_прочитано(rep) -> bool:
    return not не_прочитано(rep)


def словами(rep) -> str:
    """Короткая строка для экрана кассы и журнала точки."""
    нет = не_прочитано(rep)
    if not нет:
        return ""
    return "не прочитано: " + ", ".join(название for _к, название, _з in нет)


def почему_не_пустить(rep) -> str:
    """Фраза сотруднику: чего нет и что делать."""
    нет = не_прочитано(rep)
    if not нет:
        return ""
    если_одно = len(нет) == 1
    пункты = ", ".join(название for _к, название, _з in нет)
    return (f"Телефон не отдал {'величину' if если_одно else 'величины'}, без "
            f"{'которой' if если_одно else 'которых'} оценка будет выдумкой: {пункты}. "
            "Нажмите «Проверить телефон заново»; не поможет — замените кабель или "
            "переставьте его в другой порт.")
