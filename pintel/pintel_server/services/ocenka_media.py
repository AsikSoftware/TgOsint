# -*- coding: utf-8 -*-
"""Обмен с ботом Оценки по коду: что дошло от сотрудника и сама сделка с точки.

Зачем это серверу. Программа на точке не видит базу Оценки — порт Postgres закрыт
наружу, — а сервер стоит на том же VPS и уже читает её (магазины, импорт оценок). Поэтому
через него идёт всё, что касса не может узнать или сделать сама:

* **что дошло в бота** — фото и видео по коду обмена. До этого касса не знала о них
  ничего: кнопка «Отправить в Оценку» нажималась и без медиа, а отказ прилетал позже,
  уже от бота, с телефоном клиента в руках.
* **сама сделка** — посылка с точки. Раньше она уходила файлом в чат Telegram, и бот
  получал её ТОЛЬКО когда кто-то нажимал кнопку под карточкой: свои исходящие сообщения
  бот не видит. Значит, сделка зависела от чата — а чат отказывал по-разному
  («chat not found», «bot was blocked by the user»), и тогда создать её было нельзя
  вовсе. Теперь посылка ложится в ту же таблицу обмена, бот забирает её оттуда сам и
  сразу создаёт сделку; подтверждать кнопкой больше нечего.

Наружу отдаём только счётчики: `file_id` медиа, чат и сотрудник остаются в базе Оценки.
Строки по коду ещё нет (сотрудник не открывал ссылку) — это не ошибка, а «ничего не
прислали».

Ручной диагностики здесь нет и не спрашивается: её отмечают на экране самой программы, и
знает о ней она сама. Поля `диагностика_видна` и `не_отмечено` остались в ответе ради
сборок до doctor-64: они держали сделку, пока бот не подтвердит отметки, и ответ «я их не
вижу» для них означает «не держи» — ровно то, что нужно, пока такая точка не обновилась.
"""
from __future__ import annotations

import datetime as dt
import json
import logging
import re

from sqlalchemy import text

from pintel_core.external import ocenka_media as общее

log = logging.getLogger("pintel.ocenka")

КОД = re.compile(r"^[A-Za-z0-9]{4,16}$")
ПРЕДЕЛ_ПОСЫЛКИ = 300_000        # посылка — это текст; больше 300 КБ значит что-то не то


def состояние(код: str) -> dict:
    """Код обмена → что по нему уже есть у бота.

    `известно: False` значит ровно одно — сервер не смог посмотреть (связи с базой Оценки
    нет или она не настроена). Это не «медиа нет»: разницу обязана видеть и касса, иначе
    она либо остановит работу на ровном месте, либо назовёт собранным то, чего не видела.
    """
    код = str(код or "").strip()
    if not КОД.match(код):
        return {"известно": False, "почему": "код обмена не похож на код"}
    # что отдаём про диагностику: её тут нет, и держать из-за неё сделку нельзя
    диагностика = {"диагностика_видна": False, "не_отмечено": [],
                   "диагностика": "отмечается на экране программы"}
    try:
        строка = _строка(код)
    except Exception as exc:                                     # noqa: BLE001 — молчать нельзя
        log.warning("медиа %s: базу Оценки не спросить: %s", код, exc)
        return {"известно": False, "почему": "касса не видит базу Оценки"}
    if строка is None:
        # Строку заводит сам бот, когда сотрудник открывает ссылку из QR. Её нет — значит
        # ссылку ещё не открывали, и это нормальное начало сделки, а не сбой.
        return {"известно": True, "начали": False, "фото": 0, "видео": False,
                "готово": False, "сделка": None, "посылка_ждёт": False, "ошибка": "",
                **диагностика}
    фото = len([x for x in str(строка["photos"] or "").split("||") if x])
    видео = bool(строка["video"])
    return {"известно": True, "начали": True, "фото": фото, "видео": видео,
            "готово": фото >= общее.НУЖНО_ФОТО and видео,
            "сделка": строка["device_id"],
            # посылка уже у бота и ждёт своей очереди: касса по этому полю показывает
            # «ждём номер сделки», а не предлагает отправить ещё раз
            "посылка_ждёт": bool(строка.get("parcel")),
            # почему сделка не создалась — словами с той стороны. Пусто, пока всё хорошо.
            "ошибка": str(строка.get("parcel_error") or ""),
            **диагностика}


def принять(код: str, посылка: dict) -> dict:
    """Сделка с точки → в таблицу обмена, боту. → {принято: True} или `почему`.

    Касса по ответу решает, показывать ли «ждём сделку» или уходить в запасной путь —
    отправку карточки в Telegram. Поэтому каждый отказ назван словами: «не принято»
    без причины здесь хуже, чем ничего.
    """
    код = str(код or "").strip()
    if not КОД.match(код):
        return {"принято": False, "почему": "код обмена не похож на код"}
    if not isinstance(посылка, dict) or not посылка:
        return {"принято": False, "почему": "пустая посылка"}
    if str(посылка.get("код") or "") != код:
        return {"принято": False, "почему": "код в посылке не тот"}
    текст = json.dumps(посылка, ensure_ascii=False)
    if len(текст) > ПРЕДЕЛ_ПОСЫЛКИ:
        return {"принято": False, "почему": "посылка слишком большая"}
    try:
        строка = _строка(код)
    except Exception as exc:                                     # noqa: BLE001
        log.warning("посылка %s: базу Оценки не спросить: %s", код, exc)
        return {"принято": False, "почему": "сервер не видит базу Оценки"}
    if строка is None:
        # медиа по коду ещё не присылали — сделку боту не из чего собрать
        return {"принято": False, "почему": "по этому коду сотрудник не присылал медиа"}
    if строка["device_id"]:
        return {"принято": True, "сделка": int(строка["device_id"]),
                "почему": "сделка по этому коду уже создана"}
    try:
        from .ocenka_import import _ocenka_engine
        with _ocenka_engine().begin() as conn:
            # `device_id IS NULL` в условии — чтобы посылка не легла поверх уже созданной
            # сделки, если бот успел её сделать, пока шёл этот запрос
            взято = conn.execute(text(
                "UPDATE kiosk_media SET parcel = :p, parcel_at = :t, parcel_error = NULL "
                "WHERE code = :c AND device_id IS NULL"),
                {"p": текст, "t": dt.datetime.now(dt.timezone.utc), "c": код}).rowcount
    except Exception as exc:                                     # noqa: BLE001
        # колонок может не быть (базу ещё не обновили) — тогда касса уйдёт в Telegram
        log.warning("посылка %s: не записать: %s", код, exc)
        return {"принято": False, "почему": "сервер не принял посылку"}
    if not взято:
        return {"принято": False, "почему": "строку обмена не нашли"}
    log.info("посылка %s принята, ждёт бота", код)
    return {"принято": True}


def _строка(код: str):
    """Строка обмена по коду или None. Берём целиком: таблица на сервере живёт своей
    жизнью (колонок `checks`, `parcel` может не быть), а запрос с несуществующей колонкой
    упал бы целиком — и касса перестала бы видеть даже фото с видео."""
    from .ocenka_import import _ocenka_engine
    with _ocenka_engine().connect() as conn:
        return conn.execute(text("SELECT * FROM kiosk_media WHERE code = :c"),
                            {"c": код}).mappings().first()
