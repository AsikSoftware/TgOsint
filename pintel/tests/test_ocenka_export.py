# диапазоны — её кнопки akb_kb и ключи прайса AKB_COL_INDEX_BY_STATE
ЕЁ_ДИАПАЗОНЫ = {"100 (0-30)", "100", "96-99", "91-95", "86-90", "80-85", "75-79", "0-74",
                "нет информации"}


@pytest.mark.parametrize("здоровье,циклы,ждём", [
    (86, 1642, "86-90"),
    (100, 5, "100 (0-30)"),      # почти без циклов — у неё отдельная колонка в прайсе
    (100, 400, "100"),
    (96, 100, "96-99"),
    (95, 100, "91-95"),
    (85, 100, "80-85"),
    (79, 10, "75-79"),
    (74, 10, "0-74"),
    (1, 10, "0-74"),
    (None, None, "нет информации"),
    (100, None, "100"),          # циклов не знаем — не выдаём батарею за новую
])
def test_battery_is_a_range_not_a_percent(здоровье, циклы, ждём):
    """У неё akb — диапазон, а не «86%»: по нему google_price выбирает колонку цены, а
    приёмка — строку товара. Чужое значение ломает автооценку, а не вид карточки."""
    итог = ocenka.акб_для_оценки(здоровье, циклы)
    assert итог == ждём and итог in ЕЁ_ДИАПАЗОНЫ


