# -*- coding: utf-8 -*-
"""История телефона — словами для экрана.

Сервер отдаёт историю по IMEI тремя списками: сделки Оценки, заявки с сайта и наши прошлые
проверки (`pintel_server/services/history.py`). Здесь из них получается ровно то, что
сотрудник читает в углу экрана, пока клиент стоит рядом, — и то, что открывается окном по
центру, когда кабель дочитал телефон, а записи про него у нас уже есть (`записи`, `сводка`).

Почему отдельный модуль, а не метод окна: правила тут не про кнопки, а про смысл —
что считается записью, в каком порядке их читать и как называть источник, который не ответил.
Их надо проверять тестами на любой машине, а оконные проверки идут только в сборке под
Windows, где есть Qt.

Главное правило: **молчать нельзя**. Если Оценка не ответила или таблица заявок не
прочиталась, в углу стоит это, а не «ничего не нашли»: «ничего не нашли» сотрудник примет за
«аппарат у нас впервые» и назовёт цену с нуля.
"""
from __future__ import annotations

ПУСТО = "по этому IMEI у нас ничего"
ЖДЁМ = "спрашиваем…"


def _деньги(значение) -> str:
    """120000 → «120 000 ₸». Пусто и нули — пустая строка: ноль цены не бывает."""
    try:
        число = int(str(значение).strip())
    except (TypeError, ValueError):
        return ""
    if число <= 0:
        return ""
    return f"{число:,}".replace(",", " ") + " ₸"


def _сколько_записей(n: int) -> str:
    """«1 запись», «2 записи», «5 записей» — число читает человек, а не программа."""
    остаток = n % 100
    if 11 <= остаток <= 14:
        слово = "записей"
    elif остаток % 10 == 1:
        слово = "запись"
    elif остаток % 10 in (2, 3, 4):
        слово = "записи"
    else:
        слово = "записей"
    return f"{n} {слово}"


def строки(данные) -> list:
    """Три списка сервера → строки для экрана, самое свежее и самое важное сверху.

    Порядок намеренный: сначала заявка с сайта (клиенту уже назвали цену, и он придёт с
    ней), потом сделки Оценки (сколько мы давали и давали ли), потом наши проверки по
    кабелю (что было с аппаратом технически).
    """
    д = данные or {}
    готово = []
    for з in (д.get("заявки") or []):
        первая = " · ".join(x for x in (f"Заявка {з.get('номер')}" if з.get("номер") else "Заявка",
                                        з.get("когда") or "",
                                        " ".join(x for x in (з.get("имя") or "",
                                                             з.get("телефон") or "") if x).strip())
                            if x)
        второе = " · ".join(x for x in (з.get("модель") or "",
                                        ("онлайн " + _деньги(з.get("цена"))) if _деньги(з.get("цена")) else "",
                                        з.get("вид") or "",
                                        ("не работает: " + з["не_работает"]) if (з.get("не_работает") or "").strip()
                                        and з["не_работает"] != "всё работает" else "",
                                        ("ремонт: " + з["ремонт"]) if (з.get("ремонт") or "").strip() else "")
                            if x)
        готово.append((первая, второе))
    for о in (д.get("оценки") or []):
        первая = " · ".join(x for x in (f"Оценка №{о.get('сделка')}", о.get("когда") or "",
                                        о.get("точка") or "") if x)
        деньги = " · ".join(x for x in (("автоцена " + _деньги(о.get("автоцена"))) if _деньги(о.get("автоцена")) else "",
                                        ("выкуп " + _деньги(о.get("выкуп"))) if _деньги(о.get("выкуп")) else "")
                            if x)
        второе = " · ".join(x for x in (о.get("модель") or "", str(о.get("акб") or ""), деньги,
                                        о.get("статус") or "", о.get("состояние") or "") if x)
        готово.append((первая, второе))
    for н in (д.get("наши") or []):
        батарея = f"{н['акб']}%" if н.get("акб") else ""
        циклы = f"{н['циклы']} циклов" if н.get("циклы") else ""
        первая = " · ".join(x for x in ("Диагностика" + (f" №{н['номер']}" if н.get("номер") else ""),
                                        н.get("когда") or "") if x)
        второе = " · ".join(x for x in (н.get("модель") or "", батарея, циклы,
                                        н.get("вердикт") or "",
                                        ("цена " + _деньги(н.get("цена"))) if _деньги(н.get("цена")) else "",
                                        н.get("детали") or "") if x)
        готово.append((первая, второе))
    return готово


def _счёт(n: int, один: str, два: str, много: str) -> str:
    """«1 сделка», «2 сделки», «5 сделок»."""
    остаток = n % 100
    if 11 <= остаток <= 14:
        слово = много
    elif остаток % 10 == 1:
        слово = один
    elif остаток % 10 in (2, 3, 4):
        слово = два
    else:
        слово = много
    return f"{n} {слово}"


# Виды записей в окне по центру: как назвать вид одной записи и как сосчитать несколько.
ВИДЫ = {"заявка": ("Заявка с сайта", ("заявка с сайта", "заявки с сайта", "заявок с сайта")),
        "оценка": ("Сделка Оценки", ("сделка Оценки", "сделки Оценки", "сделок Оценки")),
        "проверка": ("Диагностика", ("диагностика", "диагностики", "диагностик"))}


def записи(данные) -> list:
    """Те же записи, что в `строки`, и в том же порядке — но по частям, для окна по центру.

    Окно открывается само, когда кабель дочитал телефон, и закрывает его сотрудник: это
    единственный способ не пропустить, что аппарат у нас уже был. Строкой через точку такое
    окно читать нельзя — в нём у записи свои места для вида, даты, денег и подробностей,
    чтобы глаз находил цену, не читая всю строку.

    → [{"вид": "заявка" | "оценка" | "проверка", "название", "когда",
        "деньги": [(подпись, сумма), …], "подробно": [факт, …]}]
    """
    д = данные or {}
    готово = []
    for з in (д.get("заявки") or []):
        не_работает = (з.get("не_работает") or "").strip()
        готово.append({
            "вид": "заявка",
            "название": f"Заявка {з.get('номер')}" if з.get("номер") else "Заявка",
            "когда": з.get("когда") or "",
            "деньги": [("онлайн-оценка", _деньги(з.get("цена")))] if _деньги(з.get("цена")) else [],
            "подробно": [x for x in (
                " ".join(x for x in (з.get("имя") or "", з.get("телефон") or "") if x).strip(),
                з.get("модель") or "",
                з.get("вид") or "",
                ("не работает: " + не_работает) if не_работает and не_работает != "всё работает" else "",
                ("ремонт: " + з["ремонт"]) if (з.get("ремонт") or "").strip() else "") if x]})
    for о in (д.get("оценки") or []):
        акб = str(о.get("акб") or "").strip()
        готово.append({
            "вид": "оценка",
            "название": f"Оценка №{о.get('сделка')}",
            "когда": о.get("когда") or "",
            "деньги": [(подпись, _деньги(о.get(ключ))) for ключ, подпись in
                       (("автоцена", "автоцена"), ("выкуп", "выкуп")) if _деньги(о.get(ключ))],
            "подробно": [x for x in (о.get("точка") or "", о.get("модель") or "",
                                     ("АКБ " + акб) if акб else "",
                                     о.get("статус") or "", о.get("состояние") or "") if x]})
    for н in (д.get("наши") or []):
        циклы = н.get("циклы")
        готово.append({
            "вид": "проверка",
            "название": "Диагностика" + (f" №{н['номер']}" if н.get("номер") else ""),
            "когда": н.get("когда") or "",
            "деньги": [("цена", _деньги(н.get("цена")))] if _деньги(н.get("цена")) else [],
            "подробно": [x for x in (
                н.get("модель") or "",
                f"АКБ {н['акб']}%" if н.get("акб") else "",
                _счёт(int(циклы), "цикл", "цикла", "циклов") if str(циклы or "").isdigit() and int(циклы) else "",
                н.get("вердикт") or "",
                н.get("детали") or "") if x]})
    return готово


def сводка(данные) -> list:
    """Сколько записей какого вида: [("оценка", "2 сделки Оценки"), …] — без нулевых."""
    виды = [з["вид"] for з in записи(данные)]
    return [(вид, _счёт(виды.count(вид), *формы)) for вид, (_, формы) in ВИДЫ.items()
            if виды.count(вид)]


def словами(данные) -> dict:
    """Что показать в углу: подпись на плашке, строки списка и тревожность.

    `данные` — ответ сервера, `None` — ещё спрашиваем, `{}` или с `почему` — не вышло.
    → {"подпись", "строки", "сколько", "беда", "ждём"}
    """
    if данные is None:
        return {"подпись": f"История телефона · {ЖДЁМ}", "строки": [], "сколько": 0,
                "беда": "", "ждём": True}
    if not данные:
        # Ещё не спрашивали: телефона на кабеле нет или сделка только началась. Это не
        # «ничего не нашли» — обещать такое, не спросив, нельзя.
        return {"подпись": "История телефона", "строки": [], "сколько": 0,
                "беда": "", "ждём": False}
    список = строки(данные)
    почему = [str(x) for x in ((данные or {}).get("почему") or []) if str(x or "").strip()]
    беда = "; ".join(почему)
    if список:
        подпись = f"История телефона · {_сколько_записей(len(список))}"
        # Источник, который не ответил, остаётся в подписи даже когда что-то нашлось:
        # «две записи» при молчащей Оценке — это не вся история, и сотрудник обязан знать.
        if беда:
            подпись += " · часть не спросилась"
    elif беда:
        подпись = "История телефона · не спросилась"
    else:
        подпись = f"История телефона · {ПУСТО}"
    return {"подпись": подпись, "строки": список, "сколько": len(список),
            "беда": беда, "ждём": False}
