from pintel_admin.client import Клиент, НетСвязи, НуженВход      # noqa: E402


@pytest.fixture(scope="module")
def приложение():
    return QApplication.instance() or QApplication([])


def сервер_который(ответы: dict):
    """Поддельный сервер: путь → (код, данные). Сеть в тестах не трогаем."""
    def обработчик(запрос: httpx.Request) -> httpx.Response:
        код, данные = ответы.get(запрос.url.path, (404, {"detail": "нет такого"}))
        return httpx.Response(код, json=данные)
    return httpx.MockTransport(обработчик)


