# -*- coding: utf-8 -*-
"""Дыры в чтении: что у таких телефонов читается всегда, а у этого не пришло.

Владелец 18.11.2026: «Те которые не прочитали хотя могли — мы должны заставлять читать. Без
него не давать оценку». Здесь проверяется, что «могли» определяется ПО ДАННЫМ, а не на глаз,
и что гейт не срабатывает там, где величины у модели не бывает вовсе.

Отдельно — ловушка на систематическую дыру: статистика её не видит (если величину не читает
никто, это выглядит нормой модели), поэтому у Pro-моделей сверяется глазами список того, что
у них есть физически. Именно так нашлось, что «Деталь: Телефото камера» пустовала у ВСЕХ
Pro из-за расхождения в имени сигнала («Телефото» против «Телефото камера»).
"""
import pytest

from pintel_core.analysis import ожидания
from pintel_core.external import ms_update


def test_a_generation_is_taken_from_the_ios_version():
    assert ожидания.поколение("17.4.1") == "17"
    assert ожидания.поколение("26") == "26"
    assert ожидания.поколение(None) == "?"
    assert ожидания.поколение("мусор") == "?"


def test_an_unknown_model_demands_nothing():
    """Новой модели ожиданий не предъявляем вовсе.

    Цена ошибки несимметрична: лучше пропустить дыру на незнакомом аппарате, чем остановить
    выкуп на всех, потребовав то, чего у этой модели не бывает."""
    assert ожидания.ждём("iPhone 42 Ultra", "30") == ()
    assert ожидания.дыры({"АКБ: процент": None}, "iPhone 42 Ultra", "30") == []


def test_a_value_everyone_reads_but_this_phone_did_not_is_a_hole():
    """Главное правило: у таких читается всегда, у этого нет — дыра."""
    группа = next(iter(sorted(ожидания.ТАБЛИЦА)))
    модель, ios = группа
    ждём = ожидания.ждём(модель, ios)
    assert ждём, "в таблице обязана быть хоть одна группа с ожиданиями"
    поля = {и: "есть" for и in ждём}
    assert ожидания.дыры(поля, модель, ios) == [], "всё прочитано — дыр нет"
    поля[ждём[0]] = None
    assert ожидания.дыры(поля, модель, ios) == [ждём[0]]


def test_an_empty_string_counts_as_unread():
    """Пустая строка — это тоже «не прочиталось»: МойСклад пустых строк не хранит."""
    группа = next(iter(sorted(ожидания.ТАБЛИЦА)))
    ждём = ожидания.ждём(*группа)
    поля = {и: "есть" for и in ждём}
    поля[ждём[0]] = ""
    assert ожидания.дыры(поля, *группа) == [ждём[0]]


def test_advice_separates_the_cable_from_the_external_base():
    """Совет зависит от источника: телефон перечитывают, базу переспрашивают.

    Перепутать нельзя — сотрудник будет дёргать кабель там, где это не поможет. На боевых
    чтениях гейт срабатывал чаще как раз из-за внешней базы, а не из-за телефона."""
    врозь = ожидания.по_источнику(["Деталь: Корпус", "Верификация IMEI 1", "Замок: чёрный список"])
    assert врозь["кабель"] == ["Деталь: Корпус"]
    assert врозь["база"] == ["Верификация IMEI 1", "Замок: чёрный список"]
    текст = ожидания.почему_к_человеку(["Деталь: Корпус", "Верификация IMEI 1"])
    assert "переподключите кабель" in текст
    assert "кабель тут не поможет" in текст
    assert "оценит человек" in текст
    assert ожидания.почему_к_человеку([]) == "", "дыр нет — и говорить нечего"


def test_no_holes_means_no_words():
    assert ожидания.словами([]) == ""
    assert "не прочитано (2)" in ожидания.словами(["а", "б"])


def test_the_card_carries_the_unread_list():
    """Строка «Не прочитано» едет в карточку товара вместе с полями.

    Без неё пустое поле в карточке читается как «всё хорошо»: по самому полю не отличить
    «у этой модели такого нет» от «не смогли прочитать»."""
    поля = ms_update.доп_поля({"паспорт": {"модель": "нет такой модели", "ios": "26"}})
    assert поля["Не прочитано"] is None, "у незнакомой модели ожиданий нет — и дыр нет"
    assert "Не прочитано" in поля, "поле обязано упоминаться всегда: замена его очищает"


@pytest.mark.parametrize("модель, деталь", [
    ("iPhone 14 Pro", "Деталь: Телефото камера"),
    ("iPhone 15 Pro", "Деталь: Телефото камера"),
    ("iPhone 14 Pro Max", "Деталь: Телефото камера"),
])
def test_a_part_the_model_physically_has_must_be_readable_somewhere(модель, деталь):
    """Ловушка на систематическую дыру, которую статистика не видит.

    У Pro-моделей телефото есть физически. Если такая деталь не попала в ожидания НИ У ОДНОЙ
    группы этой модели, значит мы её не читаем нигде — и это наша недоработка, а не
    особенность телефона. Так и нашлось расхождение в имени сигнала: поле было пустым у
    всех 8 Pro-моделей в архиве."""
    группы = [к for к in ожидания.ТАБЛИЦА if к[0] == модель]
    if not группы:
        pytest.skip(f"{модель}: в архиве нет группы с достаточным числом проверок")
    assert any(деталь in ожидания.ТАБЛИЦА[к] for к in группы), (
        f"{деталь} не читается ни в одной группе {модель} — ищите расхождение имён, "
        "физически эта деталь у модели есть")
