# -*- coding: utf-8 -*-
"""Прайс по точному проценту АКБ: шапка «72% | 73% | … | 100%» вместо диапазонов.

Владелец перевёл прайс с диапазонов («91-95») на точные проценты. Правило его же:
**цена диапазона — это цена его верхнего процента**, между верхами соседних диапазонов —
ровная лестница. Отсюда и главное, что здесь проверяется:

* какая вкладка перед нами, решает её шапка — старые вкладки читаются как раньше, и точки
  переводятся по одной, без правки кода;
* сделка без точного процента (продавец выбрал диапазон кнопкой) стоит на новой вкладке
  ровно столько же, сколько на старой;
* там, где процент неизвестен или ниже таблицы, цены нет — её называет человек.

Проверяются обе стороны: модуль бота Оценки (`deploy/оценка_бот/google_price.py`) и разбор
прайса в ядре диагностики (`gsheet` + `pricing`).
"""
import asyncio
import inspect

import pytest

from bot_price import загрузить
from pintel_core.analysis.passport import MODELS
from pintel_core.external import gsheet, pricing

ШАПКА_ДИАПАЗОНЫ = ["Модель", "Марка", "Память", "нет информации", "0-74", "75-79", "80-85",
                   "86-90", "91-95", "96-99", "100", "100 (0-30)"]
ШАПКА_ПРОЦЕНТЫ = ["Модель", "Марка", "Память"] + [f"{p}%" for p in range(72, 101)]

# iPhone 16 Pro Max 1024 — строка листа «Актау» и она же после перевода на проценты
# (лист «Актау (копия) 1» от 11.11.2026).
СТРОКА_ДИАПАЗОНЫ = ["Apple", "iPhone 16 Pro Max", "1024", "", "", "310000", "330000",
                    "370000", "390000", "400000", "420000", "420000"]
ЛЕСТНИЦА = [294, 296, 299, 301, 303, 305, 308, 310,          # 72–79
            313, 317, 320, 323, 327, 330,                    # 80–85
            338, 346, 354, 362, 370,                         # 86–90
            374, 378, 382, 386, 390,                         # 91–95
            392, 395, 397, 400,                              # 96–99
            420]                                             # 100
СТРОКА_ПРОЦЕНТЫ = ["Apple", "iPhone 16 Pro Max", "1024"] + [str(v * 1000) for v in ЛЕСТНИЦА]
# Samsung: цена от батареи не зависит — все клетки равны
РОВНАЯ_ДИАПАЗОНЫ = ["Samsung", "Galaxy S24", "128"] + ["100000"] * 9
РОВНАЯ_ПРОЦЕНТЫ = ["Samsung", "Galaxy S24", "128"] + ["100000"] * 29


@pytest.fixture
def бот(monkeypatch):
    return загрузить(monkeypatch)


# ───────────────────────── бот Оценки ─────────────────────────

def test_the_old_tab_is_read_exactly_as_before(бот):
    """Вкладка по диапазонам: колонка по состоянию, точный процент на неё не влияет."""
    assert бот.price_in_row(ШАПКА_ДИАПАЗОНЫ, СТРОКА_ДИАПАЗОНЫ, "86-90") == 370000
    assert бот.price_in_row(ШАПКА_ДИАПАЗОНЫ, СТРОКА_ДИАПАЗОНЫ, "86-90", 88) == 370000
    assert бот.price_in_row(ШАПКА_ДИАПАЗОНЫ, СТРОКА_ДИАПАЗОНЫ, "0-74") is None
    assert бот.price_in_row(ШАПКА_ДИАПАЗОНЫ, СТРОКА_ДИАПАЗОНЫ, "нет информации") is None
    assert бот.price_in_row(ШАПКА_ДИАПАЗОНЫ, РОВНАЯ_ДИАПАЗОНЫ, "нет информации") == 100000
    assert бот.price_in_row(ШАПКА_ДИАПАЗОНЫ, СТРОКА_ДИАПАЗОНЫ, "почти новый") is None


def test_the_exact_percent_picks_its_own_column(бот):
    """Процент с кассы — своя колонка: 88% стоит 354, а не 370 всего диапазона."""
    цена = lambda акб, точно=None: бот.price_in_row(ШАПКА_ПРОЦЕНТЫ, СТРОКА_ПРОЦЕНТЫ, акб, точно)
    assert цена("86-90", 88) == 354000
    assert цена("86-90", "88") == 354000, "из базы процент может прийти строкой"
    assert цена("75-79", 75) == 301000
    assert цена("100", 100) == 420000
    assert цена("100 (0-30)", 100) == 420000
    assert цена("0-74", 73) == 296000, "72–74% в таблице есть — это уже не «ниже таблицы»"


@pytest.mark.parametrize("акб", ["75-79", "80-85", "86-90", "91-95", "96-99", "100", "100 (0-30)"])
def test_a_deal_without_the_exact_percent_costs_what_it_did(бот, акб):
    """Продавец выбрал диапазон кнопкой — берём его верх, и цена та же, что на старой вкладке.

    На этом держится перевод прайса: меняется только то, что измерено точно."""
    старая = бот.price_in_row(ШАПКА_ДИАПАЗОНЫ, СТРОКА_ДИАПАЗОНЫ, акб)
    assert бот.price_in_row(ШАПКА_ПРОЦЕНТЫ, СТРОКА_ПРОЦЕНТЫ, акб) == старая and старая


def test_an_exact_percent_that_argues_with_the_range_is_not_trusted(бот):
    """Диапазон поправили руками, а процент остался прежним — верим диапазону."""
    assert бот.price_in_row(ШАПКА_ПРОЦЕНТЫ, СТРОКА_ПРОЦЕНТЫ, "91-95", 88) == 390000
    assert бот.price_in_row(ШАПКА_ПРОЦЕНТЫ, СТРОКА_ПРОЦЕНТЫ, "100", 103) == 420000
    assert бот.price_in_row(ШАПКА_ПРОЦЕНТЫ, СТРОКА_ПРОЦЕНТЫ, "86-90", "много") == 370000


def test_no_price_where_the_battery_is_unknown_or_below_the_table(бот):
    """Сомнение — не автоцена: такую сделку оценит человек."""
    цена = lambda акб, точно=None: бот.price_in_row(ШАПКА_ПРОЦЕНТЫ, СТРОКА_ПРОЦЕНТЫ, акб, точно)
    assert цена("0-74", 60) is None, "60% ниже таблицы"
