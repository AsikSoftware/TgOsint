# -*- coding: utf-8 -*-
"""Тест на телефоне клиента: словарь тестов и разбор результата.

Киоск поднимает мини-сервер в локальной сети и показывает QR с одноразовым токеном
(`pintel_kiosk/phoneweb.py`). Клиент сканирует его своим телефоном, открывается страница
(`pintel_kiosk/assets/diag.html`) и **телефон сам прогоняет тесты**: тач-сетка с
автозачётом, мультитач, заливка экрана цветами, звук, снимки обеих камер, микрофон.
Результат улетает обратно в киоск, показывается на экране сотрудника и уходит в сделку.

Почему страница, а не приложение: iOS не пускает сторонние приложения на чужой аппарат, а
кабель ничего из этого не умеет — он читает прошивку и привязку модулей, но не нажмёт на
экран, не послушает динамик и не посмотрит в камеру.

Почему «на полуавтомате»: часть тестов телефон зачитывает сам (сетку закрасили целиком —
сенсор жив; пять касаний поймались — мультитач жив; снимок пришёл и он не чёрный — камера
снимает), а часть может оценить только человек, который смотрит и слушает (пятна и полосы
на залитом экране, хрип в динамике). Поэтому у теста два вида ответа, и в сделке они
различаются: «не прошёл» — это дефект, «не проверили» — это неполная проверка.

Этот модуль — общий словарь: его читают страница (ключи в JSON), киоск (экран и посылка) и
обработчик бота (копия в `deploy/оценка_бот/kiosk_core.py`, сверяется тестом).
"""
from __future__ import annotations

import os

# Сама страница. Её отдаёт и мини-сервер киоска (локальная сеть, работает без интернета), и
# наш сервер на домене (HTTPS, телефон пускает страницу к микрофону). Файл один на оба пути.
СТРАНИЦА_ФАЙЛ = os.path.join(os.path.dirname(os.path.abspath(__file__)), "assets", "diag.html")

ОК, ПЛОХО, ПРОПУСК = "ok", "fail", "skip"
ОТВЕТЫ = (ОК, ПЛОХО, ПРОПУСК)

# Ключи ASCII: они едут в JSON со страницы и в посылку боту. Порядок — порядок тестов на
# странице. Третье поле — как тест проходит, одной строкой для экрана кассы.
ТЕСТЫ = (
    ("sensor", "Сенсор", "закрасить пальцем всю сетку — зачёт автоматом"),
    ("multitouch", "Мультитач", "пять касаний одновременно — зачёт автоматом"),
    ("screen", "Экран", "заливка цветами: пятна, полосы, битые точки"),
    ("speaker", "Динамик", "мелодия через динамик"),
    ("mic", "Микрофон", "запись голоса и воспроизведение"),
    ("camera_back", "Камера сзади", "снимок: не чёрный, в фокусе"),
    ("camera_front", "Камера спереди", "снимок: не чёрный, в фокусе"),
)
КЛЮЧИ = tuple(k for k, _, _ in ТЕСТЫ)
ИМЕНА = {k: n for k, n, _ in ТЕСТЫ}
КАК = {k: h for k, _, h in ТЕСТЫ}

ПРЕДЕЛ_ЗАМЕТКИ = 300


def разобрать(данные) -> dict:
    """JSON со страницы → результат теста. Всё чужое отбрасываем молча.

    Страница открыта на телефоне клиента, то есть на устройстве, которого мы не знаем:
    в посылку и в базу Оценки отсюда не должно попасть ничего, кроме наших же ключей и
    наших же трёх ответов.
    """
    if not isinstance(данные, dict):
        return {}
    из = {}
    for k in КЛЮЧИ:
        v = данные.get(k)
        if isinstance(v, str) and v in ОТВЕТЫ:
            из[k] = v
    for поле in ("устройство", "когда", "заметка"):
        v = данные.get(поле)
        if isinstance(v, str) and v.strip():
            из[поле] = v.strip()[:ПРЕДЕЛ_ЗАМЕТКИ]
    return из


def ответы(res: dict) -> dict:
    return {k: v for k, v in (res or {}).items() if k in КЛЮЧИ}


def был(res: dict) -> bool:
    """Тест вообще приходил с телефона (хотя бы один ответ)."""
    return bool(ответы(res))


def готов(res: dict) -> bool:
    """По всем тестам есть ответ — любой, в том числе «не проверили»."""
    return len(ответы(res)) == len(КЛЮЧИ)


def плохие(res: dict) -> list:
    """Тесты, которые телефон НЕ прошёл → [(ключ, имя)]. Это дефект аппарата."""
    return [(k, ИМЕНА[k]) for k in КЛЮЧИ if (res or {}).get(k) == ПЛОХО]


def пропущенные(res: dict) -> list:
    """Тесты без ответа или отмеченные «не проверили» → [(ключ, имя)]. Это неполная
    проверка: про аппарат мы в этой части просто ничего не узнали."""
    return [(k, ИМЕНА[k]) for k in КЛЮЧИ
            if (res or {}).get(k) in (None, ПРОПУСК)]


def словами(res: dict) -> str:
    """Результат одной строкой — в комментарий оценщика и на экран. Пусто — теста не было."""
    if not был(res):
        return ""
    плох = [имя for _, имя in плохие(res)]
    проп = [имя for _, имя in пропущенные(res)]
    куски = [f"Тест на телефоне ({len(ответы(res))} из {len(КЛЮЧИ)})"]
    куски.append("НЕ ПРОШЛИ: " + ", ".join(плох) if плох else "всё прошло")
    if проп:
        куски.append("не проверили: " + ", ".join(проп))
    if (res or {}).get("заметка"):
        куски.append(str(res["заметка"])[:ПРЕДЕЛ_ЗАМЕТКИ])
    return " · ".join(куски)


def коротко(res: dict) -> list:
    """Для экрана кассы: [(имя, ответ)] по порядку тестов, без ответа — None."""
    return [(ИМЕНА[k], (res or {}).get(k)) for k in КЛЮЧИ]
