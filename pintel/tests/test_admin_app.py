# -*- coding: utf-8 -*-
"""Административная программа: связь с сервером, хранение токена, экраны.

Главное, что здесь проверяется, — не кнопки, а два обещания:

* программа НИЧЕГО не считает сама. Число на экране владельца и число в выгрузке обязаны
  совпадать, а совпадают они только если считаются в одном месте — на сервере;
* пусто остаётся пустым. Ноль вместо «не знаем» на экране владельца это ложь, по которой
  принимают решения.
"""
import os
import tempfile

import httpx
import pytest

pytest.importorskip("PySide6")
os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
os.environ.setdefault("LOCALAPPDATA", tempfile.mkdtemp())

from PySide6.QtWidgets import QApplication                       # noqa: E402

from pintel_admin import config, ui                              # noqa: E402
from pintel_admin.app import Окно                                # noqa: E402
from pintel_admin.client import Клиент, НетСвязи, НуженВход      # noqa: E402


@pytest.fixture(scope="module")
def приложение():
    return QApplication.instance() or QApplication([])


def сервер_который(ответы: dict):
    """Поддельный сервер: путь → (код, данные). Сеть в тестах не трогаем."""
    def обработчик(запрос: httpx.Request) -> httpx.Response:
        код, данные = ответы.get(запрос.url.path, (404, {"detail": "нет такого"}))
        return httpx.Response(код, json=данные)
    return httpx.MockTransport(обработчик)


# ---------------------------------------------------------------- связь


def test_the_password_is_traded_for_a_token_and_never_kept():
    """Пароль не сохраняется нигде: он меняется на токен, и дальше живёт только токен."""
    к = Клиент("http://сервер", транспорт=сервер_который({
        "/api/admin/login": (200, {"токен": "t0ken", "имя": "Владелец", "роль": "admin"})}))
    итог = к.войти("vladelec", "секрет")
    assert итог["имя"] == "Владелец" and к.токен == "t0ken"

    config.save(токен=к.токен, имя=итог["имя"])
    сохранено = config.load()
    assert сохранено["токен"] == "t0ken"
    assert "пароль" not in сохранено and "секрет" not in str(сохранено)


def test_a_closed_door_and_a_broken_wire_are_different_conversations():
    """401 — войти заново, 403 — сюда нельзя, обрыв — «сервер не ответил».

    Это не формальность: на первое программа предлагает вход, на второе объясняет, что
    учётная запись не та, а на третье просто ждёт. Одна фраза на три случая заставляла бы
    человека гадать."""
    закрыто = Клиент("http://сервер", "staryj", транспорт=сервер_который({
        "/api/admin/overview": (401, {"detail": "нужен вход"})}))
    with pytest.raises(НуженВход):
        закрыто.обзор()

    чужой = Клиент("http://сервер", "kassir", транспорт=сервер_который({
        "/api/admin/overview": (403, {"detail": "нельзя"})}))
    with pytest.raises(НетСвязи) as отказ:
        чужой.обзор()
    assert "администратор" in str(отказ.value)

    def рвётся(_запрос):
        raise httpx.ConnectError("нет сети")
    оборван = Клиент("http://сервер", "t", транспорт=httpx.MockTransport(рвётся))
    with pytest.raises(НетСвязи) as сбой:
        оборван.точки()
    assert "сервер не ответил" in str(сбой.value)


def test_the_client_asks_the_server_and_does_not_count_anything():
    """Клиент отдаёт ровно то, что прислал сервер: своей арифметики у программы нет."""
    к = Клиент("http://сервер", "t", транспорт=сервер_который({
        "/api/admin/overview": (200, {"проверок": 47, "выкуплено": 19, "выдано": 3_240_000}),
        "/api/admin/points": (200, {"точки": [{"точка": "Тарлан"}]}),
        "/api/admin/machines": (200, {"компьютеры": [{"машина": "KASSA-1"}]}),
        "/api/admin/alerts": (200, {"тревоги": [{"важность": "беда"}]}),
        "/api/admin/people": (200, {"люди": [{"имя": "Данияр К."}]})}))
    assert к.обзор()["выдано"] == 3_240_000
    assert к.точки()[0]["точка"] == "Тарлан"
    assert к.компьютеры()[0]["машина"] == "KASSA-1"
    assert к.тревоги()[0]["важность"] == "беда"
    assert к.люди()[0]["имя"] == "Данияр К."


def test_the_token_file_is_not_readable_by_the_neighbours():
    """Токен — это доступ ко всей сети. Файл с ним закрыт от чужих программ."""
    config.save(токен="t0ken")
    режим = os.stat(os.path.join(config.data_dir(), config.ФАЙЛ)).st_mode & 0o777
    assert режим == 0o600, oct(режим)


