class Pipeline(QThread):
    status = Signal(str, str)                 # состояние связи: state, текст
    step = Signal(str, str, str)              # шаг: ключ, состояние (wait|run|done|warn|fail), подпись
    apple_prompt = Signal(bool)               # показать/скрыть панель «один шаг на телефоне»
    done = Signal(dict)                       # результат (отчёт, ответ сервера, …)
    # Паспорт прочитан (модель, IMEI) — это первые секунды проверки, а дальше идут журнал
    # Apple, база IMEI и реестр: ещё около минуты. Кому нужен только IMEI, тому ждать нечего:
    # в режиме обновления по нему ищут товар в МойСкладе, и поиск идёт параллельно.
    паспорт = Signal(dict)                    # первый отчёт: паспорт, батарея, замки
    прошлая = Signal(dict)                    # взяли проверку, сделанную недавно (не читали заново)
    history = Signal(dict)                    # история Apple пришла позже: обновлённый результат
    failed = Signal(str)                      # человеческий текст ошибки
    модем = Signal(str)                       # телефон стал сетью этого компьютера (режим модема)

    def __init__(self, cfg, client, parent=None, заново=False, отложить_отправку=False):
        super().__init__(parent)
        self.cfg, self.client = cfg, client
        self.skip_apple = threading.Event()
        self.cancel = threading.Event()
        # `заново` ставит кнопка «Проверить телефон заново»: тогда прошлую проверку не берём
        # даже если она свежая — сотрудник сказал, что хочет перечитать аппарат.
        self.заново = bool(заново)
        # `отложить_отправку` ставит режим обновления МойСклада: оценка там создаётся ПОСЛЕ
        # теста и проверок руками (владелец, 19.11.2026). Созданная до них, она ушла бы на
        # сервер без них, и её сертификат — то самое «Заключение» карточки товара — не
        # открылся бы вовсе: страница ждёт пройденных этапов. Отчёт и слепок при этом
        # сохраняются на точке как обычно, в `out/`: отложена отправка, а не проверка.
        self.отложить_отправку = bool(отложить_отправку)
        self.serial = None
        self.started = datetime.now()                 # имя эталона за этот прогон — одно на все перезаписи
        self._listener = None                         # чтобы закрыть канал к телефону снаружи
        self._loop = None
        self._слепок_готов_в = None                   # от этого момента ждём процент батареи
        self._ld = None                               # соединение, которым дочитали слепок
        self._сбор = None                             # сбор доменов телефона (идёт в фоне)
        self._ld_жив = None                           # соединение, через которое открываем боковые
        self._диск = None                             # вопрос про память (телефон считает его долго)

    def run(self):
        try:
            asyncio.run(self._main())
        except Exception as e:                                   # noqa: BLE001
            log_line(traceback.format_exc())
            self.failed.emit(f"{type(e).__name__}: {e}")

    def остановить_слушателя(self):
        """Закрыть канал к телефону немедленно, из чужого потока.

        `cancel` поток замечает не сразу: он может сидеть в запросе к серверу (до 90 с).
        Пока он там сидит, его слушатель журнала держит и переоткрывает канал к тому же
        телефону — а новая проверка уже открыла свой. Два слушателя на одном аппарате
        дерутся за usbmux, и в журнале точки это видно как обрывы раз в секунду."""
        loop = self._loop
        if loop is not None and not loop.is_closed():
            # Отложенные вопросы держат свои соединения lockdown к тому же телефону. Новая
            # проверка начинается через три секунды — и обе читали бы один аппарат.
            try:
                loop.call_soon_threadsafe(lambda: asyncio.ensure_future(self._закрыть_добор()))
            except RuntimeError:
                pass
        слушатель = self._listener
        if слушатель is None or loop is None or loop.is_closed():
            return
        слушатель._stop = True
        задача = getattr(слушатель, "_task", None)
        if задача is not None:
            try:
                loop.call_soon_threadsafe(задача.cancel)
            except RuntimeError:                      # цикл уже остановлен — канал и так закрыт
                pass

    def _step(self, key, state, text=""):
        log_line(f"шаг {key}: {state} {text}".rstrip())
        self.step.emit(key, state, text)

    async def _main(self):
        self._loop = asyncio.get_running_loop()
        self._step("connect", "run", "ждём «Доверять»")
        st = None
        сказано = None

        def связь(s):
            # В журнал — только смена состояния. Цикл спрашивает телефон каждые две секунды,
            # и аппарат в режиме восстановления писал одну и ту же строку сотнями.
            nonlocal сказано
            if s.state != сказано:
                log_line(f"связь: {s.state} {s.human}")
                сказано = s.state
            self.status.emit(s.state, s.human)

        while not self.cancel.is_set():
            st = await connect.wait_ready(on_status=связь, deadline=time.monotonic() + 2.0)
            if st.state == READY:
                break
            if st.state == "NO_DEVICE":
                self.failed.emit("телефон отключили")
                return
            await asyncio.sleep(0.5)
        if self.cancel.is_set():
            return
        ld = st.lockdown
        self.serial = st.serial
        self._step("connect", "done", "телефон на связи")

        # Этот телефон проверяли только что? Тогда берём готовый отчёт и ведём сотрудника
        # дальше — к тесту и медиа. Смотрим ДО слушателя журнала и слепка: ради того же
        # ответа держать клиента минуты незачем.
        if await self._взять_прошлую(ld):
            return

        # Слушатель журнала — с первой секунды: если клиент откроет раздел, пока идёт
        # слепок, записи не пропадут.
        listener = repair_history.Listener(ld, log=log_line)
        self._listener = listener
        await listener.start()
        self.apple_prompt.emit(True)
        try:
            await self._flow(ld, st, listener)
        finally:
            await self._закрыть_добор()
            await listener.stop()

    async def _дождаться_батареи(self, listener):
        """Дать телефону назвать процент батареи — не дольше ЖДАТЬ_БАТАРЕЮ секунд после
        чтения слепка. Обычно ждать почти нечего: за это время сотрудник делает шаг с
        историей Apple, идут Sickw и реестр."""
        if self._слепок_готов_в is None:
            return
        сказали = False
        while not self.cancel.is_set():
            meta = getattr(listener, "meta", None) or {}
            if meta.get("батарея_телефона") or meta.get("канал_потерян"):
                return
            if time.monotonic() - self._слепок_готов_в >= ЖДАТЬ_БАТАРЕЮ:
                log_line(f"батарея: за {ЖДАТЬ_БАТАРЕЮ} с телефон свой процент не назвал — считаем сами")
                return
            if not сказали:
                self._step("battery", "run", "ждём число от телефона")
                сказали = True
            await asyncio.sleep(0.25)

    @staticmethod
    def _донести_батарею(snap, listener):
        """Последнее, что телефон сказал о батарее, — в слепок, из которого строится отчёт."""
        сказал = (getattr(listener, "meta", None) or {}).get("батарея_телефона")
        if сказал:
            snap.setdefault("repair_history_meta", {})["батарея_телефона"] = dict(сказал)

    def _не_ушло(self) -> str:
        """Что написать на шаге «отправка», когда оценка до сервера не дошла.

        «Отправим позже» — только если она правда стоит в очереди. Сервер её отверг — она
        лежит на киоске и сама никуда не уйдёт, обещать обратное нельзя."""
        if not self.client.enabled or getattr(self.client, "отвергнуто", ""):
            return "сохранено на киоске"
        return "отправим позже"

    async def _взять_прошлую(self, ld) -> bool:
        """Взять проверку этого телефона, сделанную недавно. → взяли (и `done` уже ушёл)?

        Что здесь происходит и почему именно так:

        * ищем самый свежий отчёт того же аппарата за окно (`reuse_days`, по умолчанию
          один день) — дольше хранить «свежесть» нельзя, отчёт перестаёт быть про этот
          телефон;
        * **сверяем с живым телефоном то, что читается мгновенно**: серийник, IMEI и
          правовой статус (Найти iPhone, активация, пароль). Один вызов `get_value` — это не
          минуты, а доли секунды, и без этой сверки прошлый отчёт мог бы прикрыть включённый
          за это время «Найти iPhone», то есть заблокированный аппарат в выкупе;
        * расхождение — читаем заново, молча ничего не подменяем. Не прочиталось вовсе —
          так и пишем в отметке: «не сверили», и это видно и на экране, и в карточке.

        Отчёт уезжает на сервер как оценка этого визита: к ней потом прицепляются тест с
        телефона клиента и чек, и без своей оценки их было бы некуда дописать.
        """
        if self.заново or self.cancel.is_set():
            return False
        дней = self.cfg.get("reuse_days", previous.ДНЕЙ)
        находка = previous.найти(os.path.join(data_dir(), "out"), self.serial, дней)
        if not находка:
            return False
        отчёт = находка["отчёт"]
        сверка, почему = await self._сверить_живьём(ld, отчёт)
        if сверка is False:
            log_line(f"прошлая проверка ({находка['словами']}) не подошла: {почему} — читаем заново")
            self._step("passport", "run", "телефон изменился — читаем заново")
            return False
        rep = previous.отметить(отчёт, находка)
        rep["повторная_проверка"]["сверка"] = "сошлась" if сверка else почему
        for ключ, подпись in (("passport", "взята прошлая проверка"),
                              ("battery", находка["словами"]),
                              ("locks", "сверено с телефоном" if сверка else почему),
                              ("apple", "из прошлой проверки"),
                              ("sickw", "из прошлой проверки"),
                              ("rfs", "из прошлой проверки")):
            self._step(ключ, "done", подпись)
        self._step("upload", "run")
        cid = f"{self.serial or 'phone'}-{uuid.uuid4().hex[:12]}"
        payload = {"client_id": cid, "report": json.loads(snapshot.dumps(rep)),
                   "snapshot": _прочитать_слепок(находка["путь"])}
        server = await asyncio.to_thread(self.client.upload, payload)
        if not server:
            server = {"номер": self.client.local_number(), "локально": True}
            self._step("upload", "done" if not self.client.enabled else "warn", self._не_ушло())
        else:
            self._step("upload", "done", "отправлено")
        log_line(f"взята прошлая проверка: {находка['словами']}, папка {находка['путь']}, "
                 f"сверка с телефоном: {rep['повторная_проверка']['сверка']}")
        self.прошлая.emit(dict(rep["повторная_проверка"]))
        self.done.emit({"report": rep, "server": server, "client_id": cid,
                        "serial": self.serial, "out": находка["путь"], "повторная": True})
        return True

    async def _сверить_живьём(self, ld, отчёт: dict):
        """Прошлый отчёт против живого телефона по тому, что читается мгновенно.

        → (True, "") сошлось · (False, почему) расходится · (None, почему) не прочитали.

        Сравниваем только однозначное: серийник и IMEI (это тот же аппарат?) и правовой
        статус (его могли изменить в промежутке). «Не определился» расхождением не считаем —
        это незнание, и врать про сверку из-за него нельзя, поэтому оно едет в отметку
        словами.
        """
        try:
            # с пределом: это последнее чтение по основному соединению, которое его не имело,
            # а телефон, который не отвечает, держал бы здесь всю проверку
            root = await asyncio.wait_for(ld.get_value(), snapshot.ЖДАТЬ_ОТВЕТА) or {}
        except asyncio.TimeoutError:
            return None, f"не сверили: телефон не ответил за {snapshot.ЖДАТЬ_ОТВЕТА:g} с"
        except Exception as exc:                                 # noqa: BLE001
            return None, f"не сверили: телефон не ответил ({type(exc).__name__})"
        # Третий канал «Найти iPhone» — на своём соединении и недолго: этот вопрос телефон
        # может обдумывать минутами, а главный ответ уже есть в корневом домене выше.
        fmip, _почему = await snapshot.спросить_в_стороне(
            lambda: connect.второе_соединение(ld), домен="com.apple.fmip", ждать=3.0)
        fmip = fmip or {}
        пас = (отчёт.get("паспорт") or {})
        for поле, было in (("SerialNumber", пас.get("серийник")),
                           ("InternationalMobileEquipmentIdentity", пас.get("imei"))):
            сейчас = str(root.get(поле) or "").strip()
            if сейчас and было and сейчас.casefold() != str(было).strip().casefold():
                return False, f"{поле}: было {было}, стало {сейчас}"
        живой = legal_mod.build({"root": root, "domains": {"com.apple.fmip": fmip}, "nodes": {}})
        прошлый = отчёт.get("правовой") or {}
        for поле in ("найти_iphone", "активация"):
            стало, было = живой.get(поле), прошлый.get(поле)
            if not стало or стало == "не определился":
                return None, f"не сверили: {поле} сейчас не прочитался"
            if было and стало != было:
                return False, f"{поле}: было «{было}», стало «{стало}»"
        if живой.get("пароль") is not прошлый.get("пароль"):
            return False, "пароль на телефоне изменился"
        return True, ""

    async def _боковое(self):
        """Ещё одно соединение с тем же телефоном — через то, которое живо сейчас."""
        return await connect.второе_соединение(self._ld_жив)

    async def _дождаться_телефона(self):
        """Связь оборвалась посреди чтения — ждём, пока телефон вернётся на кабель.
        → новое соединение; None — отменили или не дождались (тогда `failed` уже сказан)."""
        до = time.monotonic() + ЖДАТЬ_ТЕЛЕФОН_С
        while not self.cancel.is_set():
            st = await connect.wait_ready(deadline=time.monotonic() + 2.0)
            if st.state == READY:
                return st.lockdown
            if time.monotonic() > до:
                self.failed.emit("связь с телефоном пропала и не вернулась — проверьте кабель и порт")
                return None
            await asyncio.sleep(0.5)
        return None

    async def _прочитать_телефон(self, ld):
        """Слепок телефона. Оборвалась связь — ждём телефон и читаем заново, до `ЧТЕНИЙ` раз.

        Раньше чтение на оборванной связи шло дальше: по три раза с паузами стучалось в
        мёртвое соединение за каждым из двадцати узлов. Шаг «Модель и память» крутился
        1,5–3,5 минуты и кончался отчётом с «? ГБ» — на точке 16/38 так кончалось каждое
        третье чтение. → (слепок, попыток диагностики) или (None, 0), если отменили."""
        # Сбор доменов — один на весь телефон, а не на попытку чтения: аппарат тот же, и
        # перечитывание после обрыва не должно выбрасывать ни уже собранное, ни то, что
        # телефон ещё обдумывает. Соединения он открывает через `_боковое`, то есть всегда
        # через живое соединение, а не через то, которое оборвалось.
        self._ld_жив = ld
        if self._сбор is None:
            self._сбор = snapshot.СборДоменов(
                self._боковое, жив=lambda: not self.cancel.is_set(), log=log_line)
        до = time.monotonic() + ЖДАТЬ_ЧТЕНИЕ_ВСЕГО
        частичный = None                          # самое полное, что удалось прочитать
        for попытка in range(1, ЧТЕНИЙ + 1):
            diag = None
            self._ld_жив = ld
            if попытка > 1 and time.monotonic() > до:
                log_line(f"чтение телефона: отведённые {ЖДАТЬ_ЧТЕНИЕ_ВСЕГО:g} с вышли, "
                         f"перечитывать не начинаем")
                if частичный and (частичный.get("root") or {}).get("SerialNumber"):
                    частичный.setdefault("quality", {}).setdefault("не_прочиталось", {})[
                        "чтение телефона"] = f"не дочитали за {ЖДАТЬ_ЧТЕНИЕ_ВСЕГО:g} с"
                    self._ld = ld
                    return частичный, 0
                self.failed.emit("телефон не читается — замените кабель или переставьте в другой порт")
                return None, 0
            try:
                # Шаг виден ДО открытия диагностики: её лестница попыток — это тоже секунды,
                # и раньше в них на экране не двигалось ничего.
                self._step("passport", "run", "открываем диагностику"
                           if попытка == 1 else f"читаем заново · попытка {попытка}")
                # на перечитке лестница попыток короче: о телефоне мы уже знаем, что он капризный
                diag, tries = await connect.open_diagnostics(ld, attempts=6 if попытка == 1 else 3)
                if self.cancel.is_set():
                    return None, 0
                self._step("passport", "run", "" if попытка == 1 else f"читаем заново · попытка {попытка}")
                # про память здесь не спрашиваем: телефон отвечает на это когда как, а объём
                # и так есть с контроллера — спросим в самом конце (`_добрать_память`)
                # Домены телефона собираются в стороне и ВСЕ до единого: ни один вопрос не
                # держит чтение, а тот, что телефон обдумывает, догоняет слепок позже
                # (`_добрать_остаток`, а после отчёта — `_дособрать`).
                snap = await snapshot.collect(
                    ld, diag, log=lambda что: log_line(f"чтение телефона: {что}"),
                    жив=lambda: not self.cancel.is_set(), память=False,
                    соединить=self._боковое, сбор=self._сбор)
                snap["quality"]["диагностика_попыток"] = tries
                # Обязательное дочитываем, а не записываем в «не прочиталось»: телефон на
                # кабеле, и ещё одно чтение стоит секунды. Сделку по неполной проверке касса
                # всё равно не пустит (`ui_deal.можно_отправить`), так что лучше перечитать.
                отчёт = report_mod.build(snap)
                нет_обяз = обязательное.не_прочитано(отчёт)
                # Перечитываем только из-за того, что даёт само чтение. Цвет на новых iOS
                # телефон не отдаёт вовсе, он приходит из базы IMEI уже после чтения или
                # кнопкой сотрудника — а телефон из-за него читали по три раза: за 10 дней
                # на точках 1310 перечитываний и 650 раз «цвет так и не прочитался».
                стоит_перечитать = обязательное.не_прочитано(отчёт, только_кабель=True)
                if стоит_перечитать and попытка < ЧТЕНИЙ and time.monotonic() < до:
                    чего = ", ".join(н for _к, н, _з in стоит_перечитать)
                    log_line(f"обязательное не прочитано ({чего}) — читаем телефон заново, "
                             f"попытка {попытка + 1} из {ЧТЕНИЙ}")
                    self._step("passport", "run", f"не прочитано: {чего} — читаем заново")
                    частичный = _полнее(snap, частичный)
                    continue
                if нет_обяз:
                    log_line("обязательное так и не прочиталось: "
                             + ", ".join(н for _к, н, _з in нет_обяз))
                    snap = _полнее(snap, частичный) or snap
                ждём = snap["quality"].get("ждём_домены") or {}
                if ждём:
                    log_line("телефон ещё обдумывает ответ про: "
                             + ", ".join(д.replace("com.apple.", "") for д in ждём)
                             + " — идём дальше, ответ заберём позже")
                if попытка > 1:
                    snap["quality"]["чтений_из_за_обрыва"] = попытка
                self._ld = ld
                return snap, tries
            except snapshot.Остановлено:
                return None, 0
            except snapshot.СвязьПропала as e:
                log_line(f"чтение оборвалось (попытка {попытка} из {ЧТЕНИЙ}): {e}")
                # Прочитанное этой попыткой не выбрасываем: держим самое полное. Иначе обрыв
                # на последнем узле обнулял всю попытку, и телефон оставался непрочитанным
                # вовсе — ни слепка, ни отчёта, ни сделки.
                частичный = _полнее(getattr(e, "слепок", None), частичный)
                if попытка == ЧТЕНИЙ:
                    if частичный and (частичный.get("root") or {}).get("SerialNumber"):
                        кач = частичный.setdefault("quality", {})
                        кач.setdefault("не_прочиталось", {})["чтение телефона"] = (
                            f"связь рвалась, прочитано не всё: {str(e)[:120]}")
                        кач["чтений_из_за_обрыва"] = попытка
                        log_line("отдаём, что прочитали: проверка неполная, "
                                 f"узлов {len(частичный.get('nodes') or {})}, "
                                 f"доменов {len(частичный.get('domains') or {})}")
                        self._ld = ld
                        return частичный, 0
                    self.failed.emit("связь с телефоном рвётся — замените кабель или переставьте в другой порт")
                    return None, 0
                self._step("passport", "run", "связь пропала — поправьте кабель")
                ld = await self._дождаться_телефона()
                if ld is None:
                    if частичный and (частичный.get("root") or {}).get("SerialNumber"):
                        return частичный, 0      # телефон унесли — но прочитанное отдадим
                    return None, 0
            finally:
                if diag is not None:
                    try:
                        await diag.close()
                    except Exception:                            # noqa: BLE001
                        pass
        return None, 0

    async def _заметить_режим_модема(self, snap) -> None:
        """Телефон раздаёт интернет этому компьютеру по кабелю? — в слепок и в журнал.

        Так бывает, когда на телефоне включён режим модема, а на компьютере работает драйвер
        Apple для него (`tether`): интернет кассы уходит на телефон клиента. Чтению это уже
        не мешает, но в слепке должно быть видно — по этой отметке потом сверяют, какие
        телефоны отвечают медленно. Касса после сделки попросит права и отключит драйвер."""
        try:
            адрес = await asyncio.wait_for(asyncio.to_thread(tether.сеть_телефона), 20)
        except Exception:                                        # noqa: BLE001
            return
        if not адрес:
            return
        snap.setdefault("quality", {})["режим_модема_по_кабелю"] = адрес
        log_line(f"режим модема: телефон раздаёт интернет этой кассе по кабелю (адрес кассы в его сети {адрес})")
        self.модем.emit(адрес)

    async def _добрать_остаток(self, snap) -> list:
        """Дособрать то, что телефон обдумывает, — перед тем как показать отчёт.

        Ничего не бросаем: вопросы без ответа остаются в работе и после отчёта
        (`_дособрать`), пока телефон на кабеле. → какие домены пришли."""
        if self._сбор is None:
            return []
        пришли = await self._сбор.собрать(snap, ждать=snapshot.ЖДАТЬ_ОСТАТОК)
        self._сбор.итог(snap)
        осталось = self._сбор.осталось()
        if пришли or осталось:
            log_line("дособрали: " + (", ".join(д.replace("com.apple.", "") for д in пришли) or "ничего")
                     + ("; ещё обдумывает: " + ", ".join(д.replace("com.apple.", "") for д in осталось)
                        if осталось else "; телефон ответил на всё"))
        return пришли

    def _ждём_память(self) -> bool:
        """Телефон ещё не ответил про память (и не отказал). `готово_за` бывает 0.0 —
        поэтому сравниваем с None, а не «есть ли значение»."""
        диск = self._диск
        return диск is not None and диск.готово_за is None and not диск.беда

    def _ещё_ждём(self) -> bool:
        """Есть ли ещё чего ждать от телефона."""
        домены = self._сбор is not None and bool(self._сбор.осталось())
        return bool(домены or self._ждём_память())

    async def _дособрать(self, snap, out, server, result) -> None:
        """Остаток данных — уже после того, как отчёт показан.

        Телефон всё это время лежит на кабеле: сотрудник снимает фото и видео. Бросать
        ответ, который телефон вот-вот додумает, незачем — он дописывается в слепок, в отчёт
        и в оценку на сервере, как это делает и поздний вердикт Apple. Ждём короткими
        отрезками: сделку могут закрыть в любую секунду, и держать поток нельзя."""
        до = time.monotonic() + snapshot.ЖДАТЬ_ОСТАТОК_ДОЛГО
        try:
            while self._ещё_ждём() and not self.cancel.is_set() and time.monotonic() < до:
                пришло = []
                # ссылки берём разом: закрытие из чужого потока (`остановить_слушателя`)
                # обнуляет их в любой момент, и `self._сбор.итог` упал бы на None
                сбор, диск = self._сбор, self._диск
                if сбор is not None and сбор.осталось():
                    пришло += await сбор.собрать(snap, ждать=1.0)
                    сбор.итог(snap)
                if диск is not None and self._ждём_память() and await диск.вложить(snap, ждать=1.0):
                    пришло.append("память")
                if self.cancel.is_set():
                    return
                if пришло:
                    log_line("телефон додумал уже после отчёта: "
                             + ", ".join(str(д).replace("com.apple.", "") for д in пришло))
                    await self._дописать(snap, out, server, result)
        except asyncio.CancelledError:
            raise
        except Exception:                                        # noqa: BLE001
            log_line("добор остатка: " + traceback.format_exc())

    async def _дописать(self, snap, out, server, result) -> None:
        """Слепок изменился после отчёта — пересобрать отчёт, сохранить и дослать на сервер.

        Запрос к серверу — в отдельном потоке: он может идти до минуты, а в это время по
        этому же циклу событий читается журнал телефона, и там ждут записи Apple."""
        if self.cancel.is_set():
            return                               # сделку закрыли — дописывать уже некуда
        rep = report_mod.build(snap)
        self._save(out, snap, rep)
        self._reference(snap, rep)
        if server and server.get("id") and not server.get("локально") and self.client.enabled:
            try:
                await asyncio.to_thread(
                    self.client.update_evaluation, server["id"], json.loads(snapshot.dumps(rep)),
                    {"domains": snap.get("domains"), "quality": snap.get("quality")})
            except ServerError as e:
                log_line(f"обновление оценки не ушло: {e}")
        if not self.cancel.is_set():
            self.history.emit({**result, "report": rep})

    async def _закрыть_добор(self, snap=None) -> None:
        """Снять все отложенные вопросы и закрыть их соединения.

        `snap` — куда сложить то, что телефон успел сказать перед закрытием: эти ответы
        оплачены ожиданием, и выбрасывать их при закрытии нельзя."""
        if self._сбор is not None:
            await self._сбор.закрыть(snap)
            self._сбор = None
        if self._диск is not None:
            await self._диск.закрыть()
            self._диск = None

    async def _добрать_память(self, snap) -> None:
        """Спросить телефон про память — один раз, в самом конце и недолго.

        В конце — потому что, пока телефон считает ответ, его журнал завален строками службы
        `deleted`, и в этом потоке терялись процент батареи и записи Apple. Недолго — потому
        что объём уже известен с контроллера, а «сколько занято» владельцу не нужно: ответ
        нужен только для сверки объёма. Не успел — идём дальше, в отчёте об этом сказано."""
        if self.cancel.is_set() or self._ld is None:
            return
        ld = self._ld
        self._диск = snapshot.ЧтениеДиска(lambda: connect.второе_соединение(ld))
        if not await self._диск.вложить(snap, ждать=ЖДАТЬ_ПАМЯТЬ):
            # не бросаем: телефон досчитает — ответ допишется в отчёт (`_дособрать`)
            почему = (f"не вышло спросить: {self._диск.беда}" if self._диск.беда
                      else f"телефон не ответил за {ЖДАТЬ_ПАМЯТЬ} с")
            log_line(f"память: {почему} — объём с контроллера, с диском пока не сверен")

    async def _flow(self, ld, st, listener):
        snap, tries = await self._прочитать_телефон(ld)
        if snap is None or self.cancel.is_set():
            # отменённое чтение ничего не рисует и не отдаёт: иначе его шаги ложились бы
            # поверх новой проверки, которую окно уже начало
            return
        self._слепок_готов_в = time.monotonic()
        snap["quality"]["подключение"] = st.timings
        rep = report_mod.build(snap)
        pas, bat = rep["паспорт"], rep["батарея"]
        self._step("passport", "done", f"{pas['модель']} · {rep['память'].get('объём_гб') or '?'} ГБ")
        h = bat.get("здоровье_%")
        self._step("battery", "done" if h is not None else "warn", f"{h} %" if h is not None else "не прочиталась")
        leg = rep["правовой"]
        locks = [x for x, ok in (("Найти iPhone", leg["найти_iphone"] != "включён"),
                                 ("надзор MDM", leg["mdm"] is not True), ("пароль", not leg["пароль"])) if not ok]
        self._step("locks", "done" if not locks else "warn", "чисто" if not locks else ", ".join(locks))
        # Паспорт готов — отдаём его наружу, не дожидаясь остального. Дальше ещё около
        # минуты: журнал Apple, база IMEI, реестр и доборы. Режим обновления по IMEI ищет
        # товар в МойСкладе, и держать этот поиск до конца диагностики незачем.
        if not self.cancel.is_set():
            self.паспорт.emit(rep)

        # Что Apple сказала по кабелю. Это не «ждём ответа», а готовый ответ: проверку
        # подлинности телефон держит в своём IORegistry и сам читает её оттуда, поэтому
        # ради неё никого ждать не надо. Журнал с экрана телефона добавляет к ней экран и
        # камеры — но уже не на пустом месте.
        кабель_apple = authcp.словами((rep.get("детали_вердикт") or {}).get("apple_кабель"))
        if кабель_apple:
            log_line("проверка Apple по кабелю: " + кабель_apple)

        # история Apple: у модели вообще есть? (iPhone X и старше, iOS < 15.2 — нет, не держим клиента)
        hist_ok, hist_why = repair_history.supported(pas["код_модели"], pas["ios"])
        if not hist_ok:
            self.apple_prompt.emit(False)
            items, raw, waited = {}, "", 0
            self._step("apple", "done", hist_why)
        else:
            # Вердикт по деталям уже собран с кабеля (привязка + печать Apple). Журнал Apple —
            # только обогащение датами, поэтому ждём коротко и не держим клиента.
            secs = int(self.cfg.get("apple_history_seconds") or 45)
            self._step("apple", "run", f"ждём один шаг на телефоне · {secs} с")
            items, raw, waited = await listener.wait(
                secs, keep_going=lambda: not (self.skip_apple.is_set() or self.cancel.is_set()),
                on_tick=lambda s: self.step.emit(
                    "apple", "run", ("экран открыт, читаем…" if listener.meta.get("раздел_открыт")
                                     else f"«Об этом устройстве» на телефоне · {max(0, secs - s)} с")))
            self.apple_prompt.emit(False)
            # Ожидание кончилось — значит у шага есть ответ. Висеть он права не имеет:
            # «ждём Apple» без конца это не результат, а тупик, в котором сотрудник решает,
            # что подвисла программа. Слушатель при этом работает дальше, пока телефон на
            # кабеле, и пришедший позже вердикт шаг и отчёт дописывают (_дослушать_apple).
            хвост = (" · " + кабель_apple) if кабель_apple else ""
            if items:
                self._step("apple", "done", "получена")
            elif listener.state == "opened_unknown":
                # «Настройки» держат разбор в памяти: на втором заходе телефон печатает
                # короткий кусок без вердикта. Советовать «откройте раздел» тут бесполезно —
                # его уже открыли; помогает закрыть «Настройки» целиком и зайти заново.
                self._step("apple", "warn", "раздел открыт, вердикта телефон не прислал" + хвост)
            else:
                self._step("apple", "warn", "раздел на телефоне не открывали" + хвост)
        snap["repair_history"], snap["repair_history_raw"] = items, raw
        meta = dict(getattr(listener, "meta", None) or {})
        meta.update({"статус": listener.state if hist_ok else "не поддерживается", "почему": hist_why})
        snap["repair_history_meta"] = meta
        rep = report_mod.build(snap)
        log_line(f"история Apple: {listener.state if hist_ok else hist_why} за {waited} с; формат "
                 f"{meta.get('формат')}; строк журнала {listener.lines}, по теме {meta.get('строк_по_теме')}, "
                 f"подключений {listener.connects}, обрывов {listener.reconnects}")
        if self.cancel.is_set():
            return

        # Sickw через сервер (ключ только там). Непроверенный чёрный список — это НЕ чистый
        # чёрный список: шаг горел оранжевым, а в отчёте о нём не было ни слова.
        # Запрос блокирующий, поэтому в отдельный поток: иначе на всё время ожидания
        # встаёт цикл событий и слушатель журнала не читает syslog — а именно там приходит
        # ПОВТОРНАЯ печать записей Apple, в которой и появляются замены.
        не_проверено = snap.setdefault("quality", {}).setdefault("не_проверено", {})
        imei = pas.get("imei") or ""
        if self.cfg.get("sickw", True) and self.client.enabled and sickw.luhn_ok(imei):
            self._step("sickw", "run")
            try:
                snap["sickw"] = await asyncio.to_thread(self.client.sickw, imei)
                rep = report_mod.build(snap)
                sk = rep.get("sickw") or {}
                if sk.get("в_чёрном_списке") is None:
                    # ответ пришёл, а поля чёрного списка в нём нет — «проверено» тут неправда
                    не_проверено["чёрный список (Sickw)"] = "в ответе базы IMEI нет статуса чёрного списка"
                self._step("sickw", "done" if sk.get("в_чёрном_списке") is not True else "fail",
                           "чисто" if sk.get("в_чёрном_списке") is False else (sk.get("чёрный_список") or "проверено"))
            except ServerError as e:
                self._step("sickw", "warn", "база недоступна")
                не_проверено["чёрный список (Sickw)"] = "база IMEI недоступна"
                log_line(f"sickw: {e}")
        elif not sickw.luhn_ok(imei):
            self._step("sickw", "warn", "у телефона нет IMEI")
            не_проверено["чёрный список (Sickw)"] = "у телефона не прочитался IMEI"
        else:
            self._step("sickw", "warn", "выключена в кассе")
            не_проверено["чёрный список (Sickw)"] = "проверка по базе IMEI выключена в настройках"

        # Реестр РФС РК — оба IMEI, при любой оценке
        рфс, рфс_нет = await asyncio.to_thread(
            проверить_рфс, self.cfg, [pas.get("imei"), pas.get("imei2")], self._step)
        if рфс_нет:
            не_проверено["реестр РФС"] = рфс_нет
        if рфс is not None:
            snap["rfs"] = рфс
        # Процент батареи телефон называет сам, но раз в 20 секунд: строка могла прийти уже
        # после того, как метаданные слушателя сняты выше, или не успеть вовсе, если проверка
        # прошла быстро. Добираем её и кладём в слепок самое свежее, что слышали.
        await self._дождаться_батареи(listener)
        self._донести_батарею(snap, listener)
        было_гб = rep["память"].get("объём_гб")
        # Телефон прочитан, и дальше ничего не имеет права его потерять: любая осечка добора
        # — это строка в журнале, а не отмена проверки.
        поздние = []
        try:
            await self._добрать_память(snap)
            поздние = await self._добрать_остаток(snap)
            await self._заметить_режим_модема(snap)
        except (asyncio.CancelledError, snapshot.Остановлено):
            raise
        except Exception:                                        # noqa: BLE001
            log_line("добор перед отчётом: " + traceback.format_exc())
        rep = report_mod.build(snap)
        if rep["память"].get("объём_гб") != было_гб:
            self._step("passport", "done", f"{pas['модель']} · {rep['память'].get('объём_гб') or '?'} ГБ")
        if поздние:
            # поздний ответ мог изменить замки (третий канал «Найти iPhone», ограничения)
            leg = rep["правовой"]
            locks = [x for x, ok in (("Найти iPhone", leg["найти_iphone"] != "включён"),
                                     ("надзор MDM", leg["mdm"] is not True), ("пароль", not leg["пароль"])) if not ok]
            self._step("locks", "done" if not locks else "warn", "чисто" if not locks else ", ".join(locks))
        h = rep["батарея"].get("здоровье_%")
        self._step("battery", "done" if h is not None else "warn", f"{h} %" if h is not None else "не прочиталась")
        if self.cancel.is_set():
            return

        # сохраняем локально и отправляем
        cid = f"{self.serial or 'phone'}-{uuid.uuid4().hex[:12]}"
        out = os.path.join(data_dir(), "out", f"{datetime.now():%Y%m%d_%H%M%S}_{(self.serial or 'phone')[:12]}")
        os.makedirs(out, exist_ok=True)
        self._save(out, snap, rep)
        payload = {"client_id": cid, "report": json.loads(snapshot.dumps(rep)),
                   "snapshot": json.loads(snapshot.dumps(snap))}
        if self.отложить_отправку:
            # заключение создадут после проверок — отсюда оценка не уходит вовсе
            server = {"отложено": True}
            self._step("upload", "wait", "после проверок")
        else:
            self._step("upload", "run")
            # в отдельный поток по той же причине: пока ждём сервер, журнал Apple должен читаться
            server = await asyncio.to_thread(self.client.upload, payload)   # без связи кладёт в очередь сама
            if not server:
                server = {"номер": self.client.local_number(), "локально": True}
                self._step("upload", "done" if not self.client.enabled else "warn", self._не_ушло())
            else:
                self._step("upload", "done", "отправлено")
        result = {"report": rep, "server": server, "client_id": cid, "serial": self.serial, "out": out}
        if self.cancel.is_set():
            # Отменили, пока оценка уходила на сервер: окно уже ведёт новую проверку, и этот
            # результат лёг бы поверх неё. Оценка при этом сохранена — на диске и на сервере.
            return
        self.done.emit(result)
        self._reference(snap, rep)                    # эталон с каждого телефона, уже после результата
        if self.cancel.is_set():
            return

        # Пока телефон на кабеле (сотрудник снимает фото и видео), догоняем две вещи сразу:
        # вердикт Apple, который мог прийти позже, и ответы, которые телефон ещё обдумывает.
        # Обе дописывают слепок, отчёт и оценку на сервере; ни одна не держит другую.
        задачи = [asyncio.ensure_future(self._дособрать(snap, out, server, result))]
        if hist_ok:
            задачи.append(asyncio.ensure_future(
                self._дослушать_apple(snap, out, server, result, listener, items)))
        try:
            # ждём обе: вердикт Apple мог прийти позже, а телефон — додумать ответ. Одна
            # закончилась — вторая продолжает: бросать её из-за этого незачем. Осечка одной
            # тоже не гасит вторую: отчёт уже показан, и терять из-за неё нечего.
            for итог in await asyncio.gather(*задачи, return_exceptions=True):
                if isinstance(итог, BaseException) and not isinstance(итог, asyncio.CancelledError):
                    log_line(f"после отчёта: {type(итог).__name__}: {итог}")
        finally:
            for задача in задачи:
                задача.cancel()
            await asyncio.gather(*задачи, return_exceptions=True)

    async def _дослушать_apple(self, snap, out, server, result, listener, items) -> None:
        """Слушаем дальше, пока телефон на кабеле: вердикт мог прийти позже (клиент открыл
        раздел после результата) или ИЗМЕНИТЬСЯ — iOS печатает записи повторно, когда
        подгрузит список ремонтов Apple, и только тогда в них появляются замены."""
        # Шаг здесь НЕ открываем заново. Прежде он уходил в «ждём историю Apple» и больше
        # не закрывался никогда: вердикта с экрана телефона могло не быть вовсе (iPhone 14
        # на iOS 16.5.1, 24.11.2026 — телефон написал свой кусок журнала без вердикта), а
        # на кассе это выглядело как зависшая программа. Слушаем молча; пришёл вердикт —
        # шаг закрывается ниже с «получена».
        seen = repair_history.signature(items)
        while not self.cancel.is_set():
            items, raw, waited = await listener.wait_change(seen, keep_going=lambda: not self.cancel.is_set())
            if self.cancel.is_set() or repair_history.signature(items) == seen:
                return
            seen = repair_history.signature(items)
            snap["repair_history"], snap["repair_history_raw"] = items, raw
            snap["repair_history_meta"] = {**(getattr(listener, "meta", None) or {}), "статус": "found", "почему": ""}
            rep = report_mod.build(snap)
            self._save(out, snap, rep)
            self._reference(snap, rep)                # вердикт пришёл позже — перезаписываем эталон
            log_line(f"история Apple обновилась через {waited} с: {len(items)} записей")
            if server and server.get("id") and not server.get("локально") and self.client.enabled:
                try:
                    # в отдельном потоке: запрос идёт до минуты, а в это время по этому же
                    # циклу событий читается журнал телефона и дособирается остаток
                    await asyncio.to_thread(
                        self.client.update_evaluation, server["id"], json.loads(snapshot.dumps(rep)),
                        {"repair_history": items, "repair_history_raw": raw,
                         "repair_history_meta": getattr(listener, "meta", None)})
                except ServerError as e:
                    log_line(f"обновление оценки не ушло: {e}")
            self._step("apple", "done", "получена")
            self.history.emit({**result, "report": rep})

    def _reference(self, snap, rep):
        """Эталон с КАЖДОГО телефона: обезличенный слепок, сырой журнал Apple и наш вердикт.
        На этом учится разбор: новая iOS пишет вердикт по-своему, и угадывать нечего — нужен
        живой аппарат. Пишем после результата, чтобы не задержать экран; если вердикт пришёл
        позже, файл за тот же прогон перезаписывается.

        Обезличиваем здесь же: наружу (и даже в папку на точке) серийники и IMEI не уходят.
        Замена не удалась или изменила выводы — эталон не пишем вовсе."""
        try:
            clean, ok, why = reference.pseudonymize(snap, report_mod.build)
            if not ok:
                log_line(f"эталон не сохранён (обезличивание): {why}")
                return
            clean_rep = report_mod.build(clean)
            path = os.path.join(data_dir(), "эталоны", reference.bundle_name(clean_rep, self.started))
            reference.save_bundle(
                path, clean, clean_rep,
                reference.auto_truth(раздел_открывали=bool((snap.get("repair_history_meta") or {}).get("раздел_открыт"))),
                raw=clean.get("repair_history_raw") or "", dumps=snapshot.dumps)
            keep = int(self.cfg.get("reference_keep") or 500)
            старые = sorted(glob.glob(os.path.join(data_dir(), "эталоны", "эталон_*.zip")),
                            key=os.path.getmtime, reverse=True)[keep:]
            for p in старые:                           # диск на точке не резиновый
                try:
                    os.remove(p)
                except OSError:
                    pass
        except Exception as exc:                       # noqa: BLE001 — эталон не имеет права сорвать приём
            log_line(f"эталон не сохранён: {type(exc).__name__}: {exc}")

    @staticmethod
    def _save(out, snap, rep):
        open(os.path.join(out, "snapshot.json"), "w", encoding="utf-8").write(snapshot.dumps(snap))
        open(os.path.join(out, "report.json"), "w", encoding="utf-8").write(snapshot.dumps(rep))


class SealedPipeline(QThread):
    """Запечатанный аппарат: кабеля нет. По IMEI с коробки — база IMEI (Sickw, служба для
    запечатанных: модель, объём, цвет, активация) и реестр РФС; из них отчёт в тех же
    ключах, что и с кабеля, чтобы экран, чек и посылка в Оценку читали его одинаково.

    На кассу такая оценка не уходит: там ждут слепок телефона, а его нет. Отчёт лежит в
    out/ рядом с остальными."""
    step = Signal(str, str, str)
    done = Signal(dict)
    failed = Signal(str)

    def __init__(self, cfg, client, imeis, parent=None):
        super().__init__(parent)
        self.cfg, self.client = cfg, client
        self.imeis = [str(x or "").strip() for x in (imeis or []) if str(x or "").strip()]

    def run(self):
        try:
            self._main()
        except Exception as e:                                   # noqa: BLE001
            log_line(traceback.format_exc())
            self.failed.emit(f"{type(e).__name__}: {e}")

    def _step(self, key, state, text=""):
        log_line(f"запечатанный · шаг {key}: {state} {text}".rstrip())
        self.step.emit(key, state, text)

    def _main(self):
        имеи = self.imeis
        if not имеи or not sickw.luhn_ok(имеи[0]):
            self.failed.emit("IMEI с коробки не проходит контрольную цифру — проверьте цифры")
            return
        self._step("passport", "run", "по базе IMEI")
        sk, не_проверено = None, {}
        службы = [int(x) for x in (self.cfg.get("sickw_services_sealed") or [sickw.SERVICE_SEALED])]
        if self.cfg.get("sickw", True) and self.client.enabled:
            self._step("sickw", "run", "служба " + ", ".join(map(str, службы)))
            try:
                sk = self.client.sickw(имеи[0], services=службы)
                if sk.get("в_чёрном_списке") is None:
                    не_проверено["чёрный список (Sickw)"] = "в ответе базы IMEI нет статуса чёрного списка"
                self._step("sickw", "done" if sk.get("в_чёрном_списке") is not True else "fail",
                           "чисто" if sk.get("в_чёрном_списке") is False
                           else (sk.get("чёрный_список") or "проверено"))
            except ServerError as e:
                self._step("sickw", "warn", "база недоступна")
                не_проверено["чёрный список (Sickw)"] = "база IMEI недоступна"
                log_line(f"sickw: {e}")
        else:
            self._step("sickw", "warn", "выключена в кассе")
            не_проверено["чёрный список (Sickw)"] = "проверка по базе IMEI выключена в настройках"
        if sk and sk.get("модель"):
            self._step("passport", "done", f"{sk['модель']} · {sk.get('объём_гб') or '?'} ГБ")
        else:
            self._step("passport", "warn", "модель по базе не определилась")

        рфс, рфс_нет = проверить_рфс(self.cfg, имеи, self._step)
        if рфс_нет:
            не_проверено["реестр РФС"] = рфс_нет
        rep = sealed_mod.build(sk, имеи, рфс, не_проверено=не_проверено)
        out = os.path.join(data_dir(), "out", f"{datetime.now():%Y%m%d_%H%M%S}_box_{имеи[0][-6:]}")
        os.makedirs(out, exist_ok=True)
        open(os.path.join(out, "report.json"), "w", encoding="utf-8").write(snapshot.dumps(rep))
        self.done.emit({"report": rep, "server": {"номер": self.client.local_number(), "локально": True},
                        "client_id": f"box-{uuid.uuid4().hex[:12]}", "serial": None, "out": out,
                        "запечатанный": True})
