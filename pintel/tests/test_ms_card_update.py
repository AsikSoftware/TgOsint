def test_the_update_mode_ticks_the_diagnostics_box_and_writes_the_date(м):
    """В режиме обновления телефон точно читали кабелем — для этого режим и сделан. Значит
    галочка «Прошёл диагностику» ставится, а дату присылает касса (просьба владельца 18.11.2026)."""
