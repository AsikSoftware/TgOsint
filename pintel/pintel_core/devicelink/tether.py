# -*- coding: utf-8 -*-
"""Режим модема iPhone на компьютере кассы: телефон клиента не должен становиться её сетью.

Что происходит. iPhone с включённым «Режимом модема», подключённый кабелем к доверенному
компьютеру с драйверами Apple, сам становится для него проводной сетью: Windows видит
адаптер «Apple Mobile Device Ethernet», получает от телефона адрес 172.20.10.x и, как любую
проводную сеть, ставит её выше Wi-Fi. Интернет кассы уходит на телефон клиента: на телефоне
загорается «Режим модема: 1 подключение», касса работает за счёт клиента, а когда кабель
вынимают — остаётся без сети, пока Windows не вернётся на Wi-Fi. Владелец заметил, что
именно с такими телефонами чтение и зависало (17.11.2026); зависание само закрыто в
`snapshot._читать_домены` — ни один вопрос телефону больше не ждут без предела.

Касса сетью телефона не пользуется вовсе: она читает его через usbmux. Режим модема на
Windows — отдельный драйвер из того же пакета Apple (служба `Netaapl`, netaapl64.sys).
Поэтому:

  * `отключить` — под администратором ставит этому драйверу тип запуска «отключено».
    Адаптер больше не поднимается ни для одного телефона, телефон на «режим модема: 1
    подключение» не переходит, а читается как раньше. Обратно — `включить`;
  * `драйвер` — без прав: что с драйвером сейчас. Служба появляется в Windows только когда
    к компьютеру впервые подключат телефон с режимом модема, и обновление драйвера может
    включить её снова — поэтому касса смотрит на это при каждом запуске;
  * `сеть_телефона` — без прав: стал ли телефон сетью этого компьютера прямо сейчас. Для
    журнала и слепка — на случай, если драйвер отключить не дали.

Наружу всё ходит через то же «окружение», что и `apple_service` (в тестах подменяется).
"""
import re

from . import apple_service

СЛУЖБА = "Netaapl"                                # драйвер «Apple Mobile Device Ethernet»
АДАПТЕР = "Apple Mobile Device Ethernet"
# «не прочитан» — отдельное состояние, а не «нет»: `sc` мог отказать в доступе, не успеть
# или ответить на незнакомом языке. Называть это «драйвера нет» значило бы отрапортовать
# сотруднику «режим модема отключён», ничего не проверив.
НЕТ, ВКЛЮЧЁН, ОТКЛЮЧЁН, НЕ_ЗНАЕМ = "нет", "включён", "отключён", "не прочитан"
ГОТОВО, НУЖНЫ_ПРАВА, НЕ_ВЫШЛО, НЕ_WINDOWS = (apple_service.ГОТОВО, apple_service.НУЖНЫ_ПРАВА,
                                             apple_service.НЕ_ВЫШЛО, apple_service.НЕ_WINDOWS)
ЧЕЛОВЕКУ = {
    ГОТОВО: "Режим модема iPhone на этом компьютере отключён: телефон клиента не станет сетью кассы.",
    НЕ_ЗНАЕМ: "Windows не сказала, что с драйвером режима модема. Попробуйте ещё раз.",
    НУЖНЫ_ПРАВА: "Windows не дала прав: в окне «Разрешить?» нужно нажать «Да».",
    НЕ_ВЫШЛО: "Режим модема iPhone отключить не удалось.",
    НЕ_WINDOWS: "Режим модема по кабелю мешает только на Windows.",
}

_IPV4 = re.compile(r"(?<![\d.])(\d{1,3}(?:\.\d{1,3}){3})(?![\d.])")


def драйвер(окр=None) -> str:
    """Что с драйвером режима модема: нет / включён / отключён / не прочитан. Прав не нужно."""
    окр = окр or apple_service.Windows()
    try:
        код, текст = окр.запустить(["sc", "qc", СЛУЖБА])
    except Exception:                                             # noqa: BLE001 — `sc` не ответил
        return НЕ_ЗНАЕМ
    if код == apple_service.НЕТ_ТАКОЙ_СЛУЖБЫ:
        return НЕТ                                # 1060: драйвер ещё не ставился на этот компьютер
    if код != 0:
        return НЕ_ЗНАЕМ                           # отказано в доступе и прочее — это не «нет»
    запуск = apple_service._ЗАПУСК.search(текст)
    if not запуск:
        return НЕ_ЗНАЕМ
    return ОТКЛЮЧЁН if запуск.group(2) == "DISABLED" else ВКЛЮЧЁН


def отключить(окр=None) -> bool:
    """Под администратором: драйвер режима модема больше не запускается. → вышло ли.

    Службы нет — делать нечего, это тоже «вышло»: появится (первый телефон с режимом
    модема) — касса увидит это при следующем запуске и отключит."""
    окр = окр or apple_service.Windows()
    if драйвер(окр) == НЕТ:
        return True
    try:
        окр.запустить(["sc", "config", СЛУЖБА, "start=", "disabled"])
        # уже поднятый адаптер снимаем сразу; откажет (драйвер занят телефоном на кабеле) —
        # не беда: со следующего подключения он не поднимется
        окр.запустить(["sc", "stop", СЛУЖБА])
    except Exception:                                             # noqa: BLE001 — `sc` не ответил
        return False
    return драйвер(окр) == ОТКЛЮЧЁН


def включить(окр=None) -> bool:
    """Под администратором: вернуть режим модема по кабелю, как было у Apple."""
    окр = окр or apple_service.Windows()
    if драйвер(окр) == НЕТ:
        return True
    try:
        окр.запустить(["sc", "config", СЛУЖБА, "start=", "demand"])
    except Exception:                                             # noqa: BLE001 — `sc` не ответил
        return False
    return драйвер(окр) == ВКЛЮЧЁН


def обеспечить(окр=None):
    """Без прав посмотреть, с правами — отключить. Одно окно Windows «Разрешить?», и только
    если драйвер включён. → (итог, текст для человека)."""
    окр = окр or apple_service.Windows()
    if not окр.это_windows():
        return НЕ_WINDOWS, ЧЕЛОВЕКУ[НЕ_WINDOWS]
    что = драйвер(окр)
    if что == НЕ_ЗНАЕМ:
        # не прочитали — так и говорим: «отключено» здесь было бы неправдой
        return НЕ_ВЫШЛО, ЧЕЛОВЕКУ[НЕ_ЗНАЕМ]
    if что != ВКЛЮЧЁН:
        return ГОТОВО, ЧЕЛОВЕКУ[ГОТОВО]
    try:
        окр.от_администратора(["--apple-setup", "--modem-off"], ждать_мс=120_000)
    except apple_service.ОтказПрав:
        return НУЖНЫ_ПРАВА, ЧЕЛОВЕКУ[НУЖНЫ_ПРАВА]
    except Exception as e:                                        # noqa: BLE001
        return НЕ_ВЫШЛО, f"{ЧЕЛОВЕКУ[НЕ_ВЫШЛО]} ({e})"
    if драйвер(окр) == ОТКЛЮЧЁН:
        return ГОТОВО, ЧЕЛОВЕКУ[ГОТОВО]
    return НЕ_ВЫШЛО, ЧЕЛОВЕКУ[НЕ_ВЫШЛО]


def адрес_из_ipconfig(текст: str):
    """Вывод `ipconfig /all` → адрес этого компьютера в сети телефона, или None.

    Подписи в выводе переведены, а название адаптера и адреса — нет, поэтому ищем блок с
    «Apple Mobile Device Ethernet» и первый настоящий IPv4 в нём (адрес стоит раньше маски,
    шлюза и DNS). Кабель в адаптере «не подключён» — адресов в блоке нет вовсе."""
    for блок in re.split(r"(?m)^(?=\S)", str(текст or "")):
        if АДАПТЕР.lower() not in блок.lower():
            continue
        for m in _IPV4.finditer(блок):
            адрес = m.group(1)
            if адрес.startswith(("169.254.", "255.", "0.")):      # сам себе назначил / маска
                continue
            return адрес
    return None


def сеть_телефона(окр=None):  # noqa: D401
    """Телефон сейчас раздаёт интернет этому компьютеру по кабелю? → адрес компьютера в его
    сети или None. Прав не нужно; не Windows или не вышло спросить — None."""
    окр = окр or apple_service.Windows()
    try:
        if not окр.это_windows():
            return None
        код, текст = окр.запустить(["ipconfig", "/all"], ждать=15)
    except Exception:                                             # noqa: BLE001
        return None
    return адрес_из_ipconfig(текст) if код == 0 else None
