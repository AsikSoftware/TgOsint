# -*- coding: utf-8 -*-
"""Батарея из узла AppleSmartBattery.

**Процент здоровья телефон называет сам.** `powerd` печатает его в журнал без всяких
открытых экранов: на кабеле — раз в 20 секунд, без питания — примерно раз в две минуты.
Это ровно то число, что стоит в «Максимальной ёмкости». iOS 27 пишет «Updated battery
health (… maxCap=79 cycleCount=1064)», iOS 14–26 — «Previous Battery Health: Flags:…
State:… MaxCapacity:75 CycleCount:1756» и следом «Updated Battery Health: MaxCapacity:75».
Вторая форма одна и та же с iOS 14: исходники powerd открыты
(apple-oss-distributions/PowerManagement, pmconfigd/BatteryTimeRemaining.m,
`_setBatteryHealthData`), вживую она снята на iOS 18.7.8 и на iOS 26. Число приходит из
слушателя журнала (`repair_history`), и касса ждёт первую строку до 25 секунд после
чтения слепка (`worker.ЖДАТЬ_БАТАРЕЮ`).

**Строка не пришла — считаем сами, и это нижняя граница экрана.** Правило телефона из тех
же исходников (`checkNominalCapacity`): процент = ceil(NominalChargeCapacity /
DesignCapacity × 100), и на экране он только убывает — на единицу и не чаще, чем раз в
пять циклов. Значит, экран не должен быть ниже ceil(NCCMin / DesignCapacity × 100) — это мы
и считаем — и изредка стоит на процент выше, пока не «дошёл». На семи аппаратах, где
известны и число телефона, и ёмкости, совпало шесть (79 при 78,41; 77 при 76,52; 76 при
75,81; 94 при 93,14; 82 при 81,48; 75 при 74,03), у седьмого экран 69 при наших 68.
Текущая NominalChargeCapacity гуляет выше экрана на процент-три. Где NCCMin не отдают — а
iOS 27 его не отдаёт вовсе — остаётся расчёт по текущей ёмкости. Поэтому отчёт всегда
говорит, откуда взято число.

**Циклы в строке телефона — не текущие.** Это счётчик на момент последнего изменения
процента (там же, `checkNominalCapacity`), поэтому он отстаёт от узла: 1810 и 1756, 1241 и
1021. Текущие циклы — в узле. Обратное — узел меньше, чем запомнил телефон, — у той же
батареи невозможно: при смене серийника батареи телефон свою запись стирает.

MaxCapacity — НЕ процент здоровья, а константа шкалы (100 даже на убитой батарее).
В новых iOS (26/27) ёмкости переехали во вложенный словарь BatteryData — deep() достаёт их
на любой глубине.
"""
from ..devicelink.nodes import deep, num, txt

# Отпечаток батареи по модели: заводская ёмкость одна на модель
# (iPhone13,2 = 2798, а не рекламные 2815).
# Порог подделки 1.03 обоснован сверкой с вердиктом Apple на шести аппаратах.

# На сколько циклов счётчик батареи может быть меньше запомненного телефоном, прежде чем мы
# назовём это сбросом счётчика. По смыслу — ни на сколько; два цикла — запас на неизвестное.
ЗАПАС_ЦИКЛОВ = 2


def analyze(node, телефон=None):
    """`телефон` — что сказал сам аппарат (meta слушателя, ключ «батарея_телефона»)."""
    b = node or {}
    design = num(deep(b, "DesignCapacity"))
    nominal = num(deep(b, "NominalChargeCapacity")) or num(deep(b, "AppleRawMaxCapacity"))
    # Минимум за жизнь: лежит в BatteryData.LifetimeData, у разных iOS на разной глубине.
    минимум = num(deep(b, "NCCMin"))
    сырые_циклы = deep(b, "CycleCount")
    cycles = num(сырые_циклы)
    op_h = num(deep(b, "TotalOperatingTime"))
    tmax = num(deep(b, "MaximumTemperature")) // 10
    serial = txt(deep(b, "Serial"))
    # iOS 27 этот счётчик не отдаёт вовсе. Нет ключа — значит «не знаем», а не «ноль снятий».
    сырой_шлейф = deep(b, "BatteryCellDisconnectCount")
    disconnects = num(сырой_шлейф)
    health = текущее = None
    основание = ""
    if design and nominal:
        текущее = min(round(nominal * 100 / design), 100)
        # NCCMin берём только когда он действительно минимум и в разумных пределах: на одном
        # аппарате он пришёл больше заводской ёмкости, и доверять ему вслепую нельзя.
        по_экрану = минимум if (минимум and 0.4 * design <= минимум <= nominal) else None
        if по_экрану:
            # вверх, как считает сам телефон; ниже этого числа экран не опускается (см. шапку)
            health = min(-(-по_экрану * 100 // design), 100)
        else:
            health = min(round(nominal * 100 / design), 100)
        основание = "минимум за жизнь" if по_экрану else "текущая ёмкость (завышает)"

    # Что сказал сам телефон — главнее всего, что мы можем посчитать.
    сам = (телефон or {}).get("процент")
    if isinstance(сам, int) and 1 <= сам <= 200:
        health = min(сам, 100)                   # выше ста телефон и сам не рисует
        основание = "сказал сам телефон"

    flags, doubts = [], []
    if design and nominal:
        r = nominal / design
        if r > 1.08:
            flags.append(f"заявляет {nominal} мА·ч при заводских {design} (+{(r-1)*100:.0f}%) — для родной физически невозможно")
        elif r > 1.03:
            flags.append(f"заявляет {nominal} мА·ч при заводских {design} (+{(r-1)*100:.0f}%) — выше заводской, у родной так не бывает")
        elif r < 0.45:
            flags.append(f"заявляет {nominal} мА·ч при заводских {design} — ниже рабочего предела")
    years = round(op_h / 8760, 1) if op_h else None
    if сырые_циклы is not None and cycles == 0 and years and years > 0.25:
        flags.append(f"ноль циклов при наработке {years} года — пак новее аппарата")
    if disconnects:
        doubts.append(f"шлейф батареи снимали {disconnects} раз(а) — аппарат вскрывали")
    циклы_телефона = (телефон or {}).get("циклы")
    if (isinstance(циклы_телефона, int) and сырые_циклы is not None
            and циклы_телефона - cycles > ЗАПАС_ЦИКЛОВ):
        # Телефон помнит циклы на момент последнего изменения процента, а счётчик батареи с
        # тех пор мог только вырасти. На восьми проверках так и есть (узел/телефон): 403/402,
        # 424/423, 22/22, 0/0, 101/101, 1045/1035, 1241/1021, 1810/1756 — отставание телефона
        # сомнением не считаем. А вот счётчик МЕНЬШЕ запомненного у той же батареи невозможен:
        # его сбросили, оставив серийник (при честной замене телефон свою запись стирает).
        # По циклам идёт самая дорогая колонка прайса, молчать об этом нельзя.
        doubts.append(f"счётчик циклов {cycles}, а телефон запомнил {циклы_телефона} — "
                      f"похоже, счётчик батареи сбрасывали")

    return {
        # «Есть данные» — это есть ЦИФРЫ, а не «узел не пустой». Узел без DesignCapacity и
        # NominalChargeCapacity (так бывает, когда Apple переносит ключи, и так было в iOS 26)
        # не даёт ни здоровья, ни проверки на подделку — значит батарея не прочитана, и отчёт
        # обязан сказать это, а не молча объявить ёмкость «в норме заводской».
        "есть_данные": bool(design and nominal),
        "узел_есть": bool(b),
        "здоровье_%": health,
        # По какой ёмкости посчитали и что дала бы текущая: если на точке скажут, что число
        # опять расходится с экраном телефона, разбирать это надо по сохранённой оценке, а не
        # на словах.
        "здоровье_основание": основание,
        # Что телефон сказал сам и что вышло бы у нас — рядом: по ним разбирают спор у
        # стойки, не гадая, какое число откуда.
        "здоровье_по_телефону_%": (телефон or {}).get("процент"),
        "обслуживание_флаг": (телефон or {}).get("состояние"),
        "здоровье_текущее_%": текущее,
        "минимум_мАч": минимум or None,
        "ёмкость_мАч": nominal or None,
        "заводская_мАч": design or None,
        # ноль циклов — самая дорогая колонка прайса Оценки («100 (0-30)»). Отсутствие
        # ключа ею быть не должно.
        "циклы": cycles if сырые_циклы is not None else None,
        # что запомнил сам телефон: циклы на момент последнего изменения процента, не
        # текущие (см. шапку). Лежат рядом, чтобы спор разбирался по сохранённой оценке.
        "циклы_по_телефону": циклы_телефона if isinstance(циклы_телефона, int) else None,
        "наработка_лет": years,
        "макс_температура": tmax if 0 < tmax <= 90 else None,
        "серийник": serial,
        "снятий_шлейфа": disconnects if сырой_шлейф is not None else None,
        "заряд_%": num(deep(b, "CurrentCapacity")) or None,
        "подделка": flags,
        "сомнения": doubts,
    }
